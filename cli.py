            if помощь is None:
                помощь = ревью_в_чате(чат, аргументы, реплика)
            if помощь is not None:
                if помощь:
                    return помощь
                continue
            try:
                with _ХодЧата():
                    ход = чат.ход(реплика)
                напечатать_ход(ход)
            except (ОшибкаЧата, ValueError) as exc:
                print(f"Ошибка: {exc}", file=sys.stderr)
                return 1
