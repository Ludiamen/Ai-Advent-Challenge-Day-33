def _поправки(аргументы) -> dict:
    """Поправки режима поиска из ключей: реранкер, K до/после, порог, rewrite."""
    поправки: dict = {}
    if аргументы.reranker is not None:
        поправки["реранкер"] = "" if аргументы.reranker == "нет" else аргументы.reranker
    if аргументы.k_before:
        поправки["k_до"] = аргументы.k_before
    if аргументы.k_after:
        поправки["k_после"] = аргументы.k_after
    if аргументы.cutoff is not None:
        поправки["порог"] = аргументы.cutoff
    if аргументы.rewrite is not None:
        поправки["rewrite"] = аргументы.rewrite == "да"
    return поправки


def _поиск(agent: MemoryAgent, аргументы, режим: str = ""):
    """Имя режима или, если есть поправки, готовые Настройки."""
    from dataclasses import replace
    режим = режим or аргументы.search_mode
    поправки = _поправки(аргументы)
    if not поправки:
        return режим
    основа = agent._отвечатель(_стратегия_rag(аргументы)).поисковик.настройки(режим or "полный")
    return replace(основа, имя=f"{режим or 'полный'}*", **поправки)


