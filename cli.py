def напечатать_флоу(флоу: dict, подробно: bool = True) -> None:
    """Протокол длинного флоу: план, вызовы по порядку, сверка."""
    print(f"Флоу №{флоу['номер']} — {флоу['состояние']} "
          f"({_секунды(флоу.get('секунд', 0))}, кругов {флоу.get('кругов', 0)}, "
          f"вызовов {флоу.get('вызовов', 0)})")
    print(f"  запрос: {флоу.get('запрос', '')}")
    if флоу.get("маршрут"):
        напечатать_маршрут(флоу["маршрут"])
    план = флоу.get("план") or {}
    if план.get("шаги"):
        цепочка = " → ".join(ш["инструмент"] for ш in план["шаги"])
        print(f"  план: {план.get('цель', '')}")
        print(f"        {цепочка}")
        for замечание in план.get("замечания", []):
            print(f"        замечание: {замечание}")
    elif план.get("замечания"):
        print(f"  план: не составлен ({'; '.join(план['замечания'])})")
    if подробно and флоу.get("шаги"):
        print("  шаги:")
        for шаг in флоу["шаги"]:
            метка = f"по плану {шаг['по_плану']}" if шаг["по_плану"] else "сверх плана"
            print(f"   {шаг['место']}. {шаг['инструмент']} [{шаг['состояние']}, {метка}]"
                  + (f" — {шаг['зачем']}" if шаг.get("зачем") else ""))
            if шаг.get("причина"):
                print(f"      {шаг['причина']}")
            elif шаг.get("текст"):
                # Ответ инструмента — это JSON в несколько десятков строк.
                # В протоколе нужна одна строка: видно, что вернулось, и
                # протокол остаётся читаемым. Полный ответ — в базе.
                одной_строкой = " ".join(шаг["текст"].split())
                print(f"      {одной_строкой[:200]}")
    сверка = флоу.get("сверка") or {}
    if сверка.get("словами"):
        print(f"  сверка: {сверка['словами']}")
    if флоу.get("итог"):
        print(f"  итог: {флоу['итог']}")
    if флоу.get("состояние") == "ждёт":
        ожидание = флоу.get("ожидание") or {}
        print(f"  ждёт заявку №{флоу.get('заявка')} на «{ожидание.get('инструмент', '')}»:")
        print(f"    подтвердить: --подтвердить {флоу.get('заявка')} · "
              f"продолжить: --флоу-продолжить {флоу['номер']}")


