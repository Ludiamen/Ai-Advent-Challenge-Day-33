        запись = ответ.routing_entry
        решение = "записано" if запись["применено"] else "не записано"
        print(f"  маршрутизатор: {решение} -> {запись['слой']}"
              f"{'/' + запись['подслой'] if запись['подслой'] else ''}; {запись['причина']}")
