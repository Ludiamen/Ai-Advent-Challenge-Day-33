def напечатать_прогон(прогон: dict, подробно: bool = True) -> None:
    """Протокол прогона: шаги, что в них подставилось и что они вернули.

    Подстановки печатаются отдельной строкой намеренно: это и есть ответ на
    вопрос задания «корректно ли данные передаются между инструментами» —
    видно, какое поле предыдущего шага ушло в следующий и чем оно оказалось.
    """
    значок = {"готов": "✓", "сбой": "✗", "идёт": "…"}.get(прогон["состояние"], "?")
    print(f"{значок} Прогон №{прогон['номер']} «{прогон['конвейер']}» — "
          f"{прогон['состояние']}, шагов {прогон['сделано']} из {прогон['шагов']}, "
          f"{прогон['секунд']:g} с ({_время_коротко(прогон['начат'])})")
    if прогон.get("вход"):
        print(f"   вход: {_аргументы_кратко(прогон['вход'])}")
    if прогон.get("кто"):
        print(f"   запустил: {прогон['кто']}" + (f" · зачем: {прогон['зачем']}"
                                                 if прогон.get("зачем") else ""))
    for шаг in прогон.get("шаги", []):
        метка = "✓" if шаг["ок"] else "✗"
        print(f"   {метка} {шаг['место']}. {шаг['имя']} → {шаг['инструмент']} "
              f"({шаг['секунд']:g} с)")
        if подробно and шаг["подстановки"]:
            for путь, что in шаг["подстановки"]:
                print(f"        получил {путь} → {что}")
        if подробно and шаг["вход"]:
            print(f"        вход: {_аргументы_кратко(шаг['вход'])}")
        if шаг["ок"]:
            текст = " ".join((шаг["текст"] or "").split())
            if текст:
                print(f"        вернул: {текст[:160]}")
        else:
            print(f"        ошибка: {шаг['ошибка']}")
    if прогон.get("итог"):
        print(f"   итог: {прогон['итог']}")
    if прогон.get("ошибка"):
        print(f"   встали: {прогон['ошибка']}")


def протокол_прогона(протокол: dict) -> dict:
    """Ответ инструмента run_pipeline в тот же вид, что даёт хранилище.

    Сервер возвращает протокол коротко (для модели), а печатать хочется одним
    и тем же кодом — и то, что пришло от инструмента, и то, что прочитано из
    базы. Поэтому здесь имена полей приводятся к одному виду.
    """
    шаги = []
    for место, шаг in enumerate(протокол.get("шаги", []), 1):
        получил = [с.split(" → ", 1) for с in шаг.get("получил", [])]
        шаги.append({
            "место": место, "имя": шаг.get("шаг", ""), "инструмент": шаг.get("инструмент", ""),
            "ок": bool(шаг.get("ок")), "секунд": шаг.get("секунд", 0),
            "подстановки": [п if len(п) == 2 else [п[0], ""] for п in получил],
            "вход": шаг.get("вход", {}), "текст": шаг.get("вернул", ""),
            "ошибка": шаг.get("ошибка", ""),
        })
    return {
        "номер": протокол.get("прогон", 0), "конвейер": протокол.get("конвейер", ""),
        "состояние": протокол.get("состояние", ""), "шагов": протокол.get("шагов", 0),
        "сделано": протокол.get("сделано", 0), "секунд": протокол.get("секунд", 0),
        "начат": протокол.get("начат", ""), "вход": протокол.get("вход", {}),
        "кто": протокол.get("кто", ""), "зачем": протокол.get("зачем", ""),
        "итог": протокол.get("итог", ""), "ошибка": протокол.get("ошибка", ""),
        "шаги": шаги,
    }


