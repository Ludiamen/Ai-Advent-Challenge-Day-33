def этапы_строкой(этапы: list[dict]) -> str:
    """Разбор → поиск → ответ: модель, секунды, токены (День 27)."""
    части = []
    for э in этапы:
        if э.get("этап") == "поиск":
            подробно = (f"{э.get('реранкер') or 'без реранкера'} {э.get('k_до', '')}→{э.get('k_после', '')}"
                        if э.get("реранкер") is not None else "")
            if э.get("подвопросов"):
                подробно += f", подвопросов {э['подвопросов']}"
            части.append(f"поиск{' · ' + подробно if подробно else ''} · {э.get('секунд', 0)} с")
            continue
        модель = э.get("модель", "")
        где = " (локально)" if э.get("локально") else (" (облако)" if модель else "")
        токены = (f", вход {э['вход']} / выход {э['выход']} ток." if "вход" in э else "")
        if э.get("окна"):
            токены += f", фрагменты → лучшие окна ({', '.join(э['окна'])} симв.)"
        части.append(f"{э.get('этап')} · {модель}{где} · {э.get('секунд', 0)} с{токены}")
    return " → ".join(части)


