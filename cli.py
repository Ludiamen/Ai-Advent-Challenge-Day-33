def выполнить_флоу(agent: MemoryAgent, вопрос: str, продолжить: int = 0) -> int:
    """Запускает длинный флоу или продолжает остановленный."""
    флоу = (agent.продолжить_флоу(продолжить) if продолжить
            else agent.флоу(вопрос))
    print(LINE)
    print("ДЛИННЫЙ ФЛОУ")
    print(LINE)
    напечатать_флоу(флоу)
    print(LINE)
    if флоу["состояние"] == "ждёт":
        print("Флоу остановлен до вашего решения — добытое сохранено, "
              "переделывать шаги не придётся.")
        return 0
    if флоу["состояние"] in ("сбой", "оборван"):
        return 1
    print(f"Полный протокол: python cli.py --флоу-показать {флоу['номер']}")
    return 0


