    итог: dict = {}
    мысли = False
    сообщения = [{"role": "user", "content": вопрос}]
    if коротко and bench.системная_подсказка():
        сообщения.insert(0, {"role": "system", "content": bench.системная_подсказка()})
    for с in stream.поток(ключ, сообщения, думать=думать):
        if с["тип"] == "думает":
            if not мысли:
                print("(размышления) ", end="", flush=True)
                мысли = True
            print(с["текст"], end="", flush=True)
        elif с["тип"] == "текст":
            if мысли:
                print("\n(ответ) ", end="", flush=True)
                мысли = False
            print(с["текст"], end="", flush=True)
        else:
            итог = с
    print()
    return итог


