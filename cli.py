def команда_индекса(аргументы) -> int | None:
    """Ключи индекса документов. None — ни одного такого ключа не было.

    Агент им не нужен, как и «--mcp»: индекс собирается и ищется без модели и
    памяти, и поднимать ради этого диалог незачем.
    """
    действия = (
        ("rag_extract", показать_извлечённое), ("rag_build", собрать_индекс),
        ("rag_show", показать_индекс), ("rag_search", найти_в_документах),
        ("rag_chunk", показать_чанк), ("rag_compare", сравнить_стратегии),
    )
    for ключ, действие in действия:
        if getattr(аргументы, ключ, None):
            try:
                return действие(аргументы)
            except (rag.ОшибкаИндекса, rag.ОшибкаЭмбеддера, OSError, ValueError,
                    RuntimeError) as exc:
                print(f"Ошибка: {exc}", file=sys.stderr)
                return 1
    return None


