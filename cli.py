def наблюдатели(agent: MemoryAgent, трейс: bool):
    """Пара обработчиков, печатающих ход сценария по мере дела.

    Пять шагов идут от полутора минут и дольше. Печатать всё в конце — значит
    заставить человека смотреть в неподвижный экран; поэтому ответ каждого шага
    выводится сразу, как только он получен.
    """

    def перед(шаг, номер, всего):
        print(f"\n[{номер}/{всего}] {шаг.агент} — {шаг.стадия}, "
              f"{agent.runner.model_for(шаг)}…", flush=True)

    def после(результат, номер, всего):
        личный = " (ответ вам)" if номер == всего else " (вход следующего шага)"
        print("-" * 78)
        текст = результат.текст.strip()
        if not трейс and номер != всего and len(текст) > 600:
            текст = текст[:600] + "…"
        print(текст)
        print(f"[{tokens.format_tokens(результат.токенов)} токенов{личный}]", flush=True)

    return перед, после


def показать_прогон(итог, трейс: bool) -> None:
    """Печатает итог сценария. Сами шаги уже напечатаны по ходу дела."""
    print()
    print(LINE)
    print(f"СЦЕНАРИЙ «{итог.сценарий}» — шагов в этом прогоне {len(итог.шаги)}, "
          f"задача {итог.task_id}")
    if итог.на_паузе:
        print(LINE)
        print(f"ОСТАНОВЛЕНО на шаге {итог.шаг} из {итог.всего_шагов}: "
              f"{итог.причина_паузы}")
        print(f"Ждём: {итог.ожидание} — {итог.ожидание_текст}")
        чем = ("--ответ «текст»" if итог.ожидание == "ответ-пользователя"
               else "--продолжить")
        print(f"Продолжить: python cli.py --задача {итог.task_id} {чем}")
        print("Состояние лежит на диске: продолжить можно и из другого запуска.")
    if итог.решение:
        print(f"В журнал решений: №{итог.решение['id']} {итог.решение['заголовок']}")
        print("Рабочая память задачи очищена — итог теперь в долговременной.")
    print(LINE)
    print(f"Всего {tokens.format_tokens(итог.токенов)} токенов, "
          f"{tokens.format_cost(итог.стоимость)}")


def спросить(agent: MemoryAgent, вопрос: str, трейс: bool, сценарии: bool,
             по_шагам: bool = False) -> None:
    """Один вопрос: либо сценарием, если сработал триггер, либо обычным ответом."""
    сценарий = agent.match_scenario(вопрос) if сценарии else None
    if сценарий is not None:
        print(f"Сработал сценарий «{сценарий.имя}»: "
              f"{' → '.join(ш.агент for ш in сценарий.шаги)}")

        перед, после = наблюдатели(agent, трейс)
        итог = agent.run_scenario(вопрос, name=сценарий.имя, on_step=перед,
                                  on_result=после, по_шагам=по_шагам)
        показать_прогон(итог, трейс)
        return

    ответ = agent.ask(вопрос)
    print(f"\n{ответ.text}")
    показать_вызовы(ответ)
    показать_свежее(ответ)
    if ответ.blocked:
        print("\n! Ответ нарушает инварианты и не был исправлен за отведённые попытки.")
    if трейс:
        показать_трейс(ответ)
    показать_расход(ответ)


