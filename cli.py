    try:
        сводка = agent.подключить_инструменты()
    except AgentError as exc:
        print(f"Ошибка: {exc}", file=sys.stderr)
        return 1
    print(LINE)
    print("ИНСТРУМЕНТЫ MCP, доступные модели")
    print(LINE)
    for инструмент in agent.toolbox.инструменты:
        меняет = "меняет данные" if инструмент.доступ != "только чтение" else "только чтение"
