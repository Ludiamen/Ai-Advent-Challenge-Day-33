def _сек(з) -> str:
    return "—" if з is None else f"{з:.1f}".replace(".", ",")


def замеры_строкой(т: dict) -> str:
    """Поиск по шагам → окна → чтение промпта → первый токен → генерация → всего."""
    поиск = f"поиск {_сек(т.get('поиск_с'))} с"
    шаги = [f"{имя} {_сек(т.get(ключ))}" for имя, ключ in
            (("вектор", "вектор_с"), ("косинус", "косинус_с"), ("кросс-энкодер", "кросс_с")) if т.get(ключ) is not None]
    if шаги:
        поиск += f" ({' · '.join(шаги)}" + (f", оценок из кэша {т['оценок_из_кэша']}"
                                              if т.get("оценок_из_кэша") is not None else "") + ")"
    части = [поиск]
    if т.get("окна_с"):
        части.append(f"окна {_сек(т['окна_с'])} с")
    if т.get("чтение_с") is not None:
        кэш = "из кэша Ollama" if т.get("кэш_промпта") else "заново"
        части.append(f"чтение промпта {_сек(т['чтение_с'])} с ({т.get('вход', 0)} ток., "
                     f"{_сек(т.get('скорость_чтения'))} ток/с, {кэш})")
        части.append(f"первый токен {_сек(т.get('до_первого_с'))} с")
        части.append(f"генерация {_сек(т.get('генерация_с'))} с, {_сек(т.get('ток_с'))} ток/с")
    else:
        части.append(f"ответ модели {_сек(т.get('модель_с'))} с ({т.get('вход', 0)} → {т.get('выход', 0)} ток., "
                     f"{_сек(т.get('ток_с'))} ток/с по общему времени)")
    части.append(f"всего {_сек(т.get('всего_с'))} с")
    return " → ".join(части)


