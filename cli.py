def показать_mcp(имя: str, путь: str = "", схема: bool = False) -> int:
    """Подключиться к серверам и показать их инструменты."""
    реестр = _реестр(путь)
    if реестр is None:
        return 1
    if not реестр.servers:
        print(f"В {реестр.path} нет серверов.")
        return 1
    try:
        имена = None if имя == "*" else [реестр.server(имя).имя]
    except mcp.MCPConfigError as exc:
        print(f"Ошибка: {exc}", file=sys.stderr)
        return 1

    print(LINE)
    print(f"MCP: подключение к серверам из {реестр.path}")
    print(LINE)
    осмотры = реестр.inspect(имена)
    for о in осмотры:
        показать_осмотр(о, схема)
        print(LINE)
    итог = mcp.summary(осмотры)
    print(f"Подключено {итог['подключено']} из {итог['серверов']}"
          + (f", пропущено {итог['пропущено']}" if итог["пропущено"] else "")
          + (f", сбоев {итог['сбоев']}" if итог["сбоев"] else "")
          + f". Инструментов {итог['инструментов']}, разрешено {итог['разрешено']}"
          + f"; их схема ≈ {tokens.format_tokens(итог['токенов'])} ток. на каждый запрос к модели.")
    if итог["повторы_имён"]:
        print("Повторяются имена для модели: " + ", ".join(итог["повторы_имён"]))
    print("Звёздочка — обязательный параметр. «*» в фильтре — любой хвост имени.")
    return 1 if итог["сбоев"] else 0


