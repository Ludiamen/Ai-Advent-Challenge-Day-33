#!/usr/bin/env python3
"""Проверка задания Дня 24: цитаты, источники и анти-галлюцинации.

Задание: модель обязательно возвращает ответ, список источников (source +
section/chunk_id) и цитаты из найденных чанков; проверка на 10 вопросах —
есть ли источники и цитаты в каждом ответе и совпадает ли смысл ответа с
цитатами; усиление — при релевантности ниже порога ассистент говорит «не знаю»
и просит уточнение. Скрипт идёт по этим пунктам на настоящем индексе, живой
модели ответов (ds-flash) и живом судье, а агента проверяет отдельными
процессами cli.py.

  Часть 1  ЦИТАТЫ КОДОМ. На настоящих чанках: дословная цитата, шум OCR, номер
           не того фрагмента, выдумка и слишком короткая цитата — без модели.
  Часть 2  ОТВЕТ С ИСТОЧНИКАМИ И ЦИТАТАМИ. Живой ответ: JSON → паспорт
           источника по номеру → цитаты найдены в тексте фрагмента → числа
           ответа есть в цитатах.
  Часть 3  ОБЯЗАТЕЛЬНОСТЬ. Модель вернула не JSON — повторный запрос с
           перечнем нарушений; цитата выдумана и после повтора — «не знаю».
  Часть 4  «НЕ ЗНАЮ». Порог подобран на стенде Дня 21; ловушка и вопрос без
           предмета — «не знаю» по порогу, неоднозначный — по правилу модели;
           у каждого — уточняющий вопрос.
  Часть 5  ДЕСЯТЬ ВОПРОСОВ И РАСПЛЫВЧАТЫЕ. Источники, цитаты, смысл (код и
           судья), «не знаю» с уточнением; рядом — формат Дня 23 без цитат.
  Часть 6  АГЕНТ. cli.py --с-цитатами на вопросе с ответом и на ловушке.

Запуск:
    python check_citations.py                  # всё: модель ds-flash, судья groq
    python check_citations.py --без-судьи      # смысл — только кодом
    python check_citations.py --без-проверки   # без части 5 (она самая долгая)
    python check_citations.py --в RESULTS.md   # дописать протокол в файл
"""

