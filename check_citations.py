def часть_1(отчёт: Отчёт, индексатор: Индексатор) -> None:
    отчёт.часть(1, "Цитаты проверяет код: дословно, шум OCR, не тот фрагмент, выдумка")
    with sqlite3.connect(индексатор.база) as с:
        договор = с.execute("SELECT текст FROM чанки WHERE стратегия='структура' AND текст LIKE '%2.2.7%' "
                            "AND источник LIKE 'Ростелеком VPN%'").fetchone()[0]
        скан = с.execute("SELECT текст FROM чанки WHERE стратегия='структура' AND источник LIKE 'Вымпелком%' "
                         "AND распознан=1 AND текст LIKE '%неустойк%' LIMIT 1").fetchone()[0]
    пункт = договор[договор.find("2.2.7"):]
    дословно = " ".join(пункт.split()[1:16])
    кусок = скан[скан.find("неустойк"):]
    с_ошибкой = " ".join(кусок.split()[:14]).replace("е", "с", 1)       # как ошибается OCR
    р = cite.разобрать(json.dumps({"ответ": "…", "источники": [1], "цитаты": [
        {"n": 1, "текст": дословно}, {"n": 1, "текст": с_ошибкой},
        {"n": 1, "текст": "Оператор обязан уведомлять Абонента за тридцать дней до изменений"},
        {"n": 1, "текст": "10 дней"}]}, ensure_ascii=False))
    cite.проверить_цитаты(р, [договор, скан])
    for ц in р.цитаты:
        отчёт(f"    [{ц.n}] → {ц.проверка:<19} нашлась в [{ц.найдена_в}] сходство {ц.сходство:.3f}: «{ц.текст[:70]}»")
    виды = [ц.проверка for ц in р.цитаты]
    отчёт.пункт(виды[0] == cite.ДОСЛОВНО, "дословная цитата п. 2.2.7 найдена в своём фрагменте")
    отчёт.пункт(виды[1] == cite.В_ДРУГОМ and р.цитаты[1].найдена_в == 2,
                "цитата со скана с ошибкой OCR и чужим номером найдена во фрагменте [2] — номер исправляется")
    отчёт.пункт(виды[2] == cite.НЕ_НАЙДЕНА, "выдуманная «за тридцать дней» не найдена ни в одном фрагменте")
    отчёт.пункт(виды[3] == cite.КОРОТКАЯ, "«10 дней» — слишком короткая цитата, не довод")
    нарушено = cite.нарушения(р, 2, "")
    отчёт.пункт(any("нет ни в одном фрагменте" in н for н in нарушено),
                f"нарушения формата названы для повторного запроса: {len(нарушено)}")


def часть_2(отчёт: Отчёт, отвечатель: Отвечатель, модель: str) -> None:
    отчёт.часть(2, "Ответ с источниками и цитатами — живая модель")
    for вопрос in (ТАРИФЫ, НЕУСТОЙКА):
        а = отвечатель.ответить(вопрос, С_RAG, модель, поиск="фильтр")
        отчёт(f"  «{вопрос}»")
        отчёт(f"    уверенность {а.решение.уверенность:.2f} при пороге {а.решение.порог:.2f}; "
              f"вызовов {а.вызовов}{', был повторный запрос' if а.починка else ''}; "
              f"{_секунды(а.секунд_модели)}")
        отчёт(f"    > {а.текст}")
        for и in а.источники:
            отчёт(f"    источник [{и['n']}] {и['source']} · {и['section']} · {и['chunk_id']}")
        for ц in а.выдержки:
            отчёт(f"    цитата [{ц.n}] {ц.проверка}: «{' '.join(ц.текст.split())[:150]}»")
        отчёт.пункт(bool(а.источники) and all(и["source"] and и["section"] and и["chunk_id"]
                                              for и in а.источники),
                    "   источники: файл, раздел и chunk_id подставлены кодом по номеру")
        отчёт.пункт(bool(а.выдержки) and all(ц.подтверждена for ц in а.выдержки),
                    f"   цитат {len(а.выдержки)}, все найдены в тексте фрагментов")
        без_опоры = cite.числа_без_опоры(а.текст, а.выдержки, вопрос)
        отчёт.пункт(not без_опоры and not а.не_знаю,
                    "   все числа ответа стоят в цитатах" + (f" (без опоры: {без_опоры})" if без_опоры else ""))
    отчёт.пункт("Верни ТОЛЬКО объект JSON" in cite.ПРАВИЛА_ЦИТАТ and "ДОСЛОВНО" in cite.ПРАВИЛА_ЦИТАТ,
                "правила промпта: JSON с ответом, источниками и дословными цитатами")


class _ПервыйОтветПлохой:
    """Обёртка над настоящим клиентом: первые ответы на запрос с цитатами — заготовка."""

    def __init__(self, клиент, *заготовки: str) -> None:
        self.клиент, self.заготовки = клиент, list(заготовки)
        self.spent = клиент.spent

    def call(self, model_key, messages, **к):
        if self.заготовки and "ДОСЛОВНО" in messages[0]["content"]:
            return Reply(text=self.заготовки.pop(0), model_key=model_key)
        return self.клиент.call(model_key, messages, **к)


def часть_3(отчёт: Отчёт, индексатор: Индексатор, клиент, модель: str) -> None:
    отчёт.часть(3, "Обязательность: ответ не в формате — повтор; нет цитаты — нет ответа")
    отвечатель = Отвечатель(индексатор, _ПервыйОтветПлохой(клиент, "Ростелеком предупреждает за 10 дней."))
    а = отвечатель.ответить(ТАРИФЫ, С_RAG, модель, поиск="фильтр")
    отчёт(f"  первый ответ модели — текст без JSON; после повтора: «{а.текст[:120]}»")
    отчёт.пункт(а.починка and а.вызовов == 2 and not а.не_знаю and all(ц.подтверждена for ц in а.выдержки),
                "повторный запрос с перечнем нарушений вернул ответ с подтверждёнными цитатами")
    выдумка = json.dumps({"ответ": "Ростелеком предупреждает за 30 дней [1].", "источники": [1], "цитаты": [
        {"n": 1, "текст": "Оператор обязан уведомлять Абонента за тридцать дней до изменения тарифов"}]},
        ensure_ascii=False)
    отвечатель = Отвечатель(индексатор, _ПервыйОтветПлохой(клиент, выдумка, выдумка))
    а = отвечатель.ответить(ТАРИФЫ, С_RAG, модель, поиск="фильтр")
    отчёт(f"  модель дважды выдумала цитату: «{а.текст[:160]}»")
    отчёт.пункт(а.не_знаю and а.не_знаю_кто == "проверка цитат" and "30" not in а.текст.split("Уточните")[0],
                "ответ «30 дней» без подтверждённой цитаты не выдан: «не знаю» и уточнение")


def часть_4(отчёт: Отчёт, отвечатель: Отвечатель, модель: str) -> None:
    отчёт.часть(4, "«Не знаю» при слабом контексте: порог в коде, уточнение — модель")
    путь = отвечатель.поисковик.путь_настроек or путь_настроек()
    настройки = прочитать_настройки(путь)
    отчёт.пункт(bool(настройки.get("порог_уверенности")),
                f"порог «не знаю» {настройки['порог_уверенности']} — из {настройки['источник']}")
    with open(путь, encoding="utf-8") as f:
        подбор = json.load(f).get("уверенность") or {}
    for с in подбор.get("сетка", []):
        отчёт(f"    порог {с['порог']:<4} ловушки «не знаю» {с['ловушки_не_знаю']} из {с['ловушек']} · "
              f"лишние {с['лишние_не_знаю']} из {с['найденных']} · честные {с['честные_не_знаю']} из {с['слабых']}"
              + ("  ← выбран" if с["порог"] == настройки["порог_уверенности"] else ""))
    в = подбор.get("выбрано", {})
    отчёт.пункт(в.get("ловушки_не_знаю") == в.get("ловушек") and в.get("лишние_не_знаю") == 0,
                "на стенде Дня 21 все ловушки получают «не знаю», вопросы с найденным ответом — нет")
    for вопрос, ждём in ((WIFI, "порог"), ("Что с ним делать дальше?", "порог"),
                         ("А сколько это стоит?", "модель")):
        а = отвечатель.ответить(вопрос, С_RAG, модель, поиск="фильтр")
        отчёт(f"  «{вопрос}» → уверенность {а.решение.уверенность:.2f}; решил: {а.не_знаю_кто or '—'}")
        отчёт(f"    > {а.текст[:260]}")
        отчёт.пункт(а.не_знаю and а.уточнение.endswith("?") and not а.источники and а.не_знаю_кто == ждём,
                    f"   «не знаю» и уточняющий вопрос; решил {ждём}")


def часть_5(отчёт: Отчёт, отвечатель: Отвечатель, модель: str, судья: bool) -> dict:
    отчёт.часть(5, "Десять контрольных вопросов и расплывчатые: источники, цитаты, смысл, «не знаю»")
    вопросы = citecheck.загрузить_вопросы()

    def ход(что, сделано, всего, где):
        print(f"    {что} {сделано}/{всего} {где}")

    прогон = citecheck.прогнать(отвечатель, вопросы, судья, модель, прогресс=ход)
    путь = citecheck.записать(прогон, os.path.dirname(отвечатель.индексатор.база))
    for строка in citecheck.в_markdown(прогон).split("## Ответы целиком")[0].splitlines():
        if строка.startswith("|"):
            отчёт("  " + строка)
    т = прогон.итог("цитаты")
    отчёт.пункт(т["отвечено"] == т["с_ответом"], f"на все {т['с_ответом']} вопросов с ответом дан ответ — "
                                                  "лишних «не знаю» нет")
    отчёт.пункт(т["с_источниками"] == т["источники_полные"] == т["отвечено"],
                f"источники в каждом ответе: {т['с_источниками']} из {т['отвечено']}, у всех файл, раздел, chunk_id")
    отчёт.пункт(т["с_цитатами"] == т["отвечено"],
                f"цитаты в каждом ответе: {т['с_цитатами']} из {т['отвечено']}")
    отчёт.пункт(т["подтверждено"] == т["цитат"],
                f"все цитаты найдены в документах: {т['подтверждено']} из {т['цитат']} (дословно {т['дословно']})")
    отчёт.пункт(т["смысл_код"] == т["отвечено"],
                f"смысл совпадает с цитатами по коду (числа и факты ответа в цитатах): {т['смысл_код']} из {т['отвечено']}")
    if судья:
        отчёт.пункт(т["смысл_нет"] == 0 and т["судья_молчал"] == 0,
                    f"судья: да {т['смысл_да']}, частично {т['смысл_частично']}, нет {т['смысл_нет']}")
    отчёт.пункт(т["ловушки_не_знаю"] == т["ловушек"],
                f"ловушки — «не знаю» с уточнением: {т['ловушки_не_знаю']} из {т['ловушек']}")
    отчёт.пункт(т["расплывчатые_не_знаю"] == т["расплывчатых"],
                f"расплывчатые — «не знаю» с уточнением: {т['расплывчатые_не_знаю']} из {т['расплывчатых']}; "
                f"на ловушках и расплывчатых «не знаю» решил порог в {т['не_знаю_порог']} случаях, "
                f"модель — в {т['не_знаю_модель']}")
    было = прогон.итог("текст")
    отчёт(f"  формат Дня 23 на тех же вопросах: цитаты в {было['с_цитатами']} из {было['отвечено']} ответов, "
          f"ловушки с уточнением {было['ловушки_не_знаю']} из {было['ловушек']}, расплывчатые "
          f"{было['расплывчатые_не_знаю']} из {было['расплывчатых']}")
    отчёт.пункт(os.path.exists(путь), f"отчёт с ответами и цитатами целиком: {os.path.relpath(путь, КОРЕНЬ)}")
    return прогон.to_dict()


def часть_6(отчёт: Отчёт, модель: str) -> None:
    отчёт.часть(6, "Агент — отдельными процессами cli.py")
    память = os.path.join(КОРЕНЬ, "memory")
    for вопрос, что in (("Сколько лицензий Касперского закупается для Автотранса и на какую сумму?", "ответ"),
                        (WIFI, "не знаю")):
        готово = subprocess.run([sys.executable, os.path.join(КОРЕНЬ, "cli.py"), "--память-в", память,
                                 "--модель", модель, "--с-цитатами", вопрос],
                                capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=600, cwd=КОРЕНЬ)
        вывод = готово.stdout + готово.stderr
        отчёт(f"  $ python cli.py --с-цитатами «{вопрос}»")
        for строка in вывод.splitlines():
            if строка.startswith(("С RAG", "Не знаю", "Источники", "Цитаты", "  [", "«Не знаю»", "Уточняющий")) \
                    or строка[:2].isdigit():
                отчёт("    " + строка[:170])
        отчёт.пункт(готово.returncode == 0 and "Вы:" not in вывод, f"{что}: команда завершилась сама, без диалога")
        if что == "ответ":
            отчёт.пункт("✓ дословно" in вывод and "struct-" in вывод and "26731.5" in вывод.replace(" ", ""),
                        "агент: 30 лицензий на 26 731,5 — с источником и дословной цитатой")
        else:
            отчёт.пункт("«Не знаю» — решил: порог уверенности (код)" in вывод and "Уточняющий вопрос:" in вывод,
                        "агент: «не знаю» по порогу и уточняющий вопрос")


def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверка Дня 24: цитаты, источники и «не знаю».")
    разбор.add_argument("--модель", dest="model", default="", help="модель ответов (по роли — ds-flash)")
    разбор.add_argument("--без-судьи", dest="no_judge", action="store_true")
    разбор.add_argument("--без-проверки", dest="no_check", action="store_true")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ")
    аргументы = разбор.parse_args()

    модель = аргументы.model or catalog.for_role("ответ-по-документам", 0)
    отчёт = Отчёт()
    начало = time.monotonic()
    индексатор = Индексатор()
    клиент = Client()
    отвечатель = Отвечатель(индексатор, клиент)
    отчёт(LINE)
    отчёт(f"Проверка Дня 24: цитаты, источники и «не знаю» · модель {модель} · судья "
          f"{'выключен' if аргументы.no_judge else ', '.join(dict.fromkeys(catalog.for_role('судья-ответов', i) for i in range(2)))}")
    try:
        часть_1(отчёт, индексатор)
        часть_2(отчёт, отвечатель, модель)
        часть_3(отчёт, индексатор, клиент, модель)
        часть_4(отчёт, отвечатель, модель)
        if not аргументы.no_check:
            часть_5(отчёт, отвечатель, модель, not аргументы.no_judge)
        часть_6(отчёт, модель)
    finally:
        клиент.close()
    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}.")
    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as f:
            f.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
