def _cli(память: str, модель: str, *ключи: str, предел: int = 600) -> tuple[int, str]:
    готово = subprocess.run([sys.executable, os.path.join(КОРЕНЬ, "cli.py"), "--память-в", память,
                             "--модель", модель, *ключи],
                            capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=предел, cwd=КОРЕНЬ)
    return готово.returncode, готово.stdout + готово.stderr


class _Перехват:
    """Обёртка над настоящим клиентом: запоминает, что ушло в модель."""

    def __init__(self, клиент) -> None:
        self.клиент = клиент
        self.вызовы: list[list[dict]] = []
        self.spent = клиент.spent

    def call(self, model_key, messages, **kwargs):
        self.вызовы.append(messages)
        return self.клиент.call(model_key, messages, **kwargs)

    def close(self) -> None:
        self.клиент.close()


def _источники_строкой(ход) -> str:
    части = []
    for и in ход.источники:
        if и.get("вид") == "документ":
            части.append(f"{и.get('source', '')[:34]} · {и.get('section', '')[:28]} · {и.get('chunk_id')} "
                         f"(цитат {len(и.get('цитаты') or [])})")
        elif и.get("вид") == "проверено":
            части.append(f"проверено: {и.get('source', '')[:30]} · {и.get('section', '')[:24]}")
        else:
            части.append(f"память {и.get('код')}" + (f" → {len(и.get('документы') or [])} док." if и.get("документы") else ""))
    return "; ".join(части)


def _показать(отчёт: Отчёт, ход) -> None:
    отчёт(f"  [{ход.номер}] «{ход.реплика[:110]}»")
    отчёт(f"      понято: {ход.вид} · искали: «{ход.разбор.вопрос_для_поиска[:110]}»")
    for вопрос in ход.разбор.подвопросы:
        отчёт(f"      подвопрос: «{вопрос[:110]}»")
    if ход.изменения:
        отчёт(f"      память: {ход.изменения}")
    отчёт(f"      > {' '.join(ход.текст.split())[:230]}")
    отчёт(f"      источники: {_источники_строкой(ход)[:260]}")


