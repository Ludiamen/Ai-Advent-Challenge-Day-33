def часть_5(отчёт: Отчёт, модель: str, с_судьёй: bool) -> None:
    отчёт.часть(5, "Два длинных сценария: цель не теряется, источники в каждом ответе")
    агент = MemoryAgent(model_key=модель)          # память по умолчанию: отчёт ляжет в корень
    try:
        прогон = scenarios.прогнать(агент, scenarios.загрузить(), с_судьёй)
        путь = scenarios.записать(прогон, агент.memory.base_dir)
    finally:
        агент.close()
    for с in прогон.сценарии:
        т = с.итог()
        отчёт(f"  {с.сценарий['id']} «{с.сценарий['название']}»: реплик {т['ходов']}, "
              f"{_секунды(т['секунд'])}, вызовов {т['вызовов']}, токенов на входе {т['токенов_вход']}")
        отчёт(f"    цель: {(с.память.get('цель') or {}).get('текст', '—')}")
        for х, пп in zip(с.ходы, с.пункты):
            плохие = [п for п in пп if not п.ок]
            отчёт(f"    {х.номер:>2} {'✓' if not плохие else '✗'} {х.вид:<9} ист. {len(х.источники)} · "
                  f"«{х.реплика[:70]}»" + (f" — {'; '.join(f'{п.имя}: {п.пояснение}' for п in плохие)}" if плохие else ""))
        if с.судья:
            отчёт(f"    судья ({с.судья.get('модель', '—')}): цель удержана — {с.судья.get('цель_удержана') or '—'}, "
                  f"ограничения — {с.судья.get('ограничения_соблюдены') or '—'}, по делу — "
                  f"{с.судья.get('ответы_по_делу') or '—'}. {с.судья.get('пояснение', '')}")
        отчёт.пункт(10 <= т["ходов"] <= 15, f"   {с.сценарий['id']}: длинный сценарий — {т['ходов']} реплик")
        отчёт.пункт(т["с_поиском"] == т["ходов"], f"   поиск по базе на каждой реплике: {т['с_поиском']} из {т['ходов']}")
        отчёт.пункт(т["с_источниками"] == т["ходов"], f"   источники в каждом ответе: {т['с_источниками']} из {т['ходов']}")
        отчёт.пункт(т["с_документом_и_цитатой"] == т["документных"],
                    f"   ответы по документам с chunk_id и цитатой: {т['с_документом_и_цитатой']} из {т['документных']}")
        отчёт.пункт(т["цель_на_месте"][0] == т["цель_на_месте"][1] and т["цель_ключи"],
                    f"   цель на месте после каждой реплики: {т['цель_на_месте'][0]} из {т['цель_на_месте'][1]}")
        отчёт.пункт(т["факты"][0] == т["факты"][1] and т["нужный_документ"][0] == т["нужный_документ"][1],
                    f"   факты {т['факты'][0]} из {т['факты'][1]}, нужный документ "
                    f"{т['нужный_документ'][0]} из {т['нужный_документ'][1]}")
