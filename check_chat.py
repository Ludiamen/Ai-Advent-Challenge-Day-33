def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверка Дня 25: мини-чат с RAG и памятью задачи.")
    разбор.add_argument("--модель", dest="model", default="", help="модель ответов (по роли — ds-flash)")
    разбор.add_argument("--без-судьи", dest="no_judge", action="store_true")
    разбор.add_argument("--без-сценариев", dest="no_scenarios", action="store_true")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ")
    аргументы = разбор.parse_args()

    модель = аргументы.model or catalog.for_role("ответ-по-документам", 0)
    отчёт = Отчёт()
    начало = time.monotonic()
    каталог = tempfile.mkdtemp(prefix="check-chat-")
    отчёт(LINE)
    отчёт(f"Проверка Дня 25: мини-чат с RAG и памятью задачи · модель {модель} · разбор реплики "
          f"{catalog.for_role('разбор-реплики', 0)} · судья "
          f"{'выключен' if аргументы.no_judge else ', '.join(dict.fromkeys(catalog.for_role('судья-ответов', i) for i in range(2)))}")
    try:
        часть_1_4(отчёт, модель, каталог)
        if not аргументы.no_scenarios:
            часть_5(отчёт, модель, not аргументы.no_judge)
        часть_6(отчёт, модель, каталог)
    finally:
        shutil.rmtree(каталог, ignore_errors=True)
    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}.")
    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as f:
            f.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
