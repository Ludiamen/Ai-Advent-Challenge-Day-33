    отчёт.часть(3, "Чат по документам целиком на локальных моделях: три реплики, отдельные процессы")
    for номер, (реплика, факт, документ) in enumerate(РЕПЛИКИ, 1):
        код, вывод, секунд = _cli("--офлайн", "--память-в", память, "--чат", "проверка", "--реплика", реплика)
        отчёт(f"  $ python cli.py --офлайн --чат проверка --реплика «{реплика[:90]}{'…' if len(реплика) > 90 else ''}»")
        # Текст ответа — до первой пустой строки: дальше источники с цитатами,
