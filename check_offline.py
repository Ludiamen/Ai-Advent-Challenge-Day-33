        итоги[номер] = {"реплика": реплика, "секунд": round(секунд, 1), "ответ": ответ.splitlines()[0] if ответ else "",
                        "этапы": этапы}
        отчёт.пункт(код == 0 and bool(re.search(факт, ответ, re.S)),
                    f"реплика {номер}: ответ есть и в нём нужное ({факт.split('|')[0].strip(chr(92) + 'b')}) · {_секунды(секунд)}")
