def _окружение(офлайн: bool = True, **ещё: str) -> dict[str, str]:
    """Окружение процесса: ключи облака вычищены (в офлайне), свои переменные поверх."""
    окр = {**os.environ, "PYTHONIOENCODING": "utf-8", **ещё}
    if офлайн:
        for к in КЛЮЧИ_ОБЛАКА:
            окр[к] = ""
    return окр


def _cli(*ключи: str, офлайн: bool = True, предел: int = 2400, **окр: str) -> tuple[int, str, float]:
    старт = time.monotonic()
    готово = subprocess.run([sys.executable, os.path.join(КОРЕНЬ, "cli.py"), *ключи],
                            capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=предел,
                            cwd=КОРЕНЬ, env=_окружение(офлайн, **окр))
    return готово.returncode, готово.stdout + готово.stderr, time.monotonic() - старт


def _сеть(вывод: str) -> tuple[int, int, int] | None:
    # В скобках — «офлайн» или «облачный режим»: два слова, не \w+.
    м = re.search(r"Сеть за команду \([^)]+\): локальных запросов (\d+), внешних (\d+), заблокировано (\d+)", вывод)
    return tuple(int(ч) for ч in м.groups()) if м else None


def _строки(вывод: str, *начала: str, содержит: tuple[str, ...] = ()) -> list[str]:
    return [с for с in вывод.splitlines() if с.lstrip().startswith(начала) or any(к in с for к in содержит)]


