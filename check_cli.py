def _цитаты_подтверждены(текст: str) -> bool:
    """Блок «Цитаты:» есть, и у каждой цитаты отметка подтверждения кодом."""
    if "Цитаты:" not in текст:
        return False
    блок = текст.split("Цитаты:")[1].split("В промпт ушло")[0]
    строки = [с for с in блок.splitlines() if с.strip().startswith("[")]
    return bool(строки) and all(("✓" in с or "≈" in с or "↪" in с) for с in строки)


def _таблица(строка: str, значения: str) -> Callable[[str], bool]:
    """Строка итога проверки цитат: «| источники в каждом ответе | 8 из 8 | …»."""
