class МокТрекера:
    """Мок-API трекера на всё время прогона: его поднимает и гасит сам скрипт."""

    def __init__(self) -> None:
        self.порт = свободный_порт()
        self.адрес = f"http://127.0.0.1:{self.порт}"
        self.данные = os.path.join(ПАМЯТЬ, "tracker-data.json")
        self.процесс: subprocess.Popen | None = None

    def запустить(self) -> None:
        os.makedirs(ПАМЯТЬ, exist_ok=True)
        self.процесс = subprocess.Popen(
            [sys.executable, "tracker_api.py", "--порт", str(self.порт),
             "--данные", self.данные, "--сброс"],
            cwd=КОРЕНЬ, stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if not ждать_порт(self.порт):
            raise RuntimeError(f"мок-трекер не поднялся на порту {self.порт}")

    def остановить(self) -> None:
        if self.процесс is not None:
            self.процесс.terminate()
            try:
                self.процесс.wait(timeout=10)
            except subprocess.TimeoutExpired:
                self.процесс.kill()
            self.процесс = None


