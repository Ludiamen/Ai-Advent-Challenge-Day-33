def _rag_лучше(текст: str) -> bool:
    найдено = re.search(r"\| верно по правилам[^|]*\| (\d+) из \d+ \| (\d+) из \d+ \|", текст)
    return bool(найдено) and int(найдено.group(2)) > int(найдено.group(1))


