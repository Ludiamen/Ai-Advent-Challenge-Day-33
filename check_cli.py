def _строки_судьбы(текст: str, судьба: str) -> list[str]:
    return [с for с in текст.splitlines() if f" {судьба} " in с]


def _тарифы_в_промпте(текст: str) -> bool:
    return any("Ростелеком VPN" in с and "Права и обязанности" in с
               for с in _строки_судьбы(текст, "в промпт"))


def _тарифы_подняты(текст: str) -> bool:
    """Чанк с п. 2.2.7 в промпте, а по косинусу он был за пределами top-5."""
    for с in _строки_судьбы(текст, "в промпт"):
        найдено = re.match(r"\s*\d+\s+(\d+)\s", с)
        if найдено and "Права и обязанности" in с and int(найдено.group(1)) > 5:
            return True
    return False


