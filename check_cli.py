def скрыть_ключи(текст: str) -> str:
    """Ключи сервиса Дня 30 в отчёт не попадают: 30.2 печатает созданный ключ (в памяти
    проверки, потом отозван), а отчёт коммитится. Ожидания сверяются по выводу до этого."""
    текст = re.sub(r"sk-day30-[A-Za-z0-9_-]{8,}", "sk-day30-…(скрыт в отчёте)", текст)
    return re.sub(r"(?<!\d)\d{6,}:[A-Za-z0-9_-]{30,}", "…(токен Telegram скрыт в отчёте)", текст)


def main() -> int:
    разбор = argparse.ArgumentParser(
        description="Прогон консольного чек-листа (День 32 и регрессия Дней 11–31) с отчётом в markdown.")
    разбор.add_argument("--модель", dest="model", default="ds-flash",
                        help="модель для живых вызовов (по умолчанию ds-flash)")
    разбор.add_argument("--в", dest="report", default="CLI-CHECK-RESULTS.md",
                        help="файл отчёта (по умолчанию CLI-CHECK-RESULTS.md)")
    разбор.add_argument("--без-модели", dest="no_model", action="store_true",
                        help="пропустить шаги с живым вызовом модели")
    аргументы = разбор.parse_args()

    shutil.rmtree(ПАМЯТЬ, ignore_errors=True)
    начало = time.time()
    итоги: list[Итог] = []

    трекер = МокТрекера()
    трекер.запустить()
    print(f"{LINE}\nКОНСОЛЬНАЯ ПРОВЕРКА ДНЯ 32, модель {аргументы.model}")
    print(f"Мок-трекер: {трекер.адрес}, данные в {os.path.relpath(трекер.данные, КОРЕНЬ)}\n{LINE}")
    try:
        # Порядок важен: шаги_индекса() готовит копию индекса и настроек, на
        # которой работают части 23 и 22.
        индекс = шаги_индекса(not аргументы.no_model)
        for шаг in (шаги_ревью(not аргументы.no_model) + шаги_ассистента(not аргументы.no_model)
                    + шаги_сервиса(not аргументы.no_model)
                    + шаги_оптимизации(not аргументы.no_model)
                    + шаги_локального_rag(not аргументы.no_model)
                    + шаги_офлайна(not аргументы.no_model, трекер)
                    + шаги_локальной(not аргументы.no_model) + шаги_чата(not аргументы.no_model)
                    + шаги_цитат(not аргументы.no_model) + шаги_реранка(not аргументы.no_model)
                    + индекс + шаги_rag(not аргументы.no_model)
                    + шаги(not аргументы.no_model, трекер)):
            итог = запустить(шаг, аргументы.model)
            итоги.append(итог)
            print(f"  {шаг.номер} {шаг.название}: {'ок' if итог.удача else 'РАСХОЖДЕНИЕ'} "
                  f"({итог.секунд:.1f} с)")
            for описание, ок in итог.сошлось:
                if not ок:
                    print(f"      ✗ {описание}")
    finally:
        трекер.остановить()

    текст = скрыть_ключи(отчёт_в_markdown(итоги, аргументы.model, time.time() - начало))
    with open(os.path.join(КОРЕНЬ, аргументы.report), "w", encoding="utf-8") as файл:
        файл.write(текст)

    расхождений = sum(1 for и in итоги for _, ок in и.сошлось if not ок)
    print(LINE)
    print(f"Отчёт записан в {аргументы.report}. Расхождений: {расхождений}.")
    print(f"Память прогона осталась в «{ПАМЯТЬ_ОТН}» — её можно посмотреть глазами.")
    return 1 if расхождений else 0


if __name__ == "__main__":
    sys.exit(main())
