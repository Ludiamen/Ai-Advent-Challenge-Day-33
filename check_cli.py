def _лучше_базы(текст: str) -> bool:
    """В строке «верно по правилам» + фильтр или + rewrite и фильтр больше базы."""
    # У строки есть пояснение в скобках: «верно по правилам (все факты, …)».
    найдено = re.search(r"\| верно по правилам[^|]*\| (\d+) из \d+ \| (\d+) из \d+ \| (\d+) из \d+ \| "
                        r"(\d+) из \d+ \| (\d+) из \d+ \|", текст)
    if not найдено:
        return False
    без, база, фильтр, rewrite, полный = (int(х) for х in найдено.groups())
    return max(фильтр, полный) > база


