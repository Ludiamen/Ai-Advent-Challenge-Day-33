class Сервис:
    def __init__(self) -> None:
        from agent.service import certs
        н = config.загрузить()
        self.н = н
        self.адрес = f"https://127.0.0.1:{н.порт}"
        self.ca = os.path.join(manage.каталог_tls(), "ca.crt")
        self.ключи: list[str] = []
        self.адрес_в_сети = certs.адрес_в_сети()

    def ключ(self, имя: str, права: list[str]) -> str:
        полное = f"проверка31-{имя}"
        manage.отозвать(полное)
        self.ключи.append(полное)
        return manage.создать_ключ(полное, права)

    def убрать(self) -> None:
        for имя in self.ключи:
            manage.отозвать(имя)

    def http(self) -> httpx.Client:
        return httpx.Client(base_url=self.адрес, verify=self.ca, timeout=900)


