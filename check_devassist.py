def снимок_crm(п: project.Проект) -> tuple[int, str, str]:
    """mtime .git/index, HEAD и статус CRM — для короткого окна (spec NFR-01)."""
    индекс = os.stat(os.path.join(п.путь, ".git", "index")).st_mtime_ns
    return индекс, project.git(п, "rev-parse", "HEAD").strip(), project.git(п, "status", "--porcelain")


def окно(отчёт: Отчёт, п: project.Проект, что: str, работа) -> Any:
    """Работа в коротком окне; HEAD сдвинулся (коммит другой сессии) — окно повторяется один раз."""
    for попытка in (1, 2):
        до = снимок_crm(п)
        итог = работа()
        после = снимок_crm(п)
        if до[1] != после[1] and попытка == 1:
            отчёт(f"  окно «{что}»: HEAD CRM сдвинулся внутри окна (коммит другой сессии) — повтор")
            continue
        отчёт(f"  окно «{что}»: .git/index {'тот же' if до[0] == после[0] else 'ИЗМЕНИЛСЯ'}, HEAD "
              f"{до[1][:7]}→{после[1][:7]}, статус {'тот же' if до[2] == после[2] else 'ИЗМЕНИЛСЯ'}")
        return итог, до == после
    return итог, False


