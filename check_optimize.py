def _журнал_службы(с: str) -> str:
    готово = subprocess.run(["journalctl", "-u", "ollama", "--since", с, "--no-pager", "-o", "cat"],
                            capture_output=True, text=True, timeout=60)
    return готово.stdout


def _раннер_модели(журнал: str, блоб: str) -> str:
    """Блок журнала службы последнего запуска llama-server с весами блоба: окно, потоки и пакет
    у каждого раннера свои — эмбеддер bge-m3 поднимается рядом с тем же окном 4096."""
    блоки, текущий = [], None
    for строка in журнал.splitlines():
        if 'msg="starting llama-server"' in строка:
            текущий = [строка]
            блоки.append(текущий)
        elif текущий is not None:
            текущий.append(строка)
    свои = ["\n".join(б) for б in блоки if блоб and блоб in б[0]]
    return свои[-1] if свои else ""


def _pid_службы() -> str:
    готово = subprocess.run(["pgrep", "-f", "^/usr/local/bin/ollama serve$"], capture_output=True, text=True)
    return готово.stdout.split()[0] if готово.stdout.split() else ""


def _сеть_ответа(вывод: str) -> tuple[int, int, int] | None:
    м = re.search(r"Сеть за ответ: локальных (\d+), внешних (\d+), заблокировано (\d+)", вывод)
    return tuple(int(ч) for ч in м.groups()) if м else None


def _строки(вывод: str, *начала: str) -> list[str]:
    return [с for с in вывод.splitlines() if с.lstrip().startswith(начала)]


def часть_1(отчёт: Отчёт, каталог: str) -> None:
    отчёт.часть(1, "Параметры доходят до модели: тело запроса и раннер llama-server в журнале службы")
    путь = os.path.join(каталог, "local-opt.json")
    данные = tuning.прочитать()
    данные = {**данные, "конфигурации": {**(данные.get("конфигурации") or {}), ПРОВЕРКА: {
        "модель": "loc-qwen35", "опции": ОПЦИИ_ПРОВЕРКИ, "шаблон": "договоры", "описание": "проверка Дня 29"}}}
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False)
    с = time.strftime("%Y-%m-%d %H:%M:%S")
    код, вывод, секунд = _cli("--офлайн", "--rag-локально", _вопрос("c01"), "--конфигурация", ПРОВЕРКА,
                             LOCAL_OPT=путь)
    for строка in _строки(вывод, "Конфигурация:", "Замеры:", "Сеть за ответ"):
        отчёт("  " + строка[:220])
    опции = re.search(r"опции (\{.*?\}) · шаблон (\S+)", вывод)
    отчёт.пункт(код == 0 and bool(опции) and json.loads(опции.group(1)) == ОПЦИИ_ПРОВЕРКИ
                and опции.group(2) == "договоры",
                f"ответ в конфигурации «{ПРОВЕРКА}» с её опциями и шаблоном «договоры» · {_секунды(секунд)}")
    from agent.local import resources
    блоб = resources.блобы(tuning.адрес(tuning.СЛУЖБА), "qwen3.5:4b")[0]
    раннер = _раннер_модели(_журнал_службы(с), блоб)
    окно = re.search(r" -c (\d+) ", раннер)
    потоки = re.findall(r"threadpool init, n_threads = (\d+)", раннер)
    пакет = re.search(r"n_batch\s+= (\d+)", раннер)
    отчёт(f"  журнал службы, раннер весов {блоб[:19]}…: окно {окно.group(1) if окно else '—'} · "
          f"потоков {потоки[-1] if потоки else '—'} · пакет {пакет.group(1) if пакет else '—'}")
    отчёт.пункт(bool(окно and потоки and пакет) and (окно.group(1), потоки[-1], пакет.group(1)) == ("4096", "4", "512"),
                "раннер llama-server с весами qwen3.5:4b запущен с окном 4096, четырьмя потоками и пакетом 512")
    сеть = _сеть_ответа(вывод)
    отчёт.пункт(bool(сеть) and сеть[1] == 0, f"офлайн, без ключей облака: внешних запросов {сеть[1] if сеть else '?'}")


