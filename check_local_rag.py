#!/usr/bin/env python3
"""Проверка задания Дня 28: локальная LLM + RAG — RAG-система, полностью работающая локально.

Задание: подключить локальную LLM к RAG-пайплайну — индекс недели RAG, поиск
локально, генерация локальной моделью; сравнить ответы с облачной моделью и
оценить качество, скорость и стабильность. Скрипт идёт по пунктам задания так,
как работает пользователь: отдельными процессами cli.py и настоящим
веб-сервером; в офлайне ключи облачных провайдеров вычищены из окружения.

  Часть 1  ИНДЕКС НЕДЕЛИ RAG. index/docs.db: стратегия «структура», чанки,
           эмбеддер bge-m3 в Ollama на петлевом адресе — документы не уходят
           с машины ни при сборке, ни при поиске.
  Часть 2  ПОИСК ЛОКАЛЬНО. Общий поиск локального профиля выполняется с
           клиентом модели, который падает при любом вызове: поиск обходится
           без LLM (вектор → косинус → кросс-энкодер → лучшие окна); журнал
           сети — только локальные запросы.
  Часть 3  ГЕНЕРАЦИЯ ЛОКАЛЬНО. cli.py --офлайн --rag-локально без ключей облака:
           вопрос с ответом, ловушка и расплывчатый. Ответ локальной модели с
           источником и дословной цитатой, «не знаю» с уточнением, замеры по
           слоям, внешних запросов 0.
  Часть 4  СРАВНЕНИЕ. Полный прогон --сравнить-локально (index/local-rag.json):
           все ответы на месте, у локальных участников внешних 0 в каждом
           ответе и в общем поиске, у облачных — больше 0 (журнал не слеп);
           таблицы качества, скорости и стабильности.
  Часть 5  ВЕБ. web.py с AGENT_OFFLINE=1 без ключей: /api/rag/cited с профилем
           «локальный» потоком — этапы и токены, итог с цитатой, журнал сервера —
           0 внешних; «рядом с облаком» в офлайне — понятный отказ.
  Часть 6  РЯДОМ С ОБЛАКОМ. cli.py --rag-рядом c01 в облачном режиме: четыре
           участника на одном вопросе; у локальных внешних 0, у облачных > 0.

Запуск:
    python check_local_rag.py                  # всё (на CPU — около 40 минут)
    python check_local_rag.py --без-облака     # без части 6
    python check_local_rag.py --в RESULTS.md   # дописать протокол в файл
"""

