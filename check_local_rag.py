class _ЗапретныйКлиент:
    """Клиент модели, который падает при любом вызове: поиску LLM не нужна."""

    вызовов = 0

    def call(self, *а, **к):
        self.вызовов += 1
        raise AssertionError("поиск позвал языковую модель")


def часть_2(отчёт: Отчёт, итоги: dict) -> None:
    отчёт.часть(2, "Поиск локально: без LLM — вектор, косинус, кросс-энкодер, лучшие окна")
    from agent.rag import localbench
    from agent.rag import profile as rag_profile
    from agent.rag.answer import Отвечатель
    from agent.rag.indexer import Индексатор
    клиент = _ЗапретныйКлиент()
    отвечатель = Отвечатель(Индексатор(), клиент)
    профиль = rag_profile.локальный(отвечатель.поисковик)
    н = профиль.поиск
    отчёт(f"  профиль: {н.имя} · rewrite {'да' if н.rewrite else 'нет'} · порог «не знаю» "
          f"{профиль.порог_уверенности} · лучшее окно {'да' if профиль.окно_фрагмента else 'нет'}")
    offline.включить(True, "check_local_rag")
    try:
        до = offline.снимок_журнала()
        вопрос = _вопрос("c01")["вопрос"]
        старт = time.monotonic()
        подготовка = localbench.общий_поиск(отвечатель, вопрос, профиль, без_кэша=True)
        секунд = time.monotonic() - старт
        сеть = offline.разница(до, offline.снимок_журнала())
    finally:
        offline.включить(False)
    отбор = подготовка.отбор
    этапы = {э["этап"]: э for э in отбор.этапы}
    отчёт(f"  вопрос: {вопрос}")
    отчёт(f"  поиск «новым вопросом» · {_секунды(секунд)}: вектор {этапы['поиск'].get('вектор_с')} с, "
          f"косинус {этапы['поиск'].get('косинус_с')} с, кросс-энкодер {этапы.get('реранк', {}).get('секунд')} с "
          f"(оценок из кэша {этапы.get('реранк', {}).get('из_кэша')}), окна {round(подготовка.секунд_окон, 1)} с")
    for н_ in отбор.фрагменты:
        отчёт(f"    → {н_.чанк.источник} · {н_.чанк.раздел[:40]} · {н_.чанк.chunk_id} · кросс {н_.реранк:.4f}")
    for о in подготовка.окна:
        отчёт(f"    окно {о['chunk_id']}: {о['было']} → {о['стало']} симв.")
    отчёт.пункт(клиент.вызовов == 0 and not н.rewrite and н.реранкер == "кросс",
                "языковая модель в поиске не вызывалась ни разу: переписывания нет, второй этап — кросс-энкодер")
    отчёт.пункт(bool(отбор.фрагменты) and any("Ростелеком VPN" in ф.чанк.источник for ф in отбор.фрагменты),
                f"найдено фрагментов {len(отбор.фрагменты)}, среди них — договор Ростелеком VPN")
    отчёт.пункт(этапы.get("реранк", {}).get("из_кэша") == 0, "«новый вопрос»: оценки кросс-энкодера посчитаны заново, не из кэша")
    отчёт.пункт(сеть["внешних"] == 0 and сеть["заблокировано"] == 0 and сеть["локальных"] >= 1,
                f"сеть поиска: локальных {сеть['локальных']} (вектор вопроса в Ollama), внешних {сеть['внешних']}")
    итоги["поиск"] = {"секунд": round(секунд, 1), "сеть": сеть}


def часть_3(отчёт: Отчёт, итоги: dict) -> None:
    отчёт.часть(3, "Генерация локально: cli.py --офлайн --rag-локально без ключей облака")
    for ид, вид, факт in ВОПРОСЫ:
        вопрос = _вопрос(ид)["вопрос"]
        # С Дня 29 по умолчанию отвечает модель роли из карты (loc-rag-docs) — проверка Дня 28
        # идёт на основной модели, она указана явно.
        код, вывод, секунд = _cli("--офлайн", "--rag-локально", вопрос, "--модель", "loc-qwen35", предел=2400)
        отчёт(f"  $ python cli.py --офлайн --rag-локально «{вопрос[:70]}…» ({ид}, {вид}) · {_секунды(секунд)}")
        for строка in вывод.splitlines():
            if строка.startswith(("Профиль:", "Замеры:", "Сеть за ответ:", "Сеть за команду")) or "дословно" in строка \
                    or строка.startswith(("[", "  [", "Не знаю", "Уточн")):
                отчёт("    " + строка.strip()[:260])
        # Вопрос / ── / шапка «С RAG · …» / ── / текст ответа и дальше источники.
        части = вывод.split("-" * 78)
        текст = части[2].strip().split("\n\n")[0] if len(части) > 2 else ""
        отчёт(f"    > {текст.splitlines()[0][:200] if текст else '—'}")
        сеть, команда = _сеть_ответа(вывод), _сеть(вывод)
        отчёт.пункт(код == 0 and "модель loc-qwen35 (локально)" in вывод,
                    f"{ид}: ответила локальная модель loc-qwen35")
        if факт:
            отчёт.пункт(bool(re.search(факт, текст)) and "✓ дословно" in вывод and "Ростелеком VPN" in вывод,
                        f"{ид}: в ответе «20 числа», источник — договор Ростелеком VPN, цитата найдена дословно")
        else:
            не_знаю = "Не знаю" in вывод or "не знаю" in текст.lower()
            отчёт(f"    {ид}: {'«не знаю» с уточнением' if не_знаю else 'модель ответила по существу (качество — в части 4)'}")
        отчёт.пункт("Замеры:" in вывод and ("чтение промпта" in вывод or "ответ модели" in вывод),
                    f"{ид}: замеры по слоям — поиск, окна, чтение промпта, первый токен, генерация")
        отчёт.пункт(bool(сеть) and сеть[1] == 0 and bool(команда) and команда[1] == 0,
                    f"{ид}: сеть за ответ — локальных {сеть[0] if сеть else '?'}, внешних {сеть[1] if сеть else '?'}; "
                    f"за всю команду — внешних {команда[1] if команда else '?'}")
        итоги.setdefault("генерация", {})[ид] = {"секунд": round(секунд, 1), "ответ": текст[:300]}


def часть_4(отчёт: Отчёт, итоги: dict) -> None:
    отчёт.часть(4, "Сравнение: полный прогон --сравнить-локально (14 вопросов × 4 участника × 3 повтора)")
    from agent.rag import localbench
    from agent.rag.indexer import КОРЕНЬ as КОРЕНЬ_ИНДЕКСА
    данные = localbench.прочитать(os.path.join(КОРЕНЬ_ИНДЕКСА, "index"))
    if not данные:
        отчёт.пункт(False, "прогона сравнения нет: python cli.py --сравнить-локально")
        return
    св, записи = данные["сводка"], данные["записи"]
    отчёт(f"  прогон: {св['готово']} ответов из {св['всего']}, повторов {св['повторов']}")
    отчёт.пункт(св["завершён"] and св["готово"] == св["всего"] == 168, "все 168 ответов на месте")
    for код, д in св["участники"].items():
        к, с, ст, сеть = д["качество"], д["скорость"], д["стабильность"], д["сеть"]
        отчёт(f"  {д['участник']['подпись']:<34} верно {' / '.join(map(str, к['верно_по_повторам']))} из {к['вопросов']} · "
              f"новый вопрос {с['новый']['всего_с']['медиана']} с · повтор {с['повтор']['всего_с']['медиана']} с · "
              f"стабильных {ст['стабильных']} из {ст['вопросов']} · внешних {сеть['внешних']}")
    локальные = [з for з in записи if з["участник"].startswith("лок")]
    облачные = [з for з in записи if not з["участник"].startswith("лок")]
    отчёт.пункт(bool(локальные) and all(з["сеть"]["внешних"] == 0 and (з.get("сеть_поиска") or {}).get("внешних", 0) == 0
                                        for з in локальные),
                f"у локальных участников внешних запросов 0 — в каждом из {len(локальные)} ответов и в общем поиске")
    отчёт.пункт(bool(облачные) and all(з["сеть"]["внешних"] > 0 for з in облачные if not з["ошибка"]),
                "у облачных участников журнал видит внешние запросы — значит, ноль у локальных настоящий")
    путь = os.path.join(КОРЕНЬ_ИНДЕКСА, localbench.ФАЙЛ_ОТЧЁТА)
    текст = open(путь, encoding="utf-8").read() if os.path.exists(путь) else ""
    отчёт.пункт(all(р in текст for р in ("## Качество", "## Скорость", "## Стабильность", "## Условия прогона")),
                "отчёт LOCAL-RAG.md: качество, скорость (новый вопрос и повтор), стабильность, условия прогона")
    итоги["сравнение"] = {к: {"верно": д["качество"]["верно_по_повторам"],
                              "новый_с": д["скорость"]["новый"]["всего_с"]["медиана"],
                              "повтор_с": д["скорость"]["повтор"]["всего_с"]["медиана"],
                              "стабильных": д["стабильность"]["стабильных"]} for к, д in св["участники"].items()}


def часть_5(отчёт: Отчёт, каталог: str, итоги: dict) -> None:
    отчёт.часть(5, "Веб: web.py в офлайне — локальный RAG потоком, этапы и токены на странице")
    порт = _свободный_порт()
    журнал = open(os.path.join(каталог, "web.log"), "w", encoding="utf-8")
    процесс = subprocess.Popen([sys.executable, "-c", "import os, web; web.app.run(host='127.0.0.1', "
                                "port=int(os.environ['PORT']), debug=False, use_reloader=False)"],
                               cwd=КОРЕНЬ, stdout=журнал, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
                               env=_окружение(True, AGENT_OFFLINE="1", MEMORY_DIR=os.path.join(каталог, "web-memory"),
                                              PORT=str(порт)))
    адрес = f"http://127.0.0.1:{порт}"
    try:
        for _ in range(120):
            try:
                httpx.get(адрес + "/api/offline", timeout=2)
                break
            except httpx.HTTPError:
                time.sleep(0.5)
        отчёт.пункт(httpx.get(адрес + "/api/offline", timeout=10).json()["on"], "сервер стартовал в офлайне без ключей облака")
        вопрос = _вопрос("c01")["вопрос"]
        события, итог, старт = [], None, time.monotonic()
        with httpx.stream("POST", адрес + "/api/rag/cited", timeout=httpx.Timeout(2400, connect=10),
                          json={"question": вопрос, "profile": "локальный", "stream": True,
                                # С Дня 29 по умолчанию — модель роли из карты; здесь — основная Дня 28.
                                "model": "loc-qwen35"}) as ответ:
            for строка in ответ.iter_lines():
                if строка.strip():
                    событие = json.loads(строка)
                    события.append(событие)
                    if событие.get("событие") == "готово":
                        итог = событие
        секунд = time.monotonic() - старт
        этапы = [с.get("этап") for с in события if с.get("событие") == "этап"]
        токенов = [с for с in события if с.get("событие") == "токены"]
        отчёт(f"  POST /api/rag/cited (профиль «локальный», stream) · {_секунды(секунд)}: событий {len(события)}, "
              f"этапы {' → '.join(этапы)}, сообщений о токенах {len(токенов)}")
        отчёт.пункт(этапы[:2] == ["поиск", "ответ"] and len(токенов) >= 2,
                    "страница получает ход по этапам (поиск → ответ) и счётчик токенов, пока модель пишет")
        о = (итог or {}).get("answer") or {}
        отчёт(f"    > {str(о.get('text', ''))[:200]}")
        дословно = any(ц.get("check") == "дословно" for ц in о.get("quotes", []))
        отчёт.пункт(bool(re.search(r"\b20\b", о.get("text", ""))) and bool(о.get("sources")) and дословно
                    and о.get("model") == "loc-qwen35",
                    "итог: ответ loc-qwen35 «20 числа», источник с chunk_id и дословной цитатой")
        сеть = (итог or {}).get("net") or {}
        журнал_сервера = httpx.get(адрес + "/api/offline", timeout=10).json()["net"]
        отчёт.пункт(сеть.get("внешних") == 0 and журнал_сервера["внешних"] == 0,
                    f"сеть ответа: локальных {сеть.get('локальных')}, внешних {сеть.get('внешних')}; "
                    f"журнал сервера — внешних {журнал_сервера['внешних']}")
        отказ = httpx.post(адрес + "/api/rag/side", json={"question": "c01"}, timeout=30)
        отчёт.пункт(отказ.status_code == 400 and "выключенным офлайном" in отказ.json().get("error", ""),
                    "«рядом с облаком» в офлайне — понятный отказ: облачные участники ходят в сеть")
        итоги["веб"] = {"секунд": round(секунд, 1), "ответ": о.get("text", "")}
    finally:
        процесс.terminate()
        try:
            процесс.wait(timeout=15)
        except subprocess.TimeoutExpired:
            процесс.kill()
        журнал.close()


def часть_6(отчёт: Отчёт, итоги: dict) -> None:
    отчёт.часть(6, "Рядом с облаком: cli.py --rag-рядом c01 — четыре участника на одном вопросе")
    if not catalog.get("ds-flash").has_key or not catalog.get("ds-pro").has_key:
        отчёт("  ключа DeepSeek нет — часть пропущена (так и задумано: RAG-система работает без облака)")
        return
    код, вывод, секунд = _cli("--rag-рядом", "c01", офлайн=False, предел=3600)
    отчёт(f"  $ python cli.py --rag-рядом c01 · {_секунды(секунд)} · код {код}")
    итог = next((с for с in вывод.splitlines() if с.startswith("Рядом:")), "")
    отчёт("    " + итог)
    участники = re.findall(r"^(лок-4b|лок-1\.7b|облако-тот-же|облако-лучшее) · ", вывод, re.M)
    сети = re.findall(r"^Сеть: ответ — локальных (\d+), внешних (\d+)", вывод, re.M)
    for у, (л, в) in zip(участники, сети):
        отчёт(f"    {у:<14} сеть ответа: локальных {л}, внешних {в}")
    отчёт.пункт(код == 0 and участники == ["лок-4b", "лок-1.7b", "облако-тот-же", "облако-лучшее"],
                "четыре участника рядом: лок-4b, лок-1.7b, облако на тех же фрагментах, облако на лучшем конвейере")
    пары = dict(zip(участники, ((int(л), int(в)) for л, в in сети)))
    отчёт.пункт(bool(пары) and all(пары[у][1] == 0 for у in пары if у.startswith("лок"))
                and all(пары[у][1] > 0 for у in пары if not у.startswith("лок")),
                "у локальных внешних 0, у облачных больше 0 — в одном процессе, рядом")
    итоги["рядом"] = {"секунд": round(секунд, 1), "итог": итог}


def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверка Дня 28: локальная LLM + RAG, полностью локально.")
    разбор.add_argument("--без-облака", dest="no_cloud", action="store_true")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ")
    разбор.add_argument("--итоги", dest="totals", default="", metavar="JSON")
    аргументы = разбор.parse_args()

    каталог = tempfile.mkdtemp(prefix="check-local-rag-")
    отчёт = Отчёт()
    итоги: dict = {}
    начало = time.monotonic()
    отчёт(LINE)
    отчёт(f"Проверка Дня 28: локальная LLM + RAG · ответ loc-qwen35 · ключи облака в процессах офлайна: "
          f"{', '.join(КЛЮЧИ_ОБЛАКА[:3])} — пусто")
    try:
        часть_1(отчёт)
        часть_2(отчёт, итоги)
        часть_3(отчёт, итоги)
        часть_4(отчёт, итоги)
        часть_5(отчёт, каталог, итоги)
        if not аргументы.no_cloud:
            часть_6(отчёт, итоги)
    except (LLMError, subprocess.TimeoutExpired, httpx.HTTPError, RuntimeError, OSError) as exc:
        отчёт.пункт(False, f"прервано: {exc}")
    finally:
        shutil.rmtree(каталог, ignore_errors=True)
    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}.")
    if аргументы.totals:
        with open(аргументы.totals, "w", encoding="utf-8") as f:
            json.dump(итоги, f, ensure_ascii=False, indent=1)
    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as f:
            f.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
