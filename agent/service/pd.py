"""Персональные данные в тексте: поиск и маска (telegram-spec FR-T07, telegram-plan D-T10).

Шаблоны появились в Дне 29 — отбор вопросов без ПД для арендованного GPU
(`agent/rag/optbench.py`, `без_пд` — теперь отсюда). В Дне 30 Telegram-бот отправляет
ответы по документам во внешнее облако, и перед отправкой найденное заменяется маской.

Фамилии подписантов в коде не хранятся: репозиторий публичный. Список (по основе на
строку) — локальный файл pd-names.txt в корне проекта (в .gitignore) или путь из
PD_NAMES. Без файла остаются общие признаки: отчество, инициалы, e-mail, телефон.

Чего шаблоны НЕ ловят — `НЕ_ЛОВИТ`: это говорится владельцу в /help бота и в документах.

  найти(текст) -> виды находок (сами совпадения не возвращаются)
  скрыть(текст) -> (текст с «[скрыто]», {вид: сколько скрыто})
"""

from __future__ import annotations

import os
import re

ФАЙЛ_ФАМИЛИЙ = "pd-names.txt"
МАСКА = "[скрыто]"
НЕ_ЛОВИТ = "адреса, ИНН, КПП, ОГРН, расчётные счета, паспортные данные, фамилии не из списка"


class ОшибкаМаскирования(ValueError):
    """Фрагмент похож на ФИО, но безопасно отделить фамилию от обычного слова нельзя."""


def фамилии() -> tuple[str, ...]:
    путь = os.environ.get("PD_NAMES") or os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), ФАЙЛ_ФАМИЛИЙ)
    try:
        with open(путь, encoding="utf-8") as f:
            return tuple(с.strip() for с in f if с.strip() and not с.lstrip().startswith("#"))
    except OSError:
        return ()


def список_есть() -> bool:
    """Есть ли список фамилий: без него фамилии не узнаются, и бот об этом предупреждает."""
    return bool(фамилии())


# Инициалы в документах пишутся по-разному, и распознавание добавляет своё: «А.В.», «А. В.»,
# «А.В» (без второй точки), «А В.». Шаблон Дня 29 знал только первые два — «М.В Фамилия» из живого
# ответа /doc ушла в Telegram (показ, сцена 5).
_БУКВЫ = "А-ЯЁа-яё"
_СЛОВО = rf"[{_БУКВЫ}]{{2,}}"
_ДЕФИСЫ = "-‐‑"  # ASCII, U+2010 и неразрывный U+2011 из PDF/OCR
_ДЕФИС = rf"[{_ДЕФИСЫ}]"
_ФАМИЛИЯ = rf"{_СЛОВО}(?:{_ДЕФИС}{_СЛОВО})*"
_ИМЯ = rf"(?=[{_БУКВЫ}]*[А-ЯЁ]){_СЛОВО}"
_ИМЯ_ИЛИ_ФАМИЛИЯ = rf"{_ИМЯ}(?:{_ДЕФИС}{_ИМЯ})*"
_ОКОНЧАНИЯ_ОТЧЕСТВА = r"(?:ович|евич|ьич|овна|евна|ична|инична)"
_ОТЧЕСТВО = rf"{_ИМЯ}(?i:{_ОКОНЧАНИЯ_ОТЧЕСТВА})"
# Строчный контекст допускается только для мужских окончаний: обычные прилагательные
# «аналогична», «логична», «публична» не должны становиться ПД. Остальные строчные
# неоднозначности финальная проверка Telegram безопасно отклонит.
_СТРОЧНОЕ_ОТЧЕСТВО = r"[а-яё]{2,}(?:ович|евич|ьич)"
_КОНТЕКСТНОЕ_ОТЧЕСТВО = rf"(?:{_ОТЧЕСТВО}|{_СТРОЧНОЕ_ОТЧЕСТВО})"
_ВЕРХНЕЕ_СЛОВО = rf"[А-ЯЁ]{{2,}}(?:{_ДЕФИС}[А-ЯЁ]{{2,}})*"
_ИНИЦИАЛЫ = r"(?:[А-ЯЁ]\.\s?[А-ЯЁ]\.?|[А-ЯЁ]\.?\s[А-ЯЁ]\.)"
_РЕГИСТР = re.IGNORECASE
# Фамилия рядом с инициалами — с заглавной буквы. Со строчным словом «Петров А.В. вчера»
# читалось как «А.В. вчера» (инициалы и «фамилия»), маска съедала инициалы, а настоящая
# фамилия оставалась открытой (найдено тестами Дня 31; то же было в маске /doc Дня 30).
_ФАМИЛИЯ_ЗАГЛ = rf"[А-ЯЁ][{_БУКВЫ}]+(?:{_ДЕФИС}[А-ЯЁ][{_БУКВЫ}]+)*"

ШАБЛОНЫ = (
    ("отчество", re.compile(
        rf"(?<![{_БУКВЫ}])(?:{_ИМЯ_ИЛИ_ФАМИЛИЯ}\s+{_КОНТЕКСТНОЕ_ОТЧЕСТВО}|{_ОТЧЕСТВО})(?![{_БУКВЫ}])"
    )),
    ("инициалы и фамилия", re.compile(rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}]){_ИНИЦИАЛЫ}\s?{_ФАМИЛИЯ_ЗАГЛ}(?![{_БУКВЫ}{_ДЕФИСЫ}])")),
    ("фамилия и инициалы", re.compile(rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}]){_ФАМИЛИЯ_ЗАГЛ}\s{_ИНИЦИАЛЫ}(?![{_БУКВЫ}{_ДЕФИСЫ}])")),
    ("e-mail", re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")),
    ("телефон", re.compile(r"(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}")),
)
_ШАБЛОН = dict(ШАБЛОНЫ)


# Латинские двойники кириллицы. Распознанные договоры смешивают письмо: «M.B» латиницей перед
# кириллической фамилией — шаблоны с [А-ЯЁ] такое не видели, фамилия ушла в Telegram (показ,
# сцена 5). Поиск идёт по тексту, переведённому в кириллицу; замена посимвольная, длина та же —
# найденное маскируется в исходном тексте по тем же позициям.
_ДВОЙНИКИ = str.maketrans("ABCEHKMOPTXYaceopxy", "АВСЕНКМОРТХУасеорху")


def _кириллица(текст: str) -> str:
    if not isinstance(текст, str):
        raise TypeError("текст для фильтра ПД должен быть строкой")
    return текст.translate(_ДВОЙНИКИ)


def _фамилии_из_списка(фамилии_: tuple[str, ...]) -> re.Pattern[str] | None:
    """Целая дефисная фамилия, один из компонентов которой начинается с известной основы."""
    основы = tuple(sorted((_кириллица(с.strip()) for с in фамилии_ if с.strip()), key=len, reverse=True))
    if not основы:
        return None
    известная = "|".join(map(re.escape, основы))
    # Основа фамилии «Петров» не должна раньше общего шаблона съесть отчество
    # «Петрович». Такое слово обработает отдельный проход отчества вместе с именем.
    не_отчество = (
        rf"(?![{_БУКВЫ}]*(?i:ович|евич|ьич|овна|евна|ична|инична)"
        rf"(?={_ДЕФИС}|(?![{_БУКВЫ}])))"
    )
    return re.compile(
        rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}])(?:{_СЛОВО}{_ДЕФИС})*{не_отчество}"
        rf"(?:{известная})[{_БУКВЫ}]*(?:{_ДЕФИС}{_СЛОВО})*(?![{_БУКВЫ}{_ДЕФИСЫ}])",
        _РЕГИСТР,
    )


def найти(текст: str) -> list[str]:
    """Что похоже на персональные данные: названия шаблонов (сами совпадения не возвращаются)."""
    фамилия = _фамилии_из_списка(фамилии())
    шаблоны = (("фамилия из списка", фамилия),) + ШАБЛОНЫ if фамилия else ШАБЛОНЫ
    норм = _кириллица(текст)
    return [имя for имя, ш in шаблоны if ш.search(норм)]


# Маска шире поиска: вместе с отчеством уходят имя (и фамилия) перед ним, фамилия из
# списка — целым словом от основы. Составные шаблоны — раньше одиночных: иначе от
# «И.И. Иванов» осталось бы «И.И. [скрыто]», а «Подписал И.И.» сошло бы за фамилию.
# Инициалы, оставшиеся рядом с маской (фамилию скрыл другой шаблон): «А В.[скрыто]» → «[скрыто]».
_ОСТАТКИ = re.compile(
    rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}])(?:"
    rf"{_ИНИЦИАЛЫ}\s?\[скрыто\]|\[скрыто\]\s?{_ИНИЦИАЛЫ}|"
    rf"(?:{_СЛОВО}{_ДЕФИС})+\[скрыто\](?:{_ДЕФИС}{_СЛОВО})*|"
    rf"\[скрыто\](?:{_ДЕФИС}{_СЛОВО})+"
    rf")(?![{_БУКВЫ}{_ДЕФИСЫ}])",
)
_ОТЧЕСТВО_С_ИМЕНЕМ = re.compile(
    rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}])(?:"
    rf"{_ИМЯ_ИЛИ_ФАМИЛИЯ}\s+{_КОНТЕКСТНОЕ_ОТЧЕСТВО}|{_ОТЧЕСТВО}"
    rf")(?![{_БУКВЫ}{_ДЕФИСЫ}])",
)
_ОТЧЕСТВО_И_ФАМИЛИЯ = re.compile(
    rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}]){_ИМЯ}\s+{_КОНТЕКСТНОЕ_ОТЧЕСТВО}"
    rf"\s+{_ИМЯ_ИЛИ_ФАМИЛИЯ}(?![{_БУКВЫ}{_ДЕФИСЫ}])",
)
_ФИО_ВЕРХНИЙ_РЕГИСТР = re.compile(
    rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}])(?:"
    rf"{_ВЕРХНЕЕ_СЛОВО}\s+{_ВЕРХНЕЕ_СЛОВО}\s+{_ОТЧЕСТВО}|"
    rf"{_ВЕРХНЕЕ_СЛОВО}\s+{_ОТЧЕСТВО}\s+{_ВЕРХНЕЕ_СЛОВО}"
    rf")(?![{_БУКВЫ}{_ДЕФИСЫ}])",
)
_ФИО_С_ДЕФИСНОЙ_ФАМИЛИЕЙ = re.compile(
    rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}]){_ИМЯ}{_ДЕФИС}{_ИМЯ}(?:{_ДЕФИС}{_ИМЯ})*\s+{_ИМЯ}\s+{_ОТЧЕСТВО}"
    rf"(?![{_БУКВЫ}{_ДЕФИСЫ}])",
)
_НЕОДНОЗНАЧНОЕ_ФИО = re.compile(
    rf"(?<![{_БУКВЫ}{_ДЕФИСЫ}])(?P<первое>{_ИМЯ_ИЛИ_ФАМИЛИЯ})\s+{_ИМЯ}\s+{_КОНТЕКСТНОЕ_ОТЧЕСТВО}"
    rf"(?![{_БУКВЫ}{_ДЕФИСЫ}])",
)


def _проверить_неоднозначное_фио(текст: str, фамилия: re.Pattern[str] | None) -> None:
    """Не угадывать, является ли первое Titlecase-слово фамилией или глаголом («Подписал …»)."""
    норм = _кириллица(текст)
    for совпадение in _НЕОДНОЗНАЧНОЕ_ФИО.finditer(норм):
        первое = совпадение.group("первое")
        if (_ФИО_ВЕРХНИЙ_РЕГИСТР.fullmatch(совпадение.group(0)) or re.search(_ДЕФИС, первое) or
                (фамилия is not None and фамилия.fullmatch(первое))):
            continue
        # В «Согласовала Анна Сергеевна Фамилия» пропуск безопасен только когда
        # следующий компонент положительно известен локальному списку фамилий.
        следующий = re.match(
            rf"\s+(?P<фамилия>{_ИМЯ_ИЛИ_ФАМИЛИЯ})(?![{_БУКВЫ}{_ДЕФИСЫ}])",
            норм[совпадение.end():],
        )
        if следующий and фамилия is not None and фамилия.fullmatch(следующий.group("фамилия")):
            continue
        raise ОшибкаМаскирования("неоднозначный фрагмент ФИО")


# Телефон в точном профиле — отдельным числом: цифры внутри хэша («sha256:04878004256f…»)
# полный профиль считал телефоном (ворота 0 Дня 31).
_ТЕЛЕФОН_ОТДЕЛЬНО = re.compile(
    r"(?<![\w])(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?![\w])")
ПРОФИЛИ = ("полный", "точный")


def скрыть(текст: str, профиль: str = "полный") -> tuple[str, dict[str, int]]:
    """Заменить найденные ПД на «[скрыто]»; вернуть текст и сколько скрыто каждого вида.

    Профиль «полный» (по умолчанию) — для распознанных договоров: латинские двойники,
    инициалы в любом написании, отказ на неоднозначном ФИО. Профиль «точный» — для
    документации разработчика (День 31, plan D-02a): без латинских двойников — иначе
    «ORM», «MVP», «IP», «POST» превращаются в «OR[скрыто]»; телефон — отдельным
    числом; неоднозначное ФИО не поднимает ошибку, а маскируется.
    """
    if профиль not in ПРОФИЛИ:
        raise ValueError(f"профиль маски ПД — один из {ПРОФИЛИ}, а не «{профиль}»")
    _кириллица(текст)  # единая явная проверка типа до частичной обработки
    фамилия = _фамилии_из_списка(фамилии())
    точный = профиль == "точный"
    норма = (lambda т: т) if точный else _кириллица
    неоднозначных = 0
    if точный:
        текст, неоднозначных = _НЕОДНОЗНАЧНОЕ_ФИО.subn(МАСКА, текст)
    else:
        _проверить_неоднозначное_фио(текст, фамилия)
    маски: list[tuple[str, re.Pattern[str]]] = [
        ("инициалы и фамилия", _ШАБЛОН["инициалы и фамилия"]),
        ("фамилия и инициалы", _ШАБЛОН["фамилия и инициалы"]),
    ]
    if фамилия:
        маски.append(("фамилия из списка", фамилия))
    маски += [("отчество", _ФИО_ВЕРХНИЙ_РЕГИСТР),
              ("отчество", _ФИО_С_ДЕФИСНОЙ_ФАМИЛИЕЙ),
              ("отчество", _ОТЧЕСТВО_И_ФАМИЛИЯ),
              ("отчество", _ОТЧЕСТВО_С_ИМЕНЕМ),
              ("e-mail", _ШАБЛОН["e-mail"]),
              ("телефон", _ТЕЛЕФОН_ОТДЕЛЬНО if точный else _ШАБЛОН["телефон"]),
              ("инициалы и фамилия", _ОСТАТКИ)]
    виды: dict[str, int] = {"отчество": неоднозначных} if неоднозначных else {}
    for имя, шаблон in маски:
        части, конец, n = [], 0, 0
        for м in шаблон.finditer(норма(текст)):
            части += [текст[конец:м.start()], МАСКА]
            конец, n = м.end(), n + 1
        if n:
            текст = "".join(части) + текст[конец:]
            виды[имя] = виды.get(имя, 0) + n
    текст = re.sub(r"\[скрыто\](?:\s+\[скрыто\])+", МАСКА, текст)
    return текст, виды
