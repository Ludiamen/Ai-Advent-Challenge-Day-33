"""Память задачи чата (День 25): что пользователь хочет и что уже выяснено.

Короткая память (agent/memory/short.py) хранит реплики дословно, и в промпт
идёт только хвост: через десять реплик первая — с целью разговора — из окна
выпадает. Поэтому то, без чего разговор теряет смысл, лежит отдельно и идёт в
промпт целиком на каждом ходе:

    Ц   цель            ради чего разговор; меняется только явной сменой
    У   уточнения       что пользователь уточнил («Ростелеком — это VPN»)
    О   ограничения     правила ответа («суммы как в документе, с НДС или без»)
    Т   термины         определения пользователя («срок платежа — это …»)
    В   выяснено        ответы по документам с источниками и цитатами

Ц, У, О, Т извлекает модель из реплики пользователя (отдельный вызов, выбор
пользователя), а сливает их код: цель не перезаписывается без явной смены,
повтор уже записанного не дублируется, термин с новым значением заменяет
старый. В пишет только код — из ответа, у которого есть подтверждённые
цитаты: модель не может «вспомнить» факт, которого не было в документах.

У каждой записи — номер реплики, из которой она взята: ответ по памяти
ссылается на записи кодами (Ц, О1, В3), и источник «память задачи» всегда
можно проверить по истории.

Хранится память JSON-файлом на сессию чата в memory/chat/: её можно прочитать
cat'ом, она переживает перезапуск, а «новый разговор» убирает её вместе с
историей. Имя файла — латиницей (правило проекта), название сессии — внутри.

Публичное API:
  Запись, ПамятьЗадачи                — записи и состояние одной сессии
  .применить(изменения, реплика)      — слить то, что извлекла модель
  .записать_выяснено(...)             — ответ по документам с источниками
  .коды() / .текст() / .для_промпта() — записи с кодами для ответа по памяти
  ХранилищеЧатов(каталог)             — загрузить, сохранить, удалить, список
  имя_файла(сессия)                   — латинское имя файла сессии
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from difflib import SequenceMatcher
from typing import Any

from agent.rag.evaluate import записать_атомарно

УТОЧНЕНИЯ = "уточнения"
ОГРАНИЧЕНИЯ = "ограничения"
ТЕРМИНЫ = "термины"
ВЫЯСНЕНО = "выяснено"
СПИСКИ = (УТОЧНЕНИЯ, ОГРАНИЧЕНИЯ, ТЕРМИНЫ, ВЫЯСНЕНО)
КОДЫ = {УТОЧНЕНИЯ: "У", ОГРАНИЧЕНИЯ: "О", ТЕРМИНЫ: "Т", ВЫЯСНЕНО: "В"}
ЦЕЛЬ = "Ц"

# Насколько похожи две записи, чтобы считаться одной: модель пересказывает
# одно и то же уточнение то «только VPN», то «только договор VPN».
ПОХОЖЕ = 0.8
# Сколько записей каждого вида держать: память задачи идёт в промпт целиком.
ПРЕДЕЛ = 20


def _сейчас() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def нормализовать(текст: str) -> str:
    т = (текст or "").lower().replace("ё", "е")
    т = re.sub(r"[«»\"'“”„]", "", т)
    return re.sub(r"\s+", " ", т).strip(" .;:—-")


def _основы(текст: str) -> set[str]:
    """Основы значимых слов: «договорам» и «договора» — одно «догов»."""
    return {с[:5] for с in re.findall(r"[a-zа-я0-9]+", нормализовать(текст)) if len(с) > 3}


def пересказ(текст: str, образец: str, доля: float = 0.8) -> bool:
    """Почти все значимые слова текста уже есть в образце — нового в нём нет."""
    слова = _основы(текст)
    return bool(слова) and len(слова & _основы(образец)) >= доля * len(слова)


def похожи(а: str, б: str) -> bool:
    а, б = нормализовать(а), нормализовать(б)
    if not а or not б:
        return False
    return а == б or а in б or б in а or SequenceMatcher(None, а, б).ratio() >= ПОХОЖЕ


@dataclass
class Запись:
    """Одна запись памяти задачи и реплика, из которой она взята."""

    текст: str
    реплика: int
    термин: str = ""                                          # для терминов
    вопрос: str = ""                                          # для «выяснено»
    источники: list[dict[str, Any]] = field(default_factory=list)
    цитаты: list[str] = field(default_factory=list)
    было: str = ""                                            # прежнее значение термина

    def to_dict(self) -> dict[str, Any]:
        return {к: з for к, з in asdict(self).items() if з not in ("", [], None)}

    @classmethod
    def from_dict(cls, данные: dict[str, Any]) -> "Запись":
        return cls(**{к: данные[к] for к in cls.__dataclass_fields__ if к in данные})


@dataclass
class ПамятьЗадачи:
    """Состояние одной сессии чата."""

    сессия: str
    цель: Запись | None = None
    прежние_цели: list[Запись] = field(default_factory=list)
    уточнения: list[Запись] = field(default_factory=list)
    ограничения: list[Запись] = field(default_factory=list)
    термины: list[Запись] = field(default_factory=list)
    выяснено: list[Запись] = field(default_factory=list)
    реплик: int = 0
    журнал: list[dict[str, Any]] = field(default_factory=list)   # ходы чата
    создана: str = field(default_factory=_сейчас)
    обновлена: str = field(default_factory=_сейчас)

    # --- слияние ---------------------------------------------------------------

    def применить(self, изменения: dict[str, Any], реплика: int) -> dict[str, Any]:
        """Слить то, что модель извлекла из реплики; вернуть, что изменилось.

        изменения: {"цель": str, "смена_цели": bool, "уточнения": [str],
        "ограничения": [str], "термины": [{"термин", "значение"}]}.
        """
        итог: dict[str, Any] = {}
        цель = str(изменения.get("цель") or "").strip()
        if цель:
            if self.цель is None:
                self.цель = Запись(цель, реплика)
                итог["цель"] = цель
            elif изменения.get("смена_цели") and not похожи(цель, self.цель.текст):
                self.прежние_цели.append(self.цель)
                self.цель = Запись(цель, реплика)
                итог["цель"] = цель
                итог["смена_цели"] = True
            else:
                # Цель уже есть, а явной смены нет: модель пересказала ту же
                # цель другими словами — перезаписывать нельзя, иначе цель
                # «дрейфует» с каждой репликой.
                итог["цель_оставлена"] = цель
        for вид in (УТОЧНЕНИЯ, ОГРАНИЧЕНИЯ):
            добавлено = []
            for текст in изменения.get(вид) or []:
                текст = str(текст).strip()
                список: list[Запись] = getattr(self, вид)
                # Модель охотно кладёт в уточнения пересказ цели («сравниваются
                # два договора: …») — нового в нём нет, а память засоряется.
                if вид == УТОЧНЕНИЯ and self.цель is not None and пересказ(текст, self.цель.текст):
                    итог.setdefault("пропущено", []).append(текст)
                    continue
                if текст and not any(похожи(текст, з.текст) for з in список):
                    список.append(Запись(текст, реплика))
                    добавлено.append(текст)
            if добавлено:
                итог[вид] = добавлено
                del getattr(self, вид)[:-ПРЕДЕЛ]
        термины = []
        for т in изменения.get(ТЕРМИНЫ) or []:
            if not isinstance(т, dict):
                continue
            термин, значение = str(т.get("термин") or "").strip(), str(т.get("значение") or "").strip()
            if not термин or not значение:
                continue
            прежний = next((з for з in self.термины
                            if нормализовать(з.термин) == нормализовать(термин)), None)
            if прежний is None:
                self.термины.append(Запись(значение, реплика, термин=термин))
                термины.append(f"{термин} — {значение}")
            elif not похожи(значение, прежний.текст):
                прежний.было, прежний.текст, прежний.реплика = прежний.текст, значение, реплика
                термины.append(f"{термин} — {значение} (было: {прежний.было})")
        if термины:
            итог[ТЕРМИНЫ] = термины
            del self.термины[:-ПРЕДЕЛ]
        self.реплик = max(self.реплик, реплика)
        self.обновлена = _сейчас()
        return итог

    def записать_выяснено(self, вопрос: str, ответ: str, источники: list[dict[str, Any]],
                          цитаты: list[str], реплика: int) -> Запись:
        """Ответ по документам с подтверждёнными цитатами — в «выяснено»."""
        запись = Запись(ответ, реплика, вопрос=вопрос, источники=источники, цитаты=цитаты)
        # Тот же вопрос, заданный ещё раз, обновляет запись, а не плодит дубль.
        прежняя = next((з for з in self.выяснено if похожи(з.вопрос, вопрос)), None)
        if прежняя is not None:
            self.выяснено.remove(прежняя)
        self.выяснено.append(запись)
        del self.выяснено[:-ПРЕДЕЛ]
        self.обновлена = _сейчас()
        return запись

    # --- коды и текст для промпта ------------------------------------------------

    def коды(self) -> dict[str, Запись]:
        """Ц, У1…, О1…, Т1…, В1… — те же коды, что видит модель."""
        итог: dict[str, Запись] = {}
        if self.цель is not None:
            итог[ЦЕЛЬ] = self.цель
        for вид in СПИСКИ:
            for i, з in enumerate(getattr(self, вид), 1):
                итог[f"{КОДЫ[вид]}{i}"] = з
        return итог

    def вид_кода(self, код: str) -> str:
        if код == ЦЕЛЬ:
            return "цель"
        for вид, буква in КОДЫ.items():
            if код.startswith(буква) and код[1:].isdigit():
                return {УТОЧНЕНИЯ: "уточнение", ОГРАНИЧЕНИЯ: "ограничение",
                        ТЕРМИНЫ: "термин", ВЫЯСНЕНО: "выяснено"}[вид]
        return ""

    @property
    def пуста(self) -> bool:
        return self.цель is None and not any(getattr(self, в) for в in СПИСКИ)

    def текст(self, с_выясненным: bool = True, с_кодами: bool = False) -> str:
        """Память задачи строками — для промпта и для показа человеку."""
        строки = []
        def код(к: str) -> str:
            return f"{к}. " if с_кодами else ""
        if self.цель is not None:
            строки.append(f"{код(ЦЕЛЬ)}Цель разговора (реплика {self.цель.реплика}): {self.цель.текст}")
        else:
            строки.append("Цель разговора пока не названа.")
        for вид, заголовок in ((УТОЧНЕНИЯ, "Уточнения пользователя"),
                               (ОГРАНИЧЕНИЯ, "Ограничения"), (ТЕРМИНЫ, "Термины")):
            записи = getattr(self, вид)
            if not записи:
                continue
            строки.append(f"{заголовок}:")
            for i, з in enumerate(записи, 1):
                суть = f"«{з.термин}» — {з.текст}" if вид == ТЕРМИНЫ else з.текст
                строки.append(f"  {код(КОДЫ[вид] + str(i))}{суть} (реплика {з.реплика})")
        if с_выясненным and self.выяснено:
            строки.append("Выяснено по документам:")
            for i, з in enumerate(self.выяснено, 1):
                источники = "; ".join(источник_строкой(и) for и in з.источники) or "—"
                строки.append(f"  {код('В' + str(i))}(реплика {з.реплика}) Вопрос: {з.вопрос}\n"
                              f"     Ответ: {з.текст}\n     Источник: {источники}")
                for ц in з.цитаты[:3]:
                    строки.append(f"     Цитата: «{ц}»")
        return "\n".join(строки)

    def от_пользователя(self) -> str:
        """Всё, что сказал сам пользователь: цель, уточнения, ограничения, термины.

        Числа отсюда не требуют цитаты: «только 2026 год» — слова человека, а
        не факт из документа."""
        куски = [self.цель.текст] if self.цель is not None else []
        куски += [з.текст for з in self.уточнения + self.ограничения]
        куски += [f"{з.термин} {з.текст}" for з in self.термины]
        return "\n".join(куски)

    def сводка(self) -> dict[str, Any]:
        return {"цель": self.цель.текст if self.цель else "", "уточнений": len(self.уточнения),
                "ограничений": len(self.ограничения), "терминов": len(self.термины),
                "выяснено": len(self.выяснено), "реплик": self.реплик}

    # --- сериализация ------------------------------------------------------------

    def to_dict(self) -> dict[str, Any]:
        return {
            "сессия": self.сессия,
            "цель": self.цель.to_dict() if self.цель else None,
            "прежние_цели": [з.to_dict() for з in self.прежние_цели],
            **{вид: [з.to_dict() for з in getattr(self, вид)] for вид in СПИСКИ},
            "реплик": self.реплик, "журнал": self.журнал,
            "создана": self.создана, "обновлена": self.обновлена,
        }

    @classmethod
    def from_dict(cls, данные: dict[str, Any]) -> "ПамятьЗадачи":
        п = cls(сессия=данные.get("сессия", ""))
        if данные.get("цель"):
            п.цель = Запись.from_dict(данные["цель"])
        п.прежние_цели = [Запись.from_dict(з) for з in данные.get("прежние_цели", [])]
        for вид in СПИСКИ:
            setattr(п, вид, [Запись.from_dict(з) for з in данные.get(вид, [])])
        п.реплик = int(данные.get("реплик", 0))
        п.журнал = list(данные.get("журнал", []))
        п.создана = данные.get("создана", п.создана)
        п.обновлена = данные.get("обновлена", п.обновлена)
        return п


def источник_строкой(и: dict[str, Any]) -> str:
    """Паспорт документа одной строкой: файл · раздел · chunk_id."""
    части = [str(и.get("source") or ""), str(и.get("section") or "")]
    if и.get("clause"):
        части.append(f"п. {и['clause']}")
    if и.get("chunk_id"):
        части.append(str(и["chunk_id"]))
    return " · ".join(ч for ч in части if ч)


# --- хранилище -------------------------------------------------------------------

_ЛАТИНИЦА = dict(zip("абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
                     ["a", "b", "v", "g", "d", "e", "e", "zh", "z", "i", "i", "k", "l", "m", "n",
                      "o", "p", "r", "s", "t", "u", "f", "h", "c", "ch", "sh", "sch", "", "y", "",
                      "e", "yu", "ya"]))


def имя_файла(сессия: str) -> str:
    """Латинское имя файла сессии: «договоры связи» → chat-dogovory-svyazi.json."""
    т = "".join(_ЛАТИНИЦА.get(с, с) for с in (сессия or "").lower())
    т = re.sub(r"[^a-z0-9]+", "-", т).strip("-")[:48] or "main"
    return f"chat-{т}.json"


class ХранилищеЧатов:
    """Память задачи по сессиям: JSON-файл на сессию в memory/chat/."""

    def __init__(self, каталог: str) -> None:
        self.каталог = каталог
        os.makedirs(каталог, exist_ok=True)

    def путь(self, сессия: str) -> str:
        return os.path.join(self.каталог, имя_файла(сессия))

    def загрузить(self, сессия: str) -> ПамятьЗадачи:
        путь = self.путь(сессия)
        if not os.path.exists(путь):
            return ПамятьЗадачи(сессия=сессия)
        with open(путь, encoding="utf-8") as f:
            данные = json.load(f)
        if данные.get("сессия") not in ("", сессия):
            # Две сессии с одинаковой латинской записью («договор» и «договоръ»)
            # не должны читать чужую память.
            raise ValueError(f"Файл {путь} принадлежит сессии «{данные.get('сессия')}», "
                             f"а не «{сессия}». Назовите сессию иначе.")
        return ПамятьЗадачи.from_dict(данные)

    def сохранить(self, память: ПамятьЗадачи) -> None:
        записать_атомарно(self.путь(память.сессия),
                          json.dumps(память.to_dict(), ensure_ascii=False, indent=1))

    def удалить(self, сессия: str) -> bool:
        путь = self.путь(сессия)
        if os.path.exists(путь):
            os.remove(путь)
            return True
        return False

    def список(self) -> list[dict[str, Any]]:
        итог = []
        for имя in sorted(os.listdir(self.каталог)):
            if not (имя.startswith("chat-") and имя.endswith(".json")):
                continue
            try:
                with open(os.path.join(self.каталог, имя), encoding="utf-8") as f:
                    п = ПамятьЗадачи.from_dict(json.load(f))
            except (OSError, ValueError):
                continue
            итог.append({"сессия": п.сессия, "файл": имя, "обновлена": п.обновлена, **п.сводка()})
        return итог
