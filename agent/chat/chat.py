def промпт_разбора(модель: str) -> str:
    """Промпт разбора реплики: локальной модели — вариант из карты ролей."""
    from agent.local import offline
    if модель and catalog.get(модель).local:
        return ПРОМПТЫ_РАЗБОРА.get(offline.параметры_роли(РОЛЬ_РАЗБОРА).промпт, РАЗБОР)
    return РАЗБОР


def числа_без_опоры(ответ: str, опора_текст: str) -> list[str]:
    """Числа ответа по памяти, которых нет в записях опоры и в словах пользователя."""
    свои = set(cite.числа(опора_текст))
    return [ч for ч in cite.числа(ответ) if ч not in свои]


class Чат:
    """Сессия мини-чата: история в короткой памяти, память задачи — в JSON."""

    def __init__(self, отвечатель, клиент, короткая, хранилище: ХранилищеЧатов,
                 сессия: str = "основная", модель: str = "", поиск: str = ПОИСК,
                 порог_уверенности: float | None = None) -> None:
        сессия = (сессия or "").strip() or "основная"
        self.отвечатель = отвечатель
        self.клиент = клиент
        self.короткая = короткая
        self.хранилище = хранилище
        self.сессия = сессия
        self.модель = модель
        self.поиск = поиск
        self.порог = порог_уверенности

    @property
    def сессия_диалога(self) -> str:
        return ПРЕФИКС + self.сессия

    @property
    def память(self) -> ПамятьЗадачи:
        return self.хранилище.загрузить(self.сессия)

    def история(self) -> list[dict[str, Any]]:
        return self.короткая.all(self.сессия_диалога)

    def новый(self) -> dict[str, Any]:
        """Новый разговор: стереть историю и память задачи этой сессии."""
        стёрто = self.короткая.clear(self.сессия_диалога)
        return {"сессия": self.сессия, "сообщений_стёрто": стёрто,
                "память_стёрта": self.хранилище.удалить(self.сессия)}

    # --- ход ---------------------------------------------------------------------

    def ход(self, реплика: str) -> Ход:
        from agent.local import progress
        реплика = (реплика or "").strip()
        if not реплика:
            raise ValueError("Пустая реплика")
        старт = time.monotonic()
        память = self.хранилище.загрузить(self.сессия)
        ход = Ход(номер=память.реплик + 1, реплика=реплика)
        # История — до записи текущей реплики: она идёт в промпт отдельно.
        окно, символов = окно_истории()
        история = self.короткая.window(self.сессия_диалога, окно, окно * символов)
        progress.этап("начало", реплика=ход.номер)

        try:
            self._ход(ход, память, история, реплика)
        finally:
            self._этап(ход, "")
        ход.цель = память.цель.текст if память.цель else ""
        ход.сводка = память.сводка()
        ход.секунд = time.monotonic() - старт
        if ход.текст:
            self.короткая.append(self.сессия_диалога, "assistant", self._в_историю(ход),
                                 tokens=ход.токенов_вход + ход.токенов_выход, cost=ход.стоимость)
        память.журнал.append(ход.в_журнал())
        self.хранилище.сохранить(память)
        return ход

    def _ход(self, ход: Ход, память: ПамятьЗадачи, история: list[dict[str, str]], реплика: str) -> None:
        ход.разбор = self._разобрать(ход, память, история)
        ход.изменения = память.применить(ход.разбор.изменения(), ход.номер)
        self.короткая.append(self.сессия_диалога, "user", реплика)

        вопрос = ход.разбор.вопрос_для_поиска or реплика
        if ход.вид == РАЗГОВОР:
            self._по_памяти(ход, память, история, вопрос)
        else:
            self._по_документам(ход, память, история, вопрос)

    def _этап(self, ход: Ход, имя: str, **данные: Any) -> None:
        """Закрыть текущий этап хода (секунды) и открыть следующий; пусто — только закрыть."""
        from agent.local import progress
        сейчас = time.monotonic()
        if ход.этапы and "_старт" in ход.этапы[-1]:
            ход.этапы[-1]["секунд"] = round(сейчас - ход.этапы[-1].pop("_старт"), 1)
        if имя:
            ход.этапы.append({"этап": имя, **данные, "_старт": сейчас})
            progress.этап(имя, **данные)

    # --- шаг 1: разбор реплики --------------------------------------------------

    def _модели(self, роль: str) -> list[str]:
        """Модели роли по порядку: первая — основная, остальные — на случай сбоя."""
        from agent.local import offline
        варианты = [catalog.for_role(роль, i) for i in range(len(catalog.ROLES[роль]["models"]))]
        выбрана = self.модель
        if выбрана and offline.включён() and not catalog.get(выбрана).local:
            выбрана = ""     # облачная модель в офлайне не вызывается — роль из карты
        if выбрана and роль == РОЛЬ_ОТВЕТА:
            варианты = [выбрана] + [м for м in варианты if м != выбрана]
        return list(dict.fromkeys(варианты))

    def _вызвать(self, ход: Ход, роль: str, сообщения: list[dict[str, str]], предел: int,
                 схема: str = ""):
        """Вызов с переходом на запасную модель роли; None — все модели недоступны.

        Локальной модели (День 27) — схема ответа (format в Ollama) и параметры
        роли из карты офлайна: температура и длина ответа."""
        from agent.llm import LLMError
        from agent.local import offline, schemas
        ошибки = []
        for модель in self._модели(роль):
            параметры = offline.параметры_роли(роль) if catalog.get(модель).local else None
            self._этап(ход, роль, модель=модель, локально=catalog.get(модель).local)
            # Схема и температура — только когда заданы: облачный вызов уходит
            # с прежней сигнатурой.
            доп: dict[str, Any] = {}
            if параметры and параметры.температура is not None:
                доп["temperature"] = параметры.температура
            формат = schemas.формат(роль, модель, схема)
            if формат is not None:
                доп["fmt"] = формат
            try:
                reply = self.клиент.call(
                    модель, сообщения, max_tokens=(параметры.предел if параметры and параметры.предел else предел),
                    low_effort=True, **доп)
            except LLMError as exc:
                ошибки.append(f"{модель}: {exc}")
                continue
            ход.вызовов += 1
            ход.токенов_вход += reply.prompt_tokens
            ход.токенов_выход += reply.completion_tokens
            ход.стоимость += reply.cost
            замеры = getattr(reply, "timings", None) or {}
            ход.этапы[-1].update(вход=reply.prompt_tokens, выход=reply.completion_tokens,
                                 **({"до_первого_токена": замеры.get("ttft_s"),
                                     "ток_с": замеры.get("tok_s")} if замеры else {}))
            return модель, reply
        ход.ошибка = "; ".join(ошибки)[:400]
        return "", None

    def _разобрать(self, ход: Ход, память: ПамятьЗадачи, история: list[dict[str, str]]) -> Разбор:
        сообщения = [
            {"role": "system", "content": промпт_разбора(self._модели(РОЛЬ_РАЗБОРА)[0])},
            {"role": "user", "content": (
                f"Память задачи сейчас:\n{память.текст(с_выясненным=False)}\n\n"
                f"Последние реплики:\n{история_строкой(история)}\n\n"
                f"Новая реплика пользователя (№ {ход.номер}):\n{ход.реплика}")},
        ]
        модель, reply = self._вызвать(ход, РОЛЬ_РАЗБОРА, сообщения, ПРЕДЕЛ_РАЗБОРА, "разбор")
        разбор = разобрать_разбор(reply.text) if reply is not None else None
        if разбор is not None and из_инструкции(разбор.вопрос_для_поиска, сообщения[0]["content"]):
            # Маленькая модель иногда вместо вопроса переписывает кусок
            # инструкции («Назови договор, оператора, статью бюджета» — проба
            # Дня 27 на qwen3:1.7b). По такому «вопросу» поиск найдёт что
            # угодно; ищем по самой реплике и честно пишем почему.
            разбор.ошибка = f"вопрос для поиска списан из инструкции («{разбор.вопрос_для_поиска}») — искали по реплике"
            разбор.вопрос_для_поиска = ход.реплика
        if разбор is not None and модель and catalog.get(модель).local:
            поправить_разбор(разбор, ход.реплика, память)
        if разбор is None:
            # Запасной путь кодом: искать по реплике вместе с целью, память не
            # трогать. Ответ будет хуже на «а у них?», но чат не встанет.
            запас = Разбор(вид=ДОКУМЕНТЫ, модель=модель,
                           ошибка=ход.ошибка or "разбор реплики не вернул JSON")
            цель = f" ({память.цель.текст})" if память.цель else ""
            запас.вопрос_для_поиска = ход.реплика + цель
            ход.ошибка = ""
            return запас
        разбор.модель = модель
        return разбор

    # --- шаг 3а: ответ по документам ---------------------------------------------

    def _контекст(self, ход: Ход, память: ПамятьЗадачи, история: list[dict[str, str]]) -> str:
        return (f"{память.текст(с_выясненным=False)}\n\n"
                f"Последние реплики:\n{история_строкой(история)}\n\n"
                f"Реплика пользователя дословно: {ход.реплика}")

    def _по_документам(self, ход: Ход, память: ПамятьЗадачи, история: list[dict[str, str]],
                       вопрос: str) -> None:
        from agent.local import offline
        from agent.rag.embed import ОшибкаЭмбеддера
        from agent.rag.store import ОшибкаИндекса
        модели = self._модели(РОЛЬ_ОТВЕТА)
        try:
            подвопросы = ход.разбор.подвопросы
            if offline.включён():
                # Офлайн: каждый подвопрос — ещё минута кросс-энкодера на CPU.
                подвопросы = подвопросы[:offline.подвопросов()]
            составной = len(подвопросы) >= 2
            настройки = self.отвечатель.поисковик.настройки(self.поиск)
            self._этап(ход, "поиск", реранкер=настройки.реранкер, k_до=настройки.k_до,
                       k_после=настройки.k_после, подвопросов=len(подвопросы) if составной else 0)
            if составной:
                отбор = слить_отборы(вопрос, [self.отвечатель.поисковик.найти(q, self.поиск)
                                              for q in подвопросы])
                # В ответ — все подвопросы: модель разбора иногда кладёт в
                # «вопрос_для_поиска» только первый, и ответ терял второй договор.
                вопрос = "\n".join(подвопросы)
            else:
                отбор = self.отвечатель.поисковик.найти(вопрос, self.поиск)
            ход.этапы[-1]["кандидатов"] = len(отбор.кандидаты)
            ход.этапы[-1]["в_промпт"] = len(отбор.фрагменты)
            self._этап(ход, РОЛЬ_ОТВЕТА, модель=модели[0], локально=catalog.get(модели[0]).local)
            ответ = self.отвечатель.ответить(
                вопрос, С_RAG, модели[0], поиск=self.поиск, формат=ЦИТАТЫ,
                порог_уверенности=self.порог, контекст=self._контекст(ход, память, история),
                свои_числа=f"{ход.реплика}\n{память.от_пользователя()}", отбор=отбор)
        except (ValueError, ОшибкаИндекса, ОшибкаЭмбеддера) as exc:
            raise ОшибкаЧата(str(exc)) from exc
        ход.ответ_rag = ответ
        ход.модель = ответ.модель
        ход.этапы[-1].update(вызовов=ответ.вызовов, вход=ответ.токенов_вход, выход=ответ.токенов_выход,
                             **({"окна": [f"{о['было']}→{о['стало']}" for о in ответ.окна]} if ответ.окна else {}))
        if ответ.отбор is not None:
            ход.кандидатов = len(ответ.отбор.кандидаты)
        ход.вызовов += ответ.вызовов
        ход.токенов_вход += ответ.токенов_вход
        ход.токенов_выход += ответ.токенов_выход
        ход.стоимость += ответ.стоимость
        if ответ.решение is not None:
            ход.уверенность = ответ.решение.уверенность
        if ответ.ошибка:
            ход.ошибка = ответ.ошибка
            ход.текст = f"Ответ по документам не получен: {ответ.ошибка}"
            return
        ход.текст = ответ.текст
        ход.нарушения = list(ответ.нарушения)
        ход.починка = ответ.починка
        if ответ.не_знаю:
            ход.не_знаю, ход.не_знаю_кто, ход.уточнение = True, ответ.не_знаю_кто, ответ.уточнение
            # «Не знаю» тоже с источниками: какие разделы проверены и почему
            # ответа в них нет — иначе «не знаю» нельзя ни проверить, ни оспорить.
            ход.источники = [{"вид": "проверено", **н.чанк.паспорт(),
                              "rerank": None if н.реранк is None else round(н.реранк, 3)}
                             for н in ответ.ближайшие[:БЛИЖАЙШИХ]]
            if not ход.источники:
                ход.источники = [{"вид": "проверено", "source": "индекс документов",
                                  "section": "похожих фрагментов не нашлось"}]
            return
        ход.источники = источники_ответа(ответ)
        подтверждённые = [ц.текст for ц in ответ.выдержки if ц.подтверждена]
        if подтверждённые and ход.источники:
            запись = память.записать_выяснено(
                вопрос, ответ.текст, [{к: и[к] for к in ("source", "section", "clause", "pages", "chunk_id")
                                       if и.get(к)} for и in ход.источники],
                подтверждённые, ход.номер)
            ход.выяснено = f"В{память.выяснено.index(запись) + 1}"

    # --- шаг 3б: ответ по памяти задачи -------------------------------------------

    def _по_памяти(self, ход: Ход, память: ПамятьЗадачи, история: list[dict[str, str]],
                   вопрос: str) -> None:
        # Поиск идёт и здесь (выбор пользователя): что нашлось в документах по
        # предмету цели, показывается рядом с ответом, но в ответ не идёт.
        try:
            self._этап(ход, "поиск", подвопросов=0)
            отбор = self.отвечатель.поисковик.найти(вопрос, self.поиск)
            ход.кандидатов = len(отбор.кандидаты)
            ход.найдено = [{**н.чанк.паспорт(), "rerank": None if н.реранк is None else round(н.реранк, 3)}
                           for н in отбор.фрагменты[:БЛИЖАЙШИХ]]
        except Exception as exc:   # поиск — подсказка, без него ответ по памяти возможен
            ход.найдено = []
            ход.нарушения.append(f"поиск не удался: {str(exc)[:160]}")
        коды = память.коды()
        сообщения = [
            {"role": "system", "content": ПО_ПАМЯТИ},
            {"role": "user", "content": (
                f"Память задачи:\n{память.текст(с_кодами=True)}\n\n"
                f"Последние реплики:\n{история_строкой(история)}\n\n"
                f"Реплика пользователя: {ход.реплика}")},
        ]
        модель, reply = self._вызвать(ход, РОЛЬ_ОТВЕТА, сообщения, ПРЕДЕЛ_ПАМЯТИ, "по_памяти")
        ход.модель = модель
        if reply is None:
            ход.текст = f"Ответ по памяти задачи не получен: {ход.ошибка}"
            return
        ответ, опора, нарушено = self._проверить_по_памяти(reply.text, коды, ход, память)
        if нарушено:
            повтор = сообщения + [{"role": "assistant", "content": reply.text or ""},
                                  {"role": "user", "content": ПОЧИНКА_ПАМЯТИ.format(
                                      нарушения="\n".join(f"- {н}" for н in нарушено))}]
            _, reply2 = self._вызвать(ход, РОЛЬ_ОТВЕТА, повтор, ПРЕДЕЛ_ПАМЯТИ, "по_памяти")
            ход.починка = True
            if reply2 is not None:
                ответ, опора, нарушено = self._проверить_по_памяти(reply2.text, коды, ход, память)
        ход.текст = ответ
        ход.опора = опора
        ход.нарушения += нарушено
        ход.источники = источники_памяти(опора, коды, память)

    def _проверить_по_памяти(self, текст: str, коды: dict, ход: Ход,
                             память: ПамятьЗадачи) -> tuple[str, list[str], list[str]]:
        данные = _json(текст)
        нарушено: list[str] = []
        if данные is None:
            ответ, опора = (текст or "").strip(), []
            нарушено.append("ответ не в формате JSON")
        else:
            ответ = str(данные.get("ответ") or "").strip()
            # Модель пишет коды то кириллицей, то латиницей-двойником: «O1», «B2».
            опора = [str(к).strip().upper().translate(_ДВОЙНИКИ) for к in данные.get("опора") or []]
            if not ответ:
                нарушено.append("пустое поле «ответ»")
        чужие = [к for к in опора if к not in коды]
        if чужие:
            нарушено.append(f"в «опора» коды, которых нет в памяти: {', '.join(чужие)}")
        опора = [к for к in dict.fromkeys(опора) if к in коды]
        if not опора and ЦЕЛЬ in коды:
            # Ответ о разговоре без единой ссылки: держится он как минимум на цели.
            опора = [ЦЕЛЬ]
        опорный = "\n".join(
            [ход.реплика, память.от_пользователя()]
            + [f"{з.вопрос} {з.текст} {' '.join(з.цитаты)}" for к, з in коды.items() if к in опора])
        лишние = числа_без_опоры(ответ, опорный)
        if лишние:
            нарушено.append(f"в «ответ» есть числа, которых нет в записях из «опора»: {', '.join(лишние)}")
        return ответ, опора, нарушено

    # --- шаг 5: что запомнить в истории --------------------------------------------

    def _в_историю(self, ход: Ход) -> str:
        """Ответ в историю — с источниками строкой: следующий разбор реплики
        видит, о каком договоре шла речь, даже если в тексте его имени нет."""
        документы = list(dict.fromkeys(f"{и.get('source', '')} · {и.get('section', '')}"
                                       for и in ход.источники if и.get("вид") == "документ"))
        хвост = f"\n[Источники: {'; '.join(документы)}]" if документы else ""
        return ход.текст + хвост


def слить_отборы(вопрос: str, отборы: list) -> Any:
    """Отборы подвопросов → один: фрагменты по очереди от каждого, без повторов.

    Порядок «по очереди» важен: у каждого подвопроса его лучший фрагмент идёт
    в промпт раньше вторых мест других — иначе один договор занял бы все
    места. Уверенность для «не знаю» считается по всем кандидатам сразу.
    """
    from agent.rag.retrieval import Кандидат, Отбор
    первый = отборы[0]
    предел = max(первый.настройки.k_после, len(отборы))
    фрагменты, видели = [], set()
    for место in range(max(len(о.фрагменты) for о in отборы)):
        for о in отборы:
            if место < len(о.фрагменты) and len(фрагменты) < предел:
                н = о.фрагменты[место]
                if н.чанк.chunk_id not in видели:
                    видели.add(н.чанк.chunk_id)
                    фрагменты.append(н)
    кандидаты: dict[str, Кандидат] = {}
    for о in отборы:
        for к in о.кандидаты:
            было = кандидаты.get(к.находка.чанк.chunk_id)
            if было is None or (к.находка.реранк or 0) > (было.находка.реранк or 0):
                кандидаты[к.находка.чанк.chunk_id] = Кандидат(к.находка, к.rrf, к.судьба)
    for cid, к in кандидаты.items():
        if cid in видели:
            к.судьба = "в промпт"
        elif к.судьба == "в промпт":
            к.судьба = "за пределами K"
    итог = Отбор(вопрос=вопрос, настройки=первый.настройки, фрагменты=фрагменты,
                 кандидаты=list(кандидаты.values()))
    итог.этапы = [{"этап": "подвопрос", "вопрос": о.вопрос, "в промпт": len(о.фрагменты),
                   "секунд": round(о.секунд, 2)} for о in отборы]
    итог.секунд = sum(о.секунд for о in отборы)
    итог.ошибки = [ош for о in отборы for ош in о.ошибки]
    return итог


def источники_ответа(ответ: ОтветRAG) -> list[dict[str, Any]]:
    """Документы, на которые сослался ответ, и их подтверждённые цитаты."""
    по_номеру: dict[int, list[dict[str, Any]]] = {}
    for ц in ответ.выдержки:
        if ц.подтверждена:
            по_номеру.setdefault(ц.найдена_в or ц.n, []).append({"текст": ц.текст, "проверка": ц.проверка})
    итог = []
    for и in ответ.источники:
        итог.append({"вид": "документ", **{к: и.get(к) for к in
                                           ("n", "source", "section", "clause", "pages", "chunk_id")},
                     "цитаты": по_номеру.get(и["n"], [])})
    return итог


def источники_памяти(опора: list[str], коды: dict, память: ПамятьЗадачи) -> list[dict[str, Any]]:
    """Записи памяти, на которые сослался ответ; у «выяснено» — их документы."""
    итог = []
    for код in опора:
        з = коды[код]
        запись = {"вид": "память", "код": код, "что": память.вид_кода(код), "реплика": з.реплика,
                  "текст": f"«{з.термин}» — {з.текст}" if з.термин else з.текст}
        if з.источники:
            запись["документы"] = [{**и, "строка": источник_строкой(и)} for и in з.источники]
            запись["цитаты"] = list(з.цитаты)
        итог.append(запись)
    if not итог:
        итог.append({"вид": "память", "код": "", "что": "память задачи", "реплика": 0,
                     "текст": "память задачи пуста — цель ещё не названа"})
    return итог
