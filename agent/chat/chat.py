_ДВОЙНИКИ = str.maketrans({"O": "О", "B": "В", "T": "Т", "Y": "У"})


def _json(текст: str) -> dict[str, Any] | None:
    найдено = re.search(r"\{.*\}", текст or "", re.S)
    if not найдено:
        return None
    try:
        данные = json.loads(найдено.group(0))
    except json.JSONDecodeError:
        return None
    return данные if isinstance(данные, dict) else None


def _строки(значение: Any) -> list[str]:
    if isinstance(значение, str):
        значение = [значение]
    if not isinstance(значение, list):
        return []
    return [str(с).strip() for с in значение if str(с).strip()]


def разобрать_разбор(текст: str) -> Разбор | None:
    """JSON разбора реплики → Разбор; None — ответ не разобрать."""
    данные = _json(текст)
    if данные is None:
        return None
    вид = str(данные.get("вид") or "").strip().lower()
    термины = []
    for т in данные.get("термины") or []:
        if isinstance(т, dict) and т.get("термин") and т.get("значение"):
            термины.append({"термин": str(т["термин"]).strip(), "значение": str(т["значение"]).strip()})
    return Разбор(
        вид=вид if вид in ВИДЫ else ДОКУМЕНТЫ,
        вопрос_для_поиска=str(данные.get("вопрос_для_поиска") or "").strip(),
        подвопросы=_строки(данные.get("подвопросы"))[:ПОДВОПРОСОВ],
        цель=str(данные.get("цель") or "").strip(),
        смена_цели=bool(данные.get("смена_цели")),
        уточнения=_строки(данные.get("уточнения")),
        ограничения=_строки(данные.get("ограничения")),
        термины=термины)


def история_строкой(история: list[dict[str, str]]) -> str:
    кто = {"user": "Пользователь", "assistant": "Ассистент"}
    строки = []
    for с in история:
        текст = с["content"].strip()
        символов = окно_истории()[1]
        if len(текст) > символов:
            текст = текст[:символов].rstrip() + "…"
        строки.append(f"{кто.get(с['role'], с['role'])}: {текст}")
    return "\n".join(строки) or "— это первая реплика"


def _слова(текст: str) -> str:
    return " ".join(re.findall(r"\w+", (текст or "").lower().replace("ё", "е")))


def из_инструкции(вопрос: str, инструкция: str) -> bool:
    """Вопрос для поиска дословно стоит в инструкции — модель списала его оттуда."""
    слова = _слова(вопрос)
    return len(слова) >= 15 and слова in _слова(инструкция)


# Запасные пути кодом для разбора локальной модели (День 27). Проба на шести
# репликах: и qwen3:1.7b, и qwen3.5:4b не записали цель из «Мне нужно сравнить
# два договора… Начнём с…», а маленькая модель вдобавок записала в ограничения
# пересказ цели. Код берёт цель из явного «мне нужно / помоги / хочу» в начале
# предложения и не пускает в память ограничения, если в реплике нет признака
# правила ответа.
_ЦЕЛЬ = re.compile(r"(?i)(?:^|[.!?]\s+)(?:мне\s+|нам\s+)?(?:нужно|надо|необходимо|требуется|хочу|хотим|"
                   r"помоги(?:те)?|задача\s*[—:-])\s+(?!ли\b)(.{8,220}?)(?=[.!?](?:\s|$)|$)")
_ПРАВИЛО = re.compile(r"(?i)ограничени|приводи|указывай|указать|не включ|не учитыв|исключ|без пересч|"
                      r"\bтолько\b|\bпиши\b|отвечай|не расписыв|в виде|формат|кратко|подробно|округл")


def цель_из_реплики(реплика: str) -> str:
    """Цель разговора из явного «мне нужно…», «помоги…» в начале предложения."""
    найдено = _ЦЕЛЬ.search(реплика or "")
    return найдено.group(1).strip(" ,;:—-") if найдено else ""


def поправить_разбор(разбор: Разбор, реплика: str, память: ПамятьЗадачи) -> None:
    if not разбор.цель and память.цель is None:
        цель = цель_из_реплики(реплика)
        if цель:
            разбор.цель = цель
            разбор.поправки.append(f"цель взята кодом из реплики: «{цель}»")
    if разбор.ограничения and not _ПРАВИЛО.search(реплика or ""):
        разбор.поправки.append("ограничения модели отброшены — в реплике нет правила ответа: "
                               + "; ".join(f"«{о}»" for о in разбор.ограничения))
        разбор.ограничения = []


