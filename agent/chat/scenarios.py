"""Проверка мини-чата на длинных сценариях (День 25).

Два заданных сценария по 13–14 реплик (chat-scenarios.json): с уточнениями,
ограничениями, терминами, местоимениями («по нему», «у них»), ловушкой вне
документов и итогом в конце. Сценарий заданный, а не сыгранный моделью
(выбор пользователя): прогоны сравнимы между собой, и показ повторяем.

На каждом ходе код проверяет:
  поиск        на реплике шёл поиск по базе: проверены кандидаты-чанки;
  источники    у ответа есть блок источников — всегда, при любом виде ответа;
  документы    ответ по документам: источник с chunk_id и подтверждённой
               цитатой, ожидаемый документ среди источников, факты в тексте;
  не знаю      ловушка: «не знаю» с уточняющим вопросом и проверенными разделами;
  вид          реплика понята как ожидалось — «документы» или «разговор»;
  память       то, что пользователь уточнил, ограничил или определил в этой
               реплике, записано в память задачи с её номером;
  цель         цель названа на первой реплике, содержит ключевые слова сценария
               и не меняется до конца: ни ловушка, ни отступление её не сбили;
  опора        итог по памяти держится на «выяснено», а у тех — документы.

В конце судья (модели роли «судья-ответов») читает весь разговор и цель и
отвечает: удержана ли цель, соблюдены ли ограничения, по делу ли ответы.

Публичное API:
  путь_сценариев(), загрузить(путь)        — сценарии из JSON
  проверить(сценарий, ходы, памяти)          — проверки кодом по ходам
  судить(клиент, сценарий, ходы, память)     — вердикт судьи
  прогнать(агент, сценарии, с_судьёй, прогресс) → Прогон
  в_markdown(прогон), записать(прогон, каталог), прочитать(каталог)
"""

