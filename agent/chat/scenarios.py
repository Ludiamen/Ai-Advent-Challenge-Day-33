def _дробь(пара: tuple[int, int]) -> str:
    return f"{пара[0]} из {пара[1]}"


def _источники_строкой(х: dict[str, Any]) -> str:
    части = []
    for и in х.get("sources", []):
        if и.get("вид") == "документ":
            части.append(f"{источник_строкой(и)} (цитат {len(и.get('цитаты') or [])})")
        elif и.get("вид") == "проверено":
            части.append(f"проверено: {источник_строкой(и)}")
        else:
            документы = "; ".join(д.get("строка", "") for д in и.get("документы", []))
            части.append(f"память {и.get('код') or ''} ({и.get('что')}, реплика {и.get('реплика')})"
                         + (f" → {документы}" if документы else ""))
    return "<br>".join(части) or "—"


def в_markdown(прогон: dict[str, Any]) -> str:
    строки = ["# Мини-чат с RAG и памятью задачи: длинные сценарии", "",
              f"Прогон {прогон['when']}: модель ответов `{прогон['model']}`, сценариев "
              f"{len(прогон['scenarios'])}, {прогон['seconds']} с. На каждом ходе — поиск по базе "
              "(режим «фильтр»), ответ с источниками и память задачи; проверки кодом по ходам, "
              "в конце — судья по всему разговору.", "", "## Итог", "",
              "| показатель | " + " | ".join(с["title"] for с in прогон["scenarios"]) + " |",
              "|---|" + "---:|" * len(прогон["scenarios"])]
    итоги = [с["totals"] for с in прогон["scenarios"]]
    def строка(подпись: str, значения: list[str]) -> None:
        строки.append(f"| {подпись} | " + " | ".join(значения) + " |")
    строка("реплик в сценарии", [str(и["ходов"]) for и in итоги])
    строка("поиск по базе на реплике", [f"{и['с_поиском']} из {и['ходов']}" for и in итоги])
    строка("ответов с источниками", [f"{и['с_источниками']} из {и['ходов']}" for и in итоги])
    строка("ответов по документам: источник с chunk_id и цитатой",
           [f"{и['с_документом_и_цитатой']} из {и['документных']}" for и in итоги])
    строка("нужный документ среди источников", [_дробь(и["нужный_документ"]) for и in итоги])
    строка("ожидаемые факты в ответе", [_дробь(и["факты"]) for и in итоги])
    строка("ловушка — «не знаю» с уточнением", [_дробь(и["не_знаю"]) for и in итоги])
    строка("вид реплики понят верно", [_дробь(и["вид"]) for и in итоги])
    строка("уточнения, ограничения, термины записаны", [_дробь(и["память"]) for и in итоги])
    строка("цель на месте после каждой реплики", [_дробь(и["цель_на_месте"]) for и in итоги])
    строка("в цели — ключевые слова сценария", ["да" if и["цель_ключи"] else "нет" for и in итоги])
    строка("итог опирается на «выяснено» с документами", [_дробь(и["опора"]) for и in итоги])
    строка("судья: цель удержана",
           [с["judge"].get("цель_удержана") or "—" for с in прогон["scenarios"]])
    строка("судья: ограничения соблюдены",
           [с["judge"].get("ограничения_соблюдены") or "—" for с in прогон["scenarios"]])
    строка("судья: ответы по делу", [с["judge"].get("ответы_по_делу") or "—" for с in прогон["scenarios"]])
    строка("повторных запросов из-за формата", [str(и["починок"]) for и in итоги])
    строка("проверок / провалов", [f"{и['проверок']} / {и['провалов']}" for и in итоги])
    строка("вызовов модели · токенов на входе",
           [f"{и['вызовов']} · {и['токенов_вход']:,}".replace(",", " ") for и in итоги])
    строка("время, с", [str(и["секунд"]) for и in итоги])
    for с in прогон["scenarios"]:
        строки += ["", f"## {с['title']} ({с['id']})", ""]
        память = с["memory"]
        цель = (память.get("цель") or {}).get("текст", "—")
        строки.append(f"**Цель** (реплика {(память.get('цель') or {}).get('реплика', '—')}): {цель}")
        for вид, подпись in (("уточнения", "Уточнения"), ("ограничения", "Ограничения"),
                             ("термины", "Термины")):
            записи = память.get(вид) or []
            if записи:
                строки.append(f"**{подпись}:** " + "; ".join(
                    (f"«{з['термин']}» — {з['текст']}" if з.get("термин") else з["текст"])
                    + f" (р. {з['реплика']})" for з in записи))
        строки.append(f"**Выяснено по документам:** {len(память.get('выяснено') or [])} записей")
        if с["judge"]:
            строки.append(f"**Судья** ({с['judge'].get('модель', '—')}): цель — "
                          f"{с['judge'].get('цель_удержана') or '—'}, ограничения — "
                          f"{с['judge'].get('ограничения_соблюдены') or '—'}, по делу — "
                          f"{с['judge'].get('ответы_по_делу') or '—'}. {с['judge'].get('пояснение', '')}")
        строки += ["", "| # | реплика | вид | вопрос для поиска | ответ | источники | проверки |",
                   "|---|---|---|---|---|---|---|"]
        for х in с["turns"]:
            проверки = " ".join(("✓" if п["ok"] else "✗") + " " + п["name"] for п in х["checks"])
            ответ = re.sub(r"\s+", " ", х["text"])[:260].replace("|", "/")
            строки.append(f"| {х['turn']} | {х['message'].replace('|', '/')} | {х['parse']['kind']} | "
                          f"{х['parse']['search_question'].replace('|', '/')} | {ответ} | "
                          f"{_источники_строкой(х)} | {проверки} |")
        провалы = [(х["turn"], п) for х in с["turns"] for п in х["checks"] if not п["ok"]]
        if провалы:
            строки += ["", "Провалы:"] + [f"- реплика {н}: {п['name']} — {п['note']}" for н, п in провалы]
    return "\n".join(строки) + "\n"


def записать(прогон: Прогон, каталог_памяти: str) -> str:
    """JSON прогона — в memory/chat/, отчёт — в корень (или рядом с чужой памятью)."""
    from agent.rag.indexer import КОРЕНЬ
    данные = прогон.to_dict()
    каталог = os.path.join(os.path.abspath(каталог_памяти), "chat")
    os.makedirs(каталог, exist_ok=True)
    записать_атомарно(os.path.join(каталог, ФАЙЛ_ПРОГОНА), json.dumps(данные, ensure_ascii=False, indent=1))
    свой = os.path.abspath(каталог_памяти) != os.path.abspath(os.path.join(КОРЕНЬ, "memory"))
    путь = os.path.join(каталог if свой else КОРЕНЬ, ФАЙЛ_ОТЧЁТА)
    записать_атомарно(путь, в_markdown(данные))
    return путь


def прочитать(каталог_памяти: str) -> dict[str, Any] | None:
    путь = os.path.join(os.path.abspath(каталог_памяти), "chat", ФАЙЛ_ПРОГОНА)
    if not os.path.exists(путь):
        return None
    with open(путь, encoding="utf-8") as f:
        return json.load(f)
