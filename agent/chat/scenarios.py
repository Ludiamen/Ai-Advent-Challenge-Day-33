def путь_сценариев() -> str:
    from agent.rag.indexer import КОРЕНЬ
    return os.environ.get("CHAT_SCENARIOS") or os.path.join(КОРЕНЬ, "chat-scenarios.json")


def загрузить(путь: str = "") -> list[dict[str, Any]]:
    with open(путь or путь_сценариев(), encoding="utf-8") as f:
        данные = json.load(f)
    сценарии = данные.get("сценарии") if isinstance(данные, dict) else данные
    if not сценарии:
        raise ValueError("В файле сценариев нет ни одного сценария")
    for с in сценарии:
        if not с.get("id") or not с.get("ходы"):
            raise ValueError(f"У сценария нет id или ходов: {с.get('название', '?')}")
    return сценарии


# --- проверки кодом ----------------------------------------------------------------

@dataclass
class Пункт:
    имя: str
    ок: bool
    пояснение: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {"name": self.имя, "ok": self.ок, "note": self.пояснение}


def _есть(шаблон: str, текст: str) -> bool:
    return bool(re.search(шаблон, текст or "", re.IGNORECASE))


def _без_пробелов_в_числах(текст: str) -> str:
    """«24 441 696,00» и «24441696.00» ищутся одним шаблоном."""
    return re.sub(r"(?<=\d)[\s ](?=\d{3}\b)", "", текст or "")


def _текст_для_фактов(ход: Ход) -> str:
    т = ход.текст
    return f"{т}\n{_без_пробелов_в_числах(т)}"


def проверить_ход(ожидание: dict[str, Any], ход: Ход, память: ПамятьЗадачи,
                  цель_была: str) -> list[Пункт]:
    """Проверки одного хода по ожиданию сценария."""
    пункты: list[Пункт] = []
    def п(имя: str, ок: bool, пояснение: str = "") -> None:
        пункты.append(Пункт(имя, bool(ок), пояснение))

    п("поиск по базе", ход.кандидатов > 0, f"проверено кандидатов: {ход.кандидатов}")
    п("источники", ход.есть_источники,
      f"{len(ход.источники)}: " + ", ".join(sorted({и.get('вид', '') for и in ход.источники})))
    ожидаемый_вид = ожидание.get("вид", ДОКУМЕНТЫ)
    п("вид", ход.вид == ожидаемый_вид, f"понято «{ход.вид}», ожидалось «{ожидаемый_вид}»")
    if ход.ошибка:
        п("без сбоя", False, ход.ошибка[:200])

    if ожидание.get("не_знаю"):
        п("не знаю", ход.не_знаю and bool(ход.уточнение),
          f"не знаю: {ход.не_знаю}, решил {ход.не_знаю_кто or '—'}; уточнение: {ход.уточнение[:80]}")
    elif ожидаемый_вид == ДОКУМЕНТЫ:
        документы = [и for и in ход.источники if и.get("вид") == "документ"]
        п("ответ дан", not ход.не_знаю, f"не знаю ({ход.не_знаю_кто})" if ход.не_знаю else "")
        п("документ с chunk_id и цитатой",
          bool(документы) and all(и.get("chunk_id") for и in документы)
          and any(и.get("цитаты") for и in документы),
          "; ".join(f"{и.get('chunk_id')} · цитат {len(и.get('цитаты') or [])}" for и in документы) or "—")
        if ожидание.get("источник"):
            имена = " | ".join(и.get("source", "") for и in документы)
            п("нужный документ", _есть(ожидание["источник"], имена), имена[:160] or "—")
    if ожидание.get("факты"):
        текст = _текст_для_фактов(ход)
        нет = [ф for ф in ожидание["факты"] if not _есть(ф, текст)]
        п("факты", not нет, "нет: " + ", ".join(нет) if нет else "все на месте")
    if ожидание.get("выяснено"):
        с_документами = [и for и in ход.источники if и.get("вид") == "память" and и.get("документы")]
        п("опора на выяснено", bool(с_документами),
          ", ".join(и.get("код", "") for и in с_документами) or "ни одной записи «выяснено»")
    if ожидание.get("память"):
        свежие = [з for з in память.уточнения + память.ограничения + память.термины
                  if з.реплика == ход.номер]
        тексты = " | ".join(f"{з.термин} {з.текст}" for з in свежие)
        нет = [ш for ш in ожидание["память"] if not _есть(ш, тексты)]
        п("память задачи", not нет, (тексты[:200] or "ничего не записано")
          + (f"; нет: {', '.join(нет)}" if нет else ""))
    цель = память.цель.текст if память.цель else ""
    if ожидание.get("цель"):
        п("цель названа", bool(цель), цель[:160] or "цель не записана")
    elif цель_была:
        п("цель на месте", цель == цель_была, "та же" if цель == цель_была else f"стала: {цель[:120]}")
    return пункты


@dataclass
class ПрогонСценария:
    сценарий: dict[str, Any]
    ходы: list[Ход] = field(default_factory=list)
    пункты: list[list[Пункт]] = field(default_factory=list)
    память: dict[str, Any] = field(default_factory=dict)
    цель_ключи: list[Пункт] = field(default_factory=list)
    судья: dict[str, Any] = field(default_factory=dict)
    секунд: float = 0.0

    def итог(self) -> dict[str, Any]:
        ходы = self.ходы
        документные = [(х, о) for х, о in zip(ходы, self.сценарий["ходы"])
                       if о.get("вид", ДОКУМЕНТЫ) == ДОКУМЕНТЫ and not о.get("не_знаю")]
        def ок(имя: str) -> tuple[int, int]:
            вс = [п for пп in self.пункты for п in пп if п.имя == имя]
            return sum(п.ок for п in вс), len(вс)
        return {
            "ходов": len(ходы),
            "с_источниками": sum(х.есть_источники for х in ходы),
            "с_поиском": sum(х.кандидатов > 0 for х in ходы),
            "документных": len(документные),
            "с_документом_и_цитатой": ок("документ с chunk_id и цитатой")[0],
            "нужный_документ": ок("нужный документ"),
            "факты": ок("факты"),
            "вид": ок("вид"),
            "память": ок("память задачи"),
            "не_знаю": ок("не знаю"),
            "цель_на_месте": ок("цель на месте"),
            "цель_ключи": sum(п.ок for п in self.цель_ключи) == len(self.цель_ключи) and bool(self.цель_ключи),
            "опора": ок("опора на выяснено"),
            "проверок": sum(len(пп) for пп in self.пункты),
            "провалов": sum(not п.ок for пп in self.пункты for п in пп) + sum(not п.ок for п in self.цель_ключи),
            "починок": sum(х.починка for х in ходы),
            "нарушений": sum(bool(х.нарушения) for х in ходы),
            "вызовов": sum(х.вызовов for х in ходы),
            "токенов_вход": sum(х.токенов_вход for х in ходы),
            "стоимость": round(sum(х.стоимость for х in ходы), 4),
            "секунд": round(self.секунд, 1),
            "судья": self.судья.get("цель_удержана", ""),
        }

    def to_dict(self) -> dict[str, Any]:
        return {"id": self.сценарий["id"], "title": self.сценарий.get("название", ""),
                "session": self.сценарий.get("сессия", ""),
                "turns": [{**х.to_dict(), "rag": None, "expected": о,
                           "checks": [п.to_dict() for п in пп]}
                          for х, о, пп in zip(self.ходы, self.сценарий["ходы"], self.пункты)],
                "memory": self.память, "goal_keys": [п.to_dict() for п in self.цель_ключи],
                "judge": self.судья, "totals": self.итог()}


def судить(клиент, сценарий: dict[str, Any], ходы: list[Ход], память: ПамятьЗадачи) -> dict[str, Any]:
    """Вердикт судьи по всему разговору; пустой словарь — судья недоступен."""
    from agent.llm import LLMError
    from agent.rag import qa
    строки = []
    for х in ходы:
        источники = "; ".join(
            (источник_строкой(и) if и.get("вид") in ("документ", "проверено")
             else f"память {и.get('код', '')}: {str(и.get('текст', ''))[:60]}") for и in х.источники)
        # Ответ — почти целиком: итог по памяти длинный, и обрезанный на 900
        # символах он выглядел для судьи «неполным» (так было на прогоне s1).
        строки.append(f"[{х.номер}] Пользователь: {х.реплика}\n[{х.номер}] Помощник: {х.текст[:ПРЕДЕЛ_ОТВЕТА]}\n"
                      f"     Источники: {источники or '—'}")
    сообщения = [{"role": "system", "content": СУДЬЯ_ЧАТА},
                 {"role": "user", "content": f"Память задачи в конце разговора:\n"
                                             f"{память.текст(с_выясненным=False)}\n\n"
                                             "Разговор:\n" + "\n\n".join(строки)}]
    пояснение = ""
    from agent.local import schemas
    for модель in qa.модели_судьи():
        try:
            # Локальной модели — температура роли судьи из карты (28.1).
            reply = клиент.call(модель, сообщения, max_tokens=700, low_effort=True,
                                **schemas.температура_вызова(qa.РОЛЬ_СУДЬИ, модель))
        except LLMError as exc:
            пояснение = f"судья недоступен ({модель}): {exc}"[:200]
            continue
        данные = qa._json_из(reply.text)
        if данные and данные.get("цель_удержана") in ВЕРДИКТЫ:
            return {"цель_удержана": данные["цель_удержана"],
                    "ограничения_соблюдены": данные.get("ограничения_соблюдены", ""),
                    "ответы_по_делу": данные.get("ответы_по_делу", ""),
                    "ходы_с_проблемами": [int(н) for н in данные.get("ходы_с_проблемами") or []
                                          if str(н).isdigit()],
                    "пояснение": str(данные.get("пояснение") or "")[:400], "модель": модель}
        пояснение = f"вердикт не разобран ({модель}): {(reply.text or '')[:120]}"
    return {"цель_удержана": "", "пояснение": пояснение}


def прогнать_сценарий(агент, сценарий: dict[str, Any], с_судьёй: bool = True,
                      прогресс: Callable[[str, int, int, str], None] | None = None) -> ПрогонСценария:
    """Сценарий с чистого листа: своя сессия, история и память стёрты."""
    чат = агент.чат(сценарий.get("сессия") or f"сценарий-{сценарий['id']}")
    чат.новый()
    прогон = ПрогонСценария(сценарий)
    старт = time.monotonic()
    цель_была = ""
    for i, ожидание in enumerate(сценарий["ходы"], 1):
        if прогресс:
            прогресс(f"сценарий {сценарий['id']}", i - 1, len(сценарий["ходы"]), ожидание["реплика"][:60])
        ход = чат.ход(ожидание["реплика"])
        память = чат.память
        прогон.ходы.append(ход)
        прогон.пункты.append(проверить_ход(ожидание, ход, память, цель_была))
        if память.цель and not цель_была:
            цель_была = память.цель.текст
    память = чат.память
    прогон.память = память.to_dict()
    прогон.память.pop("журнал", None)
    цель = память.цель.текст if память.цель else ""
    прогон.цель_ключи = [Пункт(f"в цели есть «{к}»", _есть(к, цель), цель[:160])
                         for к in сценарий.get("цель_ключи", [])]
    if с_судьёй:
        if прогресс:
            прогресс(f"сценарий {сценарий['id']}", len(сценарий["ходы"]), len(сценарий["ходы"]),
                     "судья читает разговор")
        прогон.судья = судить(агент.client, сценарий, прогон.ходы, память)
    прогон.секунд = time.monotonic() - старт
    return прогон


@dataclass
class Прогон:
    сценарии: list[ПрогонСценария] = field(default_factory=list)
    модель: str = ""
    когда: str = field(default_factory=lambda: datetime.now().isoformat(timespec="seconds"))
    секунд: float = 0.0

    def итог(self) -> dict[str, Any]:
        итоги = [с.итог() for с in self.сценарии]
        def сумма(ключ: str) -> Any:
            значения = [и[ключ] for и in итоги]
            if значения and isinstance(значения[0], tuple):
                return (sum(з[0] for з in значения), sum(з[1] for з in значения))
            return sum(значения)
        return {"сценариев": len(итоги), "ходов": сумма("ходов"), "с_источниками": сумма("с_источниками"),
                "документных": сумма("документных"), "с_документом_и_цитатой": сумма("с_документом_и_цитатой"),
                "факты": сумма("факты"), "цель_на_месте": сумма("цель_на_месте"),
                "провалов": сумма("провалов"), "проверок": сумма("проверок")}

    def to_dict(self) -> dict[str, Any]:
        return {"when": self.когда, "model": self.модель, "seconds": round(self.секунд, 1),
                "totals": self.итог(), "scenarios": [с.to_dict() for с in self.сценарии]}


def прогнать(агент, сценарии: list[dict[str, Any]], с_судьёй: bool = True,
             прогресс: Callable[[str, int, int, str], None] | None = None) -> Прогон:
    from agent import catalog
    прогон = Прогон(модель=агент.model_key or catalog.for_role("ответ-по-документам", 0))
    старт = time.monotonic()
    for с in сценарии:
        прогон.сценарии.append(прогнать_сценарий(агент, с, с_судьёй, прогресс))
    прогон.секунд = time.monotonic() - старт
    return прогон


