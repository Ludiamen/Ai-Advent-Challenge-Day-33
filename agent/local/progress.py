"""Ход долгой операции на локальной модели: этапы и токены (День 27).

На CPU ход чата идёт минуты: разбор реплики, поиск с кросс-энкодером, ответ.
Без обратной связи это выглядит как зависание, поэтому страница и консоль
показывают, что происходит сейчас, — этап, модель, сколько токенов она уже
написала.

Наблюдатель передаётся не аргументом через все слои (чат → ответ RAG →
клиент LLM), а контекстной переменной: кто хочет видеть ход, ставит её на
время операции, а чат и клиент просто сообщают о себе. Нет наблюдателя —
сообщения уходят в никуда, и поведение то же, что до Дня 27.

Клиент LLM, увидев наблюдателя, зовёт локальную модель потоком и сообщает о
каждом новом токене (не чаще, чем раз в ЧАСТОТА секунды).

Публичное API:
  наблюдать(функция) -> метка; снять(метка); активен()
  этап(имя, **данные); токены(модель, выход, секунд, первый)
"""

from __future__ import annotations

import time
from contextvars import ContextVar
from typing import Any, Callable

ЧАСТОТА = 0.5

_наблюдатель: ContextVar[Callable[[dict[str, Any]], None] | None] = ContextVar("наблюдатель", default=None)
_последнее: ContextVar[float] = ContextVar("последнее", default=0.0)


def наблюдать(функция: Callable[[dict[str, Any]], None]):
    return _наблюдатель.set(функция)


def снять(метка) -> None:
    _наблюдатель.reset(метка)


def активен() -> bool:
    return _наблюдатель.get() is not None


def _сообщить(событие: dict[str, Any]) -> None:
    функция = _наблюдатель.get()
    if функция is None:
        return
    try:
        функция(событие)
    except Exception:   # noqa: BLE001 — наблюдатель не должен ронять сам ход
        pass


def этап(имя: str, **данные: Any) -> None:
    _сообщить({"событие": "этап", "этап": имя, **данные})


def токены(модель: str, выход: int, секунд: float, первый: float | None = None,
           последний: bool = False) -> None:
    """Сколько токенов модель уже написала; не чаще раза в ЧАСТОТА секунды."""
    сейчас = time.monotonic()
    if not последний and первый is None and сейчас - _последнее.get() < ЧАСТОТА:
        return
    _последнее.set(сейчас)
    _сообщить({"событие": "токены", "модель": модель, "выход": выход, "секунд": round(секунд, 1),
               **({"первый_токен": round(первый, 2)} if первый is not None else {}),
               **({"готово": True} if последний else {})})
