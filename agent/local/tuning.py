"""Оптимизация локальной модели под задачу (День 29): конфигурации вызова.

Конфигурация — именованный набор того, что меняет ответ локальной модели:
- модель (ключ каталога) и, если нужно, другие веса той же модели — тег
  Ollama: квант Q8_0, MTP, BF16;
- опции вызова Ollama: temperature, num_predict (предел ответа), num_ctx
  (окно контекста), num_thread, num_batch, presence_penalty;
- шаблон промпта ответа по документам: «общий» (правила Дня 24) или
  «договоры» (короче, под договоры);
- сервер: служба Ollama, второй сервер со своими переменными (server2.py) или
  арендованный GPU через SSH-туннель.

Конфигурации лежат в local-opt.json. Применяются контекстной переменной, как
ход ответа в progress.py: `with применить(конф):` — и llm.ollama_payload
кладёт опции поверх базовых, а клиент идёт по адресу сервера конфигурации.
Протаскивать параметры через пять подписей (Отвечатель → _вызвать →
Client.call → _call_ollama → ollama_payload) не нужно. Без конфигурации тело
запроса — ровно как в Дне 28.

Конфигурация действует только на свою модель: разбор реплики на 1.7B в том же
ходе чата её не получает. У модели каталога может быть своя конфигурация
(`loc-rag-docs` → «после»): тогда клиент применяет её сам, без `with`, — так у
оптимизированной модели один источник параметров (plan.md, D-10).
"""

from __future__ import annotations

import contextlib
import contextvars
import json
import os
from dataclasses import asdict, dataclass, field, replace
from typing import Any, Iterator

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# Какие опции Ollama конфигурация может задать. Остальные — опечатка: молча
# пропущенная опция дала бы «после», которое на деле равно «до».
ОПЦИИ = ("temperature", "num_predict", "num_ctx", "num_thread", "num_batch", "presence_penalty",
         "top_k", "top_p", "repeat_penalty")
# Опции, которые Ollama применяет при загрузке модели: их смена перезапускает
# раннер llama-server (ворота 0, A-1).
ОПЦИИ_ЗАГРУЗКИ = ("num_ctx", "num_thread", "num_batch")
ШАБЛОНЫ = ("общий", "договоры")
СЛУЖБА, ВТОРОЙ, GPU = "служба", "второй", "gpu"
СЕРВЕРЫ = (СЛУЖБА, ВТОРОЙ, GPU)
# Адреса по умолчанию: второй сервер (server2.py) и туннель к арендованному GPU
# (plan.md, D-09, D-11). В local-opt.json их можно переопределить.
АДРЕСА = {ВТОРОЙ: "http://127.0.0.1:11435", GPU: "http://127.0.0.1:11436"}


class ОшибкаКонфигурации(ValueError):
    pass


@dataclass(frozen=True)
class Конфигурация:
    имя: str
    модель: str = "loc-qwen35"
    тег: str = ""                     # веса в Ollama, если не те, что у модели каталога
    опции: dict[str, Any] = field(default_factory=dict)
    шаблон: str = ""                  # общий | договоры; пусто — как у роли в карте
    сервер: str = СЛУЖБА
    переменные: dict[str, str] = field(default_factory=dict)   # переменные второго сервера
    рычаг: str = ""                   # код рычага скрининга (Р-…); пусто — «до» или «после»
    описание: str = ""

    @property
    def серверная(self) -> bool:
        """Нужен ли не служба: такой рычаг в модель «после» не входит (spec, FR-09)."""
        return self.сервер != СЛУЖБА

    def опции_загрузки(self) -> dict[str, Any]:
        return {к: з for к, з in self.опции.items() if к in ОПЦИИ_ЗАГРУЗКИ}

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def путь() -> str:
    return os.getenv("LOCAL_OPT") or os.path.join(КОРЕНЬ, "local-opt.json")


def _проверить(к: Конфигурация) -> Конфигурация:
    from agent import catalog
    if к.модель not in catalog.MODELS:
        raise ОшибкаКонфигурации(f"Конфигурация «{к.имя}»: нет модели «{к.модель}» в каталоге.")
    if not catalog.get(к.модель).local:
        raise ОшибкаКонфигурации(f"Конфигурация «{к.имя}»: модель «{к.модель}» облачная — "
                                 "конфигурации бывают только у локальных моделей.")
    лишние = sorted(set(к.опции) - set(ОПЦИИ))
    if лишние:
        raise ОшибкаКонфигурации(f"Конфигурация «{к.имя}»: неизвестные опции {', '.join(лишние)}. "
                                 f"Есть: {', '.join(ОПЦИИ)}.")
    if к.шаблон and к.шаблон not in ШАБЛОНЫ:
        raise ОшибкаКонфигурации(f"Конфигурация «{к.имя}»: нет шаблона «{к.шаблон}». Есть: {', '.join(ШАБЛОНЫ)}.")
    if к.сервер not in СЕРВЕРЫ:
        raise ОшибкаКонфигурации(f"Конфигурация «{к.имя}»: нет сервера «{к.сервер}». Есть: {', '.join(СЕРВЕРЫ)}.")
    if к.переменные and к.сервер != ВТОРОЙ:
        raise ОшибкаКонфигурации(f"Конфигурация «{к.имя}»: переменные сервера бывают только у второго сервера.")
    return к


_кэш: tuple[str, float, dict[str, Any]] | None = None


def прочитать() -> dict[str, Any]:
    """Файл local-opt.json целиком (с кэшем по времени изменения); нет файла — пусто."""
    global _кэш
    п = путь()
    try:
        время = os.path.getmtime(п)
    except OSError:
        return {}
    if _кэш and _кэш[0] == п and _кэш[1] == время:
        return _кэш[2]
    with open(п, encoding="utf-8") as f:
        данные = json.load(f)
    _кэш = (п, время, данные)
    return данные


def загрузить() -> dict[str, Конфигурация]:
    """Конфигурации по именам, в порядке файла."""
    итог: dict[str, Конфигурация] = {}
    for имя, з in (прочитать().get("конфигурации") or {}).items():
        поля = {к: з[к] for к in ("модель", "тег", "опции", "шаблон", "сервер", "переменные", "рычаг", "описание")
                if к in з}
        итог[имя] = _проверить(Конфигурация(имя=имя, **поля))
    return итог


def получить(имя: str) -> Конфигурация:
    все = загрузить()
    if имя not in все:
        raise ОшибкаКонфигурации(f"Нет конфигурации «{имя}». Есть: {', '.join(все) or 'ни одной'} "
                                 f"({путь()}).")
    return все[имя]


def адрес(сервер: str) -> str:
    """Адрес Ollama для сервера конфигурации."""
    from agent import catalog
    if сервер == СЛУЖБА:
        return catalog._OLLAMA
    свои = (прочитать().get("серверы") or {}).get(сервер) or {}
    return str(свои.get("адрес") or АДРЕСА[сервер]).rstrip("/")


_активная: contextvars.ContextVar[Конфигурация | None] = contextvars.ContextVar("конфигурация", default=None)


@contextlib.contextmanager
def применить(конф: Конфигурация | None) -> Iterator[Конфигурация | None]:
    """Конфигурация действует внутри блока — для своей модели (см. для_модели)."""
    метка = _активная.set(конф)
    try:
        yield конф
    finally:
        _активная.reset(метка)


def активная() -> Конфигурация | None:
    return _активная.get()


def для_модели(ключ: str) -> Конфигурация | None:
    """Конфигурация, которая действует на вызов этой модели, или None.

    Сначала — та, что применена блоком `with` к этой же модели. Иначе — своя
    конфигурация модели каталога (`Model.конфигурация`): так `loc-rag-docs`
    всегда отвечает с параметрами «после», даже из чата или офлайна."""
    к = _активная.get()
    if к is not None and к.модель == ключ:
        return к
    from agent import catalog
    if ключ in catalog.MODELS:
        своя = catalog.get(ключ).конфигурация
        if своя:
            try:
                к = получить(своя)
            except (ОшибкаКонфигурации, OSError, json.JSONDecodeError):
                return None
            return к if к.модель == ключ else None
    return None


def модель_для_вызова(модель):
    """Копия модели каталога с адресом сервера конфигурации (или та же модель)."""
    к = для_модели(модель.key)
    if к is None or к.сервер == СЛУЖБА:
        return модель
    return replace(модель, base_url=адрес(к.сервер))


def тело_для_вызова(модель, тело: dict[str, Any]) -> dict[str, Any]:
    """Опции и веса конфигурации поверх тела запроса /api/chat (plan.md, D-02).

    Значения, которые конфигурация не задаёт, остаются как в Дне 28; значения,
    которых нет ни там, ни там, Ollama не получает вовсе."""
    к = для_модели(модель.key)
    if к is None:
        return тело
    тело = {**тело, "options": {**(тело.get("options") or {}), **к.опции}}
    if к.тег:
        тело["model"] = к.тег
    return тело


def шаблон_для(ключ: str) -> str:
    """Шаблон промпта ответа по документам для модели: конфигурация → роль в карте.

    Облачной модели — всегда общий: шаблон «договоры» подобран под локальную."""
    from agent import catalog
    if not ключ or ключ not in catalog.MODELS or not catalog.get(ключ).local:
        return "общий"
    к = для_модели(ключ)
    if к is not None and к.шаблон:
        return к.шаблон
    from agent.local import offline
    from agent.rag.answer import РОЛЬ_МОДЕЛИ
    промпт = offline.параметры_роли(РОЛЬ_МОДЕЛИ).промпт
    return промпт if промпт in ШАБЛОНЫ else "общий"


def описание() -> dict[str, Any]:
    """Сводка для консоли и веба: конфигурации, серверы, «после»."""
    данные = прочитать()
    try:
        все = загрузить()
        ошибка = ""
    except ОшибкаКонфигурации as exc:
        все, ошибка = {}, str(exc)
    return {"path": путь(), "configs": [к.to_dict() for к in все.values()],
            "after": данные.get("после", ""), "before": данные.get("до", "до"),
            "servers": {с: адрес(с) for с in СЕРВЕРЫ}, "error": ошибка,
            "vps": данные.get("vps") or {}, "choice": данные.get("выбор") or {}}
