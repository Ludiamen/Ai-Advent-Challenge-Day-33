# Облегчённый агент (выбор пользователя в Дне 27): промпт агента с
# инструментами — ≈ 4 тыс. токенов (инварианты, профиль, рамки, знания,
# решения), а у qwen3.5 кэш начала промпта в Ollama не работает, и каждый круг
# инструментов перечитывает его целиком — 5–6 минут на CPU. Плюс проверка
# самоотчёта: локальная модель его пропускает, и агент переспрашивал трижды.
АГЕНТ_ПО_УМОЛЧАНИЮ = {"сжатый_промпт": True, "самоотчёт": False, "судья_по_смыслу": False, "знаний": 2}


def агент_из(к: КартаРолей) -> dict[str, Any]:
    return {**АГЕНТ_ПО_УМОЛЧАНИЮ, **к.агент}


def агент() -> dict[str, Any]:
    """Как работает агент в офлайне: сжатый промпт, самоотчёт, судья, сколько знаний."""
    return агент_из(карта())


def задать_агента(изменения: dict[str, Any], путь: str = "") -> dict[str, Any]:
    """Поменять раздел «агент» карты ролей (страница /local, --офлайн-агент)."""
    from agent.rag.evaluate import записать_атомарно
    неизвестные = set(изменения) - set(АГЕНТ_ПО_УМОЛЧАНИЮ)
    if неизвестные:
        raise ValueError(f"Нет таких настроек агента: {', '.join(sorted(неизвестные))}. "
                         f"Есть: {', '.join(АГЕНТ_ПО_УМОЛЧАНИЮ)}")
    путь = путь or путь_карты()
    with open(путь, encoding="utf-8") as f:
        данные = json.load(f)
    агент_ = данные.setdefault("агент", {})
    for ключ, значение in изменения.items():
        if ключ == "знаний":
            if not isinstance(значение, int) or isinstance(значение, bool) or not 0 <= значение <= 10:
                raise ValueError("«знаний» — целое от 0 до 10")
            агент_[ключ] = значение
        else:
            if not isinstance(значение, bool):
                raise ValueError(f"«{ключ}» — да или нет")
            агент_[ключ] = значение
    записать_атомарно(путь, json.dumps(данные, ensure_ascii=False, indent=1) + "\n")
    return агент()


