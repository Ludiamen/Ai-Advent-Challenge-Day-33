def включить(да: bool = True, источник: str = "") -> bool:
    """Включить или выключить офлайн-режим процесса; вернуть новое состояние.

    Заодно — HF_HUB_OFFLINE: кросс-энкодер берёт веса из кэша Hugging Face и
    не должен спрашивать сайт, не вышла ли новая версия."""
    global _включён, _источник
    with _замок:
        _включён = bool(да)
        _источник = источник if да else ""
        if да:
            os.environ["HF_HUB_OFFLINE"] = "1"
        else:
            os.environ.pop("HF_HUB_OFFLINE", None)
        try:   # константа читается при импорте huggingface_hub — поправить и её
            import huggingface_hub.constants as hf
            hf.HF_HUB_OFFLINE = bool(да)
        except Exception:   # noqa: BLE001 — нет пакета или другая версия: не беда
            pass
    return _включён


