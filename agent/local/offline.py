# --- подбор поиска офлайна ----------------------------------------------------------

# Шкала кросс-энкодера не похожа на шкалу LLM-реранкера: верный фрагмент
# получает 0,02–0,1, посторонний — тысячные доли. Сетка Дня 24 (0,1–0,9)
# отправила бы в «не знаю» всё, поэтому здесь — логарифмическая.
ПОРОГИ_КРОСС = (0.0005, 0.001, 0.002, 0.003, 0.005, 0.0075, 0.01, 0.015, 0.02, 0.03, 0.05, 0.1)
ВАРИАНТЫ_K = (6, 8, 10)


def подобрать_поиск(поисковик, путь_вопросов: str, варианты_k=ВАРИАНТЫ_K) -> dict[str, Any]:
    """K_до и порог «не знаю» для поиска офлайна — на стенде вопросов Дня 21.

    K_до — сколько кандидатов первого этапа видит кросс-энкодер: на CPU это
    ≈ 6 с на кандидата, поэтому меньше — быстрее. Выбор: больше вопросов, у
    которых нужный фрагмент попал в промпт (top-K_после), при равенстве —
    меньший K. Порог — правилом Дня 24: не больше одного лишнего «не знаю» на
    найденных, при этом больше ловушек и честных «не знаю». Оценки реранкера
    в кэше, поэтому повторный подбор идёт секунды."""
    from agent.rag import abstain
    from agent.rag.evaluate import загрузить_вопросы
    from dataclasses import replace
    база = поиск()
    if база is None:
        raise ValueError(f"В {путь_карты()} нет раздела «поиск»")
    вопросы = загрузить_вопросы(путь_вопросов)
    варианты = []
    for k in варианты_k:
        н = replace(база, k_до=int(k), имя=f"офлайн · K_до {k}")
        старт = time.monotonic()
        строки = abstain.замерить(поисковик, вопросы, н)
        сетка = [abstain.оценить(строки, t) for t in ПОРОГИ_КРОСС]
        годные = [с for с in сетка if с["лишние_не_знаю"] <= 1] or сетка
        лучший = max(годные, key=lambda с: (-с["лишние_не_знаю"],
                                            с["ловушки_не_знаю"] + с["честные_не_знаю"], с["порог"]))
        с_ответом = [с for с in строки if not с["ловушка"]]
        варианты.append({"k_до": int(k), "найдено": sum(с["найден"] for с in с_ответом),
                         "с_ответом": len(с_ответом), "порог": лучший["порог"], "выбрано": лучший,
                         "секунд": round(time.monotonic() - старт, 1), "сетка": сетка, "вопросы": строки})
    выбор = max(варианты, key=lambda в: (в["найдено"], -в["k_до"]))
    return {"когда": time.strftime("%Y-%m-%dT%H:%M:%S"), "стенд": os.path.basename(путь_вопросов),
            "вопросов": len(вопросы), "k_после": база.k_после, "реранкер": база.реранкер,
            "выбор": {"k_до": выбор["k_до"], "порог_уверенности": выбор["порог"],
                      "найдено": выбор["найдено"], "с_ответом": выбор["с_ответом"], **выбор["выбрано"]},
            "варианты": варианты}


def записать_поиск(итог: dict[str, Any], путь: str = "") -> None:
    """Выбор подбора — в раздел «поиск» карты ролей; сетка — рядом, в «подбор»."""
    from agent.rag.evaluate import записать_атомарно
    путь = путь or путь_карты()
    with open(путь, encoding="utf-8") as f:
        данные = json.load(f)
    п = данные.setdefault("поиск", {})
    п["k_до"] = итог["выбор"]["k_до"]
    п["порог_уверенности"] = итог["выбор"]["порог_уверенности"]
    п["подбор"] = {"когда": итог["когда"], "стенд": f"{итог['стенд']}: {итог['вопросов']} вопросов",
                   "выбор": итог["выбор"],
                   "варианты": [{к: в[к] for к in ("k_до", "найдено", "с_ответом", "порог")}
                                for в in итог["варианты"]]}
    записать_атомарно(путь, json.dumps(данные, ensure_ascii=False, indent=1) + "\n")


def записать_роль(роль: str, модель: str, промпт: str = "", путь: str = "") -> None:
    """День 29: модель и вариант промпта роли — в карту (`--создать-модель` ставит
    оптимизированную loc-rag-docs на ответ по документам). Остальное в роли — как было."""
    from agent.rag.evaluate import записать_атомарно
    путь = путь or путь_карты()
    with open(путь, encoding="utf-8") as f:
        данные = json.load(f)
    р = данные.setdefault("роли", {}).setdefault(роль, {})
    р["модель"] = модель
    if промпт:
        р["промпт"] = промпт
    else:
        р.pop("промпт", None)
    записать_атомарно(путь, json.dumps(данные, ensure_ascii=False, indent=1) + "\n")


# --- предохранитель и журнал сети ----------------------------------------------------

_журнал: deque[dict[str, Any]] = deque(maxlen=ЖУРНАЛ_ДЛИНА)
_счёт = {"локальных": 0, "внешних": 0, "заблокировано": 0}
_номер = 0          # сквозной номер записи журнала: по нему разница находит новые записи


def _разрешённые() -> set[str]:
    хосты = {urlparse(catalog._OLLAMA).hostname or ""}
    хосты |= {х.strip().lower() for х in os.getenv("OFFLINE_ALLOW", "").split(",") if х.strip()}
    return {х for х in хосты if х}


def _разрешённые_внешние() -> set[str]:
    """Внешние хосты, которые пропускаются и в офлайне (OFFLINE_ALLOW_EXTERNAL), но считаются внешними."""
    return {х.strip().lower() for х in os.getenv("OFFLINE_ALLOW_EXTERNAL", "").split(",") if х.strip()}


# Bot API Telegram кладёт токен прямо в путь: /bot123456:AA…/getUpdates.
_ТОКЕН_В_ПУТИ = re.compile(r"/bot\d+:[A-Za-z0-9_-]+")


def _путь_для_журнала(путь: str) -> str:
    return _ТОКЕН_В_ПУТИ.sub("/bot…", путь.split("?")[0])[:80]


def локальный(хост: str) -> bool:
    """Петлевой интерфейс, адрес Ollama или явно разрешённый (OFFLINE_ALLOW)."""
    хост = (хост or "").strip("[]").lower()
    if not хост:
        return True        # запрос без хоста (unix-сокет, тестовый транспорт)
    if хост == "localhost" or хост.endswith(".localhost") or хост in _разрешённые():
        return True
    try:
        return ipaddress.ip_address(хост).is_loopback
    except ValueError:
        return False


def _записать(метод: str, хост: str, путь: str, итог: str, модель: str = "") -> None:
    global _номер
    with _замок:
        _номер += 1
        лок = локальный(хост)
        if итог == "пропущен":
            _счёт["локальных" if лок else "внешних"] += 1
        else:
            _счёт["заблокировано"] += 1
        _журнал.append({"when": time.strftime("%H:%M:%S"), "method": метод, "host": хост,
                        "path": _путь_для_журнала(путь), "local": лок, "result": итог,
                        "model": модель, "offline": _включён, "n": _номер})


def _проверить_запрос(request: httpx.Request) -> None:
    хост = request.url.host or ""
    if _включён and not локальный(хост) and хост.lower() not in _разрешённые_внешние():
        _записать(request.method, хост, request.url.path, "заблокирован")
        raise ОшибкаОфлайна(f"Офлайн-режим: запрос к {хост} заблокирован — "
                            "наружу ходить нельзя, работают только локальные модели", request=request)
    _записать(request.method, хост, request.url.path, "пропущен")


def проверить_модель(ключ: str) -> None:
    """Облачная модель в офлайне: отказ до сокета и запись в журнал."""
    if not _включён:
        return
    модель = catalog.get(ключ)
    if модель.local:
        return
    # День 31: процессу явно разрешён внешний хост этой модели (OFFLINE_ALLOW_EXTERNAL — сервис
    # пускает только api.deepseek.com для ручки проекта). Сам запрос пройдёт сетевой фильтр и
    # будет виден в журнале как внешний.
    хост = (urlparse(модель.base_url).hostname or "").lower()
    if хост and хост in _разрешённые_внешние():
        return
    _записать("POST", urlparse(модель.base_url).hostname or модель.provider,
              "/chat/completions", "заблокирован до сокета", ключ)
    from agent.llm import LLMError
    raise LLMError(f"Офлайн-режим: облачная модель «{ключ}» ({модель.label}) не вызывается — "
                   "агент работает только на локальных моделях. Выберите loc-… или выключите офлайн.")


def журнал(последних: int = 30) -> dict[str, Any]:
    with _замок:
        return {"offline": _включён, "source": _источник, **_счёт,
                "recent": list(_журнал)[-последних:] if последних else []}


def снимок_журнала() -> dict[str, int]:
    """Счётчики журнала сейчас (День 28): разница двух снимков — сеть одного ответа."""
    with _замок:
        return {**_счёт, "n": _номер}


def внешние_хосты() -> list[str]:
    """Внешние хосты в журнале сети процесса (День 31: у сервиса — только api.deepseek.com)."""
    with _замок:
        return sorted({з["host"] for з in _журнал if not з["local"]})


def разница(до: dict[str, int], после: dict[str, int]) -> dict[str, Any]:
    """Сеть между двумя снимками: счётчики и внешние хосты новых записей — чтобы
    случайный внешний запрос было видно, куда он шёл."""
    итог: dict[str, Any] = {к: после.get(к, 0) - до.get(к, 0) for к in ("локальных", "внешних", "заблокировано")}
    with _замок:
        итог["хосты"] = sorted({з["host"] for з in _журнал
                                if до.get("n", 0) < з.get("n", 0) <= после.get("n", 0) and not з["local"]})
    return итог


def сбросить_журнал() -> None:
    with _замок:
        _журнал.clear()
        for к in _счёт:
            _счёт[к] = 0


def окружение_для_дочерних() -> dict[str, str]:
    """Что передать MCP-серверу: StdioServerParameters отдаёт ребёнку только
    явно названные переменные, и без этого свой сервер с LLM внутри (конвейер,
    индекс документов) в офлайне пошёл бы в облако по ключам из .env."""
    if not _включён:
        return {}
    итог = {"AGENT_OFFLINE": "1", "HF_HUB_OFFLINE": "1", "OLLAMA_HOST": catalog._OLLAMA,
            "LOCAL_ROLES": путь_карты()}
    from agent.local import bench
    итог["LOCAL_SETTINGS"] = bench.путь_настроек()
    if os.getenv("OFFLINE_ALLOW"):
        итог["OFFLINE_ALLOW"] = os.environ["OFFLINE_ALLOW"]
    return итог


# Перехватчик ставится один раз на весь процесс: на транспорт httpx, через
# который идут все HTTP-запросы проекта (свой клиент LLM, эмбеддинги Ollama,
# MCP по HTTP, huggingface_hub 1.x). Тестовый MockTransport — другой класс, его
# это не касается.
if not getattr(httpx.HTTPTransport.handle_request, "_офлайн", False):
    _исходный = httpx.HTTPTransport.handle_request
    _исходный_async = httpx.AsyncHTTPTransport.handle_async_request

    def _перехват(self, request):
        _проверить_запрос(request)
        return _исходный(self, request)

    async def _перехват_async(self, request):
        _проверить_запрос(request)
        return await _исходный_async(self, request)

    _перехват._офлайн = True
    _перехват_async._офлайн = True
    httpx.HTTPTransport.handle_request = _перехват
    httpx.AsyncHTTPTransport.handle_async_request = _перехват_async

