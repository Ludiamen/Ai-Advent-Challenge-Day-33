"""Режим «офлайн»: агент работает только на локальных моделях (День 27).

Задание дня — приложение отправляет запросы в локальную LLM, показывает ответы
и работает без облачных моделей. До этого дня локальная модель была одним из
провайдеров каталога: выбранная в чате, она отвечала пользователю, но разбор
реплики, переписывание запроса и реранкер по-прежнему ходили в облако. Режим
«офлайн» закрывает это тремя вещами.

  карта ролей     local-roles.json: какая локальная модель стоит на каждой из
                  ролей агента (catalog.ROLES), с каким вариантом промпта,
                  схемой ответа и параметрами; «основная» — модель, выбранная
                  замером Дня 26 (local-settings.json). catalog.for_role в
                  офлайне отдаёт модель из карты — так все пути агента
                  переходят на локальные модели без правок в каждом.
  предохранитель  облачная модель в офлайне не вызывается: Client.call
                  отказывает до того, как откроется сокет, и пишет отказ в
                  журнал.
  журнал сети     каждый HTTP-запрос процесса проходит через транспорт httpx;
                  перехватчик записывает, куда он шёл и локальный ли это адрес.
                  В офлайне запрос на нелокальный адрес блокируется. Журнал
                  ведётся всегда: в облачном режиме он показывает внешние
                  запросы, в офлайне их должно быть ноль — это и есть
                  доказательство «без облака», а не «не позвал, потому что не
                  понадобилось».

Локальный адрес — петлевой интерфейс (127.0.0.0/8, ::1, localhost) и адрес
Ollama из OLLAMA_HOST, даже если она стоит на соседней машине локальной сети;
дополнительные адреса — OFFLINE_ALLOW через запятую.

Разрешённый ВНЕШНИЙ хост (День 30, Telegram-бот) — OFFLINE_ALLOW_EXTERNAL через
запятую: запрос к нему проходит и в офлайне, но считается внешним и виден в
журнале по имени; всё прочее внешнее блокируется. Токен Bot API в пути
(`/bot<токен>/…`) в журнал не попадает — для любого хоста.

Включается режим переменной AGENT_OFFLINE=1 (её же получают дочерние
MCP-серверы), ключом --офлайн в консоли и переключателем на странице.

Публичное API:
  включён(), включить(да, источник)
  карта() -> КартаРолей, модель_роли(роль), параметры_роли(роль), основная()
  путь_карты(), поиск() -> Настройки, история() -> (окно, символов)
  проверить_модель(ключ)             — отказ облачной модели в офлайне
  журнал(), сбросить_журнал(), локальный(хост); снимок_журнала(), разница(до, после) — День 28
  окружение_для_дочерних()           — переменные, которые получают MCP-серверы
  ОшибкаОфлайна
"""

