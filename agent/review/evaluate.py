"""Контрольный набор AI-ревью: посеянные ошибки и чистые изменения (spec SC-05, plan D-17).

Случай из `review-cases.json` — правки к базовому коммиту. Они накладываются во временном
клоне (`git clone --shared` в out/, свой репозиторий, не рабочий каталог) и коммитятся
как ветка PR; конвейер ревью гоняется без публикации.

Найден ли посеянный дефект: среди находок ищутся кандидаты — нужный файл, раздел из
допустимых, в сути или «почему» есть хотя бы одно из ключевых слов; судья ds-pro отвечает,
описывает ли кандидат именно этот дефект. Чистый случай засчитан, если вердикт зелёный и
нет подтверждённых критичных находок.
"""

from __future__ import annotations

import json
import os
import subprocess
import time
from dataclasses import dataclass, field
from typing import Any, Callable

ФАЙЛ = "review-cases.json"
СУДЬЯ = "ds-pro"
ОКРУЖЕНИЕ = {"GIT_AUTHOR_NAME": "review-cases", "GIT_AUTHOR_EMAIL": "cases@example.invalid",
             "GIT_COMMITTER_NAME": "review-cases", "GIT_COMMITTER_EMAIL": "cases@example.invalid",
             "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_SYSTEM": os.devnull}

ПРОМПТ_СУДЬИ = """\
Ты проверяешь работу ревьюера кода. В PR намеренно посеян дефект:
«{суть}» (файл {файл}).
Ниже — одна находка ревьюера. Ответь, описывает ли она ИМЕННО этот дефект (а не другую
проблему в том же файле). Ответ — только JSON: {{"да": true|false, "почему": "одна фраза"}}.

Находка ({раздел}, {серьёзность}, {место}):
суть: {находка_суть}
почему: {находка_почему}
"""


def загрузить(путь: str = "") -> dict[str, Any]:
    from agent.devassist.project import КОРЕНЬ
    with open(путь or os.path.join(КОРЕНЬ, ФАЙЛ), encoding="utf-8") as f:
        return json.load(f)


def _git(каталог: str, *аргументы: str) -> str:
    return subprocess.run(["git", "-C", каталог, *аргументы], check=True, capture_output=True, text=True,
                          env=dict(os.environ, **ОКРУЖЕНИЕ)).stdout


def клон(источник: str, каталог: str, база: str) -> str:
    """Свой временный клон на коммите базы (рабочий каталог проекта не трогается)."""
    if os.path.exists(каталог):
        subprocess.run(["rm", "-rf", "--", каталог], check=True)
    subprocess.run(["git", "clone", "-q", "--shared", "--no-checkout", источник, каталог], check=True,
                   env=dict(os.environ, **ОКРУЖЕНИЕ))
    _git(каталог, "checkout", "-q", "-B", "main", база)
    return _git(каталог, "rev-parse", "HEAD").strip()


def применить(каталог: str, случай: dict[str, Any], база: str = "main") -> str:
    """Ветка случая от базы, правки, коммит; вернуть хэш головы. Неналожимая правка — ошибка."""
    ветка = f"case/{случай['id']}"
    _git(каталог, "checkout", "-q", "-B", ветка, база)
    for п in случай["правки"]:
        путь = os.path.join(каталог, п["файл"])
        os.makedirs(os.path.dirname(путь) or каталог, exist_ok=True)
        if "байт" in п:
            with open(путь, "wb") as f:
                f.write(bytes(range(256)) * (int(п["байт"]) // 256 + 1))
        elif "создать" in п:
            with open(путь, "w", encoding="utf-8") as f:
                f.write(п["создать"])
        else:
            with open(путь, encoding="utf-8") as f:
                текст = f.read()
            if п["было"] not in текст:
                raise ValueError(f"{случай['id']}: в {п['файл']} нет текста «{п['было'][:60]}»")
            with open(путь, "w", encoding="utf-8") as f:
                f.write(текст.replace(п["было"], п["стало"], 1))
    _git(каталог, "add", "-A")
    _git(каталог, "commit", "-q", "-m", случай["заголовок"])
    return _git(каталог, "rev-parse", "HEAD").strip()


@dataclass
class Прогон:
    случай: str
    номер: int
    вердикт: str
    ожидался: str
    дефектов: int
    найдено: list[str] = field(default_factory=list)
    ложных_критичных: int = 0
    пропуски_верны: bool = True
    секунд: float = 0.0
    токены: int = 0
    стоимость: float = 0.0
    судья_токенов: int = 0
    сбои: list[str] = field(default_factory=list)

    @property
    def засчитан(self) -> bool:
        if not self.дефектов:
            return self.вердикт == "зелёный" and self.ложных_критичных == 0 and self.пропуски_верны
        return len(self.найдено) == self.дефектов and self.вердикт == self.ожидался

    def to_dict(self) -> dict[str, Any]:
        return {**self.__dict__, "засчитан": self.засчитан}


def кандидаты(дефект: dict[str, Any], находки: list[Any]) -> list[Any]:
    слова = [с.lower() for с in дефект.get("слова", [])]
    итог = []
    for н in находки:
        if н.файл != дефект["файл"] or н.раздел not in дефект["разделы"]:
            continue
        текст = f"{н.суть} {н.почему} {н.фрагмент_diff}".lower()
        if not слова or any(с in текст for с in слова):
            итог.append(н)
    return итог


def судья(клиент: Any, дефект: dict[str, Any], находка: Any, модель: str = СУДЬЯ) -> tuple[bool, int]:
    текст = ПРОМПТ_СУДЬИ.format(суть=дефект["суть"], файл=дефект["файл"], раздел=находка.раздел,
                                серьёзность=находка.серьёзность,
                                место=f"{находка.файл}:{находка.строка}" if находка.строка else находка.файл,
                                находка_суть=находка.суть, находка_почему=находка.почему)
    r = None
    for попытка in range(4):     # короткий обрыв сети не должен ронять весь прогон набора
        try:
            r = клиент.call(модель, [{"role": "user", "content": текст}], max_tokens=300, temperature=0)
            break
        except Exception:  # noqa: BLE001 — LLMError и сетевые: повтор с паузой
            if попытка == 3:
                raise
            time.sleep(15 * (попытка + 1))
    try:
        т = r.text[r.text.find("{"):r.text.rfind("}") + 1]
        return bool(json.loads(т).get("да")), r.total_tokens
    except (ValueError, AttributeError):
        return False, r.total_tokens


def оценить(случай: dict[str, Any], итог: Any, номер: int, клиент_судьи: Any) -> Прогон:
    сборка = итог.сборка
    п = Прогон(случай["id"], номер, сборка.вердикт, случай["вердикт"], len(случай.get("дефекты", [])),
               секунд=float(итог.метрики.get("секунд", 0)), токены=int(итог.метрики.get("токены", 0)),
               стоимость=float(итог.метрики.get("стоимость", 0)), сбои=list(итог.метрики.get("сбои", [])))
    for дефект in случай.get("дефекты", []):
        for н in кандидаты(дефект, сборка.находки):
            да, токены = судья(клиент_судьи, дефект, н)
            п.судья_токенов += токены
            if да:
                п.найдено.append(дефект["id"])
                break
    if not случай.get("дефекты"):
        п.ложных_критичных = sum(1 for н in сборка.находки
                                 if н.серьёзность == "критично" and н.подтверждена and н.раздел in ("баги", "архитектура"))
    if случай.get("пропущены") and итог.вход is not None:
        пропущенные = {ф.путь for ф in итог.вход.пропущенные}
        п.пропуски_верны = set(случай["пропущены"]) <= пропущенные
    return п


def итог(прогоны: list[Прогон], критерий: dict[str, Any]) -> dict[str, Any]:
    с_дефектами = [п for п in прогоны if п.дефектов]
    чистые = [п for п in прогоны if not п.дефектов]
    всего_дефектов = sum(п.дефектов for п in с_дефектами)
    найдено = sum(len(п.найдено) for п in с_дефектами)
    доля = найдено / всего_дефектов if всего_дефектов else 1.0
    зелёных = sum(1 for п in чистые if п.засчитан) / len(чистые) if чистые else 1.0
    ложных = sum(п.ложных_критичных for п in чистые)
    по_случаям: dict[str, dict[str, Any]] = {}
    for п in прогоны:
        с = по_случаям.setdefault(п.случай, {"прогонов": 0, "засчитано": 0, "вердикты": []})
        с["прогонов"] += 1
        с["засчитано"] += int(п.засчитан)
        с["вердикты"].append(п.вердикт)
    секунды = sorted(п.секунд for п in прогоны)
    return {"прогонов": len(прогоны), "доля_найденных": round(доля, 3), "найдено": найдено,
            "посеяно": всего_дефектов, "чистые_зелёные": round(зелёных, 3), "ложных_критичных": ложных,
            "p50_с": секунды[len(секунды) // 2] if секунды else 0,
            "стоимость": round(sum(п.стоимость for п in прогоны), 4),
            "по_случаям": по_случаям,
            "критерий_выполнен": доля >= критерий.get("доля_найденных", 0.8)
            and зелёных >= критерий.get("чистые_зелёные", 1.0) and ложных <= критерий.get("ложных_критичных", 0)}


def прогнать(набор: dict[str, Any], каталог: str, база: str, выполнить: Callable[..., Any], клиент_судьи: Any,
             прогонов: int = 0, случаи: list[str] | None = None,
             ход: Callable[[str], None] = print) -> list[Прогон]:
    """Все случаи × прогоны. «выполнить(от, до, заголовок, описание)» — конвейер на клоне."""
    прогонов = прогонов or int(набор.get("критерий", {}).get("прогонов", 3))
    итоги: list[Прогон] = []
    for случай in набор["случаи"]:
        if случаи and случай["id"] not in случаи:
            continue
        голова = применить(каталог, случай, "main")
        for номер in range(1, прогонов + 1):
            старт = time.monotonic()
            р = выполнить(база, голова, случай["заголовок"], случай.get("описание", ""))
            п = оценить(случай, р, номер, клиент_судьи)
            итоги.append(п)
            ход(f"{случай['id']} #{номер}: {п.вердикт} (ожидался {п.ожидался}), найдено "
                f"{len(п.найдено)}/{п.дефектов}, ложных критичных {п.ложных_критичных}, "
                f"{time.monotonic() - старт:.0f} с, ${п.стоимость:.4f} — {'✓' if п.засчитан else '✗'}")
    return итоги
