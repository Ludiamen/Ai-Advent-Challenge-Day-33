def роль(раздел: str, описание_проекта: str) -> str:
    р = РАЗДЕЛЫ[раздел]
    return (f"Ты — ревьюер pull request проекта: {описание_проекта}.\n"
            f"Твой раздел ревью — «{р['заголовок']}». Ищи {р['смотреть']}\n"
            "Другие разделы смотрят другие ревьюеры — не повторяй их работу.\n\n"
            + ОБЩИЕ_ПРАВИЛА.format(критично=р["критично"]))


def обезвредить(текст: str) -> str:
    """Данные PR не могут «закрыть» блок данных своей меткой и дописать инструкции после неё."""
    return (текст or "").replace(МЕТКА_НАЧАЛА, "<<ДАННЫЕ_PR").replace(МЕТКА_КОНЦА, "ДАННЫЕ_PR>>")


def _блок_файла(ф: Any) -> str:
    заголовок = f"### {ф.путь} ({ф.статус}{', было ' + ф.было if ф.было else ''}; +{ф.добавлено} −{ф.удалено})"
    хвост = "\n… diff файла обрезан по пределу" if ф.diff_обрезан else ""
    return обезвредить(f"{заголовок}\n```diff\n{ф.diff}{хвост}\n```")


def сообщение(вход: Any, опора_ревьюера: list[Any], функции: list[Any]) -> str:
    """Пользовательское сообщение ревьюеру: данные PR в метках, затем опора с номерами."""
    части = [МЕТКА_НАЧАЛА,
             f"PR: {обезвредить(вход.заголовок) or '(без заголовка)'}",
             f"база {вход.база[:12]} → голова {вход.голова[:12]}"]
    if вход.описание.strip():
        части.append("Описание PR:\n" + обезвредить(вход.описание.strip()[:3000]))
    части.append("## Изменения (diff)")
    части += [_блок_файла(ф) for ф in вход.просмотренные]
    if вход.пропущенные:
        части.append("Не показаны: " + "; ".join(f"{ф.путь} — {ф.причина}" for ф in вход.пропущенные))
    if функции:
        части.append("## Изменённые функции целиком (новая версия, с номерами строк)")
        for к in функции:
            строки = к.текст.splitlines()
            нумерованные = "\n".join(f"{к.с + i:>5}  {с}" for i, с in enumerate(строки))
            части.append(обезвредить(f"### {к.путь}: {к.имя} (строки {к.с}–{к.по})\n```\n{нумерованные}\n```"))
    части.append(МЕТКА_КОНЦА)
    if опора_ревьюера:
        части.append("## Опора: документация и код проекта (база PR)")
        for ф in опора_ревьюера:
            части.append(f"[{ф.номер}] {ф.подпись} ({ф.вид})\n{ф.текст}")
    else:
        части.append("## Опора: не найдена (ревью только по diff)")
    return "\n\n".join(части)
