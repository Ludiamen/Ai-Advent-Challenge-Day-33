"""Роли трёх ревьюеров PR и формат находок (spec FR-05, plan D-06).

Общая часть — правила находки и защита от инструкций внутри diff; разделы отличаются
тем, на что смотреть и что считать «критично». Ответ — JSON, его разбирает и проверяет
сборщик (collect.py): модель не решает, красный ли PR, она только предлагает находки.
"""

