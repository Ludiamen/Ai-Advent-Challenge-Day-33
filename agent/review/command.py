"""Команда `/review` в чатах агента — консоль и веб (День 32, spec FR-13, plan D-16).

`/review` — ревью своей ветки против main (`main...HEAD`), `/review ДИАПАЗОН` — любого
диапазона: `база...голова`, `база..голова` (то же: от общего предка) или одна ссылка
(`/review feature` = `main...feature`). Конвейер тот же, что в GitHub Actions, только итог
не публикуется, а показывается карточкой и пишется в историю чата. Разбор общий для
консоли и веба (паритет, память web-interface-must-match-cli).
"""

from __future__ import annotations

import re
from typing import Any, Callable

from agent.review import pipeline

ПО_УМОЛЧАНИЮ = ("main", "HEAD")
_REVIEW = re.compile(r"^/review(?:@[\w_]+)?(?:\s+(?P<диапазон>\S+))?\s*$", re.I)
_ССЫЛКА = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/~^@{}-]{0,99}$")
СПРАВКА = ("  /review [диапазон] — AI-ревью ветки, как в PR: три ревьюера (баги, архитектура, рекомендации) "
           "с опорой на документацию и код; по умолчанию main...HEAD")


class ОшибкаКоманды(ValueError):
    pass


def разобрать(текст: str) -> tuple[str, str] | None:
    """(база, голова) или None — это не /review. Неверный диапазон — ОшибкаКоманды."""
    м = _REVIEW.match((текст or "").strip())
    if not м:
        return None
    диапазон = м.group("диапазон") or ""
    if not диапазон:
        return ПО_УМОЛЧАНИЮ
    if "..." in диапазон:
        от, _, до = диапазон.partition("...")
    elif ".." in диапазон:
        от, _, до = диапазон.partition("..")
    else:
        от, до = ПО_УМОЛЧАНИЮ[0], диапазон
    от, до = от or ПО_УМОЛЧАНИЮ[0], до or "HEAD"
    for ссылка in (от, до):
        if not _ССЫЛКА.match(ссылка) or ".." in ссылка:
            raise ОшибкаКоманды(f"«{ссылка}» — не ссылка git (ветка, тег, хэш, HEAD~N)")
    return от, до


def выполнить(от: str, до: str, модель: str = "", канал: str = "консоль",
              этап: Callable[[str, str], None] | None = None) -> pipeline.ИтогРевью:
    from agent import catalog
    модель = модель if модель in catalog.MODELS else pipeline.reviewers.МОДЕЛЬ
    return pipeline.выполнить(от, до, модель=модель, канал=канал, этап=этап)


def в_историю(чат: Any, от: str, до: str, итог: pipeline.ИтогРевью, база: str = "") -> None:
    """Ход `/review` — в историю чата (реплика и короткий итог) и в ленту сессии для веба."""
    from agent.devassist import command
    сборка = итог.сборка.метрики()
    кратко = (f"AI-ревью {от}...{до}: {итог.вердикт} — {итог.сборка.причина}. Находки: "
              + ", ".join(f"{р} {n}" for р, n in сборка["по_разделам"].items()))
    чат.короткая.append(чат.сессия_диалога, "user", f"/review {от}...{до}")
    чат.короткая.append(чат.сессия_диалога, "assistant", кратко, tokens=int(итог.метрики.get("токены", 0)))
    if база:
        command.сохранить(база, чат.сессия, чат.память.реплик, карточка(от, до, итог))


def карточка(от: str, до: str, итог: pipeline.ИтогРевью) -> dict[str, Any]:
    """Данные карточки веба: без текстов опоры, с находками и подписями источников."""
    данные = итог.to_dict()
    данные.pop("консоль", None)
    return {"вид": "ревью", "диапазон": f"{от}...{до}", **данные,
            "база": итог.вход.база[:7] if итог.вход else "", "голова": итог.вход.голова[:7] if итог.вход else ""}
