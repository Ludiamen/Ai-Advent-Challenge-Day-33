"""Сборщик ревью: находки проверяет код, вердикт решает код (spec FR-06, plan D-08).

Модель предлагает находки — сборщик решает, чему верить:
1. файл находки должен быть среди изменённых в PR — иначе находка отбрасывается (ревью
   только этого PR);
2. строка должна попадать в изменённый участок (±3) — иначе номер строки снимается, а
   находка остаётся «к файлу»;
3. «фрагмент_diff» должен найтись в изменённых строках файла (дословно после нормализации
   пробелов или почти — сходство ≥ 0,9) — иначе находка «не подтверждена»;
4. источники — только номера фрагментов, выданных этому ревьюеру;
5. неподтверждённая «критично» понижается до «важно» — красить PR догадкой нельзя;
6. дубли между ревьюерами (тот же файл, строки ближе 5, похожая суть) сливаются в одну
   находку раздела поважнее: баги > архитектура > рекомендации.

Вердикт: красный ⇔ есть подтверждённая «критично» в «баги» или «архитектура»; «не
выполнено» — если не отработал ни один ревьюер.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

from agent.rag import cite
from agent.rag.lexical import токены
from agent.review.context import Опора
from agent.review.reviewers import ИтогРевьюера, Находка
from agent.review.source import ВходPR

ДОПУСК_СТРОКИ = 3
БЛИЗКО_СТРОК = 5
ПОХОЖЕСТЬ_СУТИ = 0.34
ПОХОЖЕСТЬ_КРИТИЧНЫХ = 0.2
МИН_ФРАГМЕНТ = 4
ВАЖНОСТЬ_РАЗДЕЛА = {"баги": 0, "архитектура": 1, "рекомендации": 2}
ВАЖНОСТЬ = {"критично": 0, "важно": 1, "мелочь": 2}
КРАСЯТ = ("баги", "архитектура")

ЗЕЛЁНЫЙ, КРАСНЫЙ, НЕ_ВЫПОЛНЕНО = "зелёный", "красный", "не выполнено"


@dataclass
class Сборка:
    находки: list[Находка] = field(default_factory=list)
    вердикт: str = ЗЕЛЁНЫЙ
    причина: str = ""
    отброшено: int = 0          # файл не из PR
    без_строки: int = 0
    не_подтверждено: int = 0
    понижено: int = 0
    дублей: int = 0
    ревьюеры: list[ИтогРевьюера] = field(default_factory=list)

    def раздел(self, имя: str) -> list[Находка]:
        return [н for н in self.находки if н.раздел == имя]

    def метрики(self) -> dict[str, Any]:
        по_разделам = {р: len(self.раздел(р)) for р in ВАЖНОСТЬ_РАЗДЕЛА}
        по_серьёзности = {с: sum(1 for н in self.находки if н.серьёзность == с) for с in ВАЖНОСТЬ}
        return {"вердикт": self.вердикт, "находок": len(self.находки), "по_разделам": по_разделам,
                "по_серьёзности": по_серьёзности,
                "подтверждено": sum(1 for н in self.находки if н.подтверждена),
                "не_подтверждено": self.не_подтверждено, "понижено": self.понижено,
                "отброшено": self.отброшено, "без_строки": self.без_строки, "дублей": self.дублей,
                "сбоев": sum(1 for р in self.ревьюеры if not р.ок)}


def _изменённые_строки(diff: str) -> str:
    """Текст добавленных и удалённых строк файла без знаков +/− (там ищется «фрагмент_diff»)."""
    строки = []
    for с in diff.splitlines():
        if с.startswith(("+++", "---")):
            continue
        if с.startswith(("+", "-")):
            строки.append(с[1:])
    return "\n".join(строки)


def _сжать(текст: str) -> str:
    return re.sub(r"\s+", " ", (текст or "").strip())


def фрагмент_найден(фрагмент: str, diff: str) -> bool:
    ф = _сжать(фрагмент).lstrip("+- ")
    if len(ф) < МИН_ФРАГМЕНТ:
        return False
    изменения = _изменённые_строки(diff)
    if ф in _сжать(изменения):
        return True
    if len(ф) < cite.МИН_СИМВОЛОВ:
        return False
    # Почти дословно: модель поправила пробел или кавычку. Сравнение — со строками по одной
    # (у длинного diff общее «самое длинное совпадение» может уехать в чужую строку).
    return any(cite.найти(ф, строка)[0] != cite.НЕ_НАЙДЕНА
               for строка in изменения.splitlines() if len(строка.strip()) >= len(ф) * 0.8)


def похожи(а: Находка, б: Находка) -> bool:
    if а.файл != б.файл:
        return False
    if а.строка and б.строка and abs(а.строка - б.строка) >= БЛИЗКО_СТРОК:
        return False
    if bool(а.строка) != bool(б.строка) and (а.фрагмент_diff or б.фрагмент_diff) \
            and _сжать(а.фрагмент_diff) != _сжать(б.фрагмент_diff):
        return False
    та, тб = set(токены(а.суть + " " + а.фрагмент_diff)), set(токены(б.суть + " " + б.фрагмент_diff))
    if not та or not тб:
        return False
    порог = ПОХОЖЕСТЬ_СУТИ
    # Одно и то же критичное место глазами двух ревьюеров («баг: ПД уходят» и «архитектура:
    # маска на выходе снята») описано разными словами — для него порог ниже. Разные находки
    # на одной строке обычно разной серьёзности, их это не склеивает.
    if (а.серьёзность == б.серьёзность == "критично" and а.строка == б.строка
            and _сжать(а.фрагмент_diff) == _сжать(б.фрагмент_diff)):
        порог = ПОХОЖЕСТЬ_КРИТИЧНЫХ
    return len(та & тб) / len(та | тб) >= порог


def проверить(находка: Находка, вход: ВходPR, выданные: set[int], сборка: Сборка) -> bool:
    """Проверки 1–5; False — находку отбросить."""
    файл = вход.файл(находка.файл)
    if файл is None or файл.пропущен:
        сборка.отброшено += 1
        return False
    if находка.строка and not файл.в_участке(находка.строка, ДОПУСК_СТРОКИ):
        находка.пометки.append(f"строка {находка.строка} вне изменённых участков — снята")
        находка.строка = 0
        сборка.без_строки += 1
    находка.подтверждена = bool(находка.фрагмент_diff) and фрагмент_найден(находка.фрагмент_diff, файл.diff)
    if not находка.подтверждена:
        сборка.не_подтверждено += 1
        находка.пометки.append("цитата diff не найдена — не подтверждена")
        if находка.серьёзность == "критично":
            находка.серьёзность = "важно"
            находка.пометки.append("«критично» понижено до «важно»: без подтверждения PR не красится")
            сборка.понижено += 1
    лишние = [н for н in находка.источники if н not in выданные]
    if лишние:
        находка.источники = [н for н in находка.источники if н in выданные]
        находка.пометки.append(f"сняты источники, которых ревьюеру не давали: {лишние}")
    return True


def собрать(вход: ВходPR, опора: Опора, итоги: list[ИтогРевьюера]) -> Сборка:
    сборка = Сборка(ревьюеры=list(итоги))
    кандидаты: list[Находка] = []
    for итог in итоги:
        выданные = {ф.номер for ф in опора.для(итог.раздел)}
        for н in итог.находки:
            if проверить(н, вход, выданные, сборка):
                кандидаты.append(н)
    # Сначала важное: так при слиянии дублей остаётся находка важного раздела и серьёзности.
    кандидаты.sort(key=lambda н: (ВАЖНОСТЬ_РАЗДЕЛА[н.раздел], ВАЖНОСТЬ[н.серьёзность], not н.подтверждена))
    for н in кандидаты:
        оригинал = next((о for о in сборка.находки if похожи(о, н)), None)
        if оригинал is None:
            сборка.находки.append(н)
            continue
        сборка.дублей += 1
        if н.раздел != оригинал.раздел and н.раздел not in оригинал.разделы:
            оригинал.разделы.append(н.раздел)
        оригинал.источники = sorted(set(оригинал.источники) | set(н.источники))
        if not оригинал.строка and н.строка:
            оригинал.строка = н.строка
    сборка.находки.sort(key=lambda н: (ВАЖНОСТЬ_РАЗДЕЛА[н.раздел], ВАЖНОСТЬ[н.серьёзность], н.файл, н.строка))

    if not any(р.ок for р in итоги):
        сборка.вердикт = НЕ_ВЫПОЛНЕНО
        сборка.причина = "ни один ревьюер не отработал: " + "; ".join(
            f"{р.раздел} — {р.ошибка}" for р in итоги)
        return сборка
    критичные = [н for н in сборка.находки if н.раздел in КРАСЯТ and н.серьёзность == "критично" and н.подтверждена]
    if критичные:
        сборка.вердикт = КРАСНЫЙ
        сборка.причина = (f"подтверждённых критичных находок: {len(критичные)} "
                          f"({', '.join(sorted({н.раздел for н in критичные}))})")
    else:
        сборка.вердикт = ЗЕЛЁНЫЙ
        сборка.причина = "критичных подтверждённых находок нет"
    return сборка
