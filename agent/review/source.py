"""Вход ревью PR: изменённые файлы, diff и текст головы — через git-сервер MCP (spec FR-03, plan D-04).

Конвейер не читает репозиторий сам: всё, что он знает о PR, приходит ответами инструментов
`git_changes`, `git_diff` и `git_show` того же сервера, которым пользуется ассистент Дня 31.
Сервер умеет только читать, поэтому ревью не может изменить репозиторий даже по ошибке.

Что модели не отдаётся (но перечисляется в ревью как «не просмотрено»): бинарные файлы,
lock-файлы, сгенерированное и медиа; файлы сверх предела числа и объёма. Порядок
просмотра — сначала код, потом документы, внутри — по числу изменённых строк: при обрезке
теряется наименее важное.
"""

from __future__ import annotations

import fnmatch
import os
import re
from dataclasses import dataclass, field
from typing import Any, Protocol

ПРЕДЕЛ_ФАЙЛОВ = 25
ПРЕДЕЛ_DIFF_ВСЕГО = 80_000
ПРЕДЕЛ_DIFF_ФАЙЛА = 15_000
ПРЕДЕЛ_ГОЛОВЫ = 400_000

ПРОПУСК = ("*.lock", "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "Pipfile.lock",
           "*.min.js", "*.min.css", "*.map", "*.svg", "*.png", "*.jpg", "*.jpeg", "*.gif", "*.ico",
           "*.webp", "*.pdf", "*.mp4", "*.webm", "*.mp3", "*.zip", "*.gz", "*.tar", "*.db", "*.sqlite",
           "*.onnx", "*.gguf", "*.bin", "*.pyc")
КОД = (".py", ".js", ".mjs", ".ts", ".sh", ".html", ".css", ".yml", ".yaml", ".toml", ".cfg", ".ini",
       ".sql")
ДОКУМЕНТЫ = (".md", ".rst", ".txt")
_ПОРЯДОК = {"код": 0, "документ": 1, "прочее": 2}

ПРИЧИНЫ = {
    "бинарный": "бинарный файл",
    "шаблон": "lock-файл, сгенерированное или медиа",
    "удалён": "файл удалён — смотреть нечего, кроме факта удаления",
    "число": f"сверх предела {ПРЕДЕЛ_ФАЙЛОВ} файлов",
    "объём": f"сверх предела {ПРЕДЕЛ_DIFF_ВСЕГО} символов diff на PR",
    "git": "git-сервер не отдал diff",
}

_УЧАСТОК = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")


class GitЧтение(Protocol):
    def вызвать(self, имя: str, аргументы: dict[str, Any] | None = None) -> tuple[bool, str, dict[str, Any]]: ...


class ОшибкаВхода(RuntimeError):
    """База или голова не найдены, git-сервер недоступен — ревью не с чем делать."""


@dataclass
class ФайлPR:
    путь: str
    статус: str
    было: str = ""
    добавлено: int = 0
    удалено: int = 0
    бинарный: bool = False
    вид: str = "прочее"
    пропущен: str = ""                    # ключ ПРИЧИНЫ; пусто — просмотрен
    diff: str = ""
    diff_обрезан: bool = False
    участки: list[tuple[int, int]] = field(default_factory=list)   # строки новой версии, включительно
    голова: str | None = None             # текст файла на голове (только в памяти, не в отчёты)

    @property
    def причина(self) -> str:
        return ПРИЧИНЫ.get(self.пропущен, self.пропущен)

    def в_участке(self, строка: int, допуск: int = 0) -> bool:
        return any(н - допуск <= строка <= к + допуск for н, к in self.участки)

    def to_dict(self) -> dict[str, Any]:
        return {"путь": self.путь, "статус": self.статус, "было": self.было, "добавлено": self.добавлено,
                "удалено": self.удалено, "бинарный": self.бинарный, "вид": self.вид,
                "пропущен": self.причина if self.пропущен else "", "diff_обрезан": self.diff_обрезан,
                "участков": len(self.участки)}


@dataclass
class ВходPR:
    от: str
    до: str
    база: str
    голова: str
    файлы: list[ФайлPR]
    всего_файлов: int
    заголовок: str = ""
    описание: str = ""
    вызовы: list[str] = field(default_factory=list)   # имена инструментов MCP по порядку

    @property
    def просмотренные(self) -> list[ФайлPR]:
        return [ф for ф in self.файлы if not ф.пропущен]

    @property
    def пропущенные(self) -> list[ФайлPR]:
        return [ф for ф in self.файлы if ф.пропущен]

    def файл(self, путь: str) -> ФайлPR | None:
        return next((ф for ф in self.файлы if ф.путь == путь), None)

    def метрики(self) -> dict[str, Any]:
        """Без текстов: числа для журнала прогона."""
        return {"файлов": self.всего_файлов, "просмотрено": len(self.просмотренные),
                "пропущено": len(self.пропущенные) + max(0, self.всего_файлов - len(self.файлы)),
                "строк_добавлено": sum(ф.добавлено for ф in self.файлы),
                "строк_удалено": sum(ф.удалено for ф in self.файлы),
                "символов_diff": sum(len(ф.diff) for ф in self.просмотренные),
                "вызовов_git": len(self.вызовы)}


def вид(путь: str) -> str:
    расширение = os.path.splitext(путь)[1].lower()
    if расширение in КОД:
        return "код"
    if расширение in ДОКУМЕНТЫ:
        return "документ"
    return "прочее"


def шаблон_пропуска(путь: str) -> bool:
    имя = путь.rsplit("/", 1)[-1]
    return any(fnmatch.fnmatch(имя, ш) for ш in ПРОПУСК)


def участки(diff: str) -> list[tuple[int, int]]:
    """Диапазоны строк новой версии из заголовков `@@ -a,b +c,d @@`. Чистое удаление (d = 0)
    даёт точку на строке c: замечание «здесь удалили важное» тоже привязывается к месту."""
    итог = []
    for строка in diff.splitlines():
        м = _УЧАСТОК.match(строка)
        if м:
            начало = int(м.group(1))
            длина = int(м.group(2)) if м.group(2) is not None else 1
            итог.append((max(1, начало), max(1, начало + длина - 1)) if длина else (max(1, начало), max(1, начало)))
    return итог


def добавленные(diff: str) -> list[tuple[int, str]]:
    """Добавленные строки с номерами в новой версии файла."""
    итог, номер = [], 0
    for строка in diff.splitlines():
        м = _УЧАСТОК.match(строка)
        if м:
            номер = int(м.group(1))
            continue
        if not номер or строка.startswith(("+++", "---", "\\")):
            continue
        if строка.startswith("+"):
            итог.append((номер, строка[1:]))
            номер += 1
        elif строка.startswith(" "):
            номер += 1
    return итог


def изменённые_номера(diff: str) -> list[int]:
    """Номера строк новой версии, которые PR тронул: добавленные и места удалений (без строк
    контекста участка — по ним нельзя судить, какую функцию меняли)."""
    итог, номер, удаление = set(), 0, False
    for строка in diff.splitlines():
        м = _УЧАСТОК.match(строка)
        if м:
            номер, удаление = int(м.group(1)), False
            continue
        if not номер or строка.startswith(("+++", "---", "\\")):
            continue
        if строка.startswith("+"):
            итог.add(номер)
            номер += 1
        elif строка.startswith("-"):
            итог.add(max(1, номер))
        elif строка.startswith(" "):
            номер += 1
    return sorted(итог)


def _вызвать(git: GitЧтение, вход: ВходPR | None, имя: str, аргументы: dict[str, Any]) -> dict[str, Any]:
    if вход is not None:
        вход.вызовы.append(имя.split("__", 1)[-1])
    ок, текст, данные = git.вызвать(имя, аргументы)
    if not ок:
        raise ОшибкаВхода(f"{имя.split('__', 1)[-1]}: {текст.strip()[:300]}")
    return данные


def получить(git: GitЧтение, от: str, до: str = "HEAD", заголовок: str = "", описание: str = "",
             предел_файлов: int = ПРЕДЕЛ_ФАЙЛОВ, предел_всего: int = ПРЕДЕЛ_DIFF_ВСЕГО,
             предел_файла: int = ПРЕДЕЛ_DIFF_ФАЙЛА) -> ВходPR:
    """Собрать вход ревью: что изменилось от общего предка «от» и «до», diff и текст головы."""
    вызовы: list[str] = []
    вызовы.append("git_changes")
    ок, текст, и = git.вызвать("git__git_changes", {"from_ref": от, "to_ref": до})
    if not ок:
        raise ОшибкаВхода(f"git_changes: {текст.strip()[:300]}")
    файлы = [ФайлPR(путь=ф["путь"], статус=ф["статус"], было=ф.get("было", ""),
                    добавлено=int(ф.get("добавлено", 0)), удалено=int(ф.get("удалено", 0)),
                    бинарный=bool(ф.get("бинарный")), вид=вид(ф["путь"])) for ф in и.get("файлы", [])]
    вход = ВходPR(от=от, до=до, база=и["база"], голова=и["голова"], файлы=[], заголовок=заголовок,
                  описание=описание, всего_файлов=int(и.get("всего", len(файлы))), вызовы=вызовы)
    for ф in файлы:
        if ф.бинарный:
            ф.пропущен = "бинарный"
        elif шаблон_пропуска(ф.путь):
            ф.пропущен = "шаблон"
    файлы.sort(key=lambda ф: (bool(ф.пропущен), _ПОРЯДОК[ф.вид], -(ф.добавлено + ф.удалено), ф.путь))
    всего_символов, просмотрено = 0, 0
    for ф in файлы:
        if ф.пропущен:
            continue
        if просмотрено >= предел_файлов:
            ф.пропущен = "число"
            continue
        if всего_символов >= предел_всего:
            ф.пропущен = "объём"
            continue
        try:
            р = _вызвать(git, вход, "git__git_diff", {"from_ref": вход.база, "to_ref": вход.голова,
                                                      "path": ф.путь, "literal_path": True,
                                                      "limit": min(предел_файла, предел_всего - всего_символов)})
        except ОшибкаВхода:
            ф.пропущен = "git"
            continue
        ф.diff, ф.diff_обрезан = р.get("diff", ""), bool(р.get("обрезано"))
        ф.участки = участки(ф.diff)
        всего_символов += len(ф.diff)
        просмотрено += 1
        if ф.статус != "D" and ф.вид in ("код", "документ"):
            try:
                г = _вызвать(git, вход, "git__git_show", {"path": ф.путь, "ref": вход.голова,
                                                          "limit": ПРЕДЕЛ_ГОЛОВЫ})
                ф.голова = None if г.get("обрезано") else г.get("текст", "")
            except ОшибкаВхода:
                ф.голова = None
    вход.файлы = файлы
    return вход
