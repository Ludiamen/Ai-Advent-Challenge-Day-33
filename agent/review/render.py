"""Текст ревью: комментарий в PR (markdown) и вывод в консоль (spec FR-07, plan D-09).

Всё, что написала модель, проходит три фильтра до публикации:
- маска ПД точного профиля (e-mail, телефоны, «А.В. Фамилия», фамилии из локального
  списка, если он есть);
- обезвреживание разметки: HTML экранируется, `@имя` не превращается в упоминание
  (GitHub разослал бы уведомления), ссылки и картинки модели не становятся ссылками
  (картинка с чужого адреса — это запрос к чужому серверу от каждого читателя);
- длина — комментарий GitHub не длиннее 65 536 символов.
Ссылки на файлы строит сам конвейер — только на этот репозиторий и коммит головы.
"""

from __future__ import annotations

import json
import re
from typing import Any
from urllib.parse import quote

from agent.review.collect import КРАСНЫЙ, НЕ_ВЫПОЛНЕНО, Сборка
from agent.review.context import Опора
from agent.review.prompts import РАЗДЕЛЫ
from agent.review.reviewers import Находка
from agent.review.source import ВходPR
from agent.service import pd

МЕТКА = "<!-- ai-review:advent -->"
МЕТКА_МЕТРИК = "ai-review-metrics"
ПРЕДЕЛ_КОММЕНТАРИЯ = 60_000
ЗНАЧКИ = {"баги": "🐞", "архитектура": "🏛", "рекомендации": "💡"}
СЕРЬЁЗНОСТЬ = {"критично": "🔴 критично", "важно": "🟠 важно", "мелочь": "⚪ мелочь"}
ВЕРДИКТ = {КРАСНЫЙ: "🔴 есть критичные находки — нужен человек до слияния",
           НЕ_ВЫПОЛНЕНО: "⚠️ AI-ревью не выполнено — нужен человек",
           "зелёный": "🟢 критичных находок нет"}


def обезвредить(текст: str) -> tuple[str, dict[str, int]]:
    """Текст модели → безопасный markdown; вернуть и счёт скрытых ПД (без значений)."""
    т, скрыто = pd.скрыть(текст or "", профиль="точный")
    т = т.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    т = re.sub(r"@(?=[\w-])", "@​", т)
    т = т.replace("](", "]​(").replace("![", "!​[")
    т = re.sub(r"\s*\n\s*", " ", т).strip()
    return т, скрыто


def _код(текст: str) -> str:
    """Фрагмент diff в строке кода markdown: обратные кавычки внутри не ломают разметку."""
    т = (текст or "").replace("\n", " ").strip()
    забор = "``" if "`" in т else "`"
    return f"{забор} {т} {забор}" if забор == "``" else f"`{т}`"


def ссылка_на_файл(путь: str, строка: int, репозиторий: str, голова: str) -> str:
    подпись = f"{путь}:{строка}" if строка else путь
    if not репозиторий:
        return f"`{подпись}`"
    якорь = f"#L{строка}" if строка else ""
    путь_url = quote(путь, safe="/")
    подпись = подпись.replace("`", "'")
    return f"[`{подпись}`](https://github.com/{репозиторий}/blob/{голова}/{путь_url}{якорь})"


def _находка(н: Находка, опора: Опора, вход: ВходPR, репозиторий: str, скрыто: dict[str, int]) -> str:
    def чисто(т: str) -> str:
        итог, с = обезвредить(т)
        for к, v in с.items():
            скрыто[к] = скрыто.get(к, 0) + v
        return итог

    строки = [f"- **{СЕРЬЁЗНОСТЬ[н.серьёзность]}** · {ссылка_на_файл(н.файл, н.строка, репозиторий, вход.голова)}"
              f" — {чисто(н.суть)}"]
    if н.почему:
        строки.append(f"  <br>**Почему:** {чисто(н.почему)}")
    if н.исправить:
        строки.append(f"  <br>**Исправить:** {чисто(н.исправить)}")
    if н.фрагмент_diff:
        фрагмент, _ = pd.скрыть(н.фрагмент_diff[:300], профиль="точный")
        строки.append(f"  <br>{'✅' if н.подтверждена else '❔'} {_код(фрагмент)}")
    по_номеру = {ф.номер: ф for ф in опора.фрагменты}
    источники = [по_номеру[i] for i in н.источники if i in по_номеру]
    if источники:
        строки.append("  <br>**Опора:** " + "; ".join(f"[{ф.номер}] `{ф.подпись[:110]}`" for ф in источники))
    if н.разделы:
        строки.append(f"  <br>_То же нашли: {', '.join(н.разделы)}_")
    if н.пометки:
        строки.append(f"  <br>_{'; '.join(н.пометки)}_")
    return "\n".join(строки)


def комментарий(вход: ВходPR, опора: Опора, сборка: Сборка, метрики: dict[str, Any],
                репозиторий: str = "", тревоги: list[str] | None = None,
                прогон: str = "") -> tuple[str, dict[str, int]]:
    """Markdown комментария PR и счёт скрытых ПД. «прогон» — адрес прогона GitHub Actions:
    из комментария можно перейти к журналу задания, где видны этапы и время."""
    скрыто: dict[str, int] = {}
    части = [МЕТКА, f"## 🤖 AI-ревью: {ВЕРДИКТ.get(сборка.вердикт, сборка.вердикт)}",
             f"{сборка.причина}. Голова `{вход.голова[:7]}`, база `{вход.база[:7]}`; просмотрено "
             f"{len(вход.просмотренные)} из {вход.всего_файлов} файлов."]
    сбои = [р for р in сборка.ревьюеры if not р.ок]
    if сбои:
        части.append("> ⚠️ Не выполнены разделы: " + "; ".join(
            f"«{РАЗДЕЛЫ[р.раздел]['заголовок']}» — {обезвредить(р.ошибка)[0]}" for р in сбои))
    for т in тревоги or []:
        части.append(f"> 📈 {т}")
    for раздел, о in РАЗДЕЛЫ.items():
        находки = сборка.раздел(раздел)
        части.append(f"### {ЗНАЧКИ[раздел]} {о['заголовок']} ({len(находки)})")
        if any(р.раздел == раздел and not р.ок for р in сборка.ревьюеры):
            части.append("_раздел не выполнен_")
        elif not находки:
            части.append("_не найдено_")
        else:
            части += [_находка(н, опора, вход, репозиторий, скрыто) for н in находки]
    пропущенные = вход.пропущенные
    лишние = max(0, вход.всего_файлов - len(вход.файлы))
    if пропущенные or лишние:
        список = "\n".join(f"- `{ф.путь}` — {ф.причина}" for ф in пропущенные[:50])
        if лишние:
            список += f"\n- ещё {лишние} файлов сверх списка git-сервера"
        части.append(f"<details><summary>Не просмотрены ({len(пропущенные) + лишние})</summary>\n\n{список}\n</details>")
    м = метрики
    ревьюеры = "\n".join(
        f"| {РАЗДЕЛЫ[р.раздел]['заголовок']} | {'да' if р.ок else 'нет'} | {р.секунд:.0f} с | "
        f"{р.токены_вход + р.токены_выход} | {len(р.находки)} |" for р in сборка.ревьюеры)
    с = сборка.метрики()
    части.append(
        "<details><summary>Как сделано ревью</summary>\n\n"
        f"Вход: {вход.всего_файлов} файлов, +{м.get('вход', {}).get('строк_добавлено', 0)} "
        f"−{м.get('вход', {}).get('строк_удалено', 0)} строк; git-сервер MCP: "
        f"{len(вход.вызовы)} вызовов.  \n"
        f"Опора (индекс базы `{вход.база[:7]}`, {м.get('поиск', '')}): {len(опора.фрагменты)} фрагментов "
        f"(документы {sum(1 for ф in опора.фрагменты if ф.вид == 'документ')}, код "
        f"{sum(1 for ф in опора.фрагменты if ф.вид == 'код')}, места вызова "
        f"{sum(1 for ф in опора.фрагменты if ф.вид == 'вызов')}).  \n"
        f"Проверка кодом: подтверждено {с['подтверждено']}, не подтверждено {с['не_подтверждено']}, "
        f"понижено {с['понижено']}, дублей слито {с['дублей']}, отброшено (файл не из PR) {с['отброшено']}.\n\n"
        "| Ревьюер | Ок | Время | Токены | Находок |\n|---|---|---|---|---|\n" + ревьюеры + "\n</details>")
    части.append("---\n"
                 f"Модель {м.get('модель', '')} · {м.get('секунд', 0):.0f} с · {м.get('токены', 0)} токенов · "
                 f"${м.get('стоимость', 0):.4f} · три ревьюера параллельно, находки проверены кодом. "
                 "Слияние решает человек. Оцените ревью реакцией 👍 / 👎 на этот комментарий."
                 + (f" [Журнал прогона]({прогон})." if прогон else ""))
    if any(скрыто.values()):
        части.append(f"_Скрыто персональных данных: {sum(скрыто.values())}._")
    тело = "\n\n".join(части)
    хвост = f"\n\n<!-- {МЕТКА_МЕТРИК} {json.dumps(метрики, ensure_ascii=False, separators=(',', ':'))} -->"
    if len(тело) + len(хвост) > ПРЕДЕЛ_КОММЕНТАРИЯ:
        тело = тело[:ПРЕДЕЛ_КОММЕНТАРИЯ - len(хвост) - 80] + "\n\n… ревью обрезано по пределу длины комментария"
    return тело + хвост, скрыто


def метрики_из(текст: str) -> dict[str, Any] | None:
    """Скрытая строка метрик из текста комментария (история прогонов — из комментариев PR)."""
    м = re.search(rf"<!-- {МЕТКА_МЕТРИК} (\{{.*?\}}) -->", текст or "", re.S)
    if not м:
        return None
    try:
        return json.loads(м.group(1))
    except json.JSONDecodeError:
        return None


def консоль(вход: ВходPR, опора: Опора, сборка: Сборка, метрики: dict[str, Any]) -> str:
    """Тот же итог простым текстом для терминала."""
    строки = [f"AI-ревью {вход.от}...{вход.до} ({вход.база[:7]} → {вход.голова[:7]}): "
              f"{ВЕРДИКТ.get(сборка.вердикт, сборка.вердикт)}",
              f"  {сборка.причина}; просмотрено {len(вход.просмотренные)} из {вход.всего_файлов} файлов"]
    for р in сборка.ревьюеры:
        if not р.ок:
            строки.append(f"  ⚠ раздел «{РАЗДЕЛЫ[р.раздел]['заголовок']}» не выполнен: {р.ошибка}")
    по_номеру = {ф.номер: ф for ф in опора.фрагменты}
    for раздел, о in РАЗДЕЛЫ.items():
        находки = сборка.раздел(раздел)
        строки.append(f"\n{ЗНАЧКИ[раздел]} {о['заголовок']} ({len(находки)})")
        for н in находки:
            место = f"{н.файл}:{н.строка}" if н.строка else н.файл
            суть = pd.скрыть(н.суть, профиль="точный")[0]
            строки.append(f"  [{н.серьёзность}{'' if н.подтверждена else ', не подтверждена'}] {место} — {суть}")
            if н.почему:
                строки.append(f"      почему: {pd.скрыть(н.почему, профиль='точный')[0]}")
            if н.источники:
                строки.append("      опора: " + "; ".join(f"[{i}] {по_номеру[i].подпись[:80]}"
                                                         for i in н.источники if i in по_номеру))
    for ф in вход.пропущенные:
        строки.append(f"  не просмотрен: {ф.путь} — {ф.причина}")
    строки.append(f"\nмодель {метрики.get('модель', '')}, {метрики.get('секунд', 0):.0f} с, "
                  f"{метрики.get('токены', 0)} токенов, ${метрики.get('стоимость', 0):.4f}")
    return "\n".join(строки)
