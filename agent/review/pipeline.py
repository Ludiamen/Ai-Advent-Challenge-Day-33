"""Конвейер ревью PR: один на Action, консоль и чат (spec FR-02…FR-12, plan § 1).

    индекс базы → вход (git-сервер MCP) → опора → три ревьюера параллельно → сборщик →
    текст ревью и метрики

Входы отличаются только тем, откуда берутся база и голова (событие GitHub, аргументы
консоли, команда чата) и куда уходит итог (комментарий PR, терминал, карточка веба).
Код выхода: 0 — зелёный, 1 — красный, 2 — ревью не выполнено.
"""

from __future__ import annotations

import dataclasses
import os
import time
from dataclasses import dataclass, field
from typing import Any, Callable

from agent import catalog
from agent.devassist import project as проекты
from agent.local import progress
from agent.review import collect, context, metrics, render, reviewers, source

ПРОЕКТ = "advent"
ЛЕКСИЧЕСКИЙ, BGE = "лексический", "bge-m3"
СПОСОБЫ = (ЛЕКСИЧЕСКИЙ, BGE)
КОДЫ = {collect.ЗЕЛЁНЫЙ: 0, collect.КРАСНЫЙ: 1, collect.НЕ_ВЫПОЛНЕНО: 2}


def способ_по_умолчанию() -> str:
    способ = os.getenv("REVIEW_SEARCH", "").strip() or ЛЕКСИЧЕСКИЙ
    return способ if способ in СПОСОБЫ else ЛЕКСИЧЕСКИЙ


class ПоискBGE:
    """Индекс bge-m3 (Ollama) с тем же интерфейсом, что у лексического поиска."""

    def __init__(self, индексатор: Any) -> None:
        self.индексатор = индексатор

    def найти(self, запрос: str, сколько: int = 10, исключить: Any = ()) -> list[Any]:
        запрет = set(исключить)
        находки = self.индексатор.найти(запрос, "структура", сколько + 3 * len(запрет) + 5)
        return [н for н in находки if н.чанк.источник not in запрет][:сколько]


_ПОИСК: dict[tuple[str, str, str], tuple[Any, dict[str, Any]]] = {}


def _индекс_готов(проект: проекты.Проект, база: str) -> bool:
    """Индекс уже собран из этого коммита (manifest.json) — пересобирать незачем."""
    import json
    try:
        with open(os.path.join(проект.индекс, проекты.СПИСОК), encoding="utf-8") as f:
            return json.load(f).get("коммит") == база and os.path.exists(os.path.join(проект.индекс, "docs.db"))
    except (OSError, ValueError):
        return False


def поисковик(проект: проекты.Проект, база: str, способ: str = "") -> tuple[Any, dict[str, Any]]:
    """Индекс проекта из коммита базы и поиск по нему. Лексический: фрагменты режутся тем же
    индексатором (эмбеддер «хэш» — без модели, векторы не нужны), поиск — BM25. Индекс,
    уже собранный из этого коммита (кэш Actions, прошлый /review), не пересобирается; поиск
    по нему переиспользуется в процессе."""
    способ = способ or способ_по_умолчанию()
    if способ == BGE:   # свой каталог: векторы bge-m3 и «хэш» в одной базе не смешиваются
        проект = dataclasses.replace(проект, индекс=проект.индекс + "-bge")
    ключ = (проект.индекс, база, способ)
    if ключ in _ПОИСК and _индекс_готов(проект, база):
        поиск, сведения = _ПОИСК[ключ]
        return поиск, {**сведения, "секунд": 0.0, "из_памяти": True}
    старт = time.monotonic()
    эмбеддер = "хэш" if способ == ЛЕКСИЧЕСКИЙ else "ollama"
    if _индекс_готов(проект, база):
        отчёт = {"файлов": None, "фрагментов": None, "изменено": [], "готов": True}
    else:
        отчёт = проекты.построить(проект, эмбеддер=эмбеддер, ссылка=база)
    индексатор = проекты.индексатор(проект, эмбеддер)
    if способ == ЛЕКСИЧЕСКИЙ:
        from agent.rag.lexical import ЛексическийПоиск
        чанки = индексатор.хранилище.чанки("структура")
        поиск: Any = ЛексическийПоиск(чанки)
        фрагментов = len(чанки)
    else:
        поиск = ПоискBGE(индексатор)
        фрагментов = отчёт.get("фрагментов") or 0
    файлов = отчёт.get("файлов") or len(проекты.файлы_индекса(проект))
    сведения = {"способ": способ, "файлов": файлов, "фрагментов": фрагментов,
                "изменено": len(отчёт.get("изменено", [])), "из_кэша_индекса": bool(отчёт.get("готов")),
                "секунд": round(time.monotonic() - старт, 1)}
    _ПОИСК.clear()          # один поиск в памяти: база меняется — прежний не нужен
    _ПОИСК[ключ] = (поиск, сведения)
    return поиск, сведения


def git_для(проект: проекты.Проект) -> Any:
    """git-сервер MCP проекта: отдельный процесс stdio из mcp-servers.json (как у /help)."""
    from agent.devassist.assistant import GitMCP
    return GitMCP(проект)


@dataclass
class ИтогРевью:
    вход: source.ВходPR | None
    опора: context.Опора
    сборка: collect.Сборка
    метрики: dict[str, Any]
    текст: str = ""
    консоль: str = ""
    тревоги: list[str] = field(default_factory=list)

    @property
    def вердикт(self) -> str:
        return self.сборка.вердикт

    @property
    def код_выхода(self) -> int:
        return КОДЫ.get(self.сборка.вердикт, 2)

    def to_dict(self) -> dict[str, Any]:
        """Для карточки веба: без текстов опоры, с находками."""
        return {"вердикт": self.сборка.вердикт, "причина": self.сборка.причина, "код": self.код_выхода,
                "находки": [н.to_dict() for н in self.сборка.находки],
                "ревьюеры": [{"раздел": р.раздел, **р.метрики()} for р in self.сборка.ревьюеры],
                "файлы": [ф.to_dict() for ф in (self.вход.файлы if self.вход else [])],
                "опора": [ф.to_dict() | {"подпись": ф.подпись} for ф in self.опора.фрагменты],
                "метрики": self.метрики, "тревоги": list(self.тревоги), "консоль": self.консоль}


def выполнить(от: str, до: str = "HEAD", модель: str = reviewers.МОДЕЛЬ, канал: str = "консоль",
              проект: проекты.Проект | None = None, git: Any = None,
              клиент_для: Callable[[], Any] | None = None, заголовок: str = "", описание: str = "",
              репозиторий: str = "", pr: int = 0, история: list[dict[str, Any]] | None = None,
              способ_поиска: str = "", поиск: Any = None, записать_метрики: bool = True, прогон: str = "",
              этап: Callable[[str, str], None] | None = None) -> ИтогРевью:
    """Ревью диапазона «от...до» (как PR: от общего предка). Ничего не публикует — это делают
    вызывающие (github.py, консоль, веб) по `ИтогРевью.текст`."""
    проект = проект or проекты.загрузить(ПРОЕКТ)
    своё_git = git is None
    git = git or git_для(проект)
    этапы: dict[str, float] = {}
    сбои: list[str] = []
    старт = time.monotonic()

    def отметить(имя: str, подпись: str = "") -> None:
        progress.этап("ревью", подпись=f"{имя}{': ' + подпись if подпись else ''}")
        if этап:
            этап(имя, подпись)

    def готово(имя: str, т: float) -> None:
        этапы[имя] = round(time.monotonic() - т, 2)

    опора = context.Опора()
    вход: source.ВходPR | None = None
    сведения_поиска: dict[str, Any] = {}
    итоги: list[reviewers.ИтогРевьюера] = []
    try:
        т = time.monotonic()
        отметить("вход", f"{от}...{до}")
        try:
            вход = source.получить(git, от, до, заголовок=заголовок, описание=описание)
        except source.ОшибкаВхода as e:
            сбои.append(f"вход: {e}")
        готово("вход", т)

        if вход is not None:
            т = time.monotonic()
            if поиск is None:
                отметить("индекс", f"база {вход.база[:7]}")
                try:
                    поиск, сведения_поиска = поисковик(проект, вход.база, способ_поиска)
                except Exception as e:  # noqa: BLE001 — без индекса ревью идёт по diff, с пометкой
                    сбои.append(f"индекс: {type(e).__name__}: {str(e)[:150]}")
                    поиск = None
            готово("индекс", т)

            т = time.monotonic()
            отметить("опора")
            опора = context.собрать(вход, поиск, git)
            готово("опора", т)

            ключ_есть = catalog.get(модель).has_key
            if not вход.всего_файлов:
                pass                                   # пустой PR: ревьюерам нечего смотреть, это не сбой
            elif not вход.просмотренные:
                сбои.append("нет файлов для ревью (все пропущены)")
            elif not ключ_есть:
                сбои.append(f"нет ключа модели {модель} ({catalog.get(модель).env_var})")
                итоги = [reviewers.ИтогРевьюера(р, ошибка="нет ключа модели") for р in context.РЕВЬЮЕРЫ]
            else:
                т = time.monotonic()
                отметить("ревьюеры", "три параллельно")
                if клиент_для is None:
                    from agent.llm import Client
                    клиент_для = lambda: Client(timeout=reviewers.ТАЙМАУТ_ЗАПРОСА)  # noqa: E731
                итоги = reviewers.выполнить_все(вход, опора, клиент_для, модель, git, проект.описание,
                                                этап=lambda р, с: отметить("ревьюер", f"{р} — {с}"))
                готово("ревьюеры", т)
    finally:
        if своё_git:
            try:
                git.закрыть()
            except Exception:  # noqa: BLE001
                pass

    т = time.monotonic()
    if вход is not None and not вход.всего_файлов:
        сборка = collect.Сборка(вердикт=collect.ЗЕЛЁНЫЙ, причина="изменений относительно базы нет — ревьюить нечего")
    elif вход is not None and not вход.просмотренные and not итоги:
        сборка = collect.Сборка(вердикт=collect.ЗЕЛЁНЫЙ, причина="нечего ревьюить: все файлы пропущены фильтром")
    elif вход is None or not итоги:
        сборка = collect.Сборка(вердикт=collect.НЕ_ВЫПОЛНЕНО, причина="; ".join(сбои) or "ревью не выполнено")
    else:
        сборка = collect.собрать(вход, опора, итоги)
        if сборка.вердикт == collect.НЕ_ВЫПОЛНЕНО and сбои:
            сборка.причина = "; ".join(сбои)
    готово("сборка", т)
    сбои += [f"{р.раздел}: {р.ошибка}" for р in итоги if not р.ок and f"{р.раздел}: {р.ошибка}" not in сбои]

    токены_вход = sum(р.токены_вход for р in итоги)
    токены_выход = sum(р.токены_выход for р in итоги)
    строка = {
        "канал": канал, "репозиторий": репозиторий, "pr": pr,
        "голова": (вход.голова[:12] if вход else ""), "база": (вход.база[:12] if вход else ""),
        "модель": модель, "поиск": сведения_поиска.get("способ", ""),
        "секунд": round(time.monotonic() - старт, 1), "этапы": этапы,
        "токены": токены_вход + токены_выход, "токены_вход": токены_вход, "токены_выход": токены_выход,
        "стоимость": round(sum(р.стоимость for р in итоги), 5),
        "ревьюеры": {р.раздел: р.метрики() for р in итоги},
        "вход": вход.метрики() if вход else {}, "опора": опора.метрики() | {"индекс": сведения_поиска},
        "сборка": сборка.метрики(), "вердикт": сборка.вердикт, "сбои": сбои,
    }
    тревоги = metrics.тревоги(строка, история or [])
    строка["тревоги"] = ["токены" if "токенов" in т else "время" for т in тревоги]
    итог = ИтогРевью(вход, опора, сборка, metrics.очистить(строка), тревоги=тревоги)
    if вход is not None:
        итог.текст, скрыто = render.комментарий(вход, опора, сборка, итог.метрики | {"поиск": сведения_поиска.get("способ", "")},
                                                репозиторий, тревоги, прогон)
        итог.консоль = render.консоль(вход, опора, сборка, итог.метрики)
        итог.метрики["скрыто_пд"] = sum(скрыто.values())
    else:
        итог.текст = (f"{render.МЕТКА}\n## 🤖 AI-ревью: {render.ВЕРДИКТ[collect.НЕ_ВЫПОЛНЕНО]}\n\n"
                      f"{render.обезвредить(сборка.причина)[0]}")
        итог.консоль = f"AI-ревью {от}...{до}: не выполнено — {сборка.причина}"
    if записать_метрики:
        try:
            metrics.записать(итог.метрики)
        except OSError:
            pass
    return итог
