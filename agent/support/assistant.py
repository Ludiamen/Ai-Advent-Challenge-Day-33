"""Ассистент поддержки: ответ в тикете по FAQ, документации и данным тикета (День 33, FR-05, FR-10, plan D-05, D-09).

На каждое сообщение пользователя:
1. контекст — через MCP-сервер `support` (закреплён за этим тикетом): тикет, заявитель и его
   учётная запись, журнал входов, прошлые тикеты, политика портала;
2. факты — плоский словарь «ключ → значение» из контекста (учётная_запись.блокировка.до, …);
3. поиск по базе знаний (FAQ + документация) — запрос из сообщения, темы и заметных фактов;
4. один вызов модели — JSON: ответ, решение, действие, факты, источники, цитаты;
5. проверка кодом: факты — только выданные ключи, источники — только выданные номера, цитаты —
   найдены в источниках (`cite.py`); «предложить_действие» без факта-основания или без вида →
   «передать_человеку»; ответ без фактов и источников → «передать_человеку»;
6. итог — через MCP: сообщение ассистента в тикет, статус, заявка на действие.

Запасной путь: облако не ответило — повтор (`llm.py`), затем локальная модель, если она
разрешена (`SUPPORT_LOCAL`, дома), иначе честное «передано специалисту». MCP недоступен —
ответа без контекста нет: «передано специалисту». Маска ПД на выходе.
"""

from __future__ import annotations

import json
import os
