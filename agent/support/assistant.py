МОДЕЛЬ = "ds-flash"
ЗАПАСНАЯ = "loc-rag-docs"
ФРАГМЕНТОВ = 6
ВХОДОВ = 6
ОТВЕТ_ТОКЕНОВ = 1500
СТАТУС = {"ответ": "Ждёт ответа заявителя", "уточнить": "Ждёт ответа заявителя",
          "передать_человеку": "Передан специалисту"}
_замок_mcp = threading.Lock()


class ОшибкаMCP(RuntimeError):
    pass


class SupportMCP:
    """Клиент MCP к серверу `support` в процессе (тот же протокол, без дочернего процесса — на VPS с
    одним ядром запуск процесса на каждый ответ дороже самого ответа). Сервер закрепляется за
    тикетом на время каждого вызова (`SUPPORT_TICKET`) под общей блокировкой."""

    def __init__(self, тикет: int) -> None:
        import support_server
        self.сервер = support_server.ассистент
        self.тикет = int(тикет)
        self.вызовы: list[str] = []

    def вызвать(self, имя: str, аргументы: dict[str, Any] | None = None) -> dict[str, Any]:
        import anyio
        from mcp import Client

        async def вызов():
            async with Client(self.сервер) as клиент:
                return await клиент.call_tool(имя, аргументы or {})
        self.вызовы.append(имя)
        with _замок_mcp:
            прежний = os.environ.get("SUPPORT_TICKET")
            os.environ["SUPPORT_TICKET"] = str(self.тикет)
            try:
                р = anyio.run(вызов)
            except Exception as e:  # noqa: BLE001
                raise ОшибкаMCP(f"{имя}: {type(e).__name__}: {e}") from e
            finally:
                if прежний is None:
                    os.environ.pop("SUPPORT_TICKET", None)
                else:
                    os.environ["SUPPORT_TICKET"] = прежний
        текст = "\n".join(getattr(б, "text", "") for б in (р.content or []))
        if р.is_error:
            raise ОшибкаMCP(f"{имя}: {текст[:300]}")
        try:
            return json.loads(текст)
        except json.JSONDecodeError:
            return {"текст": текст}


@dataclass
class ОтветПоддержки:
    тикет: int
    ответ: str = ""
    решение: str = "передать_человеку"
    действие: dict[str, Any] | None = None
    заявка: dict[str, Any] | None = None
    факты: list[str] = field(default_factory=list)
    источники: list[dict[str, Any]] = field(default_factory=list)
    цитаты: list[dict[str, Any]] = field(default_factory=list)
    статус: str = ""
    модель: str = ""
    пометки: list[str] = field(default_factory=list)
    вызовы_mcp: list[str] = field(default_factory=list)
    токены_вход: int = 0
    токены_выход: int = 0
    стоимость: float = 0.0
    секунд: dict[str, float] = field(default_factory=dict)
    ошибка: str = ""
    скрыто_пд: int = 0

    def to_dict(self) -> dict[str, Any]:
        return dict(self.__dict__)

    def метрики(self) -> dict[str, Any]:
        """Без текстов."""
        return {"тикет": self.тикет, "решение": self.решение, "действие": (self.действие or {}).get("вид"),
                "фактов": len(self.факты), "источников": len(self.источники),
                "цитат_подтверждено": sum(1 for ц in self.цитаты if ц.get("подтверждена")),
                "модель": self.модель, "токены_вход": self.токены_вход, "токены_выход": self.токены_выход,
                "стоимость": round(self.стоимость, 5), "секунд": self.секунд, "пометок": len(self.пометки),
                "ошибка": self.ошибка[:120]}


# --- факты ----------------------------------------------------------------------------------

def _плоско(префикс: str, значение: Any, итог: dict[str, Any]) -> None:
    if isinstance(значение, dict):
        for к, в in значение.items():
            _плоско(f"{префикс}.{к}", в, итог)
    elif isinstance(значение, list):
        итог[префикс] = значение
    elif значение is not None:
        итог[префикс] = значение


def факты(тикет: dict[str, Any], заявитель: dict[str, Any], входы: list[dict[str, Any]],
          история: list[dict[str, Any]], политика: dict[str, Any]) -> dict[str, Any]:
    итог: dict[str, Any] = {"сейчас": политика.get("сейчас", ""), "заявитель.роль": заявитель.get("роль", ""),
                            "заявитель.подразделение": заявитель.get("подразделение", "")}
    уз = заявитель.get("учётная_запись")
    if isinstance(уз, dict):
        _плоско("учётная_запись", уз, итог)
        if "учётная_запись.блокировка" not in итог and "учётная_запись.блокировка.с" not in итог:
            итог["учётная_запись.блокировка"] = "нет"
    else:
        итог["учётная_запись"] = уз or "нет"
    if заявитель.get("примечание"):
        итог["заявитель.примечание"] = заявитель["примечание"]
    for i, в in enumerate(входы[:ВХОДОВ], 1):
        итог[f"входы.{i}"] = f"{в['время'].replace('T', ' ')[:16]} — {в['итог']} — {в['устройство']}"
    итог["тикет.статус"] = тикет.get("статус", "")
    for т in история[:5]:
        итог[f"прошлый_тикет.{т['номер']}"] = (f"«{т['тема']}» — {т['статус']}"
                                               + (f", решение: {т['решение']}" if т.get("решение") else ""))
    for к in ("неудачных_до_блокировки", "блокировка_минут", "бездействие_минут", "срок_пароля_дней",
              "ссылка_активации_часов", "резервных_кодов"):
        if к in политика:
            итог[f"политика.{к}"] = политика[к]
    return итог


def запрос_поиска(тикет: dict[str, Any], ф: dict[str, Any]) -> str:
    последнее = next((с["текст"] for с in reversed(тикет["сообщения"]) if с["автор"] == "заявитель"), "")
    признаки = []
    if ф.get("учётная_запись.статус") == "заблокирована":
        признаки.append("заблокирована блокировка 15 минут неудачных попыток")
    if ф.get("учётная_запись.второй_фактор") in ("не подключён", "сброшен"):
        признаки.append("второй фактор подключение")
    if ф.get("учётная_запись.срок_пароля_истёк"):
        признаки.append("срок действия пароля сменить пароль")
    if ф.get("учётная_запись.статус") == "приглашён":
        признаки.append("ссылка активации просрочена 72 часа")
    return " ".join([тикет.get("тема", ""), последнее, *признаки])


# --- разбор и проверка ----------------------------------------------------------------------------

def разобрать(текст: str) -> dict[str, Any]:
    т = re.sub(r"^```(?:json)?\s*|\s*```$", "", (текст or "").strip())
    начало, конец = т.find("{"), т.rfind("}")
    if начало < 0 or конец <= начало:
        raise ValueError("нет JSON")
    данные = json.loads(т[начало:конец + 1])
    if not isinstance(данные, dict) or not str(данные.get("ответ") or "").strip():
        raise ValueError("нет ответа")
    return данные


def проверить(данные: dict[str, Any], ф: dict[str, Any], фрагменты: list[Any], ответ: ОтветПоддержки) -> None:
    """Проверки кодом (plan D-05) — пишут итог в `ответ`."""
    решение = str(данные.get("решение") or "").strip()
    if решение not in prompts.РЕШЕНИЯ:
        ответ.пометки.append(f"решение «{решение}» неизвестно — передано человеку")
        решение = "передать_человеку"
    названные = [str(к) for к in данные.get("факты") or []]
    ответ.факты = [к for к in названные if к in ф]
    лишние = [к for к in названные if к not in ф]
    if лишние:
        ответ.пометки.append(f"сняты факты, которых нет в данных тикета: {лишние[:5]}")
    номера = []
    for н in данные.get("источники") or []:
        try:
            н = int(str(н).strip("[] "))
        except ValueError:
            continue
        if 1 <= н <= len(фрагменты) and н not in номера:
            номера.append(н)
    ответ.источники = [{"n": н, "источник": фрагменты[н - 1].источник, "раздел": фрагменты[н - 1].раздел,
                        "вид": фрагменты[н - 1].вид} for н in номера]
    for ц in данные.get("цитаты") or []:
        if not isinstance(ц, dict):
            continue
        try:
            н = int(ц.get("n"))
        except (TypeError, ValueError):
            continue
        текст = str(ц.get("текст") or "")
        if 1 <= н <= len(фрагменты) and текст:
            вид, _ = cite.найти(текст, фрагменты[н - 1].текст)
            ответ.цитаты.append({"n": н, "текст": текст[:300], "подтверждена": вид != cite.НЕ_НАЙДЕНА})
    действие = данные.get("действие") if isinstance(данные.get("действие"), dict) else None
    if решение == "предложить_действие":
        from agent.support.data import ДЕЙСТВИЯ
        if not действие or действие.get("вид") not in ДЕЙСТВИЯ:
            ответ.пометки.append("действие не указано или неизвестно — передано человеку")
            решение, действие = "передать_человеку", None
        elif not ответ.факты:
            ответ.пометки.append("действие без опоры на факты тикета — передано человеку")
            решение, действие = "передать_человеку", None
    elif решение == "ответ" and not ответ.факты and not ответ.источники:
        ответ.пометки.append("ответ без фактов и источников — передано человеку")
        решение = "передать_человеку"
    ответ.решение, ответ.действие = решение, (действие if решение == "предложить_действие" else None)


# --- ассистент ---------------------------------------------------------------------------------

class Ассистент:
    def __init__(self, база: БазаЗнаний, клиент: Any = None, модель: str = МОДЕЛЬ,
                 mcp_для: Callable[[int], Any] = SupportMCP, локальная: bool | None = None) -> None:
        self.база = база
        self.клиент = клиент
        self.модель = модель
        self.mcp_для = mcp_для
        self.локальная = (os.getenv("SUPPORT_LOCAL", "1") != "0") if локальная is None else локальная

    def _клиент(self) -> Any:
        if self.клиент is None:
            from agent.llm import Client
            self.клиент = Client()
        return self.клиент

    def _звать(self, ответ: ОтветПоддержки, модель: str, сообщения: list[dict[str, Any]]) -> Any:
        r = self._клиент().call(модель, сообщения, max_tokens=ОТВЕТ_ТОКЕНОВ, temperature=0.1)
        ответ.модель = модель
        ответ.токены_вход += r.prompt_tokens
        ответ.токены_выход += r.completion_tokens
        ответ.стоимость += r.cost
        return r

    def ответить(self, номер: int, этап: Callable[[str, str], None] | None = None) -> ОтветПоддержки:
        ответ = ОтветПоддержки(int(номер))
        старт = time.monotonic()

        def отметить(имя: str, подпись: str = "") -> None:
            if этап:
                этап(имя, подпись)
        mcp = self.mcp_для(int(номер))
        # 1–2. Контекст и факты — через MCP.
        отметить("тикет", "MCP: тикет, заявитель, входы, история")
        try:
            тикет = mcp.вызвать("support_ticket", {"ticket": номер})
            заявитель = mcp.вызвать("support_requester", {"ticket": номер})
            входы = mcp.вызвать("support_logins", {"ticket": номер, "limit": ВХОДОВ}).get("входы", [])
            история = mcp.вызвать("support_history", {"ticket": номер}).get("тикеты", [])
            политика = mcp.вызвать("support_policy")
        except ОшибкаMCP as e:
            ответ.ошибка = f"MCP: {e}"[:200]
            ответ.ответ = ("Не удалось получить данные вашей заявки — я передал её специалисту поддержки, "
                           "он ответит здесь.")
            ответ.пометки.append("сервис-деск (MCP) недоступен — ответ без контекста тикета не даётся")
            ответ.решение = "передать_человеку"
            ответ.вызовы_mcp = list(mcp.вызовы)
            ответ.секунд["всего"] = round(time.monotonic() - старт, 2)
            return ответ
        ф = факты(тикет, заявитель, входы, история, политика)
        ответ.секунд["контекст"] = round(time.monotonic() - старт, 2)
        # 3. Поиск.
        т = time.monotonic()
        отметить("поиск", "FAQ и документация")
        фрагменты = [фр for фр, _ in self.база.найти(запрос_поиска(тикет, ф), ФРАГМЕНТОВ)]
        ответ.секунд["поиск"] = round(time.monotonic() - т, 2)
        # 4. Модель (повтор формата; запасная модель).
        т = time.monotonic()
        отметить("модель", self.модель)
        сообщения = [{"role": "system", "content": prompts.РОЛЬ},
                     {"role": "user", "content": prompts.сообщение(тикет, ф, фрагменты)}]
        данные = None
        модели = [self.модель] + ([ЗАПАСНАЯ] if self.локальная and self.модель != ЗАПАСНАЯ else [])
        for модель in модели:
            try:
                r = self._звать(ответ, модель, сообщения)
                try:
                    данные = разобрать(r.text)
                except (ValueError, json.JSONDecodeError):
                    r = self._звать(ответ, модель, сообщения + [{"role": "assistant", "content": r.text or ""},
                                                                {"role": "user", "content": prompts.ПОДСКАЗКА_ФОРМАТА}])
                    данные = разобрать(r.text)
                if модель != self.модель:
                    ответ.пометки.append(f"облако недоступно — ответила локальная модель {модель}")
                break
            except Exception as e:  # noqa: BLE001 — сбой модели не должен терять тикет
                ответ.ошибка = f"{модель}: {type(e).__name__}: {str(e)[:150]}"
                continue
        ответ.секунд["модель"] = round(time.monotonic() - т, 2)
        if данные is None:
            ответ.ответ = ("ИИ-помощник сейчас недоступен — я передал вашу заявку специалисту поддержки, "
                           "он ответит здесь.")
            ответ.пометки.append("модель недоступна — передано специалисту")
            ответ.решение = "передать_человеку"
        else:
            # 5. Проверка кодом.
            ответ.ответ = str(данные.get("ответ")).strip()
            проверить(данные, ф, фрагменты, ответ)
        ответ.ответ, скрыто = pd.скрыть(ответ.ответ, профиль="точный")
        ответ.скрыто_пд = sum(скрыто.values())
        # 6. Итог в тикет — через MCP.
        отметить("тикет", "ответ, статус, заявка")
        try:
            mcp.вызвать("support_reply", {
                "ticket": номер, "text": ответ.ответ, "decision": ответ.решение, "facts": ответ.факты,
                "sources": [f"{и['источник']} › {и['раздел']}"[:200] for и in ответ.источники]})
            if ответ.решение == "предложить_действие" and ответ.действие:
                ответ.заявка = mcp.вызвать("support_request_action", {
                    "ticket": номер, "action": ответ.действие["вид"],
                    "reason": str(ответ.действие.get("причина") or "по фактам тикета")[:300]})
                ответ.статус = "Ждёт подтверждения действия"
            else:
                ответ.статус = mcp.вызвать("support_set_status", {"ticket": номер,
                                                                   "status": СТАТУС[ответ.решение]})["статус"]
        except ОшибкаMCP as e:
            ответ.ошибка = f"MCP запись: {e}"[:200]
            ответ.пометки.append("ответ не записан в тикет — сервис-деск недоступен")
        ответ.вызовы_mcp = list(mcp.вызовы)
        ответ.секунд["всего"] = round(time.monotonic() - старт, 2)
        return ответ
