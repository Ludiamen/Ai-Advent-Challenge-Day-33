"""Данные мини-сервис-деска поддержки: пользователи, входы, тикеты, заявки (День 33, FR-01, plan D-01).

Источник — `support-seed.json` в репозитории (синтетика по схеме servicedesk.Ticket CRM), рабочая
копия — `memory/support/desk.json` (вне git). Запись атомарная (`os.replace`) под файловой
блокировкой: сервис, MCP-сервер и консоль — разные процессы над одним файлом.

Здесь же правила, общие для всех входов:
- переходы статусов (кто какой статус может поставить);
- заявки на действия над учётной записью: модель их только заводит, выполняет сотрудник —
  `выполнить_заявку` меняет состояние учётной записи и пишет заявителю сообщение.
"""

from __future__ import annotations

import copy
import fcntl
import json
import os
import time
from contextlib import contextmanager
from typing import Any, Iterator

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SEED = os.path.join(КОРЕНЬ, "support-seed.json")

# Кто какой статус может поставить. Ассистент — только «свои» статусы ИИ и ожидание ответа.
СТАТУСЫ_ИИ = ("Ждёт ответа заявителя", "Передан специалисту", "Ждёт подтверждения действия")
СТАТУСЫ_СОТРУДНИКА = ("Новая", "В работе", "Ждёт ответа заявителя", "Передан специалисту",
                      "Ждёт подтверждения действия", "Решена")
ДЕЙСТВИЯ = ("разблокировать", "сбросить_второй_фактор", "новые_резервные_коды", "новое_приглашение",
            "ссылка_пароля", "закрыть_сессии")
АВТОРЫ = ("заявитель", "ассистент", "исполнитель", "система")


class ОшибкаДанных(ValueError):
    """Нет такого тикета, недопустимый переход, чужие данные — понятный отказ."""


def путь_по_умолчанию() -> str:
    память = os.path.abspath(os.getenv("MEMORY_DIR") or os.path.join(КОРЕНЬ, "memory"))
    return os.getenv("SUPPORT_DATA") or os.path.join(память, "support", "desk.json")


def сейчас() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%S")


class Хранилище:
    def __init__(self, путь: str = "", seed: str = SEED) -> None:
        self.путь = os.path.abspath(путь or путь_по_умолчанию())
        self.seed = seed

    # --- файл ---------------------------------------------------------------------

    def сбросить(self) -> dict[str, Any]:
        with open(self.seed, encoding="utf-8") as f:
            данные = json.load(f)
        with self._блок():
            self._записать(данные)
        return данные

    def _читать(self) -> dict[str, Any]:
        if not os.path.exists(self.путь):
            with open(self.seed, encoding="utf-8") as f:
                данные = json.load(f)
            self._записать(данные)
            return данные
        with open(self.путь, encoding="utf-8") as f:
            return json.load(f)

    def _записать(self, данные: dict[str, Any]) -> None:
        os.makedirs(os.path.dirname(self.путь), exist_ok=True)
        временный = f"{self.путь}.{os.getpid()}.tmp"
        with open(временный, "w", encoding="utf-8") as f:
            json.dump(данные, f, ensure_ascii=False, indent=1)
        os.replace(временный, self.путь)

    @contextmanager
    def _блок(self) -> Iterator[None]:
        os.makedirs(os.path.dirname(self.путь), exist_ok=True)
        with open(self.путь + ".lock", "a") as замок:
            fcntl.flock(замок, fcntl.LOCK_EX)
            try:
                yield
            finally:
                fcntl.flock(замок, fcntl.LOCK_UN)

    @contextmanager
    def изменение(self) -> Iterator[dict[str, Any]]:
        """Прочитать, изменить, записать — под одной блокировкой."""
        with self._блок():
            данные = self._читать()
            yield данные
            self._записать(данные)

    def снимок(self) -> dict[str, Any]:
        with self._блок():
            return self._читать()

    # --- чтение ---------------------------------------------------------------------

    @staticmethod
    def _тикет(данные: dict[str, Any], номер: int) -> dict[str, Any]:
        for т in данные["тикеты"]:
            if т["номер"] == int(номер):
                return т
        raise ОшибкаДанных(f"тикета №{номер} нет")

    @staticmethod
    def _пользователь(данные: dict[str, Any], ид: str) -> dict[str, Any]:
        for п in данные["пользователи"]:
            if п["id"] == ид:
                return п
        raise ОшибкаДанных(f"пользователя {ид} нет")

    def тикет(self, номер: int) -> dict[str, Any]:
        return copy.deepcopy(self._тикет(self.снимок(), номер))

    def пользователь(self, ид: str) -> dict[str, Any]:
        return copy.deepcopy(self._пользователь(self.снимок(), ид))

    def заявитель(self, номер: int) -> dict[str, Any]:
        данные = self.снимок()
        return copy.deepcopy(self._пользователь(данные, self._тикет(данные, номер)["заявитель"]))

    def входы(self, ид: str, сколько: int = 10) -> list[dict[str, Any]]:
        записи = [в for в in self.снимок()["входы"] if в["пользователь"] == ид]
        return sorted(записи, key=lambda в: в["время"], reverse=True)[:max(1, min(int(сколько), 50))]

    def тикеты_пользователя(self, ид: str) -> list[dict[str, Any]]:
        return [copy.deepcopy(т) for т in self.снимок()["тикеты"] if т["заявитель"] == ид]

    def очередь(self, статусы: tuple[str, ...] = ()) -> list[dict[str, Any]]:
        тикеты = [т for т in self.снимок()["тикеты"] if not статусы or т["статус"] in статусы]
        return sorted(тикеты, key=lambda т: (т["вид"] == "closed", т.get("создана", "")), reverse=False)

    def заявки(self, статус: str = "") -> list[dict[str, Any]]:
        return [з for з in self.снимок().get("заявки", []) if not статус or з["статус"] == статус]

    def политика(self) -> dict[str, Any]:
        """Политика портала и «сейчас» данных: у демо-набора время зафиксировано (`сейчас` в seed),
        чтобы «блокировка до 09:29» читалась одинаково в любой день показа."""
        с = self.снимок()
        return {**с["справочники"]["политика"], "сейчас": с.get("сейчас") or сейчас()}

    # --- запись ---------------------------------------------------------------------

    def создать_тикет(self, ид: str, тема: str, текст: str, категория: str = "Вход и доступ") -> dict[str, Any]:
        with self.изменение() as данные:
            self._пользователь(данные, ид)
            номер = int(данные.get("следующий_номер", 1))
            данные["следующий_номер"] = номер + 1
            т = {"номер": номер, "тема": (тема or текст)[:120], "заявитель": ид, "категория": категория,
                 "критичность": "Обычная", "статус": "Новая", "вид": "new", "создана": сейчас(), "решение": "",
                 "сообщения": [{"автор": "заявитель", "время": сейчас(), "текст": текст}]}
            данные["тикеты"].append(т)
            return copy.deepcopy(т)

    def добавить_сообщение(self, номер: int, автор: str, текст: str, **поля: Any) -> dict[str, Any]:
        if автор not in АВТОРЫ:
            raise ОшибкаДанных(f"автор — один из {АВТОРЫ}")
        with self.изменение() as данные:
            т = self._тикет(данные, номер)
            сообщение = {"автор": автор, "время": сейчас(), "текст": текст, **поля}
            т["сообщения"].append(сообщение)
            if автор == "заявитель" and т["вид"] == "closed":
                т["статус"], т["вид"] = "В работе", "in_progress"      # открыта заново (сценарий 5 CRM)
            return copy.deepcopy(сообщение)

    def сменить_статус(self, номер: int, статус: str, кто: str = "ассистент") -> dict[str, Any]:
        разрешено = СТАТУСЫ_ИИ if кто == "ассистент" else СТАТУСЫ_СОТРУДНИКА
        if статус not in разрешено:
            raise ОшибкаДанных(f"«{статус}» не может поставить {кто}; можно: {', '.join(разрешено)}")
        with self.изменение() as данные:
            т = self._тикет(данные, номер)
            if т["вид"] == "closed" and кто == "ассистент":
                raise ОшибкаДанных("закрытый тикет ассистент не меняет")
            вид = next(с["вид"] for с in данные["справочники"]["статусы"] if с["название"] == статус)
            т["статус"], т["вид"] = статус, вид
            return copy.deepcopy(т)

    def закрыть(self, номер: int, решение: str, кто: str = "исполнитель") -> dict[str, Any]:
        if not (решение or "").strip():
            raise ОшибкаДанных("закрыть можно только с текстом решения (сценарий 5 CRM)")
        with self.изменение() as данные:
            т = self._тикет(данные, номер)
            т.update({"статус": "Решена", "вид": "closed", "решение": решение.strip(), "закрыта": сейчас(), "закрыл": кто})
            т["сообщения"].append({"автор": "исполнитель", "время": сейчас(), "текст": f"Заявка решена: {решение.strip()}"})
            return copy.deepcopy(т)

    def завести_заявку(self, номер: int, вид: str, причина: str, кто: str = "ассистент") -> dict[str, Any]:
        if вид not in ДЕЙСТВИЯ:
            raise ОшибкаДанных(f"действие — одно из {ДЕЙСТВИЯ}")
        with self.изменение() as данные:
            т = self._тикет(данные, номер)
            for з in данные.setdefault("заявки", []):
                if з["тикет"] == т["номер"] and з["вид"] == вид and з["статус"] == "ждёт подтверждения":
                    return copy.deepcopy(з)                                  # повтор не плодит заявки
            з = {"id": f"z{len(данные['заявки']) + 1:03d}", "тикет": т["номер"], "пользователь": т["заявитель"],
                 "вид": вид, "причина": причина[:300], "статус": "ждёт подтверждения", "завёл": кто, "создана": сейчас()}
            данные["заявки"].append(з)
            т["статус"], т["вид"] = "Ждёт подтверждения действия", "in_progress"
            return copy.deepcopy(з)

    def выполнить_заявку(self, ид: str, кто: str) -> dict[str, Any]:
        """Сотрудник подтвердил: действие над учётной записью + сообщение заявителю."""
        with self.изменение() as данные:
            з = next((з for з in данные.get("заявки", []) if з["id"] == ид), None)
            if з is None:
                raise ОшибкаДанных(f"заявки {ид} нет")
            if з["статус"] != "ждёт подтверждения":
                raise ОшибкаДанных(f"заявка {ид} уже {з['статус']}")
            уз = self._пользователь(данные, з["пользователь"])["учётная_запись"]
            политика = данные["справочники"]["политика"]
            вид = з["вид"]
            if вид == "разблокировать":
                уз["статус"], уз["блокировка"] = "активна", None
                текст = "Блокировка входа снята сотрудником поддержки — можно входить."
            elif вид == "сбросить_второй_фактор":
                уз["второй_фактор"], уз["резервных_кодов"] = "сброшен", 0
                текст = ("Второй фактор сброшен. При следующем входе по паролю портал проведёт вас через подключение "
                         "нового второго фактора и выдаст новые резервные коды; письмо о сбросе отправлено.")
            elif вид == "новые_резервные_коды":
                уз["резервных_кодов"] = политика["резервных_кодов"]
                текст = "Выпущен новый набор резервных кодов — старые больше не действуют. Сохраните новые коды."
            elif вид == "новое_приглашение":
                уз["приглашение"] = {"отправлено": сейчас(), "действует_до": "через 72 часа"}
                текст = "Отправлено новое приглашение: ссылка действует 72 часа, прежняя больше не работает."
            elif вид == "ссылка_пароля":
                текст = "Отправлена ссылка восстановления пароля: она действует 1 час."
            else:
                уз["последняя_сессия"] = {"завершена": сейчас(), "причина": "сессии закрыты сотрудником"}
                текст = "Сессии на всех устройствах закрыты. Войдите заново и смените пароль."
            з.update({"статус": "выполнена", "выполнил": кто, "выполнена": сейчас()})
            т = self._тикет(данные, з["тикет"])
            т["сообщения"].append({"автор": "исполнитель", "время": сейчас(), "текст": текст, "заявка": ид})
            т["статус"], т["вид"] = "Ждёт ответа заявителя", "waiting"
            return copy.deepcopy(з)

    def отклонить_заявку(self, ид: str, кто: str, причина: str) -> dict[str, Any]:
        with self.изменение() as данные:
            з = next((з for з in данные.get("заявки", []) if з["id"] == ид), None)
            if з is None:
                raise ОшибкаДанных(f"заявки {ид} нет")
            if з["статус"] != "ждёт подтверждения":
                raise ОшибкаДанных(f"заявка {ид} уже {з['статус']}")
            з.update({"статус": "отклонена", "выполнил": кто, "причина_отказа": причина[:300], "выполнена": сейчас()})
            т = self._тикет(данные, з["тикет"])
            т["статус"], т["вид"] = "В работе", "in_progress"
            return copy.deepcopy(з)
