"""Жизненный цикл тикета: чат пользователя и пульт сотрудника над одними данными (День 33, FR-06, FR-07, plan D-06).

Пользователь:
- пишет без номера тикета — создаётся тикет («Новая»), ИИ отвечает первым;
- пишет в свой тикет — сообщение в ленту; ИИ отвечает, если тикет не у человека (статусы
  «Передан специалисту» и «В работе» — ждут сотрудника; закрытый тикет открывается заново и
  тоже уходит к сотруднику);
- видит только свои тикеты (чужой номер — «тикета нет», а не «чужой»: не подсказываем, что он есть);
- оценивает ответ ассистента 👍/👎.

Сотрудник (пульт): очередь, тикет с профилем и входами, заявки — выполнить (действие над
учётной записью и сообщение заявителю) или отклонить с причиной, ответить, закрыть с решением,
вернуть тикет ИИ (ИИ отвечает на последнее сообщение заявителя).

ИИ меняет статус только через MCP-сервер `support` (assistant.py); здесь — то, что делает человек.
"""

from __future__ import annotations

import copy
from typing import Any, Callable

from agent.support import data, metrics
from agent.support.assistant import Ассистент, ОтветПоддержки

У_ЧЕЛОВЕКА = ("Передан специалисту", "В работе")


class ОшибкаДоступа(PermissionError):
    pass


class СервисДеск:
    def __init__(self, хранилище: data.Хранилище, ассистент: Ассистент | None, канал: str = "веб",
                 журнал: str = "") -> None:
        self.х = хранилище
        self.ассистент = ассистент
        self.канал = канал
        self.журнал = журнал

    # --- пользователь ----------------------------------------------------------------------------

    def мои_тикеты(self, пользователь: str) -> list[dict[str, Any]]:
        return sorted(self.х.тикеты_пользователя(пользователь), key=lambda т: т.get("создана", ""), reverse=True)

    def тикет_пользователя(self, пользователь: str, номер: int) -> dict[str, Any]:
        try:
            т = self.х.тикет(номер)
        except data.ОшибкаДанных:
            т = None
        if т is None or т["заявитель"] != пользователь:
            raise ОшибкаДоступа(f"тикета №{номер} нет")
        return т

    def написать(self, пользователь: str, текст: str, номер: int | None = None,
                 этап: Callable[[str, str], None] | None = None) -> dict[str, Any]:
        текст = (текст or "").strip()
        if not текст:
            raise ValueError("пустое сообщение")
        if номер is None:
            т = self.х.создать_тикет(пользователь, текст.split("\n")[0][:80], текст[:4000],
                                     категория="Вход и доступ" if self._про_вход(текст) else "Другое")
            номер = т["номер"]
        else:
            self.тикет_пользователя(пользователь, номер)
            self.х.добавить_сообщение(номер, "заявитель", текст[:4000])
        т = self.х.тикет(номер)
        ответ: ОтветПоддержки | None = None
        if т["статус"] not in У_ЧЕЛОВЕКА and self.ассистент is not None:
            ответ = self.ассистент.ответить(номер, этап=этап)
            self._метрика(ответ)
        return {"тикет": self.х.тикет(номер), "ответ": ответ.to_dict() if ответ else None,
                "ждёт_человека": ответ is None}

    @staticmethod
    def _про_вход(текст: str) -> bool:
        т = текст.lower()
        return any(с in т for с in ("вход", "войти", "авториз", "пароль", "блокир", "код", "второй фактор", "ссылк"))

    def оценить(self, пользователь: str, номер: int, оценка: int) -> dict[str, Any]:
        self.тикет_пользователя(пользователь, номер)
        оценка = 1 if оценка > 0 else -1
        with self.х.изменение() as д:
            т = next(т for т in д["тикеты"] if т["номер"] == номер)
            ответы = [с for с in т["сообщения"] if с["автор"] == "ассистент"]
            if not ответы:
                raise ValueError("ответа ассистента в тикете ещё нет")
            ответы[-1]["оценка"] = оценка
        metrics.записать({"канал": self.канал, "событие": "оценка", "тикет": номер, "оценка": оценка}, self.журнал)
        return {"тикет": номер, "оценка": оценка}

    # --- пульт ---------------------------------------------------------------------------------

    def очередь(self, статус: str = "") -> list[dict[str, Any]]:
        заявки = {з["тикет"] for з in self.х.заявки("ждёт подтверждения")}
        итог = []
        for т in self.х.очередь((статус,) if статус else ()):
            последнее = т["сообщения"][-1] if т["сообщения"] else {}
            итог.append({"номер": т["номер"], "тема": т["тема"], "статус": т["статус"], "вид": т["вид"],
                         "заявитель": т["заявитель"], "категория": т.get("категория", ""), "создана": т.get("создана", ""),
                         "последнее": {"автор": последнее.get("автор"), "время": последнее.get("время")},
                         "заявка": т["номер"] in заявки})
        порядок = {"Ждёт подтверждения действия": 0, "Передан специалисту": 1, "Новая": 2, "В работе": 3,
                   "Ждёт ответа заявителя": 4}
        return sorted(итог, key=lambda т: (т["вид"] == "closed", порядок.get(т["статус"], 9), т["создана"]))

    def карточка(self, номер: int) -> dict[str, Any]:
        т = self.х.тикет(номер)
        п = self.х.пользователь(т["заявитель"])
        return {"тикет": т, "заявитель": п, "входы": self.х.входы(п["id"], 10) if п.get("учётная_запись") else [],
                "заявки": [з for з in self.х.заявки() if з["тикет"] == номер],
                "история": [{к: x.get(к) for к in ("номер", "тема", "статус", "решение")}
                            for x in self.х.тикеты_пользователя(п["id"]) if x["номер"] != номер]}

    def заявки(self, статус: str = "ждёт подтверждения") -> list[dict[str, Any]]:
        return self.х.заявки(статус)

    def подтвердить(self, заявка: str, сотрудник: str) -> dict[str, Any]:
        з = self.х.выполнить_заявку(заявка, сотрудник)
        metrics.записать({"канал": self.канал, "событие": "заявка", "тикет": з["тикет"], "действие": з["вид"],
                          "итог": "выполнена"}, self.журнал)
        return з

    def отклонить(self, заявка: str, сотрудник: str, причина: str) -> dict[str, Any]:
        з = self.х.отклонить_заявку(заявка, сотрудник, причина or "отклонено сотрудником")
        metrics.записать({"канал": self.канал, "событие": "заявка", "тикет": з["тикет"], "действие": з["вид"],
                          "итог": "отклонена"}, self.журнал)
        return з

    def ответить(self, номер: int, текст: str, сотрудник: str) -> dict[str, Any]:
        self.х.добавить_сообщение(номер, "исполнитель", текст, сотрудник=сотрудник)
        return self.х.сменить_статус(номер, "Ждёт ответа заявителя", сотрудник)

    def взять(self, номер: int, сотрудник: str) -> dict[str, Any]:
        return self.х.сменить_статус(номер, "В работе", сотрудник)

    def закрыть(self, номер: int, решение: str, сотрудник: str) -> dict[str, Any]:
        return self.х.закрыть(номер, решение, сотрудник)

    def вернуть_ии(self, номер: int, сотрудник: str,
                   этап: Callable[[str, str], None] | None = None) -> dict[str, Any]:
        """Сотрудник возвращает тикет ИИ: ассистент отвечает на последнее сообщение заявителя."""
        self.х.сменить_статус(номер, "Ждёт ответа заявителя", сотрудник)
        ответ = self.ассистент.ответить(номер, этап=этап) if self.ассистент else None
        if ответ:
            self._метрика(ответ)
        return {"тикет": self.х.тикет(номер), "ответ": ответ.to_dict() if ответ else None}

    def _метрика(self, ответ: ОтветПоддержки) -> None:
        try:
            metrics.записать({"канал": self.канал, "событие": "ответ", **ответ.метрики()}, self.журнал)
        except OSError:
            pass


def копия(т: dict[str, Any]) -> dict[str, Any]:
    return copy.deepcopy(т)
