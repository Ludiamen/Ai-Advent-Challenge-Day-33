"""Метрики поддержки — без текстов (День 33, FR-11).

События: «ответ» (решение ИИ, факты, источники, токены, время), «заявка» (выполнена /
отклонена), «оценка» (👍/👎). Сводка — то, что лекция недели 7 называет метриками AI-сервиса:
время (p50/p95), стоимость, доля решённых ИИ без человека (ответ или уточнение), доля передач
человеку, доля подтверждённых заявок, доля 👍.
"""

from __future__ import annotations

import json
import os
import statistics
import threading
import time
from typing import Any, Iterable

from agent.devassist.metrics import перцентиль

ПОЛЯ = ("время", "канал", "событие", "тикет", "решение", "действие", "фактов", "источников", "цитат_подтверждено",
        "модель", "токены_вход", "токены_выход", "стоимость", "секунд", "пометок", "ошибка", "итог", "оценка")
_замок = threading.Lock()


def путь_по_умолчанию() -> str:
    """Рядом с данными сервис-деска (как журнал запросов): у копии данных — свои метрики."""
    from agent.support.data import путь_по_умолчанию as путь_данных
    return os.path.join(os.path.dirname(путь_данных()), "metrics.jsonl")


def записать(строка: dict[str, Any], путь: str = "") -> dict[str, Any]:
    путь = путь or путь_по_умолчанию()
    чисто = {к: строка[к] for к in ПОЛЯ if к in строка}
    чисто.setdefault("время", time.strftime("%Y-%m-%dT%H:%M:%S"))
    if isinstance(чисто.get("ошибка"), str):
        чисто["ошибка"] = чисто["ошибка"][:120]
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    with _замок, open(путь, "a", encoding="utf-8") as f:
        f.write(json.dumps(чисто, ensure_ascii=False) + "\n")
    return чисто


def прочитать(путь: str = "") -> list[dict[str, Any]]:
    try:
        with open(путь or путь_по_умолчанию(), encoding="utf-8") as f:
            return [json.loads(с) for с in f if с.strip()]
    except (OSError, json.JSONDecodeError):
        return []


def сводка(строки: Iterable[dict[str, Any]]) -> dict[str, Any]:
    строки = list(строки)
    ответы = [с for с in строки if с.get("событие") == "ответ"]
    заявки = [с for с in строки if с.get("событие") == "заявка"]
    оценки = [с["оценка"] for с in строки if с.get("событие") == "оценка"]
    секунды = [float((с.get("секунд") or {}).get("всего", 0)) for с in ответы]
    решения: dict[str, int] = {}
    for с in ответы:
        решения[с.get("решение", "?")] = решения.get(с.get("решение", "?"), 0) + 1
    n = len(ответы) or 1
    return {
        "ответов": len(ответы), "решения": решения,
        "сам_ИИ": round((решения.get("ответ", 0) + решения.get("уточнить", 0)) / n, 3) if ответы else 0.0,
        "передано_человеку": round(решения.get("передать_человеку", 0) / n, 3) if ответы else 0.0,
        "заявок_предложено": решения.get("предложить_действие", 0),
        "заявок_выполнено": sum(1 for з in заявки if з.get("итог") == "выполнена"),
        "заявок_отклонено": sum(1 for з in заявки if з.get("итог") == "отклонена"),
        "p50_с": round(перцентиль(секунды, 0.5), 2), "p95_с": round(перцентиль(секунды, 0.95), 2),
        "токенов_на_ответ": round(statistics.mean([с.get("токены_вход", 0) + с.get("токены_выход", 0) for с in ответы])) if ответы else 0,
        "стоимость_на_ответ": round(statistics.mean([с.get("стоимость", 0) for с in ответы]), 5) if ответы else 0.0,
        "оценок": len(оценки), "доля_👍": round(sum(1 for о in оценки if о > 0) / len(оценки), 3) if оценки else None,
        "ошибок": sum(1 for с in ответы if с.get("ошибка")),
    }
