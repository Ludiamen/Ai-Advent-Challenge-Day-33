def условия(отвечатель=None) -> dict[str, Any]:
    """Чем и на чём мерили: модели, квантование, окно, температура, профиль, машина."""
    from agent import catalog
    from agent.local import offline, ollama
    from agent.rag import profile as rag_profile
    итог: dict[str, Any] = {"когда": datetime.now().isoformat(timespec="seconds")}
    try:
        итог["ollama"] = ollama.версия()
        скачанные = {м["name"]: м for м in ollama.модели()}
    except Exception:   # noqa: BLE001 — отчёт пишется и без Ollama
        итог["ollama"], скачанные = "", {}
    модели = {}
    for у in УЧАСТНИКИ:
        м = catalog.get(у.модель)
        if м.local:
            с = скачанные.get(м.api_id, {})
            модели[у.модель] = {"id": м.api_id, "params": с.get("params", ""), "quant": с.get("quant", ""),
                               "digest": с.get("digest", ""), "num_ctx": 8192,
                               "температура": offline.параметры_роли("ответ-по-документам").температура}
        else:
            # Облаку карта ролей не указ: температура — клиента (по умолчанию 0,2).
            клиент = getattr(отвечатель, "клиент", None)
            модели[у.модель] = {"id": м.api_id, "провайдер": м.provider,
                               "температура": getattr(клиент, "temperature", None)}
    итог["модели"] = модели
    итог["судья"] = СУДЬЯ
    if отвечатель is not None:
        итог["профиль"] = rag_profile.локальный(отвечатель.поисковик).to_dict()
        итог["индекс"] = {"стратегия": отвечатель.стратегия}
    try:
        итог["машина"] = {"нагрузка": " / ".join(f"{з:.1f}" for з in os.getloadavg())}
        with open("/proc/meminfo", encoding="utf-8") as f:
            память = {с.split(":")[0]: int(с.split()[1]) for с in f if ":" in с}
        итог["машина"]["свободно_гб"] = round(память.get("MemAvailable", 0) / 1024 / 1024, 1)
        итог["машина"]["подкачка_занята_гб"] = round(
            (память.get("SwapTotal", 0) - память.get("SwapFree", 0)) / 1024 / 1024, 1)
    except OSError:
        итог["машина"] = {}
    return итог


def _ч(з: Any, знаков: int = 1) -> str:
    if з is None:
        return "—"
    if isinstance(з, float):
        return f"{з:.{знаков}f}".replace(".", ",")
    return str(з)


