"""Локальный RAG рядом с облаком (День 28): качество, скорость, стабильность.

Задание дня: подключить локальную LLM к RAG-пайплайну (индекс недели RAG,
поиск локально, генерация локально), сравнить ответы с облачной моделью и
оценить качество, скорость и стабильность. Здесь — сравнение. Сам локальный
конвейер — это профиль (profile.py) у прежнего Отвечателя.

Участники (выбор владельца, spec § 5):

  лок-4b         локальный профиль, qwen3.5:4b
  лок-1.7b       локальный профиль, qwen3:1.7b
  облако-тот-же  те же фрагменты, ds-flash — разница только в генерации
  облако-лучшее  «фильтр» Дня 24 (LLM-реранкер облака), ds-flash — система
                 против системы

У первых трёх поиск выполняется ОДИН раз на вопрос и повтор, и его результат —
вместе с лучшими окнами фрагментов — получают все трое. Так у них одинаковые
фрагменты и одно решение порога «не знаю», а расходиться они могут только в
ответе модели.

Прогон: каждый вопрос — по 3 повтора (повтор → вопрос → участники вперемешку,
чтобы все отвечали при одной и той же нагрузке машины). Повтор 1 — «новый
вопрос»: оценки кросс-энкодера не берутся из кэша, промпт модель видит
впервые. Повторы 2–3 — с живыми кэшами; у qwen3.5 Ollama восстанавливает
промпт из сохранённой точки, и это видно в замерах (кэш_промпта).

Каждый ответ сразу дописывается строкой в журнал JSONL. Прерванный прогон
продолжается с места: готовые тройки «вопрос|участник|повтор» не пересчитываются
(сессия работы уже обрывалась посреди долгих прогонов).

Качество — проверки кодом Дня 24 (citecheck.проверить) и судья ds-pro, один
на всех: он сам не отвечает (ds-flash — участник, а судья не оценивает свои
ответы). Определения метрик — spec § 6.2, они же в сводка().

Публичное API:
  УЧАСТНИКИ, участники(коды), вопросы(контроль, расплывчатые, ids)
  общий_поиск(отвечатель, вопрос, профиль, без_кэша) -> Подготовка
  рядом(отвечатель, вопрос, участники, судья, без_кэша, ход) -> [запись]
  Прогон(каталог, метка, вопросы, участники, повторов, судья).выполнить(отвечатель)
  пересудить(прогон, клиент, модель)
  сводка(записи, вопросы, участники, повторов) -> dict
  условия(отвечатель) -> dict, в_markdown(сводка, записи, условия) -> str
  записать(каталог_индекса, сводка, записи, условия, в_корень) -> (md, json); отчёт_в_корень(каталог)
  отметить(память, вопрос_id, участник, оценка, заметка), отметки(память)
"""

