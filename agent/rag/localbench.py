def _норм(текст: str) -> str:
    return re.sub(r"\s+", " ", (текст or "").strip().lower())


def _статистика(значения: list[float]) -> dict[str, Any]:
    числа = [float(з) for з in значения if з is not None]
    if not числа:
        return {"медиана": None, "мин": None, "макс": None, "n": 0}
    return {"медиана": round(statistics.median(числа), 2), "мин": round(min(числа), 2),
            "макс": round(max(числа), 2), "n": len(числа)}


def _скорость(записи: list[dict]) -> dict[str, Any]:
    итог: dict[str, Any] = {м: _статистика([з["ответ"]["timings"].get(м) for з in записи])
                            for м in МЕТРИКИ_СКОРОСТИ}
    итог["из_кэша"] = sum(з["ответ"]["timings"].get("кэш_промпта") is True for з in записи)
    итог["ответов"] = len(записи)
    return итог


def _признаки(з: dict) -> tuple:
    return (з["верно"], з["ответ"]["abstain"], з["ответ"]["abstain_by"] if з["ответ"]["abstain"] else "",
            tuple(з["проверка"].get("facts_found") or []))


def сводка(записи: list[dict], вопросы_: list[dict], участники_: list[Участник], повторов: int) -> dict:
    всего = len(вопросы_) * len(участники_) * повторов
    по_участнику: dict[str, Any] = {}
    for у in участники_:
        свои = [з for з in записи if з["участник"] == у.код]
        по_повтору = [[з for з in свои if з["повтор"] == п] for п in range(1, повторов + 1)]
        верно_по = [sum(з["верно"] for з in пп) for пп in по_повтору]
        есть = [в for в, пп in zip(верно_по, по_повтору) if пп]
        с_ответом = [з for з in свои if з["вид"] == citecheck.С_ОТВЕТОМ]
        качество = {
            "верно_по_повторам": верно_по,
            "верно_в_среднем": round(statistics.mean(есть), 2) if есть else 0.0,
            "вопросов": len({з["вопрос_id"] for з in свои}),
            "с_ответом": len(с_ответом),
            "отвечено": sum(not з["ответ"]["abstain"] and not з["ошибка"] for з in с_ответом),
            "лишние_не_знаю": sum(з["ответ"]["abstain"] for з in с_ответом),
            "ловушки_не_знаю": sum(з["верно"] for з in свои if з["вид"] == citecheck.ЛОВУШКА),
            "ловушек": sum(з["вид"] == citecheck.ЛОВУШКА for з in свои),
            "расплывчатые_не_знаю": sum(з["верно"] for з in свои if з["вид"] == citecheck.РАСПЛЫВЧАТЫЙ),
            "расплывчатых": sum(з["вид"] == citecheck.РАСПЛЫВЧАТЫЙ for з in свои),
            "смысл_да": sum((з.get("судья") or {}).get("смысл") == "да" for з in свои),
            "смысл_частично": sum((з.get("судья") or {}).get("смысл") == "частично" for з in свои),
            "смысл_нет": sum((з.get("судья") or {}).get("смысл") == "нет" for з in свои),
            "судимо": sum(bool((з.get("судья") or {}).get("смысл")) for з in свои),
            "цитат_подтверждено": sum(з["проверка"].get("confirmed") or 0 for з in свои),
            "цитат_дословно": sum(з["проверка"].get("verbatim") or 0 for з in свои),
        }
        вопросы_у = sorted({з["вопрос_id"] for з in свои})
        стабильных = дословно = 0
        кв: list[float] = []
        for вид in вопросы_у:
            ряд = sorted((з for з in свои if з["вопрос_id"] == вид), key=lambda з: з["повтор"])
            if len(ряд) < 2:
                continue
            стабильных += len({_признаки(з) for з in ряд}) == 1
            дословно += len({_норм(з["ответ"]["text"]) for з in ряд}) == 1
            времена = [з["ответ"]["timings"].get("всего_с") for з in ряд]
            времена = [в for в in времена if в]
            if len(времена) >= 2 and statistics.mean(времена):
                кв.append(statistics.pstdev(времена) / statistics.mean(времена))
        стабильность = {
            "вопросов": sum(1 for вид in вопросы_у if sum(з["вопрос_id"] == вид for з in свои) >= 2),
            "стабильных": стабильных, "дословно": дословно,
            "ответов": len(свои), "починок": sum(bool(з["ответ"]["repaired"]) for з in свои),
            "не_починено": sum(bool(з["ответ"]["violations"]) for з in свои if not з["ответ"]["abstain"]),
            "ошибок": sum(bool(з["ошибка"]) for з in свои),
            "разброс": {"кв_медиана": round(statistics.median(кв), 2) if кв else None,
                        "кв_макс": round(max(кв), 2) if кв else None},
        }
        по_участнику[у.код] = {
            "участник": у.to_dict(), "качество": качество,
            "скорость": {"новый": _скорость([з for з in свои if з["новый"]]),
                         "повтор": _скорость([з for з in свои if not з["новый"]])},
            "стабильность": стабильность,
            "сеть": {"внешних": sum((з.get("сеть") or {}).get("внешних", 0) for з in свои),
                     "локальных": sum((з.get("сеть") or {}).get("локальных", 0) for з in свои),
                     "внешних_поиска": sum((з.get("сеть_поиска") or {}).get("внешних", 0) for з in свои)},
            "стоимость": round(sum(з["ответ"].get("cost") or 0 for з in свои), 4),
        }
    по_вопросам = []
    for в in вопросы_:
        строка: dict[str, Any] = {"id": в.get("id", ""), "вид": в.get("вид", ""), "вопрос": в["вопрос"],
                                  "ожидание": в.get("ожидание", "")}
        for у in участники_:
            ряд = sorted((з for з in записи if з["участник"] == у.код and з["вопрос_id"] == в.get("id")),
                         key=lambda з: з["повтор"])
            строка[у.код] = {"верно": [з["верно"] for з in ряд],
                             "всего_с": [з["ответ"]["timings"].get("всего_с") for з in ряд],
                             "стабилен": len(ряд) >= 2 and len({_признаки(з) for з in ряд}) == 1}
        по_вопросам.append(строка)
    return {"завершён": len(записи) >= всего, "готово": len(записи), "всего": всего,
            "повторов": повторов, "участники": по_участнику, "по_вопросам": по_вопросам}


