def отметки(каталог_памяти: str) -> dict[tuple[str, str], dict]:
    """Последняя отметка на пару (вопрос, участник)."""
    from agent.local import bench
    итог = {}
    for з in bench.отметки(каталог_памяти).values():
        части = str(з.get("task", "")).split(":")
        if len(части) == 3 and части[0] == "rag":
            итог[(части[1], части[2])] = з
    return итог
