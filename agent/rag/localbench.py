@dataclass(frozen=True)
class Участник:
    код: str
    модель: str
    общий: bool            # получает общий локальный поиск или ищет сам
    подпись: str

    def to_dict(self) -> dict[str, Any]:
        from agent import catalog
        return {"код": self.код, "модель": self.модель, "общий": self.общий, "подпись": self.подпись,
                "локально": catalog.get(self.модель).local}


УЧАСТНИКИ = (
    Участник("лок-4b", "loc-qwen35", True, "локально · Qwen 3.5 4B"),
    Участник("лок-1.7b", "loc-qwen17", True, "локально · Qwen 3 1.7B"),
    Участник("облако-тот-же", "ds-flash", True, "облако · тот же поиск"),
    Участник("облако-лучшее", "ds-flash", False, "облако · лучший конвейер Дня 24"),
)


def участники(коды: list[str] | tuple[str, ...] | None = None) -> list[Участник]:
    if not коды:
        return list(УЧАСТНИКИ)
    по_коду = {у.код: у for у in УЧАСТНИКИ}
    чужие = [к for к in коды if к not in по_коду]
    if чужие:
        raise ValueError(f"Нет участника «{чужие[0]}». Есть: {', '.join(по_коду)}")
    return [по_коду[к] for к in коды]


def вопросы(путь_контроля: str = "", путь_расплывчатых: str = "",
            ids: list[str] | tuple[str, ...] | None = None) -> list[dict]:
    """Контрольные Дня 22 (8 с ответом и 2 ловушки) и расплывчатые Дня 24 — 14."""
    все = citecheck.загрузить_вопросы(путь_контроля, путь_расплывчатых)
    if not ids:
        return все
    по_id = {в.get("id"): в for в in все}
    чужие = [i for i in ids if i not in по_id]
    if чужие:
        raise ValueError(f"Нет вопроса «{чужие[0]}». Есть: {', '.join(по_id)}")
    return [по_id[i] for i in ids]


# --- общий поиск и ответ участника ---------------------------------------------------

@dataclass
class Подготовка:
    """Общий локальный поиск одного вопроса: отбор с окнами вместо длинных фрагментов."""

    профиль: Any
    отбор: Any
    окна: list[dict]
    секунд_окон: float
    сеть: dict[str, int]


def общий_поиск(отвечатель, вопрос: str, профиль=None, без_кэша: bool = False,
                ход: bool = False) -> Подготовка:
    from agent.local import offline, progress
    from agent.rag import profile as rag_profile
    профиль = профиль or rag_profile.локальный(отвечатель.поисковик)
    до = offline.снимок_журнала()
    отбор = отвечатель.поисковик.найти(вопрос, профиль.поиск, без_кэша=без_кэша)
    окна: list[dict] = []
    секунд_окон = 0.0
    if профиль.окно_фрагмента and отбор.фрагменты:
        # Окна выбираются один раз: все три участника общего поиска получают
        # одни и те же фрагменты, а кросс-энкодер не работает втрое дольше.
        временный = ОтветRAG(вопрос=вопрос, режим=С_RAG)
        отбор = replace(отбор, фрагменты=отвечатель._лучшие_окна(временный, отбор.фрагменты))
        окна, секунд_окон = временный.окна, временный.секунд_окон
    if ход:
        progress.этап("поиск", **сводка_поиска(отбор), окна=len(окна), окна_с=round(секунд_окон, 2))
    return Подготовка(профиль=профиль, отбор=отбор, окна=окна, секунд_окон=секунд_окон,
                      сеть=offline.разница(до, offline.снимок_журнала()))


def _ответить(отвечатель, участник: Участник, вопрос: str, подготовка: Подготовка | None,
              без_кэша: bool, ход: bool) -> tuple[ОтветRAG, dict[str, int], float]:
    from agent.local import offline
    from agent.rag import profile as rag_profile
    до = offline.снимок_журнала()
    старт = time.monotonic()
    if участник.общий:
        профиль = replace(подготовка.профиль, окно_фрагмента=False)
        ответ = отвечатель.ответить(вопрос, С_RAG, участник.модель, поиск=профиль.поиск, формат=ЦИТАТЫ,
                                    отбор=подготовка.отбор, профиль=профиль, ход=ход)
        ответ.окна = list(подготовка.окна)
        ответ.секунд_окон = подготовка.секунд_окон
    else:
        ответ = отвечатель.ответить(вопрос, С_RAG, участник.модель, формат=ЦИТАТЫ,
                                    профиль=rag_profile.облачный_дня24(), ход=ход, без_кэша=без_кэша)
    return ответ, offline.разница(до, offline.снимок_журнала()), time.monotonic() - старт


def _кратко(ответ: ОтветRAG) -> dict[str, Any]:
    """То, что нужно отчёту и сводке, без промптов и полных текстов фрагментов."""
    этап = (lambda имя: next((э for э in ответ.отбор.этапы if э.get("этап") == имя), {})) \
        if ответ.отбор is not None else (lambda имя: {})
    return {
        "text": ответ.текст, "abstain": ответ.не_знаю, "abstain_by": ответ.не_знаю_кто,
        "abstain_reason": ответ.причина_не_знаю, "clarification": ответ.уточнение,
        "sources": [{"n": и["n"], "source": и.get("source", ""), "section": и.get("section", ""),
                     "chunk_id": и.get("chunk_id", "")} for и in ответ.источники],
        "quotes": [ц.to_dict() for ц in ответ.выдержки],
        "violations": list(ответ.нарушения), "repaired": ответ.починка, "calls": ответ.вызовов,
        "error": ответ.ошибка, "profile": ответ.профиль, "search": ответ.поиск,
        "fragments": [н.чанк.chunk_id for н in ответ.фрагменты], "windows": list(ответ.окна),
        "selection_reranker": ответ.отбор.настройки.реранкер if ответ.отбор is not None else "",
        "selection_search": этап("поиск"), "selection_rerank": этап("реранк"),
        "confidence": ответ.решение.to_dict() if ответ.решение is not None else None,
        "tokens_in": ответ.токенов_вход, "tokens_out": ответ.токенов_выход,
        "cost": round(ответ.стоимость, 6), "timings": ответ.замеры(),
    }


def верно(п) -> bool:
    """spec § 6.2: на вопрос с ответом — ответ дан, источники полные, нужный среди
    них, цитата подтверждена, числа в цитатах, факты найдены; иначе — «не знаю»
    с уточнением. Строже правила Дня 24 (там — только факты)."""
    if п.ожидалось_не_знаю:
        return п.не_знаю and п.уточнение_есть
    return (not п.не_знаю and п.источники_полные and п.нужный_источник is not False
            and п.подтверждено > 0 and п.чисел_в_цитатах == п.чисел and п.фактов_в_ответе == п.фактов)


def _проверка(вопрос: dict, ответ: ОтветRAG) -> tuple[dict[str, Any], bool]:
    п = citecheck.проверить(вопрос, ответ)
    д = п.to_dict()
    д.pop("answer", None)
    д["facts_found"] = [] if п.не_знаю else [qa.есть_факт(ответ.текст, г) for г in вопрос.get("факты") or []]
    д["ok_day24"] = п.верно
    return д, верно(п)


def запись(вопрос: dict, участник: Участник, повтор: int, ответ: ОтветRAG, сеть: dict,
           сеть_поиска: dict | None, секунд: float) -> dict[str, Any]:
    проверка, итог = _проверка(вопрос, ответ)
    return {"ключ": f"{вопрос.get('id', '')}|{участник.код}|{повтор}", "вопрос_id": вопрос.get("id", ""),
            "вид": вопрос.get("вид", citecheck.С_ОТВЕТОМ), "вопрос": вопрос["вопрос"],
            "участник": участник.код, "модель": участник.модель, "повтор": повтор, "новый": повтор <= 1,
            "когда": datetime.now().isoformat(timespec="seconds"), "поиск_общий": участник.общий,
            "ответ": _кратко(ответ), "проверка": проверка, "верно": итог, "судья": None,
            "сеть": сеть, "сеть_поиска": сеть_поиска, "секунд": round(секунд, 2),
            "ошибка": ответ.ошибка}


def судить(клиент, з: dict, модель: str = СУДЬЯ) -> None:
    """Следует ли ответ из подтверждённых цитат — вердикт одного судьи на всех."""
    from agent.llm import LLMError
    подтверждённые = [ц for ц in з["ответ"]["quotes"] if ц.get("confirmed")]
    if not модель or з["ответ"]["abstain"] or not подтверждённые:
        з["судья"] = None
        return
    цитаты = "\n".join(f"[{ц.get('found_in') or ц.get('n')}] «{ц.get('text', '')}»" for ц in подтверждённые)
    сообщения = [{"role": "system", "content": citecheck.СУДЬЯ_ЦИТАТ},
                 {"role": "user", "content": f"Вопрос: {з['вопрос']}\n\nОтвет помощника:\n"
                                             f"{з['ответ']['text']}\n\nЦитаты:\n{цитаты}"}]
    from agent.local import schemas
    try:
        # Судья по умолчанию облачный; локальному — температура роли из карты (28.1).
        reply = клиент.call(модель, сообщения, max_tokens=400, low_effort=True,
                            **schemas.температура_вызова(qa.РОЛЬ_СУДЬИ, модель))
    except LLMError as exc:
        з["судья"] = {"смысл": "", "пояснение": f"судья недоступен: {exc}"[:200], "модель": модель}
        return
    данные = qa._json_из(reply.text) or {}
    смысл = данные.get("смысл") if данные.get("смысл") in citecheck.СМЫСЛ else ""
    з["судья"] = {"смысл": смысл, "лишнее": str(данные.get("лишнее") or "")[:300],
                  "пояснение": str(данные.get("пояснение") or (reply.text or "")[:120])[:300],
                  "модель": модель, "стоимость": round(reply.cost, 6)}


def рядом(отвечатель, вопрос: dict, участники: list[Участник] | None = None, судья: str = СУДЬЯ,
          клиент=None, без_кэша: bool = False, ход: bool = False,
          наблюдатель: Callable[[dict], None] | None = None) -> list[dict]:
    """Один вопрос — все участники рядом (FR-09). Записи — как у прогона, повтор 0."""
    клиент = клиент or отвечатель.клиент
    список = участники if участники is not None else list(УЧАСТНИКИ)
    подготовка = общий_поиск(отвечатель, вопрос["вопрос"], без_кэша=без_кэша, ход=ход) \
        if any(у.общий for у in список) else None
    итог = []
    for у in список:
        if ход:
            from agent.local import progress
            progress.этап("участник", участник=у.код, подпись=у.подпись, модель=у.модель)
        ответ, сеть, секунд = _ответить(отвечатель, у, вопрос["вопрос"], подготовка, без_кэша, ход)
        з = запись(вопрос, у, 0, ответ, сеть, подготовка.сеть if у.общий and подготовка else None,
                   секунд + (подготовка.отбор.секунд + подготовка.секунд_окон if у.общий and подготовка else 0))
        судить(клиент, з, судья)
        итог.append(з)
        if наблюдатель:
            наблюдатель(з)
    return итог


# --- прогон с продолжением -----------------------------------------------------------

class Прогон:
    """14 вопросов × участники × повторы; строка JSONL на ответ; продолжение с места."""

    def __init__(self, каталог: str, метка: str, вопросы_: list[dict],
                 участники: list[Участник] | None = None, повторов: int = ПОВТОРОВ,
                 судья: str = СУДЬЯ) -> None:
        self.каталог = каталог
        os.makedirs(каталог, exist_ok=True)
        self.метка = метка or datetime.now().strftime("%Y%m%d-%H%M")
        self.вопросы = list(вопросы_)
        self.участники = list(участники) if участники is not None else list(УЧАСТНИКИ)
        self.повторов = повторов
        self.судья = судья
        self.путь_журнала = os.path.join(каталог, f"run-{self.метка}.jsonl")
        self.путь_состояния = os.path.join(каталог, ФАЙЛ_СОСТОЯНИЯ)
        self.текущий = ""

    @property
    def всего(self) -> int:
        return len(self.вопросы) * len(self.участники) * self.повторов

    def записи(self) -> list[dict]:
        if not os.path.exists(self.путь_журнала):
            return []
        итог: dict[str, dict] = {}
        with open(self.путь_журнала, encoding="utf-8") as f:
            for строка in f:
                try:
                    з = json.loads(строка)
                except ValueError:
                    continue   # строка, оборванная вместе с процессом
                итог.setdefault(з["ключ"], з)
        return list(итог.values())

    def готовые(self) -> set[str]:
        return {з["ключ"] for з in self.записи()}

    def состояние(self, завершён: bool | None = None) -> dict[str, Any]:
        готово = len(self.готовые())
        return {"метка": self.метка, "готово": готово, "всего": self.всего,
                "завершён": готово >= self.всего if завершён is None else завершён,
                "текущий": self.текущий, "повторов": self.повторов,
                "участники": [у.код for у in self.участники], "вопросов": len(self.вопросы),
                "вопросы_ids": [в.get("id", "") for в in self.вопросы],
                "судья": self.судья, "когда": datetime.now().isoformat(timespec="seconds"),
                "журнал": os.path.basename(self.путь_журнала)}

    def _сохранить_состояние(self, **поля) -> None:
        записать_атомарно(self.путь_состояния,
                          json.dumps({**self.состояние(), **поля}, ensure_ascii=False, indent=1))

    def _дописать(self, з: dict) -> None:
        with open(self.путь_журнала, "a", encoding="utf-8") as f:
            f.write(json.dumps(з, ensure_ascii=False, default=str) + "\n")

    def выполнить(self, отвечатель, клиент=None, прогресс: Callable[[dict, dict], None] | None = None,
                  стоп: Callable[[], bool] | None = None) -> None:
        """прогресс(состояние, запись) — после каждого ответа; стоп() → True — остановиться
        между ответами (журнал при этом цел, продолжение — тем же вызовом)."""
        клиент = клиент or отвечатель.клиент
        готовые = self.готовые()
        for повтор in range(1, self.повторов + 1):
            for вопрос in self.вопросы:
                нужны = [у for у in self.участники
                         if f"{вопрос.get('id', '')}|{у.код}|{повтор}" not in готовые]
                if not нужны:
                    continue
                подготовка = None
                if any(у.общий for у in нужны):
                    self.текущий = f"{вопрос.get('id', '')}|поиск|{повтор}"
                    подготовка = общий_поиск(отвечатель, вопрос["вопрос"], без_кэша=повтор == 1)
                for у in нужны:
                    if стоп and стоп():
                        self._сохранить_состояние(завершён=False, остановлен=True)
                        return
                    self.текущий = f"{вопрос.get('id', '')}|{у.код}|{повтор}"
                    self._сохранить_состояние()
                    try:
                        ответ, сеть, секунд = _ответить(отвечатель, у, вопрос["вопрос"], подготовка,
                                                        повтор == 1, False)
                    except Exception as exc:   # noqa: BLE001 — сбой одного ответа не роняет прогон
                        ответ = ОтветRAG(вопрос=вопрос["вопрос"], режим=С_RAG, модель=у.модель,
                                         формат=ЦИТАТЫ, ошибка=f"{type(exc).__name__}: {exc}"[:300])
                        сеть, секунд = {"локальных": 0, "внешних": 0, "заблокировано": 0, "хосты": []}, 0.0
                    # Время общего поиска — каждому, кто его получил: в настоящей
                    # работе участник искал бы сам, и «всего» без поиска было бы нечестным.
                    общий = у.общий and подготовка is not None
                    з = запись(вопрос, у, повтор, ответ, сеть, подготовка.сеть if общий else None,
                               секунд + (подготовка.отбор.секунд + подготовка.секунд_окон if общий else 0))
                    судить(клиент, з, self.судья)
                    self._дописать(з)
                    готовые.add(з["ключ"])
                    if прогресс:
                        прогресс(self.состояние(), з)
        self.текущий = ""
        self._сохранить_состояние()


def прочитать_состояние(каталог: str) -> dict[str, Any] | None:
    путь = os.path.join(каталог, ФАЙЛ_СОСТОЯНИЯ)
    if not os.path.exists(путь):
        return None
    try:
        with open(путь, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def пересудить(прогон: Прогон, клиент, модель: str = СУДЬЯ) -> int:
    """Новый вердикт судьи по журналу — без новых ответов моделей."""
    записи = прогон.записи()
    for з in записи:
        судить(клиент, з, модель)
    записать_атомарно(прогон.путь_журнала,
                      "".join(json.dumps(з, ensure_ascii=False, default=str) + "\n" for з in записи))
    return len(записи)


