def отчёт_в_корень(каталог_индекса: str) -> bool:
    """LOCAL-RAG.md идёт в корень репозитория только с настоящего индекса проекта:
    прогон на чужом (чек-лист, тесты) не должен перезаписать отчёт дня."""
    from agent.rag.indexer import КОРЕНЬ
    return os.path.abspath(каталог_индекса) == os.path.abspath(os.path.join(КОРЕНЬ, "index"))


