"""Ответ с источниками и цитатами (День 24): формат, разбор и проверка кодом.

Модель отвечает объектом JSON:

    {"ответ": "Не менее чем за 10 дней до введения изменений [1].",
     "источники": [1],
     "цитаты": [{"n": 1, "текст": "извещать Абонента … не менее чем за 10 дней"}],
     "не_знаю": false,
     "уточнение": ""}

Модель называет только НОМЕРА фрагментов. Паспорт источника — файл, раздел,
пункт, страницы, chunk_id — подставляет код: выдумать путь или раздел модели
нечем. Цитата — дословный кусок фрагмента. Код ищет её в тексте фрагмента с
номером n (после нормализации регистра, ё, кавычек, пробелов и переносов OCR) и
помечает:

  дословно             нашлась в своём фрагменте целиком;
  почти                совпадает с куском фрагмента на 90 % и больше — так
                       выглядит шум OCR в сканах; цитата засчитывается;
  в другом фрагменте   нашлась, но не в том, на который сослалась модель:
                       цитата настоящая, номер код исправляет;
  слишком короткая     «10» или «оплата» нашлись бы где угодно — не довод;
  не найдена           такого текста во фрагментах нет — выдумка.

Обязательность проверяет `нарушения()`: нет ответа, нет источников, нет
цитат, ссылка на несуществующий фрагмент, неподтверждённая цитата. Что делать
с нарушениями, решает answer.py: один повторный запрос, а если и после него нет
ни одной подтверждённой цитаты — «не знаю» вместо ответа.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from difflib import SequenceMatcher
from typing import Any

ДОСЛОВНО = "дословно"
ПОЧТИ = "почти"
В_ДРУГОМ = "в другом фрагменте"
КОРОТКАЯ = "слишком короткая"
НЕ_НАЙДЕНА = "не найдена"
ПОДТВЕРЖДЁННЫЕ = (ДОСЛОВНО, ПОЧТИ, В_ДРУГОМ)
# 90 %: на сканах OCR путает «е/с», «0/О» и рвёт слова, и дословное сравнение
# отбраковало бы настоящую цитату. Ниже — это уже пересказ, а не цитата.
ПОЧТИ_ПОРОГ = 0.9
# Цитата короче — не довод: «10 дней» или «оплата» нашлись бы в любом договоре.
МИН_СИМВОЛОВ = 15
МИН_СЛОВ = 3

ПРАВИЛА_ЦИТАТ = """\
Отвечай ТОЛЬКО по фрагментам документов, которые даны в сообщении \
пользователя. Общие знания о «типичных договорах» не используй.
Верни ТОЛЬКО объект JSON, без текста вокруг и без ```:
{"ответ": "…", "источники": [1], "цитаты": [{"n": 1, "текст": "…"}], \
"не_знаю": false, "уточнение": ""}
- «ответ»: коротко — сначала прямой ответ (срок, сумма, количество, \
условие), затем одно-два пояснения; после каждого утверждения номер фрагмента \
в квадратных скобках: [1], [2].
- «источники»: номера всех фрагментов, на которые опирается ответ. Только \
номера, которые есть среди фрагментов.
- «цитаты»: для каждого источника хотя бы одна цитата — ДОСЛОВНО скопированный \
кусок текста этого фрагмента (5–40 слов), в котором есть то, что утверждает \
ответ: число, срок, сумма, условие. Не пересказывай, не сокращай слова и не \
исправляй текст цитаты, даже опечатки и ошибки распознавания.
- Ответ не шире цитат: каждое число, дата, сумма и условие из «ответ» должно \
стоять в одной из «цитаты». Нужна подробность (НДС, период, условие) — добавь \
цитату с ней; нет такой цитаты — не пиши эту подробность.
- Если во фрагментах ответа нет — {"ответ": "Не знаю", "не_знаю": true, \
"уточнение": "<один короткий вопрос пользователю, который поможет найти \
ответ>", "источники": [], "цитаты": []}. Не угадывай.
- Если вопрос неоднозначен — не назван предмет («это», «там», «он»: какой \
договор, услуга, лицензия, статья бюджета), а фрагменты отвечают на него \
по-разному, — не выбирай вариант сам: верни «не_знаю»: true, \
«неоднозначно»: true и в «уточнение» спроси, что имеется в виду, перечислив \
2–3 варианта — только названия договоров, услуг или лицензий, без сумм, сроков \
и ссылок [n].
- Если ответ есть лишь частично — ответь тем, что подтверждают цитаты, и \
прямо назови, чего во фрагментах нет."""

# День 29: шаблон «договоры» — системный промпт ответа по документам для
# локальной модели, вместо роли и правил выше. На CPU каждый токен промпта —
# время чтения (≈ 14 токенов в секунду у qwen3.5:4b), а роль с правилами Дня 24
# — около 600 токенов. Здесь то же самое короче: та же JSON-схема и те же
# проверки кодом (цитата ищется во фрагменте, числа ответа — в цитатах),
# без пояснений, которые локальная модель всё равно не использует. Примеров
# нет: они удлинили бы каждый промпт. Неизменная часть — первой.
ШАБЛОН_ДОГОВОРЫ = """\
Ты отвечаешь по договорам связи, бюджету на ИТ и лицензиям — только по \
фрагментам документов из сообщения, без общих знаний.
Верни только JSON: {"ответ": "…", "источники": [1], "цитаты": [{"n": 1, \
"текст": "…"}], "не_знаю": false, "уточнение": ""}
- ответ: коротко, сначала срок, сумма или условие; после утверждения — номер \
фрагмента [n].
- цитаты: для каждого источника — дословный кусок его текста (5–40 слов) с \
числом или условием из ответа; не пересказывай и не исправляй.
- в ответе только те числа и условия, что есть в цитатах.
- ответа во фрагментах нет — "ответ": "Не знаю", "не_знаю": true, в \
"уточнение" — один короткий вопрос.
- не назван договор, услуга или лицензия, а фрагменты отвечают по-разному — \
"не_знаю": true, "неоднозначно": true, в "уточнение" — 2–3 названия на выбор."""

ПОЧИНКА = """\
В твоём ответе нарушен обязательный формат:
{нарушения}
Верни исправленный объект JSON того же вида. Цитаты копируй из фрагментов \
дословно. Если подтвердить ответ цитатами нельзя — верни «не_знаю»: true и \
уточняющий вопрос."""


@dataclass
class Цитата:
    n: int                      # номер фрагмента, который назвала модель
    текст: str
    проверка: str = ""          # дословно | почти | в другом фрагменте | слишком короткая | не найдена
    найдена_в: int = 0          # где нашлась на самом деле (0 — нигде)
    сходство: float = 0.0

    @property
    def подтверждена(self) -> bool:
        return self.проверка in ПОДТВЕРЖДЁННЫЕ

    def to_dict(self) -> dict[str, Any]:
        return {"n": self.n, "text": self.текст, "check": self.проверка,
                "found_in": self.найдена_в, "similarity": round(self.сходство, 3),
                "confirmed": self.подтверждена}


@dataclass
class Разбор:
    """Ответ модели, разобранный из JSON (или честно неразобранный)."""

    ответ: str = ""
    источники: list[int] = field(default_factory=list)
    цитаты: list[Цитата] = field(default_factory=list)
    не_знаю: bool = False
    неоднозначно: bool = False      # «не знаю» потому, что вопрос можно понять по-разному
    уточнение: str = ""
    ошибка_формата: str = ""


def _json_из(текст: str) -> dict | None:
    """Объект JSON из ответа: модели иногда оборачивают его в ``` или пишут перед ним фразу."""
    текст = re.sub(r"^```(?:json)?\s*|\s*```$", "", (текст or "").strip())
    найдено = re.search(r"\{.*\}", текст, re.S)
    if not найдено:
        return None
    try:
        данные = json.loads(найдено.group(0))
    except json.JSONDecodeError:
        return None
    return данные if isinstance(данные, dict) else None


def _номер(значение) -> int:
    try:
        return int(str(значение).strip().strip("[]"))
    except (TypeError, ValueError):
        return 0


def разобрать(текст: str) -> Разбор:
    данные = _json_из(текст)
    if данные is None:
        # Не JSON — ответ остаётся текстом, а нарушение формата видно в отчёте.
        return Разбор(ответ=(текст or "").strip(), ошибка_формата="ответ не в формате JSON")
    итог = Разбор(ответ=str(данные.get("ответ") or "").strip(),
                  не_знаю=bool(данные.get("не_знаю")),
                  неоднозначно=bool(данные.get("неоднозначно")),
                  уточнение=str(данные.get("уточнение") or "").strip())
    for н in данные.get("источники") or []:
        номер = _номер(н)
        if номер and номер not in итог.источники:
            итог.источники.append(номер)
    for ц in данные.get("цитаты") or []:
        if isinstance(ц, dict) and str(ц.get("текст") or "").strip():
            итог.цитаты.append(Цитата(n=_номер(ц.get("n")), текст=str(ц["текст"]).strip()))
        elif isinstance(ц, str) and ц.strip():
            # «[1] текст цитаты» — модель забыла про объект, номер в начале строки.
            м = re.match(r"\s*\[?(\d{1,2})\]?\s*[:.)-]?\s*(.+)", ц, re.S)
            if м:
                итог.цитаты.append(Цитата(n=int(м.group(1)), текст=м.group(2).strip()))
    return итог


def нормализовать(текст: str) -> str:
    """Сравнимый вид: регистр, ё, кавычки, тире, переносы OCR, пробелы."""
    т = (текст or "").lower().replace("ё", "е").replace("­", "")
    т = re.sub(r"[«»„“”\"']", '"', т)
    т = re.sub(r"[‐‑‒–—−]", "-", т)
    т = re.sub(r"(\w)-\s+(\w)", r"\1\2", т)          # «предоставле- ния»
    т = re.sub(r"\s+", " ", т)
    т = re.sub(r"(?<=\d) (?=\d)", "", т)              # «24 441 696» и «24441696»
    т = re.sub(r"\s*([,.;:!?)\]])", r"\1", т)
    т = re.sub(r"([(\[])\s*", r"\1", т)
    return т.strip(' ".…')


def сходство(цитата: str, текст: str) -> float:
    """Насколько цитата совпадает с самым похожим куском текста той же длины."""
    if not цитата or not текст:
        return 0.0
    поиск = SequenceMatcher(None, цитата, текст, autojunk=False)
    м = поиск.find_longest_match(0, len(цитата), 0, len(текст))
    начало = max(0, м.b - м.a)
    лучшее = 0.0
    # Окно выравнивается по самому длинному совпадению; сдвиг на пару символов
    # прощает лишнюю или пропущенную букву в начале.
    for сдвиг in (-3, 0, 3):
        с = max(0, начало + сдвиг)
        окно = текст[с:с + len(цитата)]
        лучшее = max(лучшее, SequenceMatcher(None, цитата, окно, autojunk=False).ratio())
    return лучшее


def найти(цитата: str, текст: str) -> tuple[str, float]:
    """Вид совпадения цитаты с одним фрагментом: дословно, почти или нет."""
    ц, т = нормализовать(цитата), нормализовать(текст)
    if ц and ц in т:
        return ДОСЛОВНО, 1.0
    с = сходство(ц, т)
    return (ПОЧТИ, с) if с >= ПОЧТИ_ПОРОГ else (НЕ_НАЙДЕНА, с)


def проверить_цитаты(разбор: Разбор, тексты: list[str]) -> None:
    """Ищет каждую цитату в её фрагменте, а не найдя — во всех остальных."""
    for ц in разбор.цитаты:
        норм = нормализовать(ц.текст)
        if len(норм) < МИН_СИМВОЛОВ or len(норм.split()) < МИН_СЛОВ:
            ц.проверка, ц.найдена_в = КОРОТКАЯ, 0
            continue
        if 1 <= ц.n <= len(тексты):
            вид, с = найти(ц.текст, тексты[ц.n - 1])
            if вид != НЕ_НАЙДЕНА:
                ц.проверка, ц.найдена_в, ц.сходство = вид, ц.n, с
                continue
            ц.сходство = с
        # Не в своём фрагменте — ищем в остальных: номер мог быть перепутан.
        найденные = []
        for i, текст in enumerate(тексты, 1):
            if i != ц.n:
                вид, с = найти(ц.текст, текст)
                if вид != НЕ_НАЙДЕНА:
                    найденные.append((с, i))
        if найденные:
            с, i = max(найденные)
            ц.проверка, ц.найдена_в, ц.сходство = В_ДРУГОМ, i, с
        else:
            ц.проверка, ц.найдена_в = НЕ_НАЙДЕНА, 0


def ссылки_в_тексте(текст: str) -> list[int]:
    найдено: list[int] = []
    for м in re.finditer(r"\[(\d{1,2}(?:\s*[,;]\s*\d{1,2})*)\]", текст or ""):
        for номер in re.findall(r"\d{1,2}", м.group(1)):
            if int(номер) not in найдено:
                найдено.append(int(номер))
    return найдено


def _число(токен: str) -> str:
    """Каноническая запись: «24 441 696,00» = «24441696», «0,20» = «0.2»; «2.2.7» и даты — как есть."""
    т = токен.replace(",", ".")
    if т.count(".") == 1:
        т = т.rstrip("0").rstrip(".") if "." in т else т
    return т


# Цифры, приклеенные к буквам, — часть названия, а не факт ответа: лист
# «УИС-5», договор ВОГ396658, «Лист_1», OpenScape V2.
_ЧИСЛО = re.compile(r"(?<![^\W\d_])(?<![^\W\d_][-_])(?<!\d)(?<!\d[.,])\d+(?:[.,]\d+)*")


def числа(текст: str) -> list[str]:
    """Числа текста без ссылок [n]: суммы, сроки, проценты, даты и номера пунктов целиком."""
    без_ссылок = re.sub(r"\[\d{1,2}(?:\s*[,;]\s*\d{1,2})*\]", " ", текст or "")
    т = re.sub(r"(?<=\d)[\s\u00a0](?=\d{3}\b)", "", без_ссылок)      # «24 441 696»
    return list(dict.fromkeys(_число(х) for х in _ЧИСЛО.findall(т)))


def числа_без_опоры(ответ: str, цитаты: list[Цитата], вопрос: str = "") -> list[str]:
    """Числа ответа, которых нет ни в одной подтверждённой цитате (и нет в самом вопросе)."""
    в_цитатах = set(числа(" ".join(ц.текст for ц in цитаты if ц.подтверждена)))
    в_вопросе = set(числа(вопрос))
    return [ч for ч in числа(ответ) if ч not in в_цитатах and ч not in в_вопросе]


def нарушения(разбор: Разбор, всего: int, вопрос: str = "") -> list[str]:
    """Что нарушено в обязательном формате — для повторного запроса и отчёта."""
    итог: list[str] = []
    if разбор.ошибка_формата:
        итог.append(разбор.ошибка_формата)
    if разбор.не_знаю:
        if not разбор.уточнение:
            итог.append("«не_знаю»: true, но нет уточняющего вопроса в «уточнение»")
        return итог
    if not разбор.ответ:
        итог.append("пустое поле «ответ»")
    if not разбор.источники:
        итог.append("пустой список «источники»")
    чужие = [n for n in разбор.источники if not 1 <= n <= всего]
    if чужие:
        итог.append(f"в «источники» номера, которых нет среди фрагментов: {чужие} (всего {всего})")
    ссылки = [n for n in ссылки_в_тексте(разбор.ответ) if not 1 <= n <= всего]
    if ссылки:
        итог.append(f"в «ответ» ссылки на несуществующие фрагменты: {ссылки}")
    if not разбор.цитаты:
        итог.append("пустой список «цитаты»")
    for ц in разбор.цитаты:
        if ц.проверка == НЕ_НАЙДЕНА:
            итог.append(f"цитаты [{ц.n}] «{ц.текст[:60]}…» нет ни в одном фрагменте — "
                        "скопируй текст дословно")
        elif ц.проверка == КОРОТКАЯ:
            итог.append(f"цитата [{ц.n}] «{ц.текст}» слишком короткая — нужно 5–40 слов")
    без_цитат = [n for n in разбор.источники if 1 <= n <= всего
                 and not any(ц.подтверждена and (ц.найдена_в or ц.n) == n for ц in разбор.цитаты)]
    if разбор.цитаты and без_цитат:
        итог.append(f"у источников {без_цитат} нет подтверждённой цитаты")
    if any(ц.подтверждена for ц in разбор.цитаты):
        лишние = числа_без_опоры(разбор.ответ, разбор.цитаты, вопрос)
        if лишние:
            итог.append(f"в «ответ» есть числа, которых нет ни в одной цитате: {', '.join(лишние)} — "
                        "добавь цитаты с ними или убери их из ответа")
    return итог


def сообщение_починки(список: list[str]) -> str:
    return ПОЧИНКА.format(нарушения="\n".join(f"- {н}" for н in список))


def подтверждённые(разбор: Разбор) -> list[Цитата]:
    return [ц for ц in разбор.цитаты if ц.подтверждена]
