"""Профиль RAG-конвейера (День 28): параметры поиска и ответа — явно, а не флагом.

До Дня 28 локальные параметры — кросс-энкодер 8 → 2, порог «не знаю» под его
шкалу, лучшее окно фрагмента — включал только глобальный флаг офлайна (День
27). Но сравнение «локально ↔ облако» идёт в одном процессе в облачном режиме:
облачный участник должен ходить в сеть, а локальные — получать свои параметры.
Поэтому параметры собраны в профиль и передаются в
`Отвечатель.ответить(профиль=…)`. Без явного профиля действует текущий: в
офлайне — локальный (то же, что делал флаг в Дне 27), иначе — никакой, то есть
поведение Дня 24.

В локальном профиле поиск обходится без LLM: вектор вопроса (bge-m3 в Ollama),
косинус в SQLite, кросс-энкодер на CPU. Переписывания запроса в нём нет даже
локальной моделью — поиск остаётся детерминированным и быстрым.

Публичное API:
  ПрофильRAG(имя, поиск, порог_уверенности, окно_фрагмента)
  локальный(поисковик) -> ПрофильRAG      — из local-roles.json
  облачный_дня24() -> ПрофильRAG          — «фильтр» Дня 24, порог из rag-settings.json
  текущий(поисковик) -> ПрофильRAG | None — локальный в офлайне, иначе None
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Any

ЛОКАЛЬНЫЙ = "локальный"
ОБЛАЧНЫЙ = "облачный · фильтр Дня 24"
# Режим Дня 24, от которого локальный профиль берёт порог косинуса: тот —
# свойство эмбеддера, а не реранкера, и карта офлайна его обычно не задаёт.
РЕЖИМ_ОСНОВА = "фильтр"


@dataclass(frozen=True)
class ПрофильRAG:
    """Как искать и как отвечать. поиск — имя режима Дня 23 или готовые Настройки;
    порог_уверенности None — порог из rag-settings.json (подбор Дня 24)."""

    имя: str
    поиск: Any
    порог_уверенности: float | None = None
    окно_фрагмента: bool = False

    def to_dict(self) -> dict[str, Any]:
        поиск = self.поиск.to_dict() if hasattr(self.поиск, "to_dict") else self.поиск
        return {"имя": self.имя, "поиск": поиск, "порог_уверенности": self.порог_уверенности,
                "окно_фрагмента": self.окно_фрагмента}


def локальный(поисковик) -> ПрофильRAG:
    """Профиль из карты офлайна (local-roles.json) — независимо от флага офлайна."""
    from agent.local import offline
    from agent.rag import rerank as rr
    н = поисковик.офлайн_вариант(РЕЖИМ_ОСНОВА)
    if н is None:
        # Карты поиска нет — второй этап всё равно локальный: кросс-энкодер
        # с K режима Дня 24.
        н = replace(поисковик.режимы()[РЕЖИМ_ОСНОВА], реранкер=rr.КРОСС)
    н = replace(н, rewrite=False, имя=f"{ЛОКАЛЬНЫЙ} · {н.реранкер} {н.k_до}→{н.k_после}")
    return ПрофильRAG(имя=ЛОКАЛЬНЫЙ, поиск=н, порог_уверенности=offline.порог_уверенности(),
                      окно_фрагмента=offline.окно_фрагмента())


def облачный_дня24() -> ПрофильRAG:
    """Лучший облачный конвейер Дня 24: поиск «фильтр» (LLM-реранкер), целые фрагменты."""
    return ПрофильRAG(имя=ОБЛАЧНЫЙ, поиск=РЕЖИМ_ОСНОВА)


def текущий(поисковик) -> ПрофильRAG | None:
    """Профиль по умолчанию: в офлайне — локальный, иначе None (поведение Дня 24)."""
    from agent.local import offline
    return локальный(поисковик) if offline.включён() else None
