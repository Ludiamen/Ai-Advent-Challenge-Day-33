РАСПЛЫВЧАТЫЕ_ПО_УМОЛЧАНИЮ = "rag-vague.json"
ПОИСК = "фильтр"
С_ОТВЕТОМ, ЛОВУШКА, РАСПЛЫВЧАТЫЙ = "с ответом", "ловушка", "расплывчатый"
СМЫСЛ = ("да", "частично", "нет")

СУДЬЯ_ЦИТАТ = """\
Ты проверяешь, подтверждают ли цитаты из документов ответ помощника. Даны \
вопрос, ответ и цитаты — дословные куски документов. Оцени, следует ли ответ \
из цитат:
- «да» — все утверждения ответа (числа, сроки, суммы, условия) есть в цитатах;
- «частично» — главное подтверждено, но в ответе есть утверждения, которых в \
цитатах нет;
- «нет» — главное утверждение ответа цитатами не подтверждается или \
противоречит им.
Не оценивай, верен ли ответ по существу, — только опору на цитаты.
Верни ТОЛЬКО JSON: {"смысл": "да|частично|нет", "лишнее": "утверждения ответа \
без опоры в цитатах или пустая строка", "пояснение": "одна фраза"}"""


def путь_расплывчатых() -> str:
    from agent.rag.indexer import КОРЕНЬ
    return os.getenv("RAG_VAGUE") or os.path.join(КОРЕНЬ, РАСПЛЫВЧАТЫЕ_ПО_УМОЛЧАНИЮ)


def загрузить_вопросы(путь_контроля: str = "", путь_расплывчатых_: str = "") -> list[dict]:
    """Контрольные Дня 22 и расплывчатые; у каждого — вид."""
    вопросы = []
    for в in qa.загрузить(путь_контроля or qa.путь_по_умолчанию()):
        вопросы.append({**в, "вид": ЛОВУШКА if в.get("ловушка") else С_ОТВЕТОМ})
    путь = путь_расплывчатых_ or путь_расплывчатых()
    if os.path.exists(путь):
        with open(путь, encoding="utf-8") as f:
            данные = json.load(f)
        for в in данные.get("вопросы", данные):
            вопросы.append({**в, "вид": РАСПЛЫВЧАТЫЙ, "факты": [], "источники": []})
    return вопросы


@dataclass
class Проверка:
    вопрос: dict
    ответ: ОтветRAG
    формат: str = ЦИТАТЫ
    источников: int = 0
    источники_полные: bool = False      # у каждого — файл, раздел, chunk_id
    нужный_источник: bool | None = None
    цитат: int = 0
    подтверждено: int = 0
    дословно: int = 0
    чисел: int = 0
    чисел_в_цитатах: int = 0
    фактов: int = 0
    фактов_в_ответе: int = 0
    фактов_в_цитатах: int = 0
    смысл_код: bool | None = None
    смысл_судья: str = ""
    лишнее: str = ""
    пояснение: str = ""
    модель_судьи: str = ""
    не_знаю: bool = False
    уточнение_есть: bool = False

    @property
    def вид(self) -> str:
        return self.вопрос.get("вид", С_ОТВЕТОМ)

    @property
    def ожидалось_не_знаю(self) -> bool:
        return self.вид != С_ОТВЕТОМ

    @property
    def верно(self) -> bool:
        """На вопрос с ответом — все факты и не «не знаю»; иначе — «не знаю» с уточнением."""
        if self.ожидалось_не_знаю:
            return self.не_знаю and self.уточнение_есть
        return not self.не_знаю and self.фактов_в_ответе == self.фактов

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.вопрос.get("id", ""), "kind": self.вид, "format": self.формат,
            "sources": self.источников, "sources_complete": self.источники_полные,
            "right_source": self.нужный_источник, "quotes": self.цитат,
            "confirmed": self.подтверждено, "verbatim": self.дословно,
            "numbers": self.чисел, "numbers_in_quotes": self.чисел_в_цитатах,
            "facts": self.фактов, "facts_in_answer": self.фактов_в_ответе,
            "facts_in_quotes": self.фактов_в_цитатах, "meaning_code": self.смысл_код,
            "meaning_judge": self.смысл_судья, "extra": self.лишнее, "judge_note": self.пояснение,
            "judge_model": self.модель_судьи, "abstain": self.не_знаю,
            "abstain_by": self.ответ.не_знаю_кто, "clarification_ok": self.уточнение_есть,
            "expected_abstain": self.ожидалось_не_знаю, "ok": self.верно,
            "answer": self.ответ.to_dict(),
        }


def проверить(вопрос: dict, ответ: ОтветRAG) -> Проверка:
    """Всё, что можно проверить кодом, без модели."""
    п = Проверка(вопрос=вопрос, ответ=ответ, формат=ответ.формат)
    п.не_знаю = ответ.не_знаю or (ответ.формат == ТЕКСТ and ответ.отказ)
    п.уточнение_есть = bool((ответ.уточнение or "").strip()) or (
        ответ.формат == ТЕКСТ and ответ.отказ and "?" in ответ.текст)
    источники = ответ.источники
    п.источников = len(источники)
    п.источники_полные = bool(источники) and all(
        и.get("source") and и.get("section") and и.get("chunk_id") for и in источники)
    ожидаемые = вопрос.get("источники") or []
    if ожидаемые and not п.не_знаю:
        п.нужный_источник = any(qa._совпадает_источник(и, о) for и in источники for о in ожидаемые)
    цитаты = [ц for ц in ответ.выдержки]
    п.цитат = len(цитаты)
    подтверждённые = [ц for ц in цитаты if ц.подтверждена]
    п.подтверждено = len(подтверждённые)
    п.дословно = sum(ц.проверка == "дословно" for ц in цитаты)
    if not п.не_знаю:
        текст_цитат = " ".join(ц.текст for ц in подтверждённые)
        # Числа — так же, как их проверяет cite: по значению, без чисел из вопроса.
        числа = [ч for ч in cite.числа(ответ.текст) if ч not in set(cite.числа(ответ.вопрос))]
        без_опоры = cite.числа_без_опоры(ответ.текст, подтверждённые, ответ.вопрос)
        п.чисел, п.чисел_в_цитатах = len(числа), len(числа) - len(без_опоры)
        группы = вопрос.get("факты") or []
        п.фактов = len(группы)
        п.фактов_в_ответе = sum(1 for г in группы if qa.есть_факт(ответ.текст, г))
        п.фактов_в_цитатах = sum(1 for г in группы if qa.есть_факт(текст_цитат, г))
        if подтверждённые:
            п.смысл_код = (п.чисел_в_цитатах == п.чисел
                           and п.фактов_в_цитатах >= п.фактов_в_ответе)
    return п


def судить(клиент, п: Проверка) -> None:
    """Следует ли ответ из цитат. Судья — модели роли «судья-ответов» по порядку."""
    from agent.llm import LLMError
    if п.не_знаю or not п.подтверждено:
        return
    цитаты = "\n".join(f"[{ц.найдена_в or ц.n}] «{ц.текст}»" for ц in п.ответ.выдержки if ц.подтверждена)
    сообщения = [{"role": "system", "content": СУДЬЯ_ЦИТАТ},
                 {"role": "user", "content": f"Вопрос: {п.ответ.вопрос}\n\nОтвет помощника:\n"
                                             f"{п.ответ.текст}\n\nЦитаты:\n{цитаты}"}]
    from agent.local import schemas
    for модель in qa.модели_судьи():
        try:
            # Локальной модели — температура роли судьи из карты (28.1).
            reply = клиент.call(модель, сообщения, max_tokens=400, low_effort=True,
                                **schemas.температура_вызова(qa.РОЛЬ_СУДЬИ, модель))
        except LLMError as exc:
            п.пояснение = f"судья недоступен ({модель}): {exc}"[:200]
            continue
        данные = qa._json_из(reply.text)
        if данные and данные.get("смысл") in СМЫСЛ:
            п.смысл_судья, п.модель_судьи = данные["смысл"], модель
            п.лишнее = str(данные.get("лишнее") or "")[:300]
            п.пояснение = str(данные.get("пояснение") or "")[:300]
            return
        п.пояснение = f"вердикт не разобран: {(reply.text or '')[:120]}"


@dataclass
class Прогон:
    вопросы: list[dict]
    проверки: dict[str, list[Проверка]] = field(default_factory=dict)   # формат → проверки
    модель: str = ""
    поиск: str = ПОИСК
    порог_уверенности: float = 0.0
    когда: str = ""
    секунд: float = 0.0

    def итог(self, формат: str) -> dict[str, Any]:
        пп = self.проверки.get(формат, [])
        с_ответом = [п for п in пп if п.вид == С_ОТВЕТОМ]
        отвечено = [п for п in с_ответом if not п.не_знаю]
        ловушки = [п for п in пп if п.вид == ЛОВУШКА]
        расплывчатые = [п for п in пп if п.вид == РАСПЛЫВЧАТЫЙ]
        return {
            "вопросов": len(пп), "с_ответом": len(с_ответом), "отвечено": len(отвечено),
            "с_источниками": sum(п.источников > 0 for п in отвечено),
            "источники_полные": sum(п.источники_полные for п in отвечено),
            "нужный_источник": sum(bool(п.нужный_источник) for п in отвечено),
            "с_цитатами": sum(п.подтверждено > 0 for п in отвечено),
            "цитат": sum(п.цитат for п in отвечено),
            "подтверждено": sum(п.подтверждено for п in отвечено),
            "дословно": sum(п.дословно for п in отвечено),
            "чисел": sum(п.чисел for п in отвечено),
            "чисел_в_цитатах": sum(п.чисел_в_цитатах for п in отвечено),
            "смысл_код": sum(bool(п.смысл_код) for п in отвечено),
            "смысл_да": sum(п.смысл_судья == "да" for п in отвечено),
            "смысл_частично": sum(п.смысл_судья == "частично" for п in отвечено),
            "смысл_нет": sum(п.смысл_судья == "нет" for п in отвечено),
            "судья_молчал": sum(not п.смысл_судья for п in отвечено if п.подтверждено),
            "ловушек": len(ловушки),
            "ловушки_не_знаю": sum(п.не_знаю and п.уточнение_есть for п in ловушки),
            "расплывчатых": len(расплывчатые),
            "расплывчатые_не_знаю": sum(п.не_знаю and п.уточнение_есть for п in расплывчатые),
            "не_знаю_порог": sum(п.ответ.не_знаю_кто == "порог" for п in пп),
            "не_знаю_модель": sum(п.ответ.не_знаю_кто == "модель" for п in пп),
            "не_знаю_цитаты": sum(п.ответ.не_знаю_кто == "проверка цитат" for п in пп),
            "лишние_не_знаю": sum(п.не_знаю for п in с_ответом),
            "починок": sum(п.ответ.починка for п in пп),
            "осталось_нарушений": sum(bool(п.ответ.нарушения) for п in пп if not п.не_знаю),
            "верно": sum(п.верно for п in пп),
            "токенов_вход": sum(п.ответ.токенов_вход for п in пп),
            "стоимость": round(sum(п.ответ.стоимость for п in пп), 4),
        }

    def to_dict(self) -> dict[str, Any]:
        return {"when": self.когда, "model": self.модель, "search": self.поиск,
                "threshold": self.порог_уверенности, "seconds": round(self.секунд, 1),
                "formats": list(self.проверки),
                "totals": {ф: self.итог(ф) for ф in self.проверки},
                "questions": [{"id": в.get("id", ""), "kind": в.get("вид"), "question": в["вопрос"],
                               "expected": в.get("ожидание", ""),
                               "checks": {ф: пп[i].to_dict() for ф, пп in self.проверки.items()}}
                              for i, в in enumerate(self.вопросы)]}


def прогнать(отвечатель: Отвечатель, вопросы: list[dict], с_судьёй: bool = True,
             модель: str = "", прогресс=None, поиск: str = ПОИСК,
             форматы: tuple[str, ...] = (ЦИТАТЫ, ТЕКСТ)) -> Прогон:
    from agent import catalog
    прогон = Прогон(вопросы=вопросы, модель=модель or catalog.for_role("ответ-по-документам", 0),
                    поиск=поиск, порог_уверенности=отвечатель._порог_уверенности(),
                    когда=datetime.now().isoformat(timespec="seconds"))
    старт = time.monotonic()
    for формат in форматы:
        прогон.проверки[формат] = []
    for i, в in enumerate(вопросы, 1):
        if прогресс:
            прогресс("проверка цитат", i - 1, len(вопросы), в.get("id", ""))
        for формат in форматы:
            ответ = отвечатель.ответить(в["вопрос"], С_RAG, прогон.модель, поиск=поиск, формат=формат)
            п = проверить(в, ответ)
            if с_судьёй and формат == ЦИТАТЫ:
                судить(отвечатель.клиент, п)
            прогон.проверки[формат].append(п)
    if прогресс:
        прогресс("проверка цитат", len(вопросы), len(вопросы), "готово")
    прогон.секунд = time.monotonic() - старт
    return прогон


def _из(a: int, b: int) -> str:
    return f"{a} из {b}"


def в_markdown(прогон: Прогон) -> str:
    форматы = list(прогон.проверки)
    т = {ф: прогон.итог(ф) for ф in форматы}
    имя = {ЦИТАТЫ: "с цитатами (День 24)", ТЕКСТ: "без цитат (День 23)"}
    строки = [
        "# Цитаты, источники и «не знаю»: проверка на вопросах",
        "",
        f"Прогон {прогон.когда}: модель ответов `{прогон.модель}`, поиск «{прогон.поиск}», порог "
        f"уверенности {прогон.порог_уверенности}, {len(прогон.вопросы)} вопросов, {прогон.секунд:.0f} с. "
        "Вопросы: 10 контрольных Дня 22 (8 с ответом, 2 ловушки) и расплывчатые без предмета.",
        "",
        "## Итог",
        "",
        "| показатель | " + " | ".join(имя.get(ф, ф) for ф in форматы) + " |",
        "|---|" + "---:|" * len(форматы),
    ]

    def строка(название, f):
        строки.append(f"| {название} | " + " | ".join(f(т[ф]) for ф in форматы) + " |")

    строка("вопросов с ответом: ответ дан", lambda x: _из(x["отвечено"], x["с_ответом"]))
    строка("источники в каждом ответе", lambda x: _из(x["с_источниками"], x["отвечено"]))
    строка("у источников файл, раздел и chunk_id", lambda x: _из(x["источники_полные"], x["отвечено"]))
    строка("нужный источник среди названных", lambda x: _из(x["нужный_источник"], x["отвечено"]))
    строка("цитаты в каждом ответе", lambda x: _из(x["с_цитатами"], x["отвечено"]))
    строка("цитат подтверждено кодом (дословно)",
           lambda x: f"{x['подтверждено']} из {x['цитат']} ({x['дословно']})")
    строка("числа ответа есть в цитатах", lambda x: _из(x["чисел_в_цитатах"], x["чисел"]))
    строка("смысл совпадает с цитатами — код", lambda x: _из(x["смысл_код"], x["отвечено"]))
    строка("смысл совпадает — судья: да / частично / нет",
           lambda x: f"{x['смысл_да']} / {x['смысл_частично']} / {x['смысл_нет']}")
    строка("ловушки: «не знаю» с уточнением", lambda x: _из(x["ловушки_не_знаю"], x["ловушек"]))
    строка("расплывчатые: «не знаю» с уточнением", lambda x: _из(x["расплывчатые_не_знаю"], x["расплывчатых"]))
    строка("«не знаю» решил порог / модель / проверка цитат",
           lambda x: f"{x['не_знаю_порог']} / {x['не_знаю_модель']} / {x['не_знаю_цитаты']}")
    строка("лишние «не знаю» на вопросах с ответом", lambda x: str(x["лишние_не_знаю"]))
    строка("повторных запросов из-за формата", lambda x: str(x["починок"]))
    строка("верно по правилам", lambda x: _из(x["верно"], x["вопросов"]))
    строка("токенов на входе, всего", lambda x: f"{x['токенов_вход']:,}".replace(",", " "))
    строки += ["", "## По вопросам", "",
               "| # | вид | вопрос | " + " | ".join(имя.get(ф, ф) for ф in форматы) + " |",
               "|---|---|---|" + "---|" * len(форматы)]
    for i, в in enumerate(прогон.вопросы):
        клетки = []
        for ф in форматы:
            п = прогон.проверки[ф][i]
            if п.не_знаю:
                клетка = f"не знаю ({п.ответ.не_знаю_кто or 'модель'})" + (" + уточнение" if п.уточнение_есть else "")
            else:
                клетка = (f"ист. {п.источников} · цит. {п.подтверждено}/{п.цитат}"
                          + (f" · смысл {п.смысл_судья}" if п.смысл_судья else "")
                          + (" · код ✓" if п.смысл_код else (" · код ✗" if п.смысл_код is False else "")))
            клетки.append(("✓ " if п.верно else "✗ ") + клетка)
        строки.append(f"| {в.get('id', '')} | {в.get('вид')} | {в['вопрос']} | " + " | ".join(клетки) + " |")
    строки += ["", "## Ответы целиком (с цитатами)", ""]
    for п in прогон.проверки.get(ЦИТАТЫ, []):
        о = п.ответ
        строки += [f"### {п.вопрос.get('id', '')}. {п.вопрос['вопрос']}", "",
                   f"Ожидание: {п.вопрос.get('ожидание', '—')}", ""]
        строки += ["> " + с for с in (о.текст or "—").splitlines()] + [""]
        if о.не_знаю:
            уверенность = о.решение.уверенность if о.решение is not None else None
            строки.append(f"«Не знаю» решил: {о.не_знаю_кто}; уверенность "
                          f"{'—' if уверенность is None else f'{уверенность:.2f}'}.")
        for и in о.источники:
            строки.append(f"- источник [{и['n']}] {и['source']} · {и['section']} · `{и['chunk_id']}`")
        for ц in о.выдержки:
            строки.append(f"- цитата [{ц.n}] ({ц.проверка}) «{ц.текст}»")
        if п.смысл_судья:
            строки.append(f"- судья ({п.модель_судьи}): смысл — {п.смысл_судья}"
                          + (f"; лишнее: {п.лишнее}" if п.лишнее else "") + (f". {п.пояснение}" if п.пояснение else ""))
        if о.нарушения:
            строки.append(f"- осталось нарушено: {'; '.join(о.нарушения)}")
        строки.append("")
    return "\n".join(строки)


def записать(прогон: Прогон, каталог_индекса: str) -> str:
    from agent.rag.indexer import КОРЕНЬ
    каталог_индекса = os.path.abspath(каталог_индекса)
    os.makedirs(каталог_индекса, exist_ok=True)
    записать_атомарно(os.path.join(каталог_индекса, "citations.json"),
                      json.dumps(прогон.to_dict(), ensure_ascii=False, indent=1))
    свой = каталог_индекса != os.path.abspath(os.path.join(КОРЕНЬ, "index"))
    путь = os.path.join(каталог_индекса if свой else КОРЕНЬ, "RAG-CITATIONS.md")
    записать_атомарно(путь, в_markdown(прогон))
    return путь


def прочитать(каталог_индекса: str) -> dict | None:
    путь = os.path.join(os.path.abspath(каталог_индекса), "citations.json")
    if not os.path.exists(путь):
        return None
    with open(путь, encoding="utf-8") as f:
        return json.load(f)
