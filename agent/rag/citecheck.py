"""Проверка ответов с цитатами (День 24): четыре требования задания на вопросах.

Вопросы — десять контрольных Дня 22 (rag-control.json: 8 с ответом и 2
ловушки) и расплывчатые (rag-vague.json: у вопроса нет предмета, правильный
ответ — «не знаю» и уточнение). Ответ — в формате «цитаты» через поиск «фильтр»
(LLM-реранкер), для сравнения рядом — формат Дня 23 без цитат.

На каждый ответ:
  источники   есть ли список источников, и у каждого — файл, раздел, chunk_id;
  цитаты      есть ли цитаты, и сколько из них код нашёл в документах
              (дословно, почти или в другом фрагменте);
  смысл       код: все числа ответа есть в подтверждённых цитатах, и ключевые
              факты вопроса — тоже; судья (не та модель, что отвечает): следует
              ли ответ из цитат — «да», «частично», «нет»;
  не знаю     на ловушке и расплывчатом вопросе — «не знаю» с уточняющим
              вопросом; на вопросе с ответом — его не должно быть.
"""

