"""Первый RAG-запрос: вопрос → поиск чанков → объединение с вопросом → LLM.

Два режима на одной и той же модели и одной и той же роли:

  без RAG   модель получает только вопрос и отвечает из общих знаний. На
            вопрос о конкретном договоре она либо честно не знает, либо —
            что хуже — выдаёт правдоподобное «обычно в таких договорах…».
            Лекция называет это самым опасным случаем: похоже на правду, и
            торопящийся человек не отличит.
  с RAG     перед вызовом идёт поиск в индексе Дня 21; найденные фрагменты
            нумеруются и кладутся в промпт вместе с паспортом (файл, раздел,
            пункт, страница). Модель обязана ставить [n] после каждого
            утверждения, а если ответа во фрагментах нет — так и сказать.

Режимы отличаются ТОЛЬКО контекстом: та же роль «помощник по документам», та
же модель, тот же вопрос. Иначе сравнение мерило бы разницу промптов, а не
вклад RAG.

Ссылки [n] разбираются кодом: так видно, на какие источники опирался ответ, и
это проверяется контрольными вопросами (qa.py). Ссылка на номер, которого не
было в контексте, считается выдуманной и показывается отдельно.

С Дня 24 ответ с RAG по умолчанию — в формате «цитаты» (cite.py): модель
возвращает JSON с ответом, номерами источников и дословными цитатами, код
проверяет цитаты по тексту фрагментов и подставляет паспорта источников. Если
лучшая оценка реранкера ниже порога уверенности, по документам не отвечают
вовсе: «не знаю» и уточняющий вопрос (abstain.py). Формат «текст» — ответ Дней
22–23, оставлен для сравнения.

С Дня 25 ответ может идти внутри чата (agent/chat): тогда перед фрагментами
в промпт ложится контекст разговора — цель, уточнения, ограничения, термины
и последние реплики. Он помогает понять вопрос и оформить ответ, но фактом
не считается: числа и цитаты по-прежнему только из фрагментов.

С Дня 28 параметры конвейера можно передать явно — профилем (profile.py):
локальный (поиск без LLM: bge-m3, косинус, кросс-энкодер; свой порог «не
знаю»; лучшее окно фрагмента) или облачный Дня 24. Каждый ответ несёт замеры:
секунды поиска по шагам, чтение промпта, первый токен, генерация, взят ли
промпт из кэша Ollama. По просьбе (ход=True) ответ объявляет этапы «поиск» и
«ответ» наблюдателю progress — так страница /rag показывает ход локального
ответа, который идёт минуты.
"""

from __future__ import annotations

import re
import time
from dataclasses import dataclass, field
from typing import Any

from agent.builder import Block
from agent.rag import abstain, cite
from agent.rag.store import Находка
