С_RAG = "rag"
БЕЗ_RAG = "без"
РЕЖИМЫ = (С_RAG, БЕЗ_RAG)
РОЛЬ_МОДЕЛИ = "ответ-по-документам"

# Сколько фрагментов класть в промпт. Пять чанков «структуры» — это ≈ 3 тысячи
# токенов: хватает, чтобы ответ, лежащий на втором-пятом месте, дошёл до
# модели (hit@5 в Дне 21 заметно выше hit@1), и не так много, чтобы нужный
# пункт утонул среди соседних.
СКОЛЬКО = 5
# Ниже этого косинуса фрагмент в промпт не идёт: это фильтр откровенно
# посторонних чанков, а не детектор «ответа нет». Замер на живом индексе
# показал, что порогом ловушку не поймать: у вопросов про Office 365 и Wi-Fi,
# которых в документах нет, лучшее сходство 0,58–0,61 — столько же, сколько у
# настоящих вопросов (0,59–0,69): бюджетные таблицы ИТ по смыслу близки к
# «подписке на ПО». От выдумки защищает правило промпта «В документах этого
# нет», и держится ли оно, проверяют контрольные вопросы-ловушки.
ПОРОГ = 0.45
# Ответ по документам короткий: число, срок, сумма и пара пояснений.
ПРЕДЕЛ_ОТВЕТА = 900
# С цитатами ответ длиннее: к нему добавляются дословные куски фрагментов.
ПРЕДЕЛ_ЦИТАТ = 1500
# Промпт взят из кэша Ollama, если прочитан быстрее этого (токенов в секунду).
# Счётчик prompt_eval_count при попадании в кэш не меняется — видно только
# время (проба Дня 28: 354 токена у qwen3.5:4b — 43,9 с заново и 0,84 с из
# кэша). Без кэша на этой машине 4B читает 7–16 ток/с, 1.7B — 25–40.
ПОРОГ_КЭША_ПРОМПТА = 100.0

# Форматы ответа с RAG: «цитаты» — День 24, «текст» — Дни 22–23.
ЦИТАТЫ = "цитаты"
ТЕКСТ = "текст"
ФОРМАТЫ = (ЦИТАТЫ, ТЕКСТ)

НЕТ_В_ДОКУМЕНТАХ = "В документах этого нет"

# День 25: правила для ответа внутри чата. Контекст разговора нужен, чтобы
# понять, о каком договоре «он» и что значит термин пользователя, и чтобы
# соблюсти его ограничения. Источником фактов он не становится: ответ,
# собранный из прошлых реплик, нечем подтвердить цитатой.
ПРАВИЛА_ЧАТА = """Перед фрагментами документов дан контекст разговора: цель, уточнения, \
ограничения и термины пользователя и последние реплики. По нему пойми, о чём \
вопрос (какой договор, какая статья бюджета имеется в виду) и как оформить \
ответ: ограничения пользователя соблюдай, его термины понимай так, как он их \
определил. Факты, числа и цитаты бери ТОЛЬКО из фрагментов документов, не из \
контекста разговора."""

РОЛЬ = """\
Ты — помощник специалиста ОАО «Газпром газораспределение Воронеж» по \
договорам связи, бюджету на ИТ, лицензиям и услугам. Отвечай по-русски, \
коротко и по существу: сначала прямой ответ (срок, сумма, количество, \
условие), затем одно-два пояснения. Без вступлений и без советов «уточните \
у юриста»."""

ПРАВИЛА_RAG = f"""\
Отвечай ТОЛЬКО по фрагментам документов, которые даны в сообщении \
пользователя. Общие знания о «типичных договорах» не используй.
После каждого утверждения ставь номер фрагмента в квадратных скобках: [1], \
[2]. Ссылайся только на номера, которые есть среди фрагментов.
Если во фрагментах ответа нет, ответь одной фразой: «{НЕТ_В_ДОКУМЕНТАХ}» — и \
не пытайся угадать. Если ответ есть лишь частично, скажи, что известно, и \
прямо назови, чего во фрагментах нет."""

# Как модель говорит «не нашёл»: разбор нужен и режиму без RAG — там честное
# «не знаю» лучше выдумки, и оценка это учитывает. Только явные формулировки:
# «не указан» и «не содержит» встречаются и в содержательных ответах («если в
# договоре не указан иной срок») — первая версия шаблона принимала такой ответ
# за отказ.
ОТКАЗ = re.compile(
    r"в (?:документах|фрагментах) (?:этого |такого |таких сведений |сведений об этом )?нет"
    r"|во фрагментах (?:этого |такого )?нет|у меня нет (?:доступа|информации|сведений|данных)"
    r"|в (?:предоставленном |данном )?контексте нет"
    r"|в (?:предоставленных|имеющихся) (?:данных|материалах|документах) нет"
    r"|не располагаю|не могу (?:знать|ответить|сказать)|не знаю", re.IGNORECASE)
ССЫЛКА = re.compile(r"\[(\d{1,2})(?:\s*[,;]\s*(\d{1,2}))*\]")


@dataclass
class ОтветRAG:
    """Ответ в одном из режимов со всем, что к нему привело."""

    вопрос: str
    режим: str
    текст: str = ""
    модель: str = ""
    фрагменты: list[Находка] = field(default_factory=list)   # что ушло в промпт
    отсеяно: list[Находка] = field(default_factory=list)     # ниже порога
    цитаты: list[int] = field(default_factory=list)          # номера [n] из ответа
    выдуманные_ссылки: list[int] = field(default_factory=list)
    отказ: bool = False                                        # «в документах этого нет»
    блоки: list[Block] = field(default_factory=list)
    сообщения: list[dict[str, str]] = field(default_factory=list)
    токенов_вход: int = 0
    токенов_выход: int = 0
    стоимость: float = 0.0
    секунд_поиска: float = 0.0
    секунд_модели: float = 0.0
    стратегия: str = ""
    ошибка: str = ""
    # День 23: каким поиском найдены фрагменты и протокол его этапов.
    поиск: str = ""
    отбор: Any = None
    # День 24: ответ с цитатами и режим «не знаю».
    формат: str = ТЕКСТ
    выдержки: list = field(default_factory=list)   # cite.Цитата — дословные куски фрагментов
    не_знаю: bool = False
    уточнение: str = ""
    причина_не_знаю: str = ""
    решение: Any = None                              # abstain.Решение: уверенность и порог
    ближайшие: list[Находка] = field(default_factory=list)
    не_знаю_кто: str = ""                            # порог | модель | проверка цитат | поиск
    нарушения: list[str] = field(default_factory=list)   # что осталось нарушено в формате
    починка: bool = False                            # был ли повторный запрос
    вызовов: int = 0
    # День 25: контекст разговора для ответа в чате и текст, числа которого
    # не требуют цитаты (реплика пользователя, его ограничения и термины).
    контекст: str = ""
    свои_числа: str = ""
    # День 27: какие фрагменты в офлайне заменены лучшим окном кросс-энкодера.
    окна: list[dict[str, Any]] = field(default_factory=list)
    # День 28: профиль конвейера, замеры каждого вызова модели, секунды выбора
    # окон; ход — объявлять ли этапы наблюдателю progress.
    профиль: str = ""
    # День 29: шаблон системного промпта (общий | договоры) и конфигурация
    # вызова локальной модели (agent/local/tuning.py), если была.
    шаблон: str = "общий"
    конфигурация: str = ""
    замеры_вызовов: list[dict[str, Any]] = field(default_factory=list)
    секунд_окон: float = 0.0
    ход: bool = False

    @property
    def источники(self) -> list[dict[str, Any]]:
        """Паспорта фрагментов, на которые ответ сослался, в порядке номеров."""
        итог = []
        for номер in self.цитаты:
            if 1 <= номер <= len(self.фрагменты):
                н = self.фрагменты[номер - 1]
                итог.append({"n": номер, **н.чанк.паспорт(), "score": round(н.оценка, 4)})
        return итог

    def to_dict(self) -> dict[str, Any]:
        return {
            "question": self.вопрос, "mode": self.режим, "text": self.текст,
            "model": self.модель, "strategy": self.стратегия,
            # С цитатами — фрагмент целиком: цитата подсвечивается в его тексте.
            "fragments": [{"n": i, **н.кратко(4000 if self.формат == ЦИТАТЫ else 500)}
                          for i, н in enumerate(self.фрагменты, 1)],
            "dropped": [н.кратко(160) for н in self.отсеяно],
            "citations": list(self.цитаты), "sources": self.источники,
            "bad_citations": list(self.выдуманные_ссылки), "refusal": self.отказ,
            "blocks": [б.to_dict() for б in self.блоки],
            "tokens_in": self.токенов_вход, "tokens_out": self.токенов_выход,
            "cost": round(self.стоимость, 6), "search_seconds": round(self.секунд_поиска, 2),
            "model_seconds": round(self.секунд_модели, 2), "error": self.ошибка,
            "search": self.поиск,
            "selection": self.отбор.to_dict() if self.отбор is not None else None,
            "format": self.формат,
            "quotes": [{**ц.to_dict(), "chunk_id": (self.фрагменты[ц.найдена_в - 1].чанк.chunk_id
                                                    if 1 <= ц.найдена_в <= len(self.фрагменты) else "")}
                       for ц in self.выдержки],
            "abstain": self.не_знаю, "clarification": self.уточнение,
            "abstain_reason": self.причина_не_знаю, "abstain_by": self.не_знаю_кто,
            "confidence": self.решение.to_dict() if self.решение is not None else None,
            "nearest": [н.кратко(200) for н in self.ближайшие],
            "violations": list(self.нарушения), "repaired": self.починка, "calls": self.вызовов,
            "chat_context": self.контекст, "windows": list(self.окна),
            "profile": self.профиль, "timings": self.замеры(),
            "template": self.шаблон, "config": self.конфигурация,
        }

    def замеры(self) -> dict[str, Any]:
        """Скорость ответа по слоям (День 28): поиск, окна, чтение промпта,
        первый токен, генерация. Замеры Ollama есть только у локальной модели;
        у облачной токены в секунду считаются по общему времени ответа."""
        поиск = реранк = {}
        if self.отбор is not None:
            поиск = next((э for э in self.отбор.этапы if э.get("этап") == "поиск"), {})
            реранк = next((э for э in self.отбор.этапы if э.get("этап") == "реранк"), {})
        локальные = [в for в in self.замеры_вызовов if в.get("prompt_s") is not None]
        первый = self.замеры_вызовов[0] if self.замеры_вызовов else {}
        генерация = round(sum(в.get("gen_s", 0.0) for в in локальные), 2) if локальные else None
        if генерация:
            ток_с, по = round(self.токенов_выход / генерация, 1), "генерации"
        else:
            ток_с = round(self.токенов_выход / self.секунд_модели, 1) if self.секунд_модели else 0.0
            по = "общему времени"
        скорость = первый.get("prompt_tok_s") if локальные else None
        return {
            "поиск_с": round(self.секунд_поиска, 2), "вектор_с": поиск.get("вектор_с"),
            "косинус_с": поиск.get("косинус_с"), "кросс_с": реранк.get("секунд"),
            "оценок_из_кэша": реранк.get("из_кэша"), "оценок_посчитано": реранк.get("посчитано"),
            "окна_с": round(self.секунд_окон, 2), "модель": self.модель, "вызовов": self.вызовов,
            "вход": self.токенов_вход, "выход": self.токенов_выход,
            "чтение_с": round(sum(в.get("prompt_s", 0.0) for в in локальные), 2) if локальные else None,
            "до_первого_с": первый.get("ttft_s") if локальные else None,
            "генерация_с": генерация, "загрузка_с": (round(sum(в.get("load_s", 0.0) for в in локальные), 2)
                                                     if локальные else None),
            "ток_с": ток_с, "ток_с_по": по, "скорость_чтения": скорость,
            "кэш_промпта": (скорость >= ПОРОГ_КЭША_ПРОМПТА) if скорость is not None else None,
            "модель_с": round(self.секунд_модели, 2),
            "всего_с": round(self.секунд_поиска + self.секунд_окон + self.секунд_модели, 2),
        }


def сводка_поиска(отбор) -> dict[str, Any]:
    """Этап «поиск» для наблюдателя и консоли (День 28): что и за сколько нашли."""
    н = отбор.настройки
    поиск = next((э for э in отбор.этапы if э.get("этап") == "поиск"), {})
    реранк = next((э for э in отбор.этапы if э.get("этап") == "реранк"), {})
    return {"реранкер": н.реранкер or "—", "k_до": н.k_до, "k_после": н.k_после,
            "кандидатов": поиск.get("кандидатов", 0), "в_промпт": len(отбор.фрагменты),
            "секунд": round(отбор.секунд, 2), "вектор_с": поиск.get("вектор_с"),
            "косинус_с": поиск.get("косинус_с"), "кросс_с": реранк.get("секунд"),
            "из_кэша": реранк.get("из_кэша"), "без_кэша": реранк.get("без_кэша", False),
            "rewrite": н.rewrite}


def паспорт_строкой(находка: Находка) -> str:
    ч = находка.чанк
    части = [ч.источник, ч.раздел]
    if ч.пункт:
        части.append(f"п. {ч.пункт}")
    if ч.страницы:
        части.append(f"стр. {ч.страницы}")
    return " · ".join(части)


def собрать_сообщения(вопрос: str, режим: str, фрагменты: list[Находка],
                      формат: str = ТЕКСТ, контекст: str = "",
                      шаблон: str = "общий") -> tuple[list[dict[str, str]], list[Block]]:
    """Промпт режима и его разбор по блокам — тот же след, что у агента.

    контекст — память задачи и последние реплики чата (День 25); идёт перед
    фрагментами вместе с правилом «факты только из фрагментов».

    шаблон — «договоры» (День 29): короткий системный промпт для локальной
    модели вместо роли и правил цитирования; формат ответа и проверки те же."""
    блоки = [Block("ядро", "роль: помощник по документам", РОЛЬ, ["системный промпт"],
                   why="одна и та же в обоих режимах", tokens=estimate(РОЛЬ))]
    система = РОЛЬ
    if режим == С_RAG:
        правила = cite.ПРАВИЛА_ЦИТАТ if формат == ЦИТАТЫ else ПРАВИЛА_RAG
        if контекст:
            правила = f"{правила}\n\n{ПРАВИЛА_ЧАТА}"
        система = f"{РОЛЬ}\n\n{правила}"
        if формат == ЦИТАТЫ and шаблон == "договоры":
            правила = cite.ШАБЛОН_ДОГОВОРЫ + (f"\n\n{ПРАВИЛА_ЧАТА}" if контекст else "")
            система = правила
            блоки = []
        блоки.append(Block("ядро", "правила ответа по документам", правила,
                           ["только по фрагментам", "ссылки [n]",
                            *(["JSON: ответ, источники, цитаты", "не знаю + уточнение"]
                              if формат == ЦИТАТЫ else [НЕТ_В_ДОКУМЕНТАХ])],
                           why="режим с RAG", tokens=estimate(правила)))
        куски = []
        for номер, н in enumerate(фрагменты, 1):
            шапка = f"[{номер}] {паспорт_строкой(н)}"
            куски.append(f"{шапка}\n{н.чанк.текст}")
            блоки.append(Block("документы", f"фрагмент [{номер}]", н.чанк.текст,
                               [шапка, н.чанк.chunk_id, f"сходство {н.оценка:.3f}"],
                               why="найден поиском по вопросу", tokens=н.чанк.токенов))
        if контекст:
            блоки.append(Block("память", "контекст разговора", контекст,
                               ["цель, уточнения, ограничения, термины", "последние реплики"],
                               why="ответ внутри чата: понять вопрос, а не взять факты",
                               tokens=estimate(контекст)))
        вступление = f"Контекст разговора (не источник фактов):\n{контекст}\n\n" if контекст else ""
        if куски:
            пользователь = (вступление + "Фрагменты документов:\n\n" + "\n\n".join(куски)
                            + f"\n\nВопрос: {вопрос}")
        else:
            пользователь = (вступление + "Фрагментов, похожих на вопрос, в документах не нашлось.\n\n"
                            f"Вопрос: {вопрос}")
            блоки.append(Block("документы", "фрагментов нет", "", [],
                               why="ни один чанк не прошёл отбор", included=False))
    else:
        пользователь = вопрос
    блоки.append(Block("запрос", "вопрос", вопрос, [], tokens=estimate(вопрос)))
    return ([{"role": "system", "content": система},
             {"role": "user", "content": пользователь}], блоки)


def разобрать_ссылки(текст: str, всего: int) -> tuple[list[int], list[int]]:
    """Номера [n] из ответа: существующие по порядку появления и выдуманные."""
    найдено: list[int] = []
    for м in ССЫЛКА.finditer(текст):
        for номер in re.findall(r"\d{1,2}", м.group(0)):
            n = int(номер)
            if n not in найдено:
                найдено.append(n)
    верные = [n for n in найдено if 1 <= n <= всего]
    return верные, [n for n in найдено if n not in верные]


class Отвечатель:
    """Функция дня: вопрос → поиск → промпт → модель. Режим задаётся вызовом."""

    def __init__(self, индексатор, клиент, стратегия: str = "структура",
                 сколько: int = СКОЛЬКО, порог: float | None = None,
                 формат: str = ЦИТАТЫ, порог_уверенности: float | None = None) -> None:
        self.индексатор = индексатор
        self.клиент = клиент
        self.стратегия = стратегия
        self.сколько = сколько
        # Порог читается при создании, а не при загрузке модуля: значение по
        # умолчанию в сигнатуре вычислилось бы один раз и не видело бы правки.
        self.порог = ПОРОГ if порог is None else порог
        self.формат = формат
        # None — порог уверенности из rag-settings.json (подбор abstain.py).
        self.порог_уверенности = порог_уверенности
        self._поисковик = None

    @property
    def поисковик(self):
        """Двухэтапный поиск Дня 23 — создаётся при первом режиме с фильтром."""
        if self._поисковик is None:
            from agent.rag.retrieval import Поисковик
            self._поисковик = Поисковик(self.индексатор, self.клиент, self.стратегия)
        return self._поисковик

    def найти(self, вопрос: str) -> tuple[list[Находка], list[Находка], float]:
        старт = time.monotonic()
        находки = self.индексатор.найти(вопрос, self.стратегия, self.сколько)
        прошли = [н for н in находки if н.оценка >= self.порог]
        отсеяно = [н for н in находки if н.оценка < self.порог]
        return прошли, отсеяно, time.monotonic() - старт

    def ответить(self, вопрос: str, режим: str = С_RAG, модель: str = "",
                 найдено: tuple[list[Находка], list[Находка], float] | None = None,
                 поиск: str = "", формат: str = "",
                 порог_уверенности: float | None = None,
                 контекст: str = "", свои_числа: str = "", отбор: Any = None,
                 профиль: Any = None, ход: bool = False, без_кэша: bool = False) -> ОтветRAG:
        """поиск — режим поиска Дня 23 (база | фильтр | rewrite | полный).

        Пусто или «база» — поиск Дня 22 как был: top-«сколько» по косинусу с
        порогом. Остальные режимы идут через двухэтапный Поисковик, и протокол
        его этапов остаётся в ответе (ответ.отбор).

        формат — «цитаты» (День 24, по умолчанию) или «текст» (Дни 22–23).

        контекст и свои_числа — для ответа внутри чата (День 25): контекст
        разговора идёт в промпт перед фрагментами, а числа из своих_чисел
        (реплика пользователя, его ограничения) не требуют цитаты. отбор —
        готовый результат поиска (чат ищет по подвопросам и сливает найденное).

        профиль (День 28, profile.py) — параметры конвейера явно: поиск, если
        он не задан аргументом, порог «не знаю», лучшее окно. Без профиля — в
        офлайне локальный, иначе поведение Дня 24. ход — объявлять этапы
        «поиск» и «ответ» наблюдателю progress; без_кэша — оценки реранкера
        считаются заново («новый вопрос»).
        """
        from agent.rag import profile as rag_profile
        from agent import catalog
        вопрос = (вопрос or "").strip()
        if not вопрос:
            raise ValueError("Пустой вопрос")
        if режим not in РЕЖИМЫ:
            raise ValueError(f"Нет режима «{режим}». Есть: {', '.join(РЕЖИМЫ)}")
        формат = формат or self.формат
        if формат not in ФОРМАТЫ:
            raise ValueError(f"Нет формата «{формат}». Есть: {', '.join(ФОРМАТЫ)}")
        ответ = ОтветRAG(вопрос=вопрос, режим=режим, стратегия=self.стратегия,
                         модель=модель or catalog.for_role(РОЛЬ_МОДЕЛИ, 0),
                         контекст=(контекст or "").strip(), свои_числа=свои_числа or "", ход=ход)
        if профиль is not None and not поиск and отбор is None:
            поиск = профиль.поиск
        if профиль is None:
            профиль = rag_profile.текущий(self.поисковик)
        ответ.профиль = профиль.имя if профиль is not None else ""
        if режим == С_RAG and (отбор is not None or (поиск and поиск != "база")):
            if отбор is None:
                отбор = self.поисковик.найти(вопрос, поиск, без_кэша=без_кэша)
                if ход:
                    from agent.local import progress
                    progress.этап("поиск", **сводка_поиска(отбор))
            # поиск — имя режима или готовые Настройки (поправки порога и K).
            ответ.поиск = поиск if isinstance(поиск, str) else (поиск.имя or "свои настройки")
            ответ.отбор = отбор
            ответ.фрагменты = отбор.фрагменты
            ответ.отсеяно = [к.находка for к in отбор.кандидаты if к.судьба != "в промпт"]
            ответ.секунд_поиска = отбор.секунд
        elif режим == С_RAG:
            прошли, отсеяно, секунд = найдено or self.найти(вопрос)
            ответ.фрагменты, ответ.отсеяно, ответ.секунд_поиска = прошли, отсеяно, секунд
            ответ.поиск = "база"
        if режим == С_RAG and формат == ЦИТАТЫ:
            return self._ответить_с_цитатами(ответ, порог_уверенности, профиль)
        ответ.сообщения, ответ.блоки = собрать_сообщения(вопрос, режим, ответ.фрагменты)
        старт = time.monotonic()
        from agent.llm import LLMError
        try:
            reply = self.клиент.call(ответ.модель, ответ.сообщения, max_tokens=ПРЕДЕЛ_ОТВЕТА)
        except LLMError as exc:
            ответ.ошибка = str(exc)
            return ответ
        ответ.секунд_модели = time.monotonic() - старт
        ответ.текст = (reply.text or "").strip()
        ответ.токенов_вход, ответ.токенов_выход = reply.prompt_tokens, reply.completion_tokens
        ответ.стоимость = reply.cost
        ответ.цитаты, ответ.выдуманные_ссылки = разобрать_ссылки(ответ.текст, len(ответ.фрагменты))
        ответ.отказ = bool(ОТКАЗ.search(ответ.текст))
        return ответ

    # --- День 24: ответ с цитатами и «не знаю» -----------------------------------

    def _вызвать(self, ответ: ОтветRAG, сообщения: list[dict[str, str]], предел: int):
        """Вызов модели с учётом токенов и времени; None — сбой, причина в ответ.ошибка."""
        from agent.llm import LLMError
        from agent.local import schemas
        старт = time.monotonic()
        try:
            # Локальной модели — схема ответа с цитатами (format в Ollama):
            # маленькая модель иначе начинает JSON с рассуждения.
            формат = schemas.формат(РОЛЬ_МОДЕЛИ, ответ.модель, "цитаты")
            # И температура роли из карты (День 28) — тоже только локальной модели.
            температура = schemas.температура(РОЛЬ_МОДЕЛИ, ответ.модель)
            reply = self.клиент.call(ответ.модель, сообщения, max_tokens=предел,
                                     **({"fmt": формат} if формат is not None else {}),
                                     **({"temperature": температура} if температура is not None else {}))
        except LLMError as exc:
            ответ.ошибка = str(exc)
            return None
        self._учесть(ответ, reply, time.monotonic() - старт)
        return reply

    @staticmethod
    def _учесть(ответ: ОтветRAG, reply, секунд: float = 0.0) -> None:
        ответ.вызовов += 1
        ответ.секунд_модели += секунд
        ответ.токенов_вход += reply.prompt_tokens
        ответ.токенов_выход += reply.completion_tokens
        ответ.стоимость += reply.cost
        ответ.замеры_вызовов.append({"модель": reply.model_key, "вход": reply.prompt_tokens,
                                     "выход": reply.completion_tokens, "секунд": round(секунд, 2),
                                     # День 29: почему модель остановилась — «length» значит,
                                     # что ответ упёрся в предел (num_predict) и оборван.
                                     "done": getattr(reply, "finish_reason", "") or "",
                                     **dict(getattr(reply, "timings", None) or {})})

    def _порог_уверенности(self, поправка: float | None = None, профиль: Any = None) -> float:
        """Явная поправка → порог отвечателя → порог профиля (без профиля — текущего:
        в офлайне локального) → rag-settings.json (подбор Дня 24)."""
        if поправка is not None:
            return поправка
        if self.порог_уверенности is not None:
            return self.порог_уверенности
        if профиль is None:
            from agent.rag import profile as rag_profile
            профиль = rag_profile.текущий(self.поисковик)
        if профиль is not None and профиль.порог_уверенности is not None:
            # У кросс-энкодера своя шкала оценок: порог, подобранный под
            # LLM-реранкер (0,5), отправил бы в «не знаю» всё подряд.
            return профиль.порог_уверенности
        from agent.rag.retrieval import прочитать_настройки
        return float(прочитать_настройки(self.поисковик.путь_настроек)["порог_уверенности"])

    def _не_знаю(self, ответ: ОтветRAG, кто: str, причина: str, ближайшие: list[Находка],
                 уточнение: str = "") -> ОтветRAG:
        """«Не знаю» и уточняющий вопрос. Уточнение пишет модель по названиям
        ближайших разделов; источников и цитат у такого ответа нет."""
        if not уточнение:
            if ответ.ход:
                from agent import catalog
                from agent.local import progress
                progress.этап("уточнение", модель=ответ.модель, локально=catalog.get(ответ.модель).local,
                              кто=кто)
            старт = time.monotonic()
            from agent.local import schemas
            уточнение, reply = abstain.уточнить(self.клиент, ответ.модель, ответ.вопрос, ближайшие,
                                                schemas.температура(РОЛЬ_МОДЕЛИ, ответ.модель))
            if reply is not None:
                self._учесть(ответ, reply, time.monotonic() - старт)
        ответ.не_знаю, ответ.причина_не_знаю = True, причина
        ответ.уточнение = abstain.очистить_уточнение(уточнение)
        ответ.не_знаю_кто = кто
        ответ.ближайшие = list(ближайшие)
        ответ.текст = abstain.текст_не_знаю(причина, уточнение)
        ответ.цитаты, ответ.отказ = [], True
        return ответ

    def _лучшие_окна(self, ответ: ОтветRAG, фрагменты: list[Находка]) -> list[Находка]:
        """Офлайн (День 27): длинный фрагмент → его лучшее окно по кросс-энкодеру.

        Цитаты потом проверяются по тому же окну: модель видела только его.
        Сколько символов было и стало — в ответ.окна (видно в отчёте и на
        странице). Кросс-энкодер недоступен — фрагменты остаются целыми."""
        from dataclasses import replace as заменить
        from agent.rag import rerank as rr
        старт = time.monotonic()
        try:
            реранкер = self.поисковик.реранкер(rr.КРОСС)
        except Exception:   # noqa: BLE001 — без кросс-энкодера окно не выбрать
            return фрагменты
        итог = []
        for н in фрагменты:
            try:
                окно, оценка, окон = реранкер.лучшее_окно(ответ.вопрос, н.чанк)
            except rr.ОшибкаРеранкера:
                итог.append(н)
                continue
            if окон > 1 and len(окно) < len(н.чанк.текст):
                ответ.окна.append({"chunk_id": н.чанк.chunk_id, "было": len(н.чанк.текст),
                                   "стало": len(окно), "окон": окон, "оценка": round(оценка, 4)})
                н = заменить(н, чанк=заменить(н.чанк, текст=окно))
            итог.append(н)
        ответ.секунд_окон += time.monotonic() - старт
        return итог

    def _ответить_с_цитатами(self, ответ: ОтветRAG, поправка: float | None = None,
                             профиль: Any = None) -> ОтветRAG:
        ответ.формат = ЦИТАТЫ
        порог = self._порог_уверенности(поправка, профиль)
        if ответ.отбор is not None:
            ответ.решение = abstain.решить(ответ.отбор, порог)
            if ответ.решение.не_знаю:
                # Слабый контекст: по документам не отвечаем вовсе — в промпт
                # ничего не идёт, модель только формулирует уточнение.
                ответ.фрагменты = []
                return self._не_знаю(
                    ответ, "порог", "в документах не нашлось достаточно близкого фрагмента — лучшая "
                           f"релевантность {ответ.решение.уверенность:.2f} при пороге {порог:.2f}",
                    ответ.решение.ближайшие)
        if not ответ.фрагменты:
            return self._не_знаю(ответ, "поиск", "в документах не нашлось похожих фрагментов",
                                 ответ.отсеяно[:abstain.БЛИЖАЙШИХ])
        if профиль is not None and профиль.окно_фрагмента:
            ответ.фрагменты = self._лучшие_окна(ответ, ответ.фрагменты)
        from agent.local import tuning
        ответ.шаблон = tuning.шаблон_для(ответ.модель)
        конф = tuning.для_модели(ответ.модель)
        ответ.конфигурация = конф.имя if конф is not None else ""
        ответ.сообщения, ответ.блоки = собрать_сообщения(ответ.вопрос, С_RAG, ответ.фрагменты, ЦИТАТЫ,
                                                         ответ.контекст, ответ.шаблон)
        if ответ.ход:
            from agent import catalog
            from agent.local import progress
            progress.этап("ответ", модель=ответ.модель, локально=catalog.get(ответ.модель).local,
                          фрагментов=len(ответ.фрагменты), окна=len(ответ.окна),
                          окна_с=round(ответ.секунд_окон, 2))
        reply = self._вызвать(ответ, ответ.сообщения, ПРЕДЕЛ_ЦИТАТ)
        if reply is None:
            return ответ
        тексты = [н.чанк.текст for н in ответ.фрагменты]
        свои = f"{ответ.вопрос}\n{ответ.свои_числа}"
        разбор = cite.разобрать(reply.text)
        cite.проверить_цитаты(разбор, тексты)
        нарушено = cite.нарушения(разбор, len(тексты), свои)
        if нарушено:
            # Один повторный запрос: модель видит свой ответ и список нарушений.
            повтор = ответ.сообщения + [{"role": "assistant", "content": reply.text or ""},
                                        {"role": "user", "content": cite.сообщение_починки(нарушено)}]
            reply2 = self._вызвать(ответ, повтор, ПРЕДЕЛ_ЦИТАТ)
            ответ.починка = True
            if reply2 is not None:
                разбор = cite.разобрать(reply2.text)
                cite.проверить_цитаты(разбор, тексты)
                нарушено = cite.нарушения(разбор, len(тексты), свои)
            else:
                # Повтор не удался — остаётся первый ответ, а сбой виден в нарушениях.
                нарушено = нарушено + [f"повторный запрос не удался: {ответ.ошибка[:120]}"]
                ответ.ошибка = ""
        ответ.нарушения, ответ.выдержки = нарушено, разбор.цитаты
        if разбор.не_знаю:
            if разбор.неоднозначно:
                причина = "вопрос можно понять по-разному — подходящих ответов в документах несколько"
            elif ответ.решение is not None:
                # Поиск уверен, что близкое нашлось, а модель ответа не видит: в
                # документах может быть и несколько ответов, и ни одного прямого.
                причина = "в найденных фрагментах нет однозначного ответа"
            else:
                причина = НЕТ_В_ДОКУМЕНТАХ[:1].lower() + НЕТ_В_ДОКУМЕНТАХ[1:]
            return self._не_знаю(ответ, "модель", причина,
                                 ответ.фрагменты[:abstain.БЛИЖАЙШИХ], разбор.уточнение)
        if not cite.подтверждённые(разбор):
            # Нет цитаты — нет ответа: текст без подтверждения в документах не выдаём.
            return self._не_знаю(ответ, "проверка цитат", "ответ не подтверждается цитатами из документов",
                                 ответ.фрагменты[:abstain.БЛИЖАЙШИХ])
        всего = len(тексты)
        номера = [n for n in разбор.источники if 1 <= n <= всего]
        for n in cite.ссылки_в_тексте(разбор.ответ) + [ц.найдена_в for ц in разбор.цитаты]:
            if 1 <= n <= всего and n not in номера:
                номера.append(n)
        ответ.текст = разбор.ответ
        ответ.цитаты = номера
        ответ.выдуманные_ссылки = sorted({n for n in разбор.источники + cite.ссылки_в_тексте(разбор.ответ)
                                          if not 1 <= n <= всего})
        ответ.отказ = bool(ОТКАЗ.search(ответ.текст))
        return ответ

    def сравнить_поиск(self, вопрос: str, режимы: tuple[str, ...] | list[str] = (),
                       модель: str = "") -> dict[str, ОтветRAG]:
        """Один вопрос во всех режимах поиска Дня 23 — на одной модели."""
        from agent.rag.retrieval import РЕЖИМЫ_ПОИСКА
        return {р: self.ответить(вопрос, С_RAG, модель, поиск=р) for р in (режимы or РЕЖИМЫ_ПОИСКА)}

    def сравнить(self, вопрос: str, модель: str = "") -> dict[str, ОтветRAG]:
        """Один вопрос в обоих режимах — рядом, на одной модели."""
        return {БЕЗ_RAG: self.ответить(вопрос, БЕЗ_RAG, модель),
                С_RAG: self.ответить(вопрос, С_RAG, модель)}
