def выбрать(св: dict[str, dict[str, Any]], конфигурации: dict[str, Any], база: str = "до",
            микро: dict[str, dict[str, Any]] | None = None,
            вето_: dict[str, Any] | None = None) -> dict[str, Any]:
    """Правило D-05, версия 4 (plan.md). Время ответа на скрининге — шум: тождественные
    конфигурации расходились на ±30 % при нагрузке 3–7. Поэтому:
    - качество — парно: ни на одном вопросе не хуже «до», без обрывов и лишних починок;
    - выигрыш по детерминированным показателям (парно): токены промпта или ответа,
      пик ОЗУ — на ≥ 5 %; «Р-предел» — страховка худшего случая, берётся без выигрыша;
    - выигрыш по скорости — только из микрозамера (микро): скорость чтения или
      генерации лучше «до» на ≥ 10 % (вдвое выше шума контроля) в медиане парных раундов
      и не меньше чем в 4 из 5;
    - проигрыш по детерминированному показателю (память, токены +5 %) или по скорости
      в микрозамере — отказ.
    Из весов (квантов) — лучший один. Серверные рычаги в «после» не входят — они идут
    рекомендацией для службы (spec, FR-09).
    Версия 4: вето — рычаг, который прошёл скрининг на трёх вопросах, но провалил проверку
    вне набора (шаблон «договоры» на вопросе о двух договорах сразу — «не знаю»), отклоняется
    с причиной и фактами проверки."""
    if база not in св:
        return {"взяты": [], "серверные": [], "отклонены": [], "веса": "", "причины": {"до": "нет замера «до»"}}
    б = св[база]
    взяты, серверные, отклонены, причины = [], [], [], {}
    кандидаты_весов = []
    м_б = (микро or {}).get(база)
    for имя, с in св.items():
        if имя == база or not с.get("рычаг"):
            continue
        к = конфигурации.get(имя)
        if имя == КОНТРОЛЬ:
            м_к = (микро or {}).get(имя) or {}
            причины[имя] = ("контроль: «до» на втором сервере без переменных — мерило шума"
                            + (f" (микрозамер: чтение {_проценты(м_к.get('чтение_доля'))}, генерация "
                               f"{_проценты(м_к.get('генерация_доля'))})" if м_к else ""))
            continue
        if с.get("пропусков") and not с.get("годных"):
            отклонены.append(имя)
            причины[имя] = "не замерен: пропуск"
            continue
        if имя in (вето_ or {}):
            в = (вето_ or {})[имя]
            отклонены.append(имя)
            причины[имя] = "отклонён проверкой вне набора: " + (в.get("причина", "") if isinstance(в, dict) else str(в))
            continue
        д = сравнить(б, с)
        качество_ок = (с["годных"] > 0 and not д["хуже_на"] and с["верно"] >= б["верно"] - с.get("пропусков", 0)
                       and с["обрывов"] == 0 and с["ошибок"] == 0 and с["починок"] <= б["починок"])
        if not качество_ок:
            отклонены.append(имя)
            причины[имя] = (f"качество хуже «до»: верно {с['верно']} из {с['годных']} против {б['верно']}"
                            + (f", хуже на {', '.join(д['хуже_на'])}" if д["хуже_на"] else "")
                            + (f", обрывов {с['обрывов']}" if с["обрывов"] else "")
                            + (f", починок {с['починок']} против {б['починок']}" if с["починок"] > б["починок"] else ""))
            continue
        выигрыши, проигрыши = [], []
        for поле, слово in (("вход", "промпт"), ("выход", "ответ"), ("пик_мб", "пик ОЗУ")):
            if д[поле] is not None and д[поле] <= -ПОРОГ_ВЫИГРЫША:
                выигрыши.append(f"{слово} {_проценты(д[поле])}")
            if д[поле] is not None and д[поле] >= ПОРОГ_ВЫИГРЫША:
                проигрыши.append(f"{слово} {_проценты(д[поле])}")
        м = (микро or {}).get(имя)
        if м and м_б:
            for поле, слово in (("чтение_доля", "скорость чтения"), ("генерация_доля", "скорость генерации")):
                доля, побед = м.get(поле), м.get(поле.replace("доля", "побед"), 0)
                раундов = м.get("раундов") or 0
                if доля is not None and доля >= ПОРОГ_СКОРОСТИ and раундов and побед >= 0.8 * раундов:
                    выигрыши.append(f"{слово} {_проценты(доля)} ({побед} из {раундов} раундов)")
                if доля is not None and доля <= -ПОРОГ_ВЫИГРЫША and раундов and побед <= 0.2 * раундов:
                    проигрыши.append(f"{слово} {_проценты(доля)} ({побед} из {раундов} раундов)")
        if к is not None and к.рычаг == "Р-предел" and not проигрыши:
            выигрыши.append("предел ответа ограничивает худший случай: зацикленный ответ не идёт минутами")
        if проигрыши:
            отклонены.append(имя)
            причины[имя] = "проигрыш: " + ", ".join(проигрыши) + (f"; при этом {', '.join(выигрыши)}" if выигрыши else "")
            continue
        if not выигрыши:
            отклонены.append(имя)
            причины[имя] = ("выигрыша нет: токены и память как у «до»"
                            + (f"; микрозамер: чтение {_проценты(м.get('чтение_доля'))}, генерация "
                               f"{_проценты(м.get('генерация_доля'))} — ниже порога {ПОРОГ_СКОРОСТИ * 100:.0f} %"
                               if м else "; скорость — в микрозамер не входил или его ещё нет")
                            + "; время ответа на скрининге — в пределах шума")
            continue
        причина = ", ".join(выигрыши) + ", качество не хуже"
        if к is not None and к.серверная:
            серверные.append(имя)
            причины[имя] = причина + " — серверный рычаг: рекомендация для службы"
        elif к is not None and к.тег and к.рычаг != "Р-без-проектора":
            # Веса (квант) — один из нескольких: берём лучший. «Без проектора» —
            # не другой квант, а поправка к любым весам: она идёт отдельно.
            кандидаты_весов.append((д["пик_мб"] if д["пик_мб"] is not None else 0.0, имя))
            причины[имя] = причина
        else:
            взяты.append(имя)
            причины[имя] = причина
    веса = ""
    if кандидаты_весов:
        кандидаты_весов.sort()
        веса = кандидаты_весов[0][1]
        взяты.append(веса)
        for _, имя in кандидаты_весов[1:]:
            отклонены.append(имя)
            причины[имя] += f"; из весов взят {веса}"
    return {"взяты": взяты, "серверные": серверные, "отклонены": отклонены, "веса": веса, "причины": причины,
            "правило": "D-05, версия 4: качество парно; выигрыш — токены и память на ≥ 5 % (детерминированные) или "
                       "скорость из микрозамера на ≥ 10 % (вдвое выше шума контроля «р-сервер2»); время ответа на "
                       "скрининге — шум; вето — рычаг, проваленный проверкой вне набора скрининга"}


def _проценты(доля: float | None) -> str:
    if доля is None:
        return "—"
    return f"{доля * 100:+.0f} %".replace("-", "−")


def собрать_после(решение: dict[str, Any], конфигурации: dict[str, Any], база: str = "до") -> dict[str, Any]:
    """Конфигурация «после» из взятых рычагов: опции складываются, веса — от выбранного кванта,
    шаблон — «договоры», если взят его рычаг. Модель — loc-rag-docs (своя, D-10)."""
    б = конфигурации[база]
    опции = dict(б.опции)
    шаблон = б.шаблон or "общий"
    тег, без_проектора = "", False
    for имя in решение["взяты"]:
        к = конфигурации[имя]
        опции.update(к.опции)
        if к.шаблон and к.шаблон != (б.шаблон or "общий"):
            шаблон = к.шаблон
        if к.рычаг == "Р-без-проектора":
            без_проектора = True
        elif к.тег:
            тег = к.тег
    return {"модель": "loc-rag-docs", "опции": опции, "шаблон": шаблон,
            "веса": тег or "qwen3.5:4b", "без_проектора": без_проектора,
            "рычаги": list(решение["взяты"]),
            "описание": "после: " + (", ".join(решение["взяты"]) or "без изменений")}


