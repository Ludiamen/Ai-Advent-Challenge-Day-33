def рядом(отвечатель, вопрос: dict, имена: list[str], судья: str = СУДЬЯ, ход: bool = False) -> list[dict]:
    """Один вопрос в нескольких конфигурациях подряд на одном поиске (веб и консоль)."""
    from agent.local import progress, tuning
    конфигурации = tuning.загрузить()
    чужие = [и for и in имена if и not in конфигурации]
    if чужие:
        raise ValueError(f"Нет конфигурации «{чужие[0]}». Есть: {', '.join(конфигурации)}")
    подготовка = localbench.общий_поиск(отвечатель, вопрос["вопрос"], ход=ход)
    итог = []
    for имя in имена:
        конф = конфигурации[имя]
        ответ, сеть, секунд, замер = ответить_в_конфигурации(отвечатель, конф, вопрос["вопрос"], подготовка, ход)
        з = запись(вопрос, конф, Задание(вопрос.get("id", "свой"), имя), ответ, сеть, подготовка, секунд, замер)
        if судья and not ответ.ошибка and not замер.пропуск:
            localbench.судить(отвечатель.клиент, з, судья)
        итог.append(з)
        if ход:
            progress.этап("готово", конфигурация=имя, верно=з["верно"],
                          модель_с=(з["ответ"].get("timings") or {}).get("модель_с"))
    return итог
