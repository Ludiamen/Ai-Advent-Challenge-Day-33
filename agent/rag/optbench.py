"""Оптимизация локальной LLM под задачу (День 29): скрининг рычагов и «до / после».

Задача — ответ по договорам с источниками и дословными цитатами
(роль «ответ-по-документам», qwen3.5:4b, 14 вопросов Дня 28). Что меняется,
описано конфигурациями (agent/local/tuning.py, local-opt.json); здесь — как
их честно сравнить.

Два прогона (spec § 6.1, FR-08 и FR-10):
- скрининг — каждый рычаг меняет одну вещь относительно «до» и проходит 3
  вопроса (два с ответом и расплывчатый v1 — у него самые длинные ответы);
- качество — 14 вопросов: «до», «после», «после на Q8_0» по одному разу и
  второй повтор «после» для стабильности.

Честный замер (plan.md, D-06…D-08):
- поиск у вопроса один на все конфигурации (общий поиск Дня 28): фрагменты
  и окна одинаковые, разница только в модели;
- модель загружается отдельным запросом с теми же параметрами загрузки, потом
  идёт ответ — так в его время не входит загрузка, а кэш промпта пуст;
- пока идёт ответ, фоновый опрос /proc снимает ОЗУ раннера и секунды
  процессора; после снятия показаний модель выгружается отдельным запросом;
- конфигурации у вопроса идут в порядке, сдвинутом на номер вопроса
  (латинский квадрат), и нагрузка машины пишется в каждую запись;
- ответ, у которого промпт прочитан быстрее 100 ток/с, — из кэша Ollama: он
  помечается и в скорость «нового вопроса» не идёт;
- в памяти одна 4B: перед загрузкой на одном сервере всё выгружается на
  другом.

Каждый ответ — строка JSONL (механизм Дня 28): прерванный прогон
продолжается с места. Качество — проверки Дня 24 (localbench.запись) и судья
ds-pro.

Публичное API:
  ВОПРОСЫ_СКРИНИНГА, СКРИНИНГ, КАЧЕСТВО
  задания_скрининга(вопросы, конфигурации), задания_качества(вопросы, …)
  Прогон(каталог, метка, задания, судья).выполнить(отвечатель, прогресс, стоп)
  сводка(записи) -> {конфигурация: показатели}; выбрать(сводка, конфигурации) -> решение D-05
  без_пд(текст) -> находки; отбор_для_gpu(отвечатель, вопросы) -> список
  модельфайл(база, опции) -> текст Modelfile без проектора
  в_markdown(…), записать(…) -> OPTIMIZE.md, index/local-opt-run.json
"""

