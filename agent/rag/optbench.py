def _тег(конф) -> str:
    from agent import catalog
    return конф.тег or catalog.get(конф.модель).api_id


def _опции_загрузки(конф) -> dict[str, Any]:
    """Тело загрузки — те же опции, что уйдут с ответом: иначе ответ перезапустит раннер."""
    from agent import catalog, llm
    from agent.local import schemas, tuning
    модель = catalog.get(конф.модель)
    with tuning.применить(конф):
        тело = llm.ollama_payload(модель, [], ПРЕДЕЛ_ЦИТАТ, schemas.температура(РОЛЬ_МОДЕЛИ, конф.модель) or 0.0)
    return тело["options"]


def _сервер_для(конф) -> str:
    """Поднять нужный сервер и освободить память на другом; адрес Ollama."""
    from agent.local import resources, server2, tuning
    if конф.сервер == tuning.ВТОРОЙ:
        server2.старт(конф.переменные)
        for м in resources.в_памяти(tuning.адрес(tuning.СЛУЖБА)):
            resources.выгрузить(tuning.адрес(tuning.СЛУЖБА), м["name"])
    elif конф.сервер == tuning.СЛУЖБА:
        if server2.состояние()["running"]:
            for м in resources.в_памяти(server2.АДРЕС):
                resources.выгрузить(server2.АДРЕС, м["name"])
    return tuning.адрес(конф.сервер)


def загрузить_модель(адрес: str, тег: str, опции: dict[str, Any], http=None) -> float:
    """Загрузить модель пустым запросом /api/chat с опциями загрузки; секунды."""
    import httpx
    к = http or httpx.Client(timeout=1800)
    старт = time.monotonic()
    ответ = к.post(f"{адрес}/api/chat", json={"model": тег, "messages": [], "keep_alive": "10m",
                                               "options": опции})
    ответ.raise_for_status()
    return round(time.monotonic() - старт, 2)


def свободно_гб() -> float:
    with open("/proc/meminfo", encoding="utf-8") as f:
        for строка in f:
            if строка.startswith("MemAvailable:"):
                return round(int(строка.split()[1]) / 2**20, 1)
    return 0.0


@dataclass
class Замер:
    """Ресурсы и обстановка одного ответа (spec § 6.2)."""

    загрузка_с: float = 0.0
    ресурсы: dict[str, Any] = field(default_factory=dict)
    в_памяти: list[dict[str, Any]] = field(default_factory=list)
    свободно_гб: float = 0.0
    пропуск: str = ""


def ответить_в_конфигурации(отвечатель, конф, вопрос: str, подготовка,
                            ход: bool = False) -> tuple[ОтветRAG, dict, float, Замер]:
    """Ответ модели в конфигурации на готовом общем поиске; с ресурсами и выгрузкой.

    ход — объявлять этапы наблюдателю progress (страница «рядом» показывает загрузку и
    ответ каждой конфигурации потоком)."""
    from agent.local import offline, progress, resources, tuning
    замер = Замер(свободно_гб=свободно_гб())
    тег = _тег(конф)
    if "bf16" in тег and замер.свободно_гб < СВОБОДНО_ДЛЯ_BF16_ГБ:
        замер.пропуск = f"свободно {замер.свободно_гб} ГБ < {СВОБОДНО_ДЛЯ_BF16_ГБ} — BF16 не загружаем"
        ответ = ОтветRAG(вопрос=вопрос, режим=С_RAG, модель=конф.модель, формат=ЦИТАТЫ, ошибка=замер.пропуск)
        return ответ, {"локальных": 0, "внешних": 0, "заблокировано": 0, "хосты": []}, 0.0, замер
    if ход:
        progress.этап("загрузка", конфигурация=конф.имя, модель=тег, сервер=конф.сервер, локально=True)
    адрес = _сервер_для(конф)
    блобы = resources.блобы(адрес, тег)
    замер.загрузка_с = загрузить_модель(адрес, тег, _опции_загрузки(конф))
    профиль = replace(подготовка.профиль, окно_фрагмента=False)
    до = offline.снимок_журнала()
    старт = time.monotonic()
    # Раннер ищем по блобу весов, без условия о проекторе: в памяти одна 4B (D-09), а у
    # BF16 проектор не отдельной строкой FROM — с условием раннер не находился.
    # На арендованном GPU раннер — на другой машине: локальный /proc снял бы раннер ноутбука
    # с теми же весами. Там память — VRAM модели из /api/ps самой машины.
    удалённо = конф.сервер == tuning.GPU
    with (contextlib.nullcontext() if удалённо else resources.Наблюдатель(блобы[0], None)) as н:
        with tuning.применить(конф):
            ответ = отвечатель.ответить(вопрос, С_RAG, конф.модель, поиск=профиль.поиск, формат=ЦИТАТЫ,
                                        отбор=подготовка.отбор, профиль=профиль, ход=ход)
    секунд = time.monotonic() - старт
    ответ.окна, ответ.секунд_окон = list(подготовка.окна), подготовка.секунд_окон
    замер.в_памяти = resources.в_памяти(адрес)
    замер.ресурсы = ({"удалённо": True, "vram_мб": sum(м.get("vram_мб") or 0 for м in замер.в_памяти)}
                     if удалённо else н.итог)
    resources.выгрузить(адрес, тег)
    return ответ, offline.разница(до, offline.снимок_журнала()), секунд, замер


def запись(вопрос: dict, конф, задание: Задание, ответ: ОтветRAG, сеть: dict, подготовка,
           секунд: float, замер: Замер) -> dict[str, Any]:
    from agent.local import tuning
    у = localbench.Участник(конф.имя, конф.модель, True, конф.описание or конф.имя)
    з = localbench.запись(вопрос, у, задание.повтор, ответ, сеть, подготовка.сеть, секунд)
    т = з["ответ"]["timings"]
    з.update({"конфигурация": конф.имя, "рычаг": конф.рычаг, "тег": _тег(конф), "сервер": конф.сервер,
              "переменные": dict(конф.переменные), "опции": dict(конф.опции),
              # Кэш промпта узнаётся по скорости чтения ≥ 100 ток/с — на GPU это обычная скорость.
              # Там модель так же грузится заново на каждый ответ, кэша у раннера нет.
              "шаблон": ответ.шаблон, "новый": конф.сервер == tuning.GPU or not т.get("кэш_промпта"),
              "обрыв": any(в.get("done") == "length" for в in ответ.замеры_вызовов),
              "загрузка_с": замер.загрузка_с, "ресурсы": замер.ресурсы, "в_памяти": замер.в_памяти,
              "свободно_гб": замер.свободно_гб, "пропуск": замер.пропуск,
              "поиск_с": round(подготовка.отбор.секунд + подготовка.секунд_окон, 2)})
    return з


class Прогон:
    """Задания (вопрос × конфигурация × повтор); строка JSONL на ответ; продолжение с места."""

    def __init__(self, каталог: str, метка: str, задания: list[Задание], вопросы_: list[dict],
                 конфигурации: dict[str, Any] | None = None, судья: str = СУДЬЯ, вид: str = "скрининг") -> None:
        from agent.local import tuning
        self.каталог = каталог
        os.makedirs(каталог, exist_ok=True)
        self.метка = метка or datetime.now().strftime("%Y%m%d-%H%M")
        self.задания = list(задания)
        self.вопросы = {в["id"]: в for в in вопросы_}
        self.конфигурации = конфигурации if конфигурации is not None else tuning.загрузить()
        чужие = sorted({з.конфигурация for з in self.задания} - set(self.конфигурации))
        if чужие:
            raise ValueError(f"Нет конфигураций {', '.join(чужие)} в {tuning.путь()}")
        self.судья = судья
        self.вид = вид
        self.путь_журнала = os.path.join(каталог, f"run-{self.метка}.jsonl")
        self.путь_состояния = os.path.join(каталог, ФАЙЛ_СОСТОЯНИЯ)
        self.текущий = ""

    def записи(self) -> list[dict]:
        if not os.path.exists(self.путь_журнала):
            return []
        итог: dict[str, dict] = {}
        with open(self.путь_журнала, encoding="utf-8") as f:
            for строка in f:
                try:
                    з = json.loads(строка)
                except ValueError:
                    continue
                итог.setdefault(з["ключ"], з)
        return list(итог.values())

    def готовые(self) -> set[str]:
        return {з["ключ"] for з in self.записи()}

    def состояние(self, завершён: bool | None = None) -> dict[str, Any]:
        готово = len(self.готовые() & {з.ключ for з in self.задания})
        return {"метка": self.метка, "вид": self.вид, "готово": готово, "всего": len(self.задания),
                "завершён": готово >= len(self.задания) if завершён is None else завершён,
                "текущий": self.текущий, "судья": self.судья, "pid": os.getpid(),
                "задания": [з.ключ for з in self.задания],
                "когда": datetime.now().isoformat(timespec="seconds"),
                "журнал": os.path.basename(self.путь_журнала)}

    def _сохранить_состояние(self, **поля) -> None:
        записать_атомарно(self.путь_состояния, json.dumps({**self.состояние(), **поля}, ensure_ascii=False,
                                                           indent=1))

    def _дописать(self, з: dict) -> None:
        with open(self.путь_журнала, "a", encoding="utf-8") as f:
            f.write(json.dumps(з, ensure_ascii=False, default=str) + "\n")

    def выполнить(self, отвечатель, клиент=None, прогресс: Callable[[dict, dict], None] | None = None,
                  стоп: Callable[[], bool] | None = None,
                  ответить: Callable[..., tuple] | None = None) -> None:
        """ответить — подмена ответа в тестах (по умолчанию ответить_в_конфигурации)."""
        клиент = клиент or отвечатель.клиент
        ответить = ответить or ответить_в_конфигурации
        готовые = self.готовые()
        подготовки: dict[str, Any] = {}
        for задание in self.задания:
            if задание.ключ in готовые:
                continue
            if стоп and стоп():
                self._сохранить_состояние(завершён=False, остановлен=True)
                return
            вопрос = self.вопросы[задание.вопрос_id]
            if задание.вопрос_id not in подготовки:
                self.текущий = f"{задание.вопрос_id}|поиск"
                self._сохранить_состояние()
                подготовки[задание.вопрос_id] = localbench.общий_поиск(отвечатель, вопрос["вопрос"])
            подготовка = подготовки[задание.вопрос_id]
            конф = self.конфигурации[задание.конфигурация]
            self.текущий = задание.ключ
            self._сохранить_состояние()
            try:
                ответ, сеть, секунд, замер = ответить(отвечатель, конф, вопрос["вопрос"], подготовка)
            except Exception as exc:   # noqa: BLE001 — сбой одного ответа не роняет прогон
                ответ = ОтветRAG(вопрос=вопрос["вопрос"], режим=С_RAG, модель=конф.модель, формат=ЦИТАТЫ,
                                 ошибка=f"{type(exc).__name__}: {exc}"[:300])
                сеть, секунд, замер = {"локальных": 0, "внешних": 0, "заблокировано": 0, "хосты": []}, 0.0, Замер()
            з = запись(вопрос, конф, задание, ответ, сеть, подготовка, секунд, замер)
            if not замер.пропуск and not ответ.ошибка:
                localbench.судить(клиент, з, self.судья)
            self._дописать(з)
            готовые.add(з["ключ"])
            if прогресс:
                прогресс(self.состояние(), з)
        self.текущий = ""
        self._сохранить_состояние()


def идёт_в_другом_процессе(состояние: dict[str, Any] | None) -> bool:
    """Прогон из консоли (или другого сервера) ещё работает: PID жив и прогон не завершён."""
    if not состояние or состояние.get("завершён") or состояние.get("остановлен"):
        return False
    pid = состояние.get("pid")
    if not pid or pid == os.getpid():
        return False
    try:
        with open(f"/proc/{pid}/cmdline", "rb") as f:
            return b"python" in f.read()
    except OSError:
        return False


def прочитать_состояние(каталог: str) -> dict[str, Any] | None:
    путь = os.path.join(каталог, ФАЙЛ_СОСТОЯНИЯ)
    try:
        with open(путь, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


