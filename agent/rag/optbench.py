def замер_скорости(конф, http=None) -> dict[str, Any]:
    """Один замер: загрузка отдельно, ответ на короткий промпт с замерами Ollama и /proc, выгрузка."""
    import httpx
    from agent import catalog, llm
    from agent.local import resources, schemas, tuning
    к = http or httpx.Client(timeout=1800)
    тег = _тег(конф)
    if "bf16" in тег and свободно_гб() < СВОБОДНО_ДЛЯ_BF16_ГБ:
        return {"пропуск": f"свободно {свободно_гб()} ГБ < {СВОБОДНО_ДЛЯ_BF16_ГБ} — BF16 не загружаем"}
    адрес = _сервер_для(конф)
    блобы = resources.блобы(адрес, тег, к)
    загрузка = загрузить_модель(адрес, тег, _опции_загрузки(конф), к)
    with tuning.применить(конф):
        тело = llm.ollama_payload(catalog.get(конф.модель), сообщения_микро(), ПРЕДЕЛ_МИКРО, 0.0, fmt=schemas.ЦИТАТЫ)
    тело["options"]["num_predict"] = ПРЕДЕЛ_МИКРО
    with resources.Наблюдатель(блобы[0], None) as н:
        ответ = к.post(f"{адрес}/api/chat", json=тело).json()
    resources.выгрузить(адрес, тег, к)
    нс = 1e9
    чтение = (ответ.get("prompt_eval_duration") or 0) / нс
    генерация = (ответ.get("eval_duration") or 0) / нс
    вход, выход = ответ.get("prompt_eval_count") or 0, ответ.get("eval_count") or 0
    return {"загрузка_с": загрузка, "вход": вход, "чтение_с": round(чтение, 2),
            "чтение_ток_с": round(вход / чтение, 2) if чтение else None, "выход": выход,
            "генерация_с": round(генерация, 2), "генерация_ток_с": round(выход / генерация, 3) if генерация else None,
            "ресурсы": н.итог, "ошибка": ответ.get("error", "")}


class МикроЗамер:
    """Раунды × конфигурации; строка JSONL на замер; продолжение с места."""

    def __init__(self, каталог: str, метка: str, имена: list[str], раундов: int = РАУНДОВ,
                 конфигурации: dict[str, Any] | None = None) -> None:
        from agent.local import tuning
        self.каталог = каталог
        os.makedirs(каталог, exist_ok=True)
        self.метка = метка or f"микрозамер-{datetime.now():%Y%m%d-%H%M}"
        self.имена, self.раундов = list(имена), раундов
        self.конфигурации = конфигурации if конфигурации is not None else tuning.загрузить()
        чужие = [и for и in self.имена if и not in self.конфигурации]
        if чужие:
            raise ValueError(f"Нет конфигураций {', '.join(чужие)} в {tuning.путь()}")
        self.путь_журнала = os.path.join(каталог, f"run-{self.метка}.jsonl")
        self.путь_состояния = os.path.join(каталог, ФАЙЛ_СОСТОЯНИЯ)
        self.текущий = ""

    def ключи(self) -> list[str]:
        итог = []
        for р in range(1, self.раундов + 1):
            сдвиг = (р - 1) % len(self.имена)
            итог += [f"{р}|{и}" for и in self.имена[сдвиг:] + self.имена[:сдвиг]]
        return итог

    def записи(self) -> list[dict]:
        return Прогон(self.каталог, self.метка, [], [], конфигурации={}).записи()

    def состояние(self, завершён: bool | None = None) -> dict[str, Any]:
        готово = len({з["ключ"] for з in self.записи()} & set(self.ключи()))
        return {"метка": self.метка, "вид": "микрозамер", "готово": готово, "всего": len(self.ключи()),
                "завершён": готово >= len(self.ключи()) if завершён is None else завершён,
                "текущий": self.текущий, "pid": os.getpid(), "задания": [],
                "раундов": self.раундов, "конфигурации": self.имена,
                "когда": datetime.now().isoformat(timespec="seconds"), "журнал": os.path.basename(self.путь_журнала)}

    def выполнить(self, прогресс: Callable[[dict, dict], None] | None = None,
                  стоп: Callable[[], bool] | None = None,
                  замерить: Callable[..., dict] | None = None) -> None:
        замерить = замерить or замер_скорости
        готовые = {з["ключ"] for з in self.записи()}
        for ключ in self.ключи():
            if ключ in готовые:
                continue
            if стоп and стоп():
                записать_атомарно(self.путь_состояния, json.dumps({**self.состояние(False), "остановлен": True},
                                                                   ensure_ascii=False, indent=1))
                return
            раунд, имя = ключ.split("|", 1)
            self.текущий = ключ
            записать_атомарно(self.путь_состояния, json.dumps(self.состояние(), ensure_ascii=False, indent=1))
            конф = self.конфигурации[имя]
            try:
                итог = замерить(конф)
            except Exception as exc:   # noqa: BLE001 — сбой одного замера не роняет прогон
                итог = {"ошибка": f"{type(exc).__name__}: {exc}"[:300]}
            з = {"ключ": ключ, "раунд": int(раунд), "конфигурация": имя, "рычаг": конф.рычаг, "тег": _тег(конф),
                 "сервер": конф.сервер, "опции": dict(конф.опции), "переменные": dict(конф.переменные),
                 "когда": datetime.now().isoformat(timespec="seconds"), **итог}
            with open(self.путь_журнала, "a", encoding="utf-8") as f:
                f.write(json.dumps(з, ensure_ascii=False, default=str) + "\n")
            готовые.add(ключ)
            if прогресс:
                прогресс(self.состояние(), з)
        self.текущий = ""
        записать_атомарно(self.путь_состояния, json.dumps(self.состояние(), ensure_ascii=False, indent=1))


def сводка_микро(записи: list[dict], база: str = "до") -> dict[str, dict[str, Any]]:
    """Скорость по конфигурациям: медиана и размах; к «до» — парно по раундам."""
    по: dict[str, dict[int, dict]] = {}
    for з in записи:
        if з.get("пропуск") or з.get("ошибка"):
            continue
        по.setdefault(з["конфигурация"], {})[з["раунд"]] = з
    итог: dict[str, dict[str, Any]] = {}
    б = по.get(база, {})
    for имя, раунды in по.items():
        зз = list(раунды.values())
        с: dict[str, Any] = {"конфигурация": имя, "рычаг": зз[0].get("рычаг", ""), "раундов": len(зз)}
        for поле in ("чтение_ток_с", "генерация_ток_с", "загрузка_с"):
            значения = [з.get(поле) for з in зз if з.get(поле) is not None]
            с[поле] = _медиана(значения)
            с[поле + "_мин"] = min(значения) if значения else None
            с[поле + "_макс"] = max(значения) if значения else None
        с["пик_мб"] = _медиана([(з.get("ресурсы") or {}).get("пик_мб") for з in зз])
        с["cpu_с"] = _медиана([(з.get("ресурсы") or {}).get("cpu_с") for з in зз])
        с["нагрузка"] = _медиана([(з.get("ресурсы") or {}).get("нагрузка_до") for з in зз])
        общие = sorted(set(раунды) & set(б))
        for поле, имя_доли in (("чтение_ток_с", "чтение"), ("генерация_ток_с", "генерация")):
            доли = [_доля(б[р].get(поле), раунды[р].get(поле)) for р in общие]
            доли = [д for д in доли if д is not None]
            с[имя_доли + "_доля"] = _медиана(доли) if имя != база else 0.0
            с[имя_доли + "_побед"] = sum(1 for д in доли if д > 0) if имя != база else 0
        с["пар"] = len(общие)
        итог[имя] = с
    return итог


