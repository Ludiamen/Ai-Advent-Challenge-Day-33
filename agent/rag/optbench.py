def создать(имя: str, текст: str, путь_файла: str) -> str:
    """`ollama create ИМЯ -f Modelfile` через службу; вывод (последние строки)."""
    import shutil
    import subprocess
    with open(путь_файла, "w", encoding="utf-8") as f:
        f.write(текст)
    программа = shutil.which("ollama") or "/usr/local/bin/ollama"
    итог = subprocess.run([программа, "create", имя, "-f", путь_файла], capture_output=True, text=True,
                          timeout=900)
    вывод = (итог.stdout + итог.stderr).replace("\x1b[K", "").replace("\x1b[?25h", "").replace("\x1b[?2026l", "")
    if итог.returncode != 0:
        raise RuntimeError(f"ollama create {имя} не удалось (код {итог.returncode}): {вывод.strip()[-300:]}")
    return вывод.strip().splitlines()[-1] if вывод.strip() else "success"


