def последний(каталог: str, вид: str) -> str:
    """Метка последнего прогона вида («скрининг» | «качество» | «gpu») по времени файла."""
    if not os.path.isdir(каталог):
        return ""
    файлы = [ф for ф in os.listdir(каталог) if ф.startswith(f"run-{вид}-") and ф.endswith(".jsonl")]
    if not файлы:
        return ""
    файлы.sort(key=lambda ф: os.path.getmtime(os.path.join(каталог, ф)))
    return файлы[-1][len("run-"):-len(".jsonl")]


def записи_прогона(каталог: str, метка: str) -> list[dict]:
    if not метка:
        return []
    return Прогон(каталог, метка, [], [], конфигурации={}).записи()


def условия(адрес: str = "") -> dict[str, Any]:
    """Условия прогона для отчёта: версия Ollama, процессор, память, нагрузка."""
    import httpx
    from agent.local import tuning
    try:
        версия = httpx.get(f"{адрес or tuning.адрес(tuning.СЛУЖБА)}/api/version", timeout=5).json().get("version", "")
    except (httpx.HTTPError, ValueError):
        версия = "—"
    процессор = ""
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as f:
            процессор = next((с.split(":", 1)[1].strip() for с in f if с.startswith("model name")), "")
    except OSError:
        pass
    память = 0.0
    try:
        with open("/proc/meminfo", encoding="utf-8") as f:
            память = round(int(next(с for с in f if с.startswith("MemTotal")).split()[1]) / 2**20, 1)
    except (OSError, StopIteration):
        pass
    return {"когда": datetime.now().isoformat(timespec="minutes"), "Ollama": версия,
            "процессор": f"{процессор}, {os.cpu_count()} потока", "ОЗУ": f"{память} ГБ",
            "нагрузка сейчас": os.getloadavg()[0].__round__(1),
            "ватты": "не меряются: RAPL читается только root; вместо них — секунды процессора"}


def отчёт(каталог_индекса: str, в_корень: bool = True) -> tuple[str, str, dict[str, Any]]:
    """Собрать OPTIMIZE.md и local-opt-run.json по последним прогонам каждого вида."""
    from agent.local import tuning
    каталог = os.path.join(каталог_индекса, КАТАЛОГ)
    конфигурации = tuning.загрузить()
    данные: dict[str, Any] = {"условия": условия()}
    скр = качество = gpu = None
    решение = None
    микро = None
    метка = последний(каталог, "микрозамер")
    if метка:
        записи = записи_прогона(каталог, метка)
        микро = {"метка": метка, "сводка": сводка_микро(записи),
                 "раундов": max((з.get("раунд", 0) for з in записи), default=0),
                 "вход": next((з.get("вход") for з in записи if з.get("вход")), None)}
        данные["микро"] = микро
    метка = последний(каталог, "скрининг")
    if метка:
        записи = записи_прогона(каталог, метка)
        скр = {"метка": метка, "сводка": сводка(записи)}
        решение = выбрать(скр["сводка"], конфигурации, микро=(микро or {}).get("сводка"), вето_=вето())
        данные.update({"скрининг": скр, "решение": решение})
    метка = последний(каталог, "качество")
    if метка:
        качество = {"метка": метка, "сводка": сводка(записи_прогона(каталог, метка))}
        данные["качество"] = качество
    метка = последний(каталог, "gpu")
    файл = tuning.прочитать()
    if метка:
        gpu = {"метка": метка, "сводка": сводка(записи_прогона(каталог, метка)), **(файл.get("gpu") or {})}
        данные["gpu"] = gpu
    elif файл.get("gpu"):
        gpu = dict(файл["gpu"])
    текст = в_markdown(скр, качество, решение, данные["условия"], gpu, файл.get("vps"), микро)
    md, js = записать(каталог_индекса, текст, данные, в_корень)
    return md, js, данные


def создать_модель(каталог_индекса: str, корень: str) -> dict[str, Any]:
    """«После» по последнему скринингу (D-05) → Modelfile.rag-docs, `ollama create loc-rag-docs`,
    конфигурации «после» и «после-q8» в local-opt.json, роль ответа в карте → loc-rag-docs."""
    from agent.local import offline, schemas, tuning
    каталог = os.path.join(каталог_индекса, КАТАЛОГ)
    метка = последний(каталог, "скрининг")
    if not метка:
        raise ValueError("скрининга ещё не было — python cli.py --скрининг")
    конфигурации = tuning.загрузить()
    м = последний(каталог, "микрозамер")
    микро = сводка_микро(записи_прогона(каталог, м)) if м else None
    решение = выбрать(сводка(записи_прогона(каталог, метка)), конфигурации, микро=микро, вето_=вето())
