def _медиана(значения: list[float]) -> float | None:
    чистые = [в for в in значения if isinstance(в, (int, float))]
    return round(statistics.median(чистые), 2) if чистые else None


def _по_вопросам(годные: list[dict]) -> dict[str, dict[str, Any]]:
    """Показатели каждого вопроса (повтор 1) — для парного сравнения с «до»."""
    итог = {}
    for з in годные:
        if з.get("повтор", 1) != 1:
            continue
        т, р = з["ответ"].get("timings") or {}, з.get("ресурсы") or {}
        итог[з["вопрос_id"]] = {"модель_с": т.get("модель_с") if з.get("новый") else None,
                                "чтение_с": т.get("чтение_с") if з.get("новый") else None,
                                "вход": т.get("вход"), "выход": т.get("выход"), "пик_мб": р.get("пик_мб"),
                                "cpu_с": р.get("cpu_с"), "загрузка_с": з.get("загрузка_с"),
                                "верно": bool(з.get("верно")), "починка": bool(з["ответ"].get("repaired")),
                                "обрыв": bool(з.get("обрыв"))}
    return итог


def _стабильность(годные: list[dict]) -> dict[str, int] | None:
    """Совпадение повторов 1 и 2 на одних вопросах: итог (верно/неверно) и текст ответа."""
    п1 = {з["вопрос_id"]: з for з in годные if з.get("повтор", 1) == 1}
    п2 = {з["вопрос_id"]: з for з in годные if з.get("повтор", 1) == 2}
    общие = set(п1) & set(п2)
    if not общие:
        return None
    return {"вопросов": len(общие),
            "итог": sum(1 for в in общие if bool(п1[в].get("верно")) == bool(п2[в].get("верно"))),
            "дословно": sum(1 for в in общие if (п1[в]["ответ"].get("text") or "") == (п2[в]["ответ"].get("text") or ""))}


def сводка(записи: list[dict]) -> dict[str, dict[str, Any]]:
    """Показатели по конфигурациям (spec § 6.2). Скорость — только «новые» ответы."""
    по: dict[str, list[dict]] = {}
    for з in записи:
        по.setdefault(з.get("конфигурация", ""), []).append(з)
    итог: dict[str, dict[str, Any]] = {}
    for имя, зз in по.items():
        годные = [з for з in зз if not з.get("пропуск") and not з.get("ошибка")]
        новые = [з for з in годные if з.get("новый")]
        т = lambda поле, набор=новые: _медиана([(з["ответ"].get("timings") or {}).get(поле) for з in набор])
        р = lambda поле: _медиана([(з.get("ресурсы") or {}).get(поле) for з in годные])
        судья = [((з.get("судья") or {}).get("смысл") or "") for з in годные]
        итог[имя] = {
            "конфигурация": имя, "рычаг": зз[0].get("рычаг", ""), "тег": зз[0].get("тег", ""),
            "сервер": зз[0].get("сервер", ""), "шаблон": зз[0].get("шаблон", ""),
            "ответов": len(зз), "годных": len(годные), "пропусков": sum(1 for з in зз if з.get("пропуск")),
            "ошибок": sum(1 for з in зз if з.get("ошибка") and not з.get("пропуск")),
            "верно": sum(1 for з in годные if з.get("верно")),
            "верно_первый": sum(1 for з in годные if з.get("верно") and з.get("повтор", 1) == 1),
            "годных_первый": sum(1 for з in годные if з.get("повтор", 1) == 1),
            "стабильно": _стабильность(годные),
            "верно_по": {з["вопрос_id"] + (f"#{з['повтор']}" if з.get("повтор", 1) > 1 else ""): bool(з.get("верно"))
                         for з in годные},
            "судья": {"да": судья.count("да"), "частично": судья.count("частично"), "нет": судья.count("нет")},
            "починок": sum(1 for з in годные if з["ответ"].get("repaired")),
            "обрывов": sum(1 for з in годные if з.get("обрыв")),
            "из_кэша": sum(1 for з in годные if not з.get("новый")),
            "вход": т("вход"), "выход": т("выход"),
            "чтение_с": т("чтение_с"), "скорость_чтения": т("скорость_чтения"),
            "генерация_с": т("генерация_с"), "ток_с": т("ток_с"), "модель_с": т("модель_с"),
            "загрузка_с": _медиана([з.get("загрузка_с") for з in годные]),
            "поиск_с": _медиана([з.get("поиск_с") for з in годные]),
            "rss_мб": р("rss_мб"), "пик_мб": р("пик_мб"), "cpu_с": р("cpu_с"), "vram_мб": р("vram_мб"),
            "в_памяти_мб": _медиана([sum(м.get("size_мб", 0) for м in з.get("в_памяти") or []) for з in годные]),
            "нагрузка": _медиана([(з.get("ресурсы") or {}).get("нагрузка_до") for з in годные]),
            "по_вопросам": _по_вопросам(годные),
            "текст": {з["вопрос_id"]: з["ответ"].get("text", "") for з in годные if з.get("повтор", 1) == 1},
        }
    return итог


def _доля(было: float | None, стало: float | None) -> float | None:
    if not было or стало is None:
        return None
    return round((стало - было) / было, 3)


ПОЛЯ_СРАВНЕНИЯ = ("модель_с", "чтение_с", "вход", "выход", "пик_мб", "cpu_с", "загрузка_с")


def сравнить(база: dict[str, Any], другая: dict[str, Any]) -> dict[str, Any]:
    """Изменение относительно «до» — ПАРНОЕ: на каждом общем вопросе отношение к «до»,
    затем медиана отношений (−0,2 — на 20 % меньше). Медиана набора к медиане набора
    сравнивала бы разные вопросы (план, версия 3). Без вопросов — по сводным медианам."""
    пб, пд = база.get("по_вопросам") or {}, другая.get("по_вопросам") or {}
    общие = sorted(set(пб) & set(пд))
    итог: dict[str, Any] = {}
    for поле in ПОЛЯ_СРАВНЕНИЯ:
        if общие:
            доли = [_доля(пб[в].get(поле), пд[в].get(поле)) for в in общие]
            итог[поле] = _медиана([д for д in доли if д is not None])
        else:
            итог[поле] = _доля(база.get(поле), другая.get(поле))
    итог["rss_мб"] = итог["пик_мб"]
    итог["вопросов"] = len(общие)
    итог["верно"] = другая.get("верно", 0) - база.get("верно", 0)
    итог["хуже_на"] = sorted(в for в in общие if пб[в]["верно"] and not пд[в]["верно"])
    return итог


