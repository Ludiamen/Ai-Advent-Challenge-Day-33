             f"по скринингу {метка} (правило D-05): {', '.join(решение['взяты']) or 'рычагов не взято'}.\n"
             f"Веса — {после['веса']}" + (" без визуального проектора" if после["без_проектора"] else "")
             + ". Путь к блобу — из `ollama show … --modelfile` (блоб адресуется хэшем).\n"
