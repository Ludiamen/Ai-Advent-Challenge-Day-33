@dataclass(frozen=True)
class Задание:
    вопрос_id: str
    конфигурация: str
    повтор: int = 1

    @property
    def ключ(self) -> str:
        return f"{self.вопрос_id}|{self.конфигурация}|{self.повтор}"


def _квадрат(вопросы_: list[dict], имена: list[str], повтор: int = 1) -> list[Задание]:
    """Латинский квадрат: у вопроса i конфигурации начинаются с i-й (plan.md, D-07)."""
    итог = []
    for i, в in enumerate(вопросы_):
        сдвиг = i % len(имена) if имена else 0
        for имя in имена[сдвиг:] + имена[:сдвиг]:
            итог.append(Задание(в["id"], имя, повтор))
    return итог


def задания_скрининга(вопросы_: list[dict], конфигурации: list[str] | tuple[str, ...] = СКРИНИНГ) -> list[Задание]:
    return _квадрат(вопросы_, list(конфигурации))


def задания_качества(вопросы_: list[dict], конфигурации: list[str] | tuple[str, ...] = КАЧЕСТВО,
                     повтор_после: str = "после") -> list[Задание]:
    """Повтор 1 — все конфигурации; повтор 2 — только «после» (стабильность)."""
    итог = _квадрат(вопросы_, list(конфигурации))
    if повтор_после:
        итог += [Задание(в["id"], повтор_после, 2) for в in вопросы_]
    return итог


