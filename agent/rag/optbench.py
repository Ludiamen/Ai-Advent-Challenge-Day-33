ОПЦИИ_MODELFILE = ("temperature", "num_predict", "num_ctx", "num_thread", "num_batch", "presence_penalty",
                   "top_k", "top_p", "repeat_penalty")


def модельфайл(база: str, опции: dict[str, Any], без_проектора: bool = True, шапка: str = "") -> str:
    """Modelfile на основе `ollama show … --modelfile`: первая строка FROM — веса,
    вторая (если есть) — визуальный проектор; его убираем (A-2). Шаблон, рендерер и
    парсер — как у базы; PARAMETER базы, которые задаёт конфигурация, заменяются её
    значениями (plan.md, D-10). Лицензия базы сохраняется."""
    строки = база.splitlines()
    итог: list[str] = [f"# {с}" if с else "#" for с in шапка.splitlines()] if шапка else []
    froms = 0
    задано = {к: з for к, з in опции.items() if к in ОПЦИИ_MODELFILE}
    for с in строки:
        if с.startswith("#"):
            continue
        if с.startswith("FROM "):
            froms += 1
            if froms > 1 and без_проектора:
                continue
        м = re.match(r"PARAMETER\s+(\S+)\s+", с)
        if м and м.group(1) in задано:
            continue
        итог.append(с)
    # Параметры конфигурации — сразу после шаблона и парсера, до лицензии.
    куда = next((i for i, с in enumerate(итог) if с.startswith("LICENSE")), len(итог))
    параметры = [f"PARAMETER {к} {з}" for к, з in задано.items()]
    return "\n".join(итог[:куда] + параметры + итог[куда:]).rstrip() + "\n"


