#!/usr/bin/env python3
"""Проверка задания Дня 26: запуск локальной LLM.

Задание: установить и запустить любую локальную LLM; проверить, что модель
запускается локально, что к ней можно обратиться через CLI или HTTP API и что
она отвечает на простой запрос; сделать минимум три запроса разной сложности.
Скрипт идёт по этим пунктам на настоящей Ollama этой машины и живой облачной
модели для сравнения, а агента проверяет отдельными процессами cli.py.

  Часть 1  ЛОКАЛЬНО. Служба ollama, версия, петлевой адрес, скачанные модели
           (размер, параметры, квантование), веса на диске; после запроса
           модель в памяти и считается на CPU.
  Часть 2  CLI. `ollama run МОДЕЛЬ «вопрос» --think=false --verbose` отдельным
           процессом: ответ и замеры самой CLI.
  Часть 3  HTTP API. Тот же вопрос сырым запросом в родной /api/chat и в
           OpenAI-совместимый /v1/chat/completions; список моделей — GET /api/tags.
  Часть 4  ТРИ ЗАПРОСА РАЗНОЙ СЛОЖНОСТИ. Простой, средний и сложный — основной
           локальной модели и облачной рядом; верность проверяет код; время до
           первого токена, скорость, замеры Ollama.
  Часть 5  ЗАМЕР МОДЕЛЕЙ. Четыре локальные модели и облако на шести задачах
           (memory/local/bench.json); основная модель выбрана правилом и
           записана в local-settings.json. С --с-замером замер идёт заново (долго).
  Часть 6  АГЕНТ. cli.py --ollama, --локально --рядом, --модель loc-… с
           командой Дня 22 — локальная модель как провайдер каталога.

Запуск:
    python check_local.py                 # всё, кроме нового замера моделей
    python check_local.py --с-замером     # плюс замер всех моделей заново (десятки минут на CPU)
    python check_local.py --в RESULTS.md  # дописать протокол в файл
"""

from __future__ import annotations

import argparse
import functools
import json
import os
import subprocess
import sys
import time

print = functools.partial(print, flush=True)

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, КОРЕНЬ)

from dotenv import load_dotenv  # noqa: E402

load_dotenv(os.path.join(КОРЕНЬ, ".env"))

from agent import catalog  # noqa: E402
from agent.llm import LLMError  # noqa: E402
from agent.local import bench, ollama, stream  # noqa: E402
from check_tools import LINE, Отчёт, _секунды  # noqa: E402

ВОПРОС_CLI = "Сколько будет 17 умножить на 23? Ответь только числом."
ПАМЯТЬ = os.path.join(КОРЕНЬ, "memory")


def _cli(*ключи: str, предел: int = 900) -> tuple[int, str]:
    готово = subprocess.run([sys.executable, os.path.join(КОРЕНЬ, "cli.py"), *ключи],
                            capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=предел, cwd=КОРЕНЬ)
    return готово.returncode, готово.stdout + готово.stderr


def часть_1(отчёт: Отчёт, основная: str) -> None:
    отчёт.часть(1, "Модель запускается локально: служба, адрес, модели, память")
    с = ollama.состояние()
    отчёт(f"  Ollama {с['version']} · служба {с['service']} · адрес {с['address']} · CLI {с['cli']}")
    отчёт.пункт(not с["error"] and с["service"] == "active", "служба ollama работает и отвечает на HTTP")
    отчёт.пункт(с["loopback"], f"адрес {с['address']} — петлевой интерфейс: запросы не покидают машину")
    for м in с["models"]:
        отчёт(f"    {м['name']:<16} {м['size_gb']:>5} ГБ · {м['params']:<7} · {м['quant']:<7} · {м['family']:<8} · {м['key'] or 'эмбеддер'}")
    скачано = [к["key"] for к in с["catalog"] if к["installed"]]
    отчёт.пункт(len(скачано) >= 1 and основная in скачано,
                f"скачаны локальные модели каталога: {', '.join(скачано)}; основная — {основная}")
    отчёт.пункт(с["disk"]["size_gb"] > 1, f"веса на диске: {с['disk']['path']} — {с['disk']['size_gb']} ГБ")
    сведения = ollama.сведения(catalog.get(основная).api_id)
    отчёт(f"  /api/show {сведения['name']}: умеет {', '.join(сведения['capabilities'])}; "
          f"окно модели {сведения['context_length']}, агент просит {catalog.LOCAL_CTX}")
    ответ = stream.спросить(основная, [{"role": "user", "content": "Ответь одним словом: да."}], предел=10)
    в_памяти = [м for м in ollama.загружены() if м["key"] == основная]
    for м in в_памяти:
        отчёт(f"  /api/ps: {м['name']} · {м['size_gb']} ГБ · {м['processor']} · окно {м['context']} · выгрузится {м['until']}")
    отчёт.пункт(bool(в_памяти) and в_памяти[0]["processor"] == "100% CPU" and в_памяти[0]["context"] == catalog.LOCAL_CTX,
                "после запроса модель в памяти этой машины и считается на CPU, окно — как просит агент")
    отчёт.пункт(bool(ответ["text"]), f"модель отвечает: «{ответ['text']}» "
                f"(загрузка в память {ответ['server'].get('load_s', 0)} с, всего {ответ['total_s']} с)")


def часть_2(отчёт: Отчёт, основная: str) -> None:
    отчёт.часть(2, "Обращение через CLI: ollama run")
    р = ollama.через_cli(catalog.get(основная).api_id, ВОПРОС_CLI)
    отчёт(f"  $ {р['command']}")
    отчёт(f"    {р['stdout'][:200]}")
    for к, з in р["timings"].items():
        отчёт(f"    {к}: {з}")
    отчёт.пункт(р["code"] == 0 and "391" in р["stdout"].replace(" ", ""), "CLI ответила 391 (17 × 23), код возврата 0")
    отчёт.пункт("eval rate" in р["timings"], f"CLI показала свои замеры: скорость генерации {р['timings'].get('eval rate', '—')}")


def часть_3(отчёт: Отчёт, основная: str) -> None:
    отчёт.часть(3, "Обращение через HTTP API: родной и OpenAI-совместимый")
    import httpx
    теги = httpx.get(f"{ollama.адрес()}/api/tags", timeout=5).json()
    отчёт.пункт(any(м["name"] == catalog.get(основная).api_id for м in теги.get("models", [])),
                f"GET {ollama.адрес()}/api/tags — модель {catalog.get(основная).api_id} в списке")
    for вид in ollama.ВИДЫ_HTTP:
        р = ollama.через_http(вид, catalog.get(основная).api_id, ВОПРОС_CLI)
        отчёт(f"  POST {р['url']} → HTTP {р['status']}, {р['seconds']} с")
        отчёт(f"    запрос: {json.dumps(р['request'], ensure_ascii=False)[:220]}")
        ответ = р["response"] if isinstance(р["response"], dict) else {}
        if вид == "native":
            отчёт(f"    ответ: message.content={р['text']!r}, eval_count={ответ.get('eval_count')}, "
                  f"eval_duration={ответ.get('eval_duration')} нс, done_reason={ответ.get('done_reason')}")
        else:
            отчёт(f"    ответ: choices[0].message.content={р['text']!r}, usage={ответ.get('usage')}")
        отчёт.пункт(р["status"] == 200 and "391" in р["text"].replace(" ", ""),
                    f"{'родной /api/chat' if вид == 'native' else 'OpenAI-совместимый /v1/chat/completions'}: ответ 391")


def часть_4(отчёт: Отчёт, основная: str, облако: str) -> None:
    """Задание требует, чтобы модель ОТВЕЧАЛА на запросы разной сложности, а
    верно ли — это качество модели. Поэтому пункт: простой запрос — верно,
    средний и сложный — ответ получен; верность по коду — данными рядом. На CPU
    ответ модели зависит и от того, что спрашивали до него (Ollama
    переиспользует кэш общего начала промпта): пограничный для модели счёт
    платежей в разных прогонах выходит то 36, то 29."""
    отчёт.часть(4, "Три запроса разной сложности: локально и облако рядом, проверка кодом")
    задачи = {з["id"]: з for з in bench.загрузить_задачи()}
    верных = {}
    for ид in ("p1", "s1", "c1"):
        з = задачи[ид]
        отчёт(f"  [{з['уровень']}] {з['название']}: «{з['вопрос'][:110]}{'…' if len(з['вопрос']) > 110 else ''}»")
        верно = {}
        ответил = False
        сообщения, _ = bench.сообщения_задачи(з)
        for ключ in (основная, облако):
            try:
                и = stream.спросить(ключ, сообщения, предел=int(з.get("предел") or 300), температура=0.0)
            except LLMError as exc:
                отчёт(f"    {ключ}: сбой — {exc}")
                верно[ключ] = False
                continue
            ок, пояснение = bench.проверить(з, и["text"])
            верно[ключ] = ок
            if ключ == основная:
                ответил = bool(и["text"].strip())
            сервер = и["server"]
            отчёт(f"    {'локально' if и['local'] else 'облако  '} {catalog.get(ключ).label:<26} {'✓' if ок else '✗'} "
                  f"до 1-го токена {и['ttft_s']} с · {_скорость(и['tok_s'])} · всего {и['total_s']} с · ${и['cost']}"
                  + (f" · Ollama: промпт {сервер.get('prompt_s')} с, генерация {сервер.get('gen_s')} с" if сервер else ""))
            отчёт(f"      > {' '.join(и['text'].split())[:200]}  [{пояснение}]")
        верных[ид] = верно.get(основная, False)
        if ид == "p1":
            отчёт.пункт(верно.get(основная, False), f"   {ид}: локальная модель ответила на простой запрос верно")
        else:
            отчёт.пункт(ответил, f"   {ид}: локальная модель ответила на {з['уровень']} запрос "
                                f"({'верно' if верных[ид] else 'неверно'} по проверке кодом)")
    отчёт(f"  верно по коду у локальной модели: {sum(верных.values())} из {len(верных)}; "
          f"у облака — см. строки выше")


def _скорость(ток_с: float) -> str:
    """Скорость генерации; по ответу из 1–4 токенов она не измерима — «—», а не 0."""
    return f"{ток_с} ток/с" if ток_с else "— ток/с"


def часть_5(отчёт: Отчёт, с_замером: bool) -> None:
    отчёт.часть(5, "Замер моделей: локальные и облако на шести задачах")
    if с_замером:
        модели = [к for к in catalog.local_models() if catalog.installed(к)] + [catalog.for_role("ответ-по-документам", 0)]
        from agent.rag import Индексатор
        from agent.rag.answer import Отвечатель
        from agent.llm import Client
        прогон = bench.прогнать(модели, bench.загрузить_задачи(), отвечатель=Отвечатель(Индексатор(), Client()))
        bench.записать(прогон, ПАМЯТЬ)
        bench.записать_выбор(прогон)
    данные = bench.прочитать(ПАМЯТЬ)
    if not данные:
        отчёт.пункт(False, "прогона замера нет: python cli.py --бенчмарк-локально (или check_local.py --с-замером)")
        return
    отчёт(f"  прогон {данные['when']}, {данные['seconds']} с")
    for к in данные["models"]:
        и = данные["totals"][к]
        у = и["по_уровням"]
        отчёт(f"    {и['label']:<27} {'локально' if и['local'] else 'облако  '} верно {и['верно']} из {и['задач']} "
              f"(простой {у['простой'][0]}/{у['простой'][1]}, средний {у['средний'][0]}/{у['средний'][1]}, "
              f"сложный {у['сложный'][0]}/{у['сложный'][1]}) · {_скорость(и['tok_s'])} · до 1-го {и['ttft_s']} с"
              + (f" · загрузка {и['загрузка_s']} с" if и["local"] else ""))
    локальных = [к for к in данные["models"] if данные["totals"][к]["local"]]
    отчёт.пункт(len(локальных) >= 3, f"замерено локальных моделей: {len(локальных)} (лекция: сравнить несколько)")
    отчёт.пункт(any(not данные["totals"][к]["local"] for к in данные["models"]), "облачная модель — рядом для сравнения")
    выбор = данные.get("chosen") or {}
    отчёт.пункт(выбор.get("model") == bench.основная(),
                f"основная локальная модель — {выбор.get('label', '—')} ({выбор.get('верно')} из {выбор.get('задач')}, "
                f"{выбор.get('tok_s')} ток/с); она же в local-settings.json")


def часть_6(отчёт: Отчёт, основная: str) -> None:
    отчёт.часть(6, "Агент: отдельными процессами cli.py")
    код, вывод = _cli("--ollama")
    отчёт("  $ python cli.py --ollama")
    for строка in вывод.splitlines():
        if строка.startswith(("Ollama ", "  qwen", "  gemma", "  phi4", "Основная")) or "CPU" in строка:
            отчёт("    " + строка[:170])
    отчёт.пункт(код == 0 and "петлевой интерфейс" in вывод and "100% CPU" in вывод, "--ollama: служба, модели, память")
    вопрос = "Какая столица Франции? Ответь одним словом."
    код, вывод = _cli("--локально", вопрос, "--рядом")
    отчёт(f"  $ python cli.py --локально «{вопрос}» --рядом")
    for строка in вывод.splitlines():
        if строка.startswith(("[", "Рядом:")) or "· локально" in строка or "· облако" in строка:
            отчёт("    " + строка[:200])
    отчёт.пункт(код == 0 and "Рядом:" in вывод and вывод.count("Париж") >= 2,
                "--локально --рядом: обе модели ответили «Париж», замеры рядом")
    код, вывод = _cli("--модель", основная, "--без-rag", вопрос)
    отчёт(f"  $ python cli.py --модель {основная} --без-rag «{вопрос}»   # команда Дня 22")
    for строка in вывод.splitlines()[:6]:
        отчёт("    " + строка[:170])
    отчёт.пункт(код == 0 and "Париж" in вывод and основная in вывод,
                f"команда Дня 22 ответила локальной моделью {основная}: локальная модель — провайдер каталога")


def main() -> int:
    разбор = argparse.ArgumentParser(description="Проверка Дня 26: запуск локальной LLM.")
    разбор.add_argument("--с-замером", dest="bench", action="store_true")
    разбор.add_argument("--в", dest="out", default="", metavar="ФАЙЛ")
    аргументы = разбор.parse_args()

    основная = bench.основная()
    облако = catalog.for_role("ответ-по-документам", 0)
    отчёт = Отчёт()
    начало = time.monotonic()
    отчёт(LINE)
    отчёт(f"Проверка Дня 26: локальная LLM · основная {основная} ({catalog.get(основная).api_id}) · "
          f"облако для сравнения {облако}")
    try:
        часть_1(отчёт, основная)
        часть_2(отчёт, основная)
        часть_3(отчёт, основная)
        часть_4(отчёт, основная, облако)
        часть_5(отчёт, аргументы.bench)
        часть_6(отчёт, основная)
    except (ollama.ОшибкаOllama, LLMError) as exc:
        отчёт.пункт(False, f"прервано: {exc}")
    отчёт(LINE)
    отчёт(f"ИТОГ: проверок {отчёт.проверок}, провалов {отчёт.провалов}. "
          f"Прогон {_секунды(time.monotonic() - начало)}.")
    if аргументы.out:
        with open(аргументы.out, "a", encoding="utf-8") as f:
            f.write("\n```text\n" + "\n".join(отчёт.строки) + "\n```\n")
        print(f"Отчёт дописан в {аргументы.out}")
    return 1 if отчёт.провалов else 0


if __name__ == "__main__":
    sys.exit(main())
