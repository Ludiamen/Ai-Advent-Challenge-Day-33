def smoke(отчёт: Отчёт, адрес: str, ключ_пользователя: str, ключ_сотрудника: str) -> None:
    к = httpx.Client(base_url=адрес, verify=False, timeout=60)
    здоровье = к.get("/api/support/health").json()
    отчёт.пункт(здоровье.get("ok") is True, f"здоровье: модель {здоровье.get('модель')}, фрагментов {здоровье.get('фрагментов')}")
    вход = к.get(f"/support?key={ключ_пользователя}", follow_redirects=False)
    отчёт.пункт(вход.status_code == 303 and "key=" not in вход.headers.get("location", "")
                and "secure" in вход.headers.get("set-cookie", "").lower(),
                "вход по ключу: cookie Secure+HttpOnly, адрес без ключа")
    т = time.monotonic()
    р = к.post("/api/support/messages", json={"text": "Почему не работает авторизация?", "ticket": 1001}).json()
    секунд = time.monotonic() - т
    отчёт(f"  ответ за {_секунды(секунд)}: {р['ответ']['решение']} · «{р['ответ']['ответ'][:150]}»")
    отчёт.пункт(bool(р["ответ"]["факты"]) and секунд <= 15, "ответ по фактам тикета, не дольше 15 с (NFR-03)")
    отчёт.пункт(к.get("/api/support/tickets/1002").status_code == 404, "чужой тикет — 404")
    с = httpx.Client(base_url=адрес, verify=False, timeout=60)
