def часть_1(отчёт: Отчёт) -> None:
    отчёт.часть(1, "Данные сервис-деска: синтетика по схеме CRM")
    with open(os.path.join(КОРЕНЬ, "support-seed.json"), encoding="utf-8") as f:
        текст = f.read()
    д = json.loads(текст)
    пользователи, тикеты = д["пользователи"], д["тикеты"]
    отчёт(f"  пользователей {len(пользователи)}, тикетов {len(тикеты)}, входов {len(д['входы'])}")
    отчёт.пункт(len(пользователи) >= 8 and len(тикеты) >= 12, "не меньше 8 пользователей и 12 тикетов")
    записи = [п["учётная_запись"] for п in пользователи if п["учётная_запись"]]
    сценарии = {"блокировка": any(у["статус"] == "заблокирована" for у in записи),
                "второй фактор не подключён": any(у["второй_фактор"] == "не подключён" for у in записи),
                "истёк пароль": any(у["срок_пароля_истёк"] for у in записи),
                "просроченное приглашение": any(у["статус"] == "приглашён" for у in записи),
                "мало резервных кодов": any(0 < у["резервных_кодов"] < 5 for у in записи),
                "нет кодов": any(у["резервных_кодов"] == 0 and у["второй_фактор"] == "подключён" for у in записи),
                "сессия по бездействию": any(у.get("последняя_сессия") for у in записи),
                "новое устройство": any(any(у_.get("новое") for у_ in у.get("устройства", [])) for у in записи),
                "заявитель без учётной записи": any(п["учётная_запись"] is None for п in пользователи)}
    отчёт.пункт(all(сценарии.values()), f"сценарии: {', '.join(к for к, в in сценарии.items() if в)}")
    отчёт.пункт(all(п["роль"] in ("Сотрудник ИТ", "Руководитель", "Администратор портала")
                    for п in пользователи if п["учётная_запись"]),
                "учётные записи портала — только у ИТ (ADR-0001), остальные — заявители")
    почты = set(re.findall(r"[\w.+-]+@[\w.-]+", текст))
    адреса = set(re.findall(r"\b\d{1,3}(?:\.\d{1,3}){3}\b", текст))
    from agent.service import pd
    _, виды = pd.скрыть(текст.replace("@example.invalid", ""), профиль="точный")
    отчёт.пункт(all(п.endswith("@example.invalid") for п in почты) and not виды
                and all(а.startswith(("203.0.113.", "198.51.100.", "192.0.2.")) for а in адреса),
                f"ПД 0: почта только @example.invalid ({len(почты)}), адреса — документационные ({len(адреса)})")


def часть_2(отчёт: Отчёт) -> None:
    отчёт.часть(2, "MCP-сервер support: границы тикета, пульт отдельно, заявки с подтверждением")
    х = хранилище("mcp")
    import anyio
    import support_server
    from mcp import Client as MCPClient

    def вызвать(сервер, имя, аргументы, тикет="1001"):
        async def в():
            async with MCPClient(сервер) as к:
                return await к.call_tool(имя, аргументы)
        with mock.patch.dict(os.environ, {"SUPPORT_TICKET": тикет, "SUPPORT_DATA": х.путь}):
            return anyio.run(в)

    async def список(сервер):
        async with MCPClient(сервер) as к:
            return [и.name for и in (await к.list_tools()).tools]
    ассистент = anyio.run(список, support_server.ассистент)
    пульт = anyio.run(список, support_server.пульт)
    отчёт(f"  ассистент: {', '.join(ассистент)}")
    отчёт(f"  пульт: {', '.join(пульт)}")
    отчёт.пункт(not set(ассистент) & set(пульт) and "desk_apply" not in ассистент,
                "выполнить заявку (desk_apply) есть только у пульта")
    свой = вызвать(support_server.ассистент, "support_requester", {"ticket": 1001})
    чужой = вызвать(support_server.ассистент, "support_requester", {"ticket": 1002})
    отчёт.пункт(not свой.is_error and чужой.is_error and "только тикет №1001" in чужой.content[0].text,
                f"чужой тикет — отказ сервера: «{чужой.content[0].text[:70]}»")
    р = вызвать(support_server.ассистент, "support_request_action",
                {"ticket": 1001, "action": "разблокировать", "reason": "5 неудачных попыток"})
    с = х.пользователь("u01")["учётная_запись"]["статус"]
    отчёт.пункт(not р.is_error and с == "заблокирована", f"заявка заведена, учётная запись по-прежнему «{с}»")


