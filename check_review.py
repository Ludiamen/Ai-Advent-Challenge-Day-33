РЕПОЗИТОРИЙ = "Ludiamen/Ai-Advent-Challenge-Day-32"
# Правило, которое нарушает посеянный дефект, — фрагмент опоры должен содержать все слова.
ОПОРА_СЛОВА = {"C1": ("маск", "выход"), "C2": ("инициал", "фамили"), "C3": ("офлайн", "предохранит"),
               "C4": ("только", "чтени", "git"), "C5": ("критичн", "красн")}


class Стенд:
    """Временный клон на коммите HEAD, проект «advent» смотрит на него, память — в out/."""

    def __init__(self) -> None:
        os.makedirs(КАТАЛОГ, exist_ok=True)
        # Из снимка кода (out/snapshot.sh — без .git) клонируется настоящий корень: туда ведёт .venv.
        источник = КОРЕНЬ if os.path.isdir(os.path.join(КОРЕНЬ, ".git")) else \
            os.path.dirname(os.path.realpath(os.path.join(КОРЕНЬ, ".venv")))
        self.база = evaluate.клон(источник, РЕПО, "HEAD")
        os.environ["PROJECT_ADVENT_DIR"] = РЕПО
        os.environ["MEMORY_DIR"] = os.path.join(КАТАЛОГ, "memory")
        self.проект = project.загрузить("advent")
        self.набор = evaluate.загрузить()
        self.головы: dict[str, str] = {}

    def голова(self, ид: str) -> str:
        if ид not in self.головы:
            случай = next(с for с in self.набор["случаи"] if с["id"] == ид)
            self.головы[ид] = evaluate.применить(РЕПО, случай, "main")
        return self.головы[ид]

    def случай(self, ид: str) -> dict[str, Any]:
        return next(с for с in self.набор["случаи"] if с["id"] == ид)

    def ревью(self, ид: str, **kw: Any) -> pipeline.ИтогРевью:
        с = self.случай(ид)
        return pipeline.выполнить("main", self.голова(ид), канал="проверка", проект=self.проект,
                                  заголовок=с["заголовок"], описание=с.get("описание", ""), **kw)


# --- часть 1 --------------------------------------------------------------------------

def часть_1(отчёт: Отчёт, с: Стенд) -> None:
    отчёт.часть(1, "Вход: diff и изменённые файлы — через git-сервер MCP")
    git = GitMCP(с.проект)
    try:
        в = source.получить(git, "main", с.голова("C8"), заголовок="C8")
        for ф in в.файлы:
            отчёт(f"  {ф.путь}: {ф.статус} +{ф.добавлено} −{ф.удалено}"
                  + (f" — пропущен: {ф.причина}" if ф.пропущен else f" — diff {len(ф.diff)} симв., "
                     f"голова {'есть' if ф.голова else 'нет'}"))
        пропущены = {ф.путь: ф.пропущен for ф in в.пропущенные}
        отчёт.пункт(пропущены == {"docs/logo.png": "бинарный", "poetry.lock": "шаблон"},
                    f"бинарный и lock-файл пропущены с причиной: {пропущены}")
        render_ф = в.файл("agent/review/render.py")
        отчёт.пункт(bool(render_ф and "ПРЕДЕЛ_КОММЕНТАРИЯ" in render_ф.diff and render_ф.голова),
                    "правка кода: diff и полный текст головы получены")
        отчёт.пункт(в.вызовы[0] == "git_changes" and {"git_diff", "git_show"} <= set(в.вызовы),
                    f"вызовы git-сервера MCP по порядку: {', '.join(в.вызовы)}")
        отчёт.пункт(isinstance(git, GitMCP) and git.ящик.инструменты is not None,
                    "сервер — отдельный процесс stdio из mcp-servers.json (git_server.py)")
        большой = source.получить(git, "main", с.голова("C8"), предел_всего=200, предел_файла=150)
        отчёт.пункт(any(ф.diff_обрезан for ф in большой.просмотренные) or
                    any(ф.пропущен == "объём" for ф in большой.файлы),
                    "пределы: при 200 символах на PR diff обрезан, сверх — «объём»")
    finally:
        git.закрыть()


# --- часть 2 --------------------------------------------------------------------------

def часть_2(отчёт: Отчёт, с: Стенд) -> dict[str, Any]:
    отчёт.часть(2, "Опора: RAG по документам и коду базы PR")
    поиск, сведения = pipeline.поисковик(с.проект, с.база, pipeline.ЛЕКСИЧЕСКИЙ)
    отчёт(f"  индекс базы {с.база[:7]}: {сведения['файлов']} файлов, {сведения['фрагментов']} фрагментов, "
          f"{_секунды(сведения['секунд'])} ({сведения['способ']})")
    отчёт.пункт(сведения["фрагментов"] > 1000, "индекс собран из документов и кода репозитория")
    with open(os.path.join(с.проект.индекс, "manifest.json"), encoding="utf-8") as f:
        манифест = json.load(f)
    отчёт.пункт(манифест["коммит"] == с.база, f"индекс собран из коммита базы {с.база[:7]}, не из рабочего каталога")
    виды = {"код": 0, "документ": 0}
    for путь in манифест["файлы"]:
        виды["код" if путь.endswith(".py") else "документ"] += 1
    отчёт.пункт(виды["код"] > 50 and виды["документ"] > 10, f"в индексе код и документы: {виды}")
    git = GitMCP(с.проект)
    итог: dict[str, Any] = {}
    try:
        for ид, слова in ОПОРА_СЛОВА.items():
            в = source.получить(git, "main", с.голова(ид), заголовок=с.случай(ид)["заголовок"])
            т = time.monotonic()
            о = context.собрать(в, поиск, git)
            нужные = [ф for ф in о.фрагменты if all(сл in ф.текст.lower() or сл in ф.подпись.lower() for сл in слова)]
            выданы = set(о.на_ревьюера["баги"]) | set(о.на_ревьюера["архитектура"])
            ревьюерам = [ф for ф in нужные if ф.номер in выданы]
            итог[ид] = bool(ревьюерам)
            отчёт(f"  {'·' if ревьюерам else '○'} {ид}: правило «{' + '.join(слова)}» в опоре ревьюеров — "
                        + (f"[{ревьюерам[0].номер}] {ревьюерам[0].подпись[:80]}" if ревьюерам else
                           f"нет (в опоре {len(нужные)}, всего фрагментов {len(о.фрагменты)})")
                        + f"; места вызова {sum(1 for ф in о.фрагменты if ф.вид == 'вызов')}; "
                        f"{_секунды(time.monotonic() - т)}")
    finally:
        git.закрыть()
    доля = sum(итог.values()) / len(итог)
    отчёт.пункт(доля >= 0.8, f"полнота опоры: правило, которое нарушает посеянный дефект, у ревьюеров в "
                f"{sum(итог.values())} из {len(итог)} случаев ({доля:.0%}, порог 80 %)")
    return итог


# --- часть 3 --------------------------------------------------------------------------

def часть_3(отчёт: Отчёт, с: Стенд) -> None:
    отчёт.часть(3, "Ревьюеры и сборщик: три раздела параллельно, находки проверяет код")
    итог = с.ревью("C1")
    м = итог.метрики
    отчёт(f"  C1: {итог.вердикт}, {_секунды(м['секунд'])}, токенов {м['токены']}, ${м['стоимость']:.4f}; "
          f"этапы {м['этапы']}")
    for р in итог.сборка.ревьюеры:
        отчёт(f"  · {р.раздел}: ок={р.ок}, {_секунды(р.секунд)}, находок {len(р.находки)}, инструментов {р.инструментов}")
    отчёт.пункт(all(р.ок for р in итог.сборка.ревьюеры), "все три ревьюера отработали")
    сумма = sum(р.секунд for р in итог.сборка.ревьюеры)
    отчёт.пункт(сумма > м["этапы"]["ревьюеры"] * 1.5,
                f"параллельно: сумма времён ревьюеров {_секунды(сумма)} > этап {_секунды(м['этапы']['ревьюеры'])}")
    отчёт.пункт(any(н.источники for н in итог.сборка.находки), "у находок есть источники из опоры (номера фрагментов)")
    git = GitMCP(с.проект)
    try:
        в = source.получить(git, "main", с.голова("C1"))
        о = context.собрать(в, None, git)
    finally:
        git.закрыть()
    подставные = reviewers.ИтогРевьюера("баги", ок=True, находки=[
        reviewers.Находка("баги", "agent/llm.py", 10, "критично", "чужой файл", фрагмент_diff="x"),
        reviewers.Находка("баги", "agent/service/telegram.py", 5, "важно", "строка вне участка",
                          фрагмент_diff='части = [str(д.get("answer") or "")]'),
        reviewers.Находка("баги", "agent/service/telegram.py", 0, "критично", "выдуманная цитата",
                          фрагмент_diff="send_unmasked(answer)  # такого нет в diff")])
    сб = collect.собрать(в, о, [подставные, reviewers.ИтогРевьюера("архитектура", ок=True),
                                reviewers.ИтогРевьюера("рекомендации", ок=True)])
    отчёт.пункт(сб.отброшено == 1, "находка по файлу вне PR отброшена")
    отчёт.пункт(сб.без_строки == 1 and any(н.суть == "строка вне участка" and н.строка == 0 for н in сб.находки),
                "строка вне изменённых участков снята")
    выдуманная = next(н for н in сб.находки if н.суть == "выдуманная цитата")
    отчёт.пункт(not выдуманная.подтверждена and выдуманная.серьёзность == "важно" and сб.вердикт == "зелёный",
                "выдуманная цитата: не подтверждена, «критично» понижено, PR не красится")


