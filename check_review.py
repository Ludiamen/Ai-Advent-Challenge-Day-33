def часть_8(отчёт: Отчёт, pr: int) -> None:
    отчёт.часть(8, f"Живой GitHub: прогоны workflow пробного PR #{pr}")
    токен = os.environ.get("GITHUB_PAT", "")
    if not токен:
        отчёт.пункт(False, "нет GITHUB_PAT в .env")
        return
    к = httpx.Client(headers={"Authorization": f"Bearer {токен}", "Accept": "application/vnd.github+json"},
                     timeout=30, follow_redirects=True)
    api = f"https://api.github.com/repos/{РЕПОЗИТОРИЙ}"
    данные = к.get(f"{api}/pulls/{pr}").json()
    прогоны = [р for р in к.get(f"{api}/actions/runs", params={"event": "pull_request", "per_page": 50}).json()
               .get("workflow_runs", []) if any(p.get("number") == pr for p in р.get("pull_requests", []))
               or р.get("head_branch") == данные["head"]["ref"]]
    отчёт(f"  PR #{pr} «{данные['title']}», голова {данные['head']['sha'][:7]}; прогонов workflow {len(прогоны)}")
    for р in прогоны[:6]:
        отчёт(f"  · {р['head_sha'][:7]} {р['status']}/{р['conclusion']} {р['html_url']}")
    отчёт.пункт(len(прогоны) >= 2, "workflow запускался на открытие PR и на новый коммит")
    свои = [c for c in к.get(f"{api}/issues/{pr}/comments").json() if render.МЕТКА in (c.get("body") or "")]
    отчёт.пункт(len(свои) == 1, f"комментарий ревью один ({len(свои)}), автор {свои[0]['user']['login'] if свои else '—'}")
    if свои:
        тело = свои[0]["body"]
        м = render.метрики_из(тело) or {}
        отчёт.пункт(м.get("голова", "")[:7] == данные["head"]["sha"][:7],
                    f"комментарий обновлён для последнего коммита ({м.get('голова', '')[:7]})")
        последний = next((р for р in прогоны if р["head_sha"] == данные["head"]["sha"]), None)
        ожидание = {"зелёный": "success", "красный": "failure", "не выполнено": "failure"}.get(м.get("вердикт", ""))
        отчёт.пункт(bool(последний) and последний["conclusion"] == ожидание,
                    f"цвет проверки совпадает с вердиктом: {м.get('вердикт')} → {последний['conclusion'] if последний else '—'}")
    секреты = {к_: в for к_, в in __import__("dotenv").dotenv_values(os.path.join(КОРЕНЬ, ".env")).items()
               if в and len(в) >= 6 and any(с in к_ for с in ("KEY", "TOKEN", "PAT", "ID"))}
    утечек = 0
    for р in прогоны[:4]:
        for задание in к.get(р["jobs_url"]).json().get("jobs", []):
            журнал = к.get(f"{api}/actions/jobs/{задание['id']}/logs")
            if журнал.status_code == 200:
                утечек += sum(1 for в in секреты.values() if в in журнал.text)
    отчёт.пункт(утечек == 0, f"значений секретов в журналах заданий: {утечек} (проверено {len(секреты)} значений)")


