def часть_5(отчёт: Отчёт, с: Стенд) -> None:
    отчёт.часть(5, "Сбои: модель недоступна, нет ключа, упал один ревьюер, PR из форка")
    поиск, _ = pipeline.поисковик(с.проект, с.база)
    вызовов = []

    def недоступна(запрос: httpx.Request) -> httpx.Response:
        вызовов.append(запрос.url.host)
        return httpx.Response(503, text="service unavailable")
    def клиент_недоступен() -> Client:
        к = Client()
        к._http = httpx.Client(transport=httpx.MockTransport(недоступна))   # __post_init__ создаёт свой — подменяем после
        return к
    with mock.patch("agent.llm.time.sleep"):
        итог = с.ревью("C1", поиск=поиск, клиент_для=клиент_недоступен)
    отчёт.пункт(итог.вердикт == "не выполнено" and итог.код_выхода == 2,
                f"503 от провайдера (запросов {len(вызовов)}, с повтором): «{итог.вердикт}», код {итог.код_выхода}")
    отчёт.пункт("не выполнено" in итог.текст and "нужен человек" in итог.текст, "комментарий говорит, что нужен человек")
    with mock.patch.dict(os.environ, {"DEEPSEEK_API_KEY": ""}):
        итог = с.ревью("C1", поиск=поиск)
    отчёт.пункт(итог.код_выхода == 2 and "DEEPSEEK_API_KEY" in итог.сборка.причина,
                f"нет ключа: код {итог.код_выхода}, причина «{итог.сборка.причина[:60]}»")

    class ПадаетАрхитектура:
        def __init__(self) -> None:
            self.к = Client()

        def call(self, модель, сообщения, **kw):
            if "«Архитектурные проблемы»" in сообщения[0]["content"]:
                raise RuntimeError("архитектор недоступен")
            return self.к.call(модель, сообщения, **kw)
    итог = с.ревью("C1", поиск=поиск, клиент_для=ПадаетАрхитектура)
    ок = [р.раздел for р in итог.сборка.ревьюеры if р.ок]
    отчёт.пункт(ок == ["баги", "рекомендации"] and итог.вердикт == "красный" and "Не выполнены разделы" in итог.текст,
                f"упал ревьюер «архитектура»: отработали {ок}, вердикт {итог.вердикт}, пометка в комментарии")
    import review
    with tempfile.TemporaryDirectory() as tmp:
        сводка = os.path.join(tmp, "summary.md")
        with mock.patch.dict(os.environ, {"GITHUB_STEP_SUMMARY": сводка}):
            код = review.ревью_события(github.СобытиеPR(РЕПОЗИТОРИЙ, 99, "main", с.база, с.голова("C1"), "из форка",
                                                        "", форк=True, черновик=False), "")
        with open(сводка, encoding="utf-8") as f:
            текст = f.read()
    отчёт.пункт(код == 0 and "из форка" in текст, f"PR из форка: код {код}, пояснение в сводке задания")


