def часть_6(отчёт: Отчёт, с: Стенд) -> None:
    отчёт.часть(6, "Публикация: один комментарий, обновление, обезвреживание; Telegram без кода")
    комментарии: dict[int, dict[str, Any]] = {}
    телеграм: list[dict[str, Any]] = []

    def gh_api(запрос: httpx.Request) -> httpx.Response:
        if запрос.method == "GET" and запрос.url.path.endswith("/issues/42/comments"):
            return httpx.Response(200, json=list(комментарии.values()))
        if запрос.method == "GET":
            return httpx.Response(200, json=[])
        тело = json.loads(запрос.content)["body"]
        if запрос.method == "POST":
            ид = 500 + len(комментарии)
            комментарии[ид] = {"id": ид, "body": тело}
            return httpx.Response(201, json=комментарии[ид])
        ид = int(запрос.url.path.rsplit("/", 1)[-1])
        комментарии[ид]["body"] = тело
        return httpx.Response(200, json=комментарии[ид])

    def tg_api(запрос: httpx.Request) -> httpx.Response:
        телеграм.append(json.loads(запрос.content))
        return httpx.Response(200, json={"ok": True})
    НастоящийGitHub, настоящий_отправить = github.GitHub, notify.отправить
    поиск, _ = pipeline.поисковик(с.проект, с.база)
