#!/usr/bin/env python3
"""Проверка задания Дня 32: автоматическое AI-ревью PR (specs/032-code-review).

Скрипт идёт по пунктам задания и критериям spec SC-01…SC-07 против настоящих частей:
git-сервера MCP, индекса базы, модели ds-flash (судья — ds-pro) и живого репозитория GitHub.
Случаи контрольного набора накладываются во временном клоне в out/ — рабочий каталог не
меняется.

  Часть 1  ВХОД (SC-02). Случай C8 (бинарный, lock-файл и правка): файлы, +/−, пропуски с
           причиной; diff и текст головы — вызовами git-сервера MCP; пределы на большом diff.
  Часть 2  ОПОРА — RAG по документам и коду базы (SC-03). Индекс из коммита базы, а не головы;
           для C1–C5 в опоре есть фрагмент с правилом, которое нарушает посеянный дефект.
  Часть 3  РЕВЬЮЕРЫ И СБОРЩИК. Живой C1: три раздела, параллельность, источники; подставные
           находки (чужой файл, строка вне участка, выдуманная цитата) отброшены или понижены.
  Часть 4  КАЧЕСТВО (SC-05). review-cases.json × 3 прогона ds-flash, судья ds-pro: доля найденных
           посеянных дефектов, чистые случаи зелёные, ложных критичных 0.
  Часть 5  СБОИ (SC-06). Модель недоступна (503 через настоящий llm.Client) → «не выполнено», код
           2; нет ключа → код 2; один ревьюер упал → два раздела и пометка; PR из форка → пропуск.
  Часть 6  ПУБЛИКАЦИЯ (SC-04). Заглушка GitHub API: комментарий создаётся, при втором прогоне
           обновляется тот же; метка, скрытые метрики, обезвреживание; Telegram — без кода.
  Часть 7  МЕТРИКИ (SC-07). Журнал без текстов; сводка p50/p95, стоимость, доли; тревога на
           подставленной истории.
  Часть 8  ЖИВОЙ GITHUB (SC-01, SC-04, SC-06). Прогоны workflow пробного PR: комментарий один и
           обновлён, цвет проверки совпадает с вердиктом, секретов в журнале задания нет.

Запуск:
    python check_review.py                    # всё (часть 4 — около 25 мин и ≈ $1)
    python check_review.py --быстро           # часть 4 — по одному прогону
    python check_review.py --pr 1             # номер пробного PR для части 8
    python check_review.py --в RESULTS.md
"""

