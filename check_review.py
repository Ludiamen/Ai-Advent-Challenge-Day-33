def часть_4(отчёт: Отчёт, с: Стенд, прогонов: int) -> dict[str, Any]:
    прогонов = прогонов or int(с.набор["критерий"]["прогонов"])
    отчёт.часть(4, f"Качество: контрольный набор × {прогонов} на ds-flash, судья ds-pro")
    судья = Client()

    def выполнить(от: str, до: str, заголовок: str, описание: str) -> Any:
        return pipeline.выполнить("main", до, канал="проверка", проект=с.проект, заголовок=заголовок,
                                  описание=описание)
    for случай in с.набор["случаи"]:
        с.голова(случай["id"])
    прогоны = evaluate.прогнать(с.набор, РЕПО, с.база, выполнить, судья, прогонов, ход=lambda т: отчёт(f"  {т}"))
    итог = evaluate.итог(прогоны, с.набор["критерий"])
    with open(os.path.join(КАТАЛОГ, "cases.json"), "w", encoding="utf-8") as f:
        json.dump({"итог": итог, "прогоны": [п.to_dict() for п in прогоны]}, f, ensure_ascii=False, indent=1)
    к = с.набор["критерий"]
    отчёт.пункт(итог["доля_найденных"] >= к["доля_найденных"],
                f"посеянные дефекты найдены: {итог['найдено']} из {итог['посеяно']} "
                f"({итог['доля_найденных']:.0%}, порог {к['доля_найденных']:.0%})")
    отчёт.пункт(итог["чистые_зелёные"] >= к["чистые_зелёные"], f"чистые случаи зелёные: {итог['чистые_зелёные']:.0%}")
    отчёт.пункт(итог["ложных_критичных"] <= к["ложных_критичных"],
                f"ложных подтверждённых критичных на чистых: {итог['ложных_критичных']}")
    for ид, д in итог["по_случаям"].items():
        отчёт(f"  {ид}: засчитано {д['засчитано']} из {д['прогонов']}, вердикты {', '.join(д['вердикты'])}")
    отчёт(f"  p50 {_секунды(итог['p50_с'])} на ревью, всего ${итог['стоимость']:.3f} (без судьи)")
    return итог


